def заставка(секунд=3.2):
    """Исходник для заставки: один вид тела, та же камера, та же скорость.

    Отдельным прогоном, а не куском ролика, и причина в кадре. Сцена
    тела в ролике идёт ДВУМЯ видами сразу, и каждая половина —
    вертикальная, 640×720. Карта глубины из такой половины, растянутой
    до 16:9, выйдет мыльной, а из обеих сразу — двумя сценами в одном
    кадре, чего у настоящей глубины не бывает.

    Прогон тот же самый: та же песочница, то же тело, та же сглаженная
    камера. Меняется только то, что вид один.
    """
    import imageio.v2 as iio

    из = поднять((W, H_СЪЁМКИ))
    if из is None:
        return
    sh, ses, app, t0 = из
    st = app.st
    OUT.mkdir(parents=True, exist_ok=True)
    путь = OUT / "_заставка-исходник.mp4"
    писарь = iio.get_writer(str(путь), fps=ВИДЕО_FPS, codec="libx264",
                            quality=9, macro_block_size=1,
                            ffmpeg_params=["-pix_fmt", "yuv420p"])
    было_begin = sh.begin

    def begin():
        ctx = было_begin()
        sh.dt = МОДЕЛЬ_НА_КАДР / 1000.0
        return ctx

    sh.begin = begin
    кадров = int(секунд * ВИДЕО_FPS)
    try:
        _sb, ok = песочница(app, ses, sh, t0)
        if not ok:
            return
        st.ws.switch("sandbox")
        st.ws.dock().maximized = True
        # Полторы секунды модельного — чтобы муха расходилась: на
        # первых шагах она ещё оседает на лапы, и это видно.
        ждать(app, lambda: ses.t_ms > 1500.0, 600, sh, t0)
        база = ses.t_ms
        for k in range(кадров):
            цель = база + (k + 1) * МОДЕЛЬ_НА_КАДР
            край = time.perf_counter() + 30.0
            while ses.t_ms < цель - 1e-9 and time.perf_counter() < край:
                ses.pump(0.0)
                time.sleep(0.0005)
            app.frame()
            писарь.append_data(кадр_в_массив(sh, обрезать=True))
        app.cancel_run()
        ждать(app, lambda: not ses.busy, 180, sh, t0)
    finally:
        писарь.close()
        sh.begin = было_begin
        ses.close()
    print("  заставка: %d кадров -> %s (%.1f МБ)"
          % (кадров, путь.name, путь.stat().st_size / (1 << 20)), flush=True)


