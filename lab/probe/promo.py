def _сгладить(x, tau_s, dt_s=МОДЕЛЬ_НА_КАДР / 1000.0, звеньев=2):
    """Два звена экспоненциального сглаживания по готовому ряду.

    Ровно та же формула, что уйдёт в работника, — чтобы сравнение
    «до и после» считалось по одним и тем же числам, а не по похожим.
    """
    a = 1.0 - np.exp(-dt_s / max(tau_s, 1e-6))
    y = np.asarray(x, dtype=np.float64).copy()
    for _ in range(звеньев):
        s = y[0]
        out = np.empty_like(y)
        for i, v in enumerate(y):
            s += a * (v - s)
            out[i] = s
        y = out
    return y


def _дрожь(ряд, окно=11):
    """Отклонение от местного тренда: именно его видит глаз как тряску.

    Тренд — центрированное среднее по окну 11 шагов (0,22 с): поворот
    мухи в него попадает, а колебание походки на 12 Гц — нет.
    """
    v = np.asarray(ряд, dtype=np.float64)
    if len(v) < окно + 2:
        return 0.0, 0.0, 0.0
    k = окно // 2
    тренд = np.convolve(v, np.ones(окно) / окно, mode="valid")
    ост = v[k:len(v) - k] - тренд
    шаг = np.abs(np.diff(v))
    return (float(np.sqrt(np.mean(ост ** 2))), float(ост.max() - ост.min()),
            float(np.median(шаг)))


def проба_тряски(секунд=6.0):
    """Два замера под две правки: охват мозга при вращении и тряска камеры.

    Оба числа нужны ДО правки. Иначе выйдет «стало лучше» на глаз, а
    постоянную времени фильтра придётся выбирать гаданием.
    """
    из = поднять((W, H_СЪЁМКИ))
    if из is None:
        return
    sh, ses, app, t0 = из
    st = app.st
    st.ws.switch("brain")
    st.ws.dock().maximized = True
    for _ in range(12):
        app.frame()
    bv = app.brain

    # --- 1. охват мозга по кругу --------------------------------------
    vx, vy, vw, vh = bv._vp
    aspect = vw / max(vh, 1)
    yaw0, zoom0 = bv.yaw, bv.zoom
    d = []
    for i in range(36):
        bv.yaw = yaw0 + 2 * np.pi * i / 36.0
        bv._fit_key = None
        d.append(bv._fit(aspect))
    bv.yaw, bv.zoom = yaw0, zoom0
    bv._fit_key = None
    d = np.asarray(d)
    print("  охват при вращении: вид %dx%d, расстояние от %.3f до %.3f, "
          "размах %.0f%%" % (vw, vh, d.min(), d.max(),
                             (d.max() / d.min() - 1.0) * 100.0), flush=True)
    print("  замри на максимуме — мозг в самом узком повороте займёт "
          "%.0f%% кадра" % (d.min() / d.max() * 100.0), flush=True)
    шаг_охвата = np.abs(np.diff(np.concatenate([d, d[:1]])))
    print("  кадр к кадру при облёте 0,0035 рад: охват меняется на "
          "%.3f%% (медиана по кругу)"
          % (np.median(шаг_охвата) / d.mean() * 100.0 * (0.0035 /
             (2 * np.pi / 36.0))), flush=True)

    # --- 2. тряска камеры за мухой ------------------------------------
    sb, ok = песочница(app, ses, sh, t0)
    if not ok:
        return
    st.ws.switch("sandbox")
    st.ws.dock().maximized = True
    ждать(app, lambda: False, 1.5, sh, t0)
    край = ses.t_ms + секунд * 1000.0
    было = -1.0
    th, xs, ys = [], [], []
    while ses.t_ms < край:
        app.frame()
        if ses.t_ms > было + 1e-9:
            было = ses.t_ms
            ex = ses.extra or {}
            th.append(float(ex.get("theta", 0.0) or 0.0))
            xs.append(float(ex.get("x", 0.0) or 0.0))
            ys.append(float(ex.get("y", 0.0) or 0.0))
    app.cancel_run()
    ждать(app, lambda: not ses.busy, 180, sh, t0)
    ses.close()

    th = np.degrees(np.unwrap(np.asarray(th)))
    xs, ys = np.asarray(xs), np.asarray(ys)
    print("  шагов управления %d, модельного %.1f с, путь %.1f мм"
          % (len(th), len(th) * МОДЕЛЬ_НА_КАДР / 1000.0,
             float(np.hypot(xs[-1] - xs[0], ys[-1] - ys[0]))), flush=True)
    rms, пик, медш = _дрожь(th)
    print("  курс как есть:   дрожь %.2f° СКЗ, размах %.2f°, "
          "кадр к кадру %.2f°" % (rms, пик, медш), flush=True)
    for tau in (0.08, 0.12, 0.18, 0.25):
        s = _сгладить(th, tau)
        r2, p2, m2 = _дрожь(s)
        # Запаздывание считается, а не объявляется: сдвиг, при котором
        # сглаженный ряд ближе всего к исходному.
        лаги = [(float(np.mean((s[k:] - th[:len(th) - k]) ** 2)), k)
                for k in range(0, 40)]
        _, k = min(лаги)
        print("    tau %.2f с: дрожь %.2f° СКЗ (%.0f%% от прежней), "
              "кадр к кадру %.3f°, запаздывание %.0f мс"
              % (tau, r2, r2 / max(rms, 1e-9) * 100.0, m2,
                 k * МОДЕЛЬ_НА_КАДР), flush=True)
    for имя, v in (("x", xs), ("y", ys)):
        rms, пик, медш = _дрожь(v)
        print("  %s как есть: дрожь %.3f мм СКЗ, размах %.3f мм, "
              "кадр к кадру %.3f мм" % (имя, rms, пик, медш), flush=True)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--кадры", action="store_true")
    ap.add_argument("--видео", action="store_true")
    ap.add_argument("--цветные", action="store_true",
                    help="два крупных снимка мозга: зелёный и розовый")
    ap.add_argument("--заставка", action="store_true",
                    help="снять 3 с одного вида под карту глубины")
    ap.add_argument("--проба", action="store_true",
                    help="две сцены ролика во весь кадр, без подписей")
    ap.add_argument("--запах", action="store_true",
                    help="замерить поворот на запах, без записи видео")
    ap.add_argument("--тряска", action="store_true",
                    help="замерить охват мозга при вращении и дрожь камеры")
    ap.add_argument("--секунд", default="14")
    ap.add_argument("--до", default="13000")
    args = ap.parse_args()
    if getattr(args, "кадры"):
        кадры()
    if getattr(args, "видео"):
        видео()
    if getattr(args, "цветные"):
        цветные()
    if getattr(args, "заставка"):
        заставка()
    if getattr(args, "проба"):
        проба()
    if getattr(args, "тряска"):
        проба_тряски(float(getattr(args, "секунд")) if
                     getattr(args, "секунд") != "14" else 6.0)
    if getattr(args, "запах"):
        проба_запаха(float(getattr(args, "секунд")),
                     float(getattr(args, "до")))


if __name__ == "__main__":
    main()
