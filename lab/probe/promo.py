# Съёмка ролика идёт в окно ВЫШЕ кадра ровно на верхнюю полосу и подвал.
# Развёрнутый центр получает `body` целиком (`desk/layout.compute`), то
# есть всё, кроме этих двух полос; значит при такой высоте центр выходит
# ровно 1920×1080 и обрезается без единого пересчёта размера. Снимать
# ролик в 1920×1080 и потом тянуть обрезок обратно до 1080 значило бы
# мылить текст ради семи процентов высоты.
ВЕРХ, ПОДВАЛ = 52, 26
H_СЪЁМКИ = H + ВЕРХ + ПОДВАЛ
МОДЕЛЬ_НА_КАДР = 20.0        # мс модельного времени на кадр видео
ВИДЕО_FPS = 50               # = 1000 / МОДЕЛЬ_НА_КАДР
