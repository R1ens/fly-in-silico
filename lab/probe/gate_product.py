def r_spmv(m):
    s = m["умножение связей"]
    if s["обе дороги посчитаны"] is not True:
        return False, ("вторая дорога не посчитана: %s. Утверждение о "
                       "побитовой равнозначности проверить нечем"
                       % s["почему"])
    ok = s["отпечатки совпали"]
    return ok, ("эталонное умножение (%s) против событийного (%s): "
                "отпечатки %s и %s — %s. Побитовое равенство обеспечено "
                "условиями: значения целые %s, максимальная сумма модулей "
                "по строке %s против предела float32 16 777 216 (запас "
                "%s)"
                % (s["эталонный: дорога"], s["событийный: дорога"],
                   s["эталонный: отпечаток"], s["событийный: отпечаток"],
                   "совпали" if ok else "РАЗОШЛИСЬ",
                   s["значения целые"], s["макс сумма модулей по строке"],
                   s["запас"]))


def r_state(m):
    s = m["полнота состояния"]
    выжили = [k for k, v in s["при выбрасывании"].items() if v >= H_STEPS]
    ok = (s["полное продолжение: совпавших шагов"] == H_STEPS
          and not выжили)
    return ok, ("снимок состояния поставлен на место: совпавших шагов "
                "%d из %d. Выбрасывание по одному из семи элементов "
                "ломает продолжение на шаге: %s. Нужно: полное "
                "продолжение — все %d шагов, выбрасывание ЛЮБОГО — "
                "меньше. Пережили выбрасывание: %s. Семь — это пять "
                "тензоров состояния плюс ptr (положение кольца задержки) "
                "и gen (состояние генератора); последние два не тензоры, "
                "и потерять их проще всего. Сверка идёт ДВУМЯ мерами "
                "сразу: взвешенной суммой спайкового вектора по "
                "постоянному случайному вектору (она различает НАБОРЫ "
                "спайкующих) и просто числом спайков. Числа на сумме "
                "спайков: %s — они совпали со взвешенными, значит эти "
                "шаги совпадают по-настоящему, а не из-за грубости "
                "скаляра. «Нуль совпавших», как в `probe/resume_state.py`, "
                "там считается по шагам УПРАВЛЕНИЯ (200 шагов движка "
                "каждый), и здесь требуется не он, а то, что каждый "
                "элемент состояния НУЖЕН"
                % (s["полное продолжение: совпавших шагов"], H_STEPS,
                   ", ".join("%s %d" % (k, v)
                             for k, v in s["при выбрасывании"].items()),
                   H_STEPS, ", ".join(выжили) or "никто",
                   s.get("на сумме спайков переживало", "—")))


