def измерить_справочник(rep):
    """Каждое поле спеки объявлено в окне или помечено с причиной."""
    from flybrain import catalog as C, spec as S

    в_окне = set()
    for kind in C.KINDS:
        for f in C.fields_of(kind):
            в_окне.add((f.block, f.key))
    классы = {"RunSpec": S.RunSpec}
    классы.update({cls.__name__: cls for cls in S._BLOCKS.values()})
    блок_по_классу = {cls.__name__: name
                      for name, cls in S._BLOCKS.items()}
    всего, помечено, без = 0, 0, []
    for имя, cls in классы.items():
        блок = блок_по_классу.get(имя)
        for f in dataclasses.fields(cls):
            всего += 1
            if (блок, f.name) in в_окне or (None, f.name) in в_окне:
                continue
            почему = C.NOT_IN_UI.get((имя, f.name))
            if почему:
                помечено += 1
            else:
                без.append("%s.%s" % (имя, f.name))
    k = {
        "полей в спеке": всего,
        "полей в справочнике": len(в_окне),
        "помечено NOT_IN_UI": помечено,
        "поля без объявления": без,
        "видов прогона": list(C.KINDS),
    }
    rep.measure("справочник окна", k)
    print("  справочник: полей спеки %d, в окне %d, помечено %d, без "
          "объявления %d" % (всего, len(в_окне), помечено, len(без)),
          flush=True)
    return k


def измерить_побитово(rep):
    """Шлюз H: отпечатки движка, две дороги умножения, полнота состояния."""
    import torch

    from flybrain import data as D, sim as S

    neurons = D.load_neurons()
    W = D.load_weights()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    n = len(neurons)
    # Раздражитель объявлен и постоянен: вход на обонятельные рецепторы.
    from flybrain import world

    drv = np.unique(np.concatenate([
        D.select(neurons, world.SENSORS["odour_left"]),
        D.select(neurons, world.SENSORS["odour_right"])]))
    t_drv = torch.as_tensor(drv, device=dev)

    def отпечаток(seed, steps=H_STEPS, spmv=None):
        eng = S.build_engine(weights=W, neurons=neurons, device=dev,
                             seed=seed, no_refractory=drv, spmv=spmv)
        rates = torch.zeros(1, n, device=dev)
        rates[0, t_drv] = 80.0
        сп = []
        for _ in range(steps):
            сп.append(int(eng.step(rates).sum().item()))
        st = eng.snapshot()
        инфо = eng.spmv_info() if hasattr(eng, "spmv_info") else {}
        del eng
        return (fp(np.asarray(сп, dtype=np.int64)), int(sum(сп)), st,
                инфо)

    f1, сп1, st1, инфо1 = отпечаток(0)
    f2, сп2, _, _ = отпечаток(0)
    f3, _, _, _ = отпечаток(1)
    b = {
        "шагов": H_STEPS, "раздражитель": "80 Гц на %d обонятельных "
                                          "рецепторов" % len(drv),
        "зерно": 0, "другое зерно": 1,
        "зерно: отпечаток 1": f1, "зерно: отпечаток 2": f2,
        "другое зерно: отпечаток": f3,
        "спайков за отрезок": сп1,
        "то же зерно: отпечатки совпали": f1 == f2,
        "другое зерно: отпечатки совпали": f1 == f3,
    }
    rep.measure("побитово", b)
    print("  побитово: зерно 0 -> %s и %s (%s), зерно 1 -> %s"
          % (f1, f2, "совпали" if f1 == f2 else "РАЗОШЛИСЬ", f3),
          flush=True)

    # --- две дороги умножения связей ---
    s = {"обе дороги посчитаны": None, "почему": ""}
    try:
        fe, _, _, инфо_э = отпечаток(0, spmv=S.SPMV_CSR)
        fv, _, _, инфо_в = отпечаток(0, spmv=S.SPMV_EVENT)
        усл = (инфо_в.get("условия равенства") or {})
        s = {
            "обе дороги посчитаны": True,
            "почему": "",
            "эталонный: дорога": инфо_э.get("умножение связей"),
            "событийный: дорога": инфо_в.get("умножение связей"),
            "эталонный: отпечаток": fe,
            "событийный: отпечаток": fv,
            "отпечатки совпали": fe == fv,
            "значения целые": усл.get("значения целые"),
            "макс сумма модулей по строке":
                усл.get("макс сумма модулей по строке"),
            "запас": усл.get("запас"),
            "ядро собрано": (инфо_в.get("сборка ядра") or {}).get("ядро"),
        }
        print("  умножение: эталонный %s против событийного %s — %s"
              % (fe, fv, "совпали" if fe == fv else "РАЗОШЛИСЬ"),
              flush=True)
    except Exception as e:                                   # noqa: BLE001
        s["почему"] = repr(e)
        rep.broke("вторая дорога умножения не посчиталась: %r" % (e,))
    rep.measure("умножение связей", s)

    # --- полнота состояния: продолжение и выбрасывание ---
    # Сверяются ДВЕ меры сразу: взвешенная сумма спайкового вектора по
    # постоянному случайному вектору и просто число спайков. Вторая —
    # один скаляр на 138 639 нейронов, и у разных наборов спайкующих он
    # совпадает запросто; первая набор различает. Обе здесь нужны именно
    # затем, чтобы различить две причины совпадения: грубость меры и
    # настоящее совпадение динамики. Замер показал второе — числа у двух
    # мер одинаковые, то есть выбрасывание `spikes` действительно даёт
    # семь совпадающих шагов, а не выглядит так из-за скаляра.
    g = torch.Generator(device="cpu").manual_seed(777)
    hv = torch.rand(n, generator=g, dtype=torch.float64).to(dev)

    def отр(eng, steps):
        """Ряд отпечатков спайкового вектора и ряд их количеств."""
        hs, cs = [], []
        for _ in range(steps):
            sp = eng.step(rates)[0].to(torch.float64)
            hs.append(float((sp * hv).sum().item()))
            cs.append(int(sp.sum().item()))
        return hs, cs

    eng = S.build_engine(weights=W, neurons=neurons, device=dev, seed=0,
                         no_refractory=drv)
    rates = torch.zeros(1, n, device=dev)
    rates[0, t_drv] = 80.0
    for _ in range(H_WARM):
        eng.step(rates)
    снимок = eng.snapshot()
    эт_h, эт_c = отр(eng, H_STEPS)
    del eng

    def продолжить(drop=()):
        e = S.build_engine(weights=W, neurons=neurons, device=dev, seed=0,
                           no_refractory=drv)
        e.restore(снимок, drop=drop)
        h, c = отр(e, H_STEPS)
        del e

        def сколько(a, b):
            k = 0
            for x, y in zip(a, b):
                if x != y:
                    break
                k += 1
            return k

        return сколько(эт_h, h), сколько(эт_c, c)

    полное, полное_c = продолжить()
    бр, бр_c = {}, {}
    for имя in ("v", "conductance", "spikes", "refrac", "delay_buffer",
                "ptr", "gen"):
        бр[имя], бр_c[имя] = продолжить(drop=(имя,))
    st = {
        "элементов состояния": 7,
        "перечень": ["v", "conductance", "spikes", "refrac",
                     "delay_buffer", "ptr", "gen"],
        "шагов сверки": H_STEPS,
        "шагов разогрева до снимка": H_WARM,
        "чем сверяется": "взвешенная сумма спайкового вектора по "
                         "постоянному случайному вектору (зерно 777)",
        "полное продолжение: совпавших шагов": полное,
        "при выбрасывании": бр,
        "на сумме спайков: полное продолжение": полное_c,
        "на сумме спайков: при выбрасывании": бр_c,
        "на сумме спайков переживало":
            ", ".join("%s %d" % (k, v) for k, v in бр_c.items()),
    }
    rep.measure("полнота состояния", st)
    print("  состояние: полное продолжение %d из %d; при выбрасывании %s"
          % (полное, H_STEPS,
             ", ".join("%s %d" % (k, v) for k, v in бр.items())),
          flush=True)
    print("             на одной сумме спайков переживало бы: %s — "
          "скаляр расхождения не видит"
          % ", ".join("%s %d" % (k, v) for k, v in бр_c.items()),
          flush=True)
    return b, s, st


def измерить_объявленное(rep):
    """У каждого режима объявлены параметры и происхождение данных."""
    from flybrain import motor as M

    # Что требуется от спеки режима, и почему именно это. «имя» и
    # «версия» — чтобы два прогона можно было сравнить, не разбирая кода.
    # «параметры» — чтобы числа режима были видны целиком, а не прятались
    # в значениях по умолчанию. «происхождение» — главное: откуда взято
    # каждое число. Режим без происхождения — это число без основания, и
    # отличить замер от выдумки в нём нельзя.
    НУЖНО = ("имя", "версия", "параметры", "происхождение")
    # Отпечаток данных требуется ТОЛЬКО от режимов, которые читают файл:
    # у режима с объявленными вручную числами отпечатывать нечего, и
    # требовать от него sha256 значило бы требовать пустого поля.
    режимы = {}
    пробы = [("декодер legacy", lambda: M.make_decoder("legacy"), False),
             ("декодер dn_linear", lambda: M.make_decoder("dn_linear"),
              False),
             ("мост GF none", lambda: M.GiantFiberBridge(kind="none"),
              False),
             ("мост GF gain_v1",
              lambda: M.GiantFiberBridge(kind="gain_v1"), False),
             ("стабилизация головы", lambda: M.HeadStabilizer(), True)]
    for имя, сделать, с_файлом in пробы:
        try:
            obj = сделать()
            спека = obj.spec()
        except Exception as e:                               # noqa: BLE001
            режимы[имя] = {"имя": None, "не хватает": list(НУЖНО),
                           "ошибка": repr(e)}
            continue
        ключи = set(str(x) for x in спека)
        не_хватает = [k for k in НУЖНО if k not in ключи]
        if с_файлом and not any("sha256" in k for k in ключи):
            не_хватает.append("sha256 файла данных")
        прои = str(спека.get("происхождение") or "")
        if not прои.strip():
            не_хватает.append("происхождение непустое")
        режимы[имя] = {
            "имя": спека.get("имя"),
            "версия": спека.get("версия"),
            "ключей в спеке": len(ключи),
            "ключи": sorted(ключи),
            "параметров": len(спека.get("параметры") or {}),
            "происхождение, знаков": len(прои),
            "читает файл данных": bool(с_файлом),
            "не хватает": не_хватает,
            "оговорка есть": bool(getattr(obj, "caveat", None)),
        }
    без_команды = [э["что"] for э in ЭТАЛОНЫ
                   if not э.get("проба") or not э.get("ожидается")]
    d = {
        "режимы": режимы,
        "эталонов": len(ЭТАЛОНЫ),
        "эталоны": list(ЭТАЛОНЫ),
        "эталоны без проверяющей команды": без_команды,
        "версия моторного пути": M.MOTOR_VERSION,
    }
    rep.measure("объявленные режимы", d)
    print("  объявленное: режимов %d (не хватает у %d), эталонов %d, без "
          "команды %d"
          % (len(режимы), sum(1 for v in режимы.values() if v["не хватает"]),
             len(ЭТАЛОНЫ), len(без_команды)), flush=True)
    return d


