def f_frozen(m):
    """Замороженный движок: любой прогон даёт один отпечаток."""
    m = dict(m)
    b = dict(m["побитово"])
    b["другое зерно: отпечаток"] = b["зерно: отпечаток 1"]
    b["другое зерно: отпечатки совпали"] = True
    m["побитово"] = b
    return m


def f_spmv_diff(m):
    m = dict(m)
    s = dict(m["умножение связей"])
    s["отпечатки совпали"] = False
    s["событийный: отпечаток"] = "0000000000000000"
    m["умножение связей"] = s
    return m


def f_leaky_state(m):
    """Выбрасывание элемента ничего не изменило: состояние неполно учтено.

    Если правило это пропустит, оно не проверяет полноту состояния: при
    «нуле совпавших у всех» и «всё совпало у одного» вывод о том, что
    элемент нужен, не следует.
    """
    m = dict(m)
    s = dict(m["полнота состояния"])
    бр = dict(s["при выбрасывании"])
    первый = next(iter(бр))
    бр[первый] = H_STEPS
    s["при выбрасывании"] = бр
    m["полнота состояния"] = s
    return m


def f_no_basis(m):
    m = dict(m)
    d = dict(m["объявленные режимы"])
    реж = {k: dict(v) for k, v in d["режимы"].items()}
    первый = next(iter(реж))
    реж[первый] = dict(реж[первый], **{"не хватает": ["основание"]})
    d["режимы"] = реж
    m["объявленные режимы"] = d
    return m


