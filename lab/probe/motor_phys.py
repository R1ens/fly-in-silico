def _side_actuators(bd):
    """Индексы позиционных приводов по сторонам, по имени СТОРОНЫ сустава.

    Имя привода — ``…/actuator_position_joint_LFCoxa``: сторона стоит
    первой буквой сегмента после ``joint_``. Берётся именно она, а не
    порядок приводов в модели: порядок FlyGym ничего не обещает, и
    молчаливая перестановка перевернула бы лево и право в замере.
    """
    import mujoco

    m = bd.physics.model.ptr
    left, right = [], []
    for i in range(m.nu):
        nm = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_ACTUATOR, i) or ""
        if "actuator_position_joint_" not in nm:
            continue
        seg = nm.split("actuator_position_joint_")[1]
        (left if seg[0] == "L" else right).append(i)
    return left, right


def episode(neurons, weights, device, label, **kw):
    """Один эпизод в теле. ``kw`` уезжает в `BodyConfig` как есть.

    Попутно снимается УРОВЕНЬ МОТОРНЫХ КОМАНД MuJoCo: позиционные цели и
    моменты 42 приводов ног, разнесённые по сторонам. Без этого уровня
    цепь «нейрон → команда → движение» проверялась бы через дырку: два
    числа декодера и траектория есть, а что именно получили приводы —
    нет, и перекрёстная разводка «левое полушарие → правые ноги»
    осталась бы утверждением про траекторию, а не про приводы.
    """
    from flybrain import body as B

    cfg = B.BodyConfig(duration_s=DURATION, control_ms=CONTROL_MS, seed=0,
                       device=device, readout="ALPN", motor="dn_linear", **kw)
    hook, act = {}, {"cl": [], "cr": [], "fl": [], "fr": []}

    def on_body(bd):
        hook["body"] = bd
        hook["idx"] = _side_actuators(bd)

    def on_step(step, rec, _bins):
        bd, (li, ri) = hook["body"], hook["idx"]
        d = bd.physics.data.ptr
        c = np.asarray(d.ctrl, float)
        f = np.abs(np.asarray(d.actuator_force, float))
        act["cl"].append(float(c[li].mean()))
        act["cr"].append(float(c[ri].mean()))
        act["fl"].append(float(f[li].max()))
        act["fr"].append(float(f[ri].max()))

    t0 = time.perf_counter()
    run = B.run_episode(cfg=cfg, neurons=neurons, weights=weights,
                        progress=False, on_body=on_body, on_step=on_step)
    wall = time.perf_counter() - t0
    recs = run.records

    # --- физический эффект, снятый с MuJoCo ---
    th = np.array([r["theta"] for r in recs], float)
    # Развёртка: курс пишется как atan2 и прыгает через ±pi. Без
    # развёртки накопленный поворот считался бы по модулю 2pi и на
    # развороте давал бы знак наугад.
    dth = np.unwrap(th) - np.unwrap(th)[0]
    x = np.array([r["x"] for r in recs], float)
    y = np.array([r["y"] for r in recs], float)
    c, s = math.cos(th[0]), math.sin(th[0])
    # Поперечный снос в системе НАЧАЛЬНОГО курса: плюс — влево.
    lateral = -(x - x[0]) * s + (y - y[0]) * c
    along = (x - x[0]) * c + (y - y[0]) * s

    skip = min(int(round(3 * TAU_S / (CONTROL_MS / 1000.0))),
               max(len(recs) - 10, 0))
    turn = np.array([r.get("cmd_turn", 0.0) for r in recs], float)
    r02l = np.array([r.get("readout_DNa02_l", 0.0) for r in recs], float)
    r02r = np.array([r.get("readout_DNa02_r", 0.0) for r in recs], float)
    out = {
        "эпизод": label,
        "поворот курса за эпизод, рад": round(float(dth[-1]), 4),
        "поперечный снос, мм": round(float(lateral[-1]), 4),
        "продольный путь, мм": round(float(along[-1]), 4),
        "путь, мм": run.metrics.get("path_mm"),
        "cmd_turn среднее (после 3τ)": round(float(turn[skip:].mean()), 5),
        "cmd_turn разброс (после 3τ)": round(float(turn[skip:].std()), 6),
        "amp_l среднее": round(float(np.mean([r["amp_l"] for r in recs])), 4),
        "amp_r среднее": round(float(np.mean([r["amp_r"] for r in recs])), 4),
        "readout_DNa02_l среднее, Гц": round(float(r02l.mean()), 3),
        "readout_DNa02_r среднее, Гц": round(float(r02r.mean()), 3),
        "readout_DNa02_l макс, Гц": round(float(r02l.max()), 3),
        "шагов": len(recs),
        "по стене, с": round(wall, 1),
        "оговорки": run.timing.get("оговорки", []),
        "вмешательство в engineered":
            "прямое вмешательство" in (run.engineered or {}),
    }

    # --- УРОВЕНЬ МОТОРНЫХ КОМАНД MuJoCo ---
    cl = np.array(act["cl"], float)
    cr = np.array(act["cr"], float)
    fl = np.array(act["fl"], float)
    fr = np.array(act["fr"], float)
    out.update({
        "цель приводов Л среднее, рад": round(float(cl.mean()), 5),
        "цель приводов П среднее, рад": round(float(cr.mean()), 5),
        "перекос целей Л−П, рад": round(float((cl - cr).mean()), 5),
        "момент Л пик": round(float(fl.max()), 3),
        "момент П пик": round(float(fr.max()), 3),
        "момент Л среднее": round(float(fl.mean()), 3),
        "момент П среднее": round(float(fr.mean()), 3),
    })

    # --- ДИНАМИКА: накачка включается ступенью на первом шаге эпизода ---
    # Поэтому по ряду видно, за сколько шагов отвечает съём и за сколько
    # команда. Второе — свойство ИНЖЕНЕРНОГО сглаживания (dn_tau_s), а
    # не нейронов, и названо так же.
    r0 = float(r02l[:1].mean())
    hi = float(r02l[len(r02l) // 2:].mean())
    plateau = float(turn[len(turn) // 2:].mean())
    out.update({
        "съём на 1-м шаге, Гц": round(r0, 3),
        "съём во 2-й половине, Гц": round(hi, 3),
        "съём: 1-й шаг в долях полки": round(r0 / hi, 4) if hi else None,
        "cmd_turn на 1-м шаге": round(float(turn[0]), 5),
        "cmd_turn на полке": round(plateau, 5),
        "cmd_turn: 1-й шаг в долях полки":
            round(float(turn[0]) / plateau, 4) if abs(plateau) > 1e-9
            else None,
        # Потолок инженерного слоя: z обрезается до ±1, дальше делится на
        # сумму модулей весов. У `TURN_WEIGHTS_V1` она 1,8, то есть
        # |cmd_turn| не может превысить 1/1,8 = 0,5556 ни при какой
        # активности. Это предел ОБЪЯВЛЕННОГО преобразования, и когда
        # команда стоит на нём с нулевым разбросом, дальше по дозе
        # измерять уже нечего.
        "потолок |cmd_turn| по весам": round(1.0 / 1.8, 5),
        "на потолке": bool(abs(plateau) >= 1.0 / 1.8 - 1e-6),
    })

    # Перекос калибровки по DNa02: сколько накачки вычла бы калибровка,
    # если бы накачка шла и на разогреве. Здесь она на разогреве
    # выключена, поэтому число обязано быть маленьким — это и есть
    # проверка того, что порядок соблюдён.
    pp = ((run.calib or {}).get("зонды") or {}).get("DNa02") or {}
    out["перекос калибровки DNa02, Гц"] = pp.get("перекос, Гц")
    print("   %-28s поворот %+8.4f рад, снос %+8.4f мм, cmd_turn %+8.5f "
          "(sd %.6f), DNa02 Л %7.2f Гц"
          % (label, out["поворот курса за эпизод, рад"],
             out["поперечный снос, мм"], out["cmd_turn среднее (после 3τ)"],
             out["cmd_turn разброс (после 3τ)"],
             out["readout_DNa02_l среднее, Гц"]))
    return out, run


def main():
    import torch

    from flybrain import data as D

    t0 = time.perf_counter()
    device = "cuda" if torch.cuda.is_available() else "cpu"
    neurons = D.load_neurons()
    weights = D.load_weights(device=device)
    print("Физический отклик на прямое вмешательство. устройство:", device)
    part_source(neurons)
    map_banc, map_zero = part_map(neurons)

    print("\n3. Восемь эпизодов одним зерном, декодер dn_linear")
    base, run0 = episode(neurons, weights, device, "опора, без вмешательства")
    left, _ = episode(neurons, weights, device, "DNa02 слева 200 Гц",
                      dn_drive="DNa02:left=%g" % DRIVE_HZ)
    right, _ = episode(neurons, weights, device, "DNa02 справа 200 Гц",
                       dn_drive="DNa02:right=%g" % DRIVE_HZ)
    weak, _ = episode(neurons, weights, device, "DNa02 слева 50 Гц",
                      dn_drive="DNa02:left=50")
    neg, _ = episode(neurons, weights, device,
                     "ОТРИЦ.: DNa02 слева 200 Гц + DNa02 заглушена",
                     dn_drive="DNa02:left=%g" % DRIVE_HZ,
                     dn_silence="DNa02")
    off, _ = episode(neurons, weights, device,
                     "МИМО-ЦЕЛЕВОЙ: DNp03 слева 200 Гц",
                     dn_drive="sel:celltype=DNp03:left=%g" % DRIVE_HZ)
    # Второй мимо-целевой, и он строже первого: `DNp10` — нисходящий с
    # ИЗМЕРЕННЫМ сильным премоторным выходом (1844 синапса к
    # мотонейронам в BANC, 93-й процентиль), которого в декодере нет ни
    # в одном варианте. Если бы поворот давала «любая накачка в сильный
    # нисходящий», он бы его и дал.
    off2, _ = episode(neurons, weights, device,
                      "МИМО-ЦЕЛЕВОЙ-2: DNp10 слева 200 Гц",
                      dn_drive="sel:celltype=DNp10:left=%g" % DRIVE_HZ)
    # Ручка адресации ДАННЫМИ: та же накачка, но вес DNa02 в файле
    # обнулён. Если ручка доходит до команды, поворот обязан исчезнуть.
    zmap, _ = episode(neurons, weights, device,
                      "ДАННЫЕ: DNa02 слева 200 Гц, вес DNa02 в файле = 0",
                      dn_drive="DNa02:left=%g" % DRIVE_HZ,
                      motor_map=str(map_zero))
    rows = [base, left, right, weak, neg, off, off2, zmap]
    note("эпизоды", rows)

    print("\n4. Происхождение вмешательства едет в прогон")
    eng = run0.engineered or {}
    note("engineered опоры", {"ключи": sorted(eng)})
    check("у опоры блока вмешательства в прогоне НЕТ",
          not base["вмешательство в engineered"],
          "ключ «прямое вмешательство» отсутствует: %s"
          % (not base["вмешательство в engineered"]))
    check("у накачанного эпизода блок вмешательства ЕСТЬ и оговорка "
          "записана",
          left["вмешательство в engineered"]
          and any("ПРЯМОЕ ВМЕШАТЕЛЬСТВО" in c for c in left["оговорки"]),
          "оговорок %d, первая: %s" % (len(left["оговорки"]),
                                       (left["оговорки"] or [""])[0][:90]))

    print("\n5. Накачка доходит до съёма, и съём это видит")
    # ВАЖНАЯ ПОПРАВКА К ПРЕЖНЕЙ РЕДАКЦИИ `MOTOR.md`. Там §10 п. 2
    # записано «DNa02 на раздражитель не отвечает, 0,00 Гц», и это
    # верно, но только ПРИ НАДВИГАНИИ. В теле, под обонятельной
    # накачкой, DNa02 слева идёт на опорных 61,6 Гц — то же число, что
    # §0 той же редакции приводит как 64,5 Гц на стенде без тела.
    # Поэтому отсчёт здесь идёт от ЗАМЕРЕННОЙ ОПОРЫ, а не от нуля:
    # проверка «поднимает с нуля» провалилась бы на верном результате.
    b_l = base["readout_DNa02_l среднее, Гц"]
    b_r = base["readout_DNa02_r среднее, Гц"]
    note("опорная частота DNa02 в теле",
         {"слева, Гц": b_l, "справа, Гц": b_r,
          "слева макс, Гц": base["readout_DNa02_l макс, Гц"],
          "поправка": ("это НЕ ноль: 0,00 Гц у DNa02 из прежней редакции "
                       "относится к надвиганию, а здесь сеть накачана "
                       "обонятельным входом")})
    check("накачка DNa02 слева поднимает ЕГО частоту заметно выше "
          "замеренной опоры",
          left["readout_DNa02_l среднее, Гц"] > 1.5 * max(b_l, 1.0),
          "опора %.2f Гц → накачка %.2f Гц, в %.2f раза"
          % (b_l, left["readout_DNa02_l среднее, Гц"],
             left["readout_DNa02_l среднее, Гц"] / max(b_l, 1e-9)))
    check("встречный: накачка СПРАВА поднимает правую, а левая остаётся "
          "на опоре",
          right["readout_DNa02_r среднее, Гц"] > 1.5 * max(b_r, 1.0)
          and abs(right["readout_DNa02_l среднее, Гц"] - b_l) < 0.25 * b_l,
          "справа %.2f → %.2f Гц; слева %.2f → %.2f Гц"
          % (b_r, right["readout_DNa02_r среднее, Гц"], b_l,
             right["readout_DNa02_l среднее, Гц"]))

    print("\n6. ФИЗИЧЕСКИЙ ЭФФЕКТ: что сделало тело")
    dl = left["поворот курса за эпизод, рад"] - base["поворот курса за эпизод, рад"]
    dr = right["поворот курса за эпизод, рад"] - base["поворот курса за эпизод, рад"]
    dw = weak["поворот курса за эпизод, рад"] - base["поворот курса за эпизод, рад"]
    dn = neg["поворот курса за эпизод, рад"] - base["поворот курса за эпизод, рад"]
    do = off["поворот курса за эпизод, рад"] - base["поворот курса за эпизод, рад"]
    do2 = off2["поворот курса за эпизод, рад"] - base["поворот курса за эпизод, рад"]
    dz = zmap["поворот курса за эпизод, рад"] - base["поворот курса за эпизод, рад"]
    sl = left["поперечный снос, мм"] - base["поперечный снос, мм"]
    sr = right["поперечный снос, мм"] - base["поперечный снос, мм"]
    note("отклонение от опоры", {
        "DNa02 слева 200 Гц": {"Δкурс, рад": round(dl, 4),
                               "Δснос, мм": round(sl, 4)},
        "DNa02 справа 200 Гц": {"Δкурс, рад": round(dr, 4),
                                "Δснос, мм": round(sr, 4)},
        "DNa02 слева 50 Гц": {"Δкурс, рад": round(dw, 4)},
        "ОТРИЦ. (заглушена)": {"Δкурс, рад": round(dn, 4)},
        "МИМО-ЦЕЛЕВОЙ (DNp03)": {"Δкурс, рад": round(do, 4)},
        "МИМО-ЦЕЛЕВОЙ-2 (DNp10)": {"Δкурс, рад": round(do2, 4)},
        "ДАННЫЕ (вес DNa02 = 0)": {"Δкурс, рад": round(dz, 4)},
    })
    check("накачка рулевого нисходящего поворачивает тело, и слева со "
          "справа дают ПРОТИВОПОЛОЖНЫЙ знак",
          dl * dr < 0 and min(abs(dl), abs(dr)) > 0.05,
          "Δкурс слева %+.4f рад, справа %+.4f рад; Δснос %+.3f и %+.3f мм"
          % (dl, dr, sl, sr))
    check("ОТРИЦАТЕЛЬНЫЙ контроль: при заглушённой DNa02 съём ровно "
          "нулевой и команда ровно постоянна",
          neg["readout_DNa02_l макс, Гц"] == 0.0
          and neg["cmd_turn разброс (после 3τ)"] == 0.0,
          "съём макс %.3f Гц, разброс cmd_turn %.8f"
          % (neg["readout_DNa02_l макс, Гц"],
             neg["cmd_turn разброс (после 3τ)"]))
    # Траектория у заглушённой НЕ обязана совпасть с опорой: постоянная
    # команда — это не та же команда, что у опоры, и муха с ней идёт
    # иначе. Требуется ровно то, что можно требовать: поворот не в
    # сторону накачки. Числом: знак другой или величина много меньше.
    check("ОТРИЦАТЕЛЬНЫЙ контроль: поворот НЕ идёт в сторону накачки",
          (dn * dl < 0) or abs(dn) < 0.5 * abs(dl),
          "Δкурс у заглушённой %+.4f рад против %+.4f рад у накачанной "
          "(знаки %s)" % (dn, dl, "разные" if dn * dl < 0 else "одинаковые"))
    for nm, row, dd in (("DNp03", off, do), ("DNp10", off2, do2)):
        check("МИМО-ЦЕЛЕВОЙ контроль %s: те же 200 Гц мимо декодера не "
              "дают поворота и не трогают съём DNa02" % nm,
              abs(row["readout_DNa02_l среднее, Гц"] - b_l) < 0.25 * b_l
              and abs(dd) < 0.25 * abs(dl),
              "съём DNa02 слева %.2f Гц против опорных %.2f; Δкурс %+.4f "
              "рад против %+.4f (%.0f %% эффекта)"
              % (row["readout_DNa02_l среднее, Гц"], b_l, dd, dl,
                 100.0 * abs(dd) / max(abs(dl), 1e-9)))
    # Ручка адресации ДАННЫМИ. Замер вышел сильнее задуманного, и
    # формулировку пришлось исправить по нему: с обнулённым весом DNa02
    # команда стала РОВНО нулевой, а не «как у опоры». Это не сбой, а
    # второй результат: раз пять остальных зондов молчат (их z равны
    # нулю), вся команда едет на одном DNa02, и обнуление его веса
    # обнуляет её целиком. Проверяется поэтому именно это: ручка
    # доходит до команды, и команда держится на одном зонде.
    note("ручка адресации данными", {
        "cmd_turn: опора / накачка / накачка с нулевым весом DNa02":
            [base["cmd_turn среднее (после 3τ)"],
             left["cmd_turn среднее (после 3τ)"],
             zmap["cmd_turn среднее (после 3τ)"]],
        "разброс cmd_turn с нулевым весом":
            zmap["cmd_turn разброс (после 3τ)"],
        "следствие": ("вся команда поворота держится на одном зонде "
                      "DNa02: остальные пять молчат, их z равны нулю, и "
                      "обнуление веса DNa02 обнуляет команду целиком"),
    })
    check("ручка адресации ДАННЫМИ доходит до команды: с обнулённым "
          "весом DNa02 та же накачка даёт РОВНО нулевую команду",
          zmap["cmd_turn среднее (после 3τ)"] == 0.0
          and zmap["cmd_turn разброс (после 3τ)"] == 0.0,
          "cmd_turn: опора %+.5f, накачка %+.5f, накачка с нулевым весом "
          "%+.5f (разброс %.8f)"
          % (base["cmd_turn среднее (после 3τ)"],
             left["cmd_turn среднее (после 3τ)"],
             zmap["cmd_turn среднее (после 3τ)"],
             zmap["cmd_turn разброс (после 3τ)"]))

    # ДОЗОВАЯ ЗАВИСИМОСТЬ проверяется НА КОМАНДЕ, а не на траектории, и
    # это не уступка: замер показал, почему на траектории её проверять
    # нельзя. Накопленный за эпизод поворот при 50 Гц вышел меньше
    # опорного, а при 200 Гц — много больше, то есть по ОДНОЙ траектории
    # на уровень доза не монотонна. Петля замкнута: муха повернула,
    # запах изменился, и дальше курс гуляет сам. На команде, которую
    # декодер считает в тот же момент, монотонность есть, и она
    # проверяема.
    cb = base["cmd_turn среднее (после 3τ)"]
    cw = weak["cmd_turn среднее (после 3τ)"]
    cl = left["cmd_turn среднее (после 3τ)"]
    note("дозовая зависимость", {
        "cmd_turn: опора / 50 Гц / 200 Гц": [cb, cw, cl],
        "Δкурс: 50 Гц / 200 Гц": [round(dw, 4), round(dl, 4)],
        "почему не по траектории": (
            "по одной траектории на уровень доза не монотонна: Δкурс при "
            "50 Гц вышел %+.4f рад, при 200 Гц %+.4f. Петля замкнута, и "
            "накопленный курс одного эпизода дозой не управляется. "
            "Утверждения о дозовой зависимости ПОВЕДЕНИЯ здесь нет и "
            "быть не может: на это нужно не меньше четырёх зёрен на "
            "уровень" % (dw, dl)),
    })
    check("дозовая НА КОМАНДЕ монотонна: опора < 50 Гц < 200 Гц",
          cb < cw < cl,
          "cmd_turn %+.5f → %+.5f → %+.5f" % (cb, cw, cl))

    # ---------------- уровень МОТОРНЫХ КОМАНД MuJoCo ----------------
    print("\n7. Уровень моторных команд MuJoCo: что получили 42 привода")
    rows_act = [{"эпизод": r["эпизод"],
                 "перекос целей Л−П, рад": r["перекос целей Л−П, рад"],
                 "момент Л пик": r["момент Л пик"],
                 "момент П пик": r["момент П пик"]}
                for r in rows]
    note("моторные команды по сторонам", rows_act)
    for r in rows_act:
        print("   %-46s перекос целей %+8.5f рад, момент Л/П %6.2f/%6.2f"
              % (r["эпизод"][:46], r["перекос целей Л−П, рад"],
                 r["момент Л пик"], r["момент П пик"]))
    ab = base["перекос целей Л−П, рад"]
    al = left["перекос целей Л−П, рад"] - ab
    ar = right["перекос целей Л−П, рад"] - ab
    an = neg["перекос целей Л−П, рад"] - ab
    ao = off["перекос целей Л−П, рад"] - ab
    ao2 = off2["перекос целей Л−П, рад"] - ab
    note("перекос целей приводов относительно опоры", {
        "DNa02 слева 200 Гц": round(al, 5),
        "DNa02 справа 200 Гц": round(ar, 5),
        "ОТРИЦ. (заглушена)": round(an, 5),
        "МИМО-ЦЕЛЕВОЙ (DNp03)": round(ao, 5),
        "МИМО-ЦЕЛЕВОЙ-2 (DNp10)": round(ao2, 5),
        "опора, абсолютный": round(ab, 5),
    })
    check("накачка доходит до ПРИВОДОВ: перекос позиционных целей ног "
          "меняется, и слева со справа дают противоположный знак",
          al * ar < 0 and min(abs(al), abs(ar)) > 1e-4,
          "Δперекос целей: слева %+.5f рад, справа %+.5f рад (опора "
          "%+.5f)" % (al, ar, ab))
    # ЛЕВО-ПРАВО НА ПРИВОДАХ, а не на траектории. Перекрёстная разводка
    # уже замерена в проекте командой [1, 0.2]; здесь проверяется, что
    # знак перекоса ЦЕЛЕЙ следует знаку команды, то есть что между
    # декодером и приводами ничего не перевернулось.
    check("лево-право: знак перекоса целей приводов следует знаку "
          "cmd_turn",
          (left["cmd_turn среднее (после 3τ)"] - cb) * al > 0
          and (right["cmd_turn среднее (после 3τ)"] - cb) * ar > 0,
          "слева Δcmd %+.5f и Δперекос %+.5f; справа Δcmd %+.5f и "
          "Δперекос %+.5f"
          % (left["cmd_turn среднее (после 3τ)"] - cb, al,
             right["cmd_turn среднее (после 3τ)"] - cb, ar))
    for nm, dd in (("ОТРИЦ.", an), ("МИМО-ЦЕЛЕВОЙ DNp03", ao),
                   ("МИМО-ЦЕЛЕВОЙ-2 DNp10", ao2)):
        check("контроль %s не сдвигает цели приводов как накачка" % nm,
              abs(dd) < 0.5 * abs(al),
              "Δперекос %+.5f против %+.5f у накачки (%.0f %%)"
              % (dd, al, 100.0 * abs(dd) / max(abs(al), 1e-12)))

    # ---------------- динамика отклика ----------------
    print("\n8. Динамика: накачка включается ступенью на первом шаге")
    # Замер вышел не тем, что задумывалось, и формулировка исправлена по
    # нему. Переходного процесса НЕТ ВОВСЕ: и съём, и команда стоят на
    # своей полке с первого же шага эпизода. Причина в коде и названа:
    # `decoder.reset_state()` обнуляет накопитель сглаживания перед
    # эпизодом, и первое измерение садится в него напрямую, без
    # релаксации. Значит τ = 0,5 с действует только на ИЗМЕНЕНИЯ внутри
    # эпизода, а на ступень в его начале — нет, и измерять по этой
    # ступени время нарастания нечего.
    note("динамика отклика", {
        "накачка на разогреве": "выключена (см. motor.DnIntervention)",
        "перекос калибровки DNa02 у опоры, Гц":
            base["перекос калибровки DNa02, Гц"],
        "перекос калибровки DNa02 у накачки, Гц":
            left["перекос калибровки DNa02, Гц"],
        "съём: 1-й шаг / полка, Гц":
            [left["съём на 1-м шаге, Гц"], left["съём во 2-й половине, Гц"]],
        "съём: 1-й шаг в долях полки": left["съём: 1-й шаг в долях полки"],
        "cmd_turn: 1-й шаг / полка":
            [left["cmd_turn на 1-м шаге"], left["cmd_turn на полке"]],
        "τ сглаживания декодера, с": TAU_S,
        "почему переходного процесса нет": (
            "`decoder.reset_state()` обнуляет накопитель сглаживания "
            "перед эпизодом, и первое измерение садится в него "
            "напрямую. Это поведение прежнего кода, сохранённое ради "
            "побитовой сверки легаси (`MOTOR.md` §3), и менять его "
            "здесь нельзя. Следствие: τ = %g с действует на изменения "
            "ВНУТРИ эпизода, а не на ступень в его начале" % TAU_S),
        "что из этого нейронное": (
            "задержка СЪЁМА ограничена снизу шагом управления: 20 мс — "
            "это один блок, и быстрее съём ответить не может по "
            "построению. Потолок КОМАНДЫ и её сглаживание — инженерные"),
    })
    check("калибровка НЕ съела накачку: перекос калибровки DNa02 у "
          "накачанного эпизода такой же, как у опоры",
          abs((left["перекос калибровки DNa02, Гц"] or 0.0)
              - (base["перекос калибровки DNa02, Гц"] or 0.0)) < 10.0,
          "опора %s Гц, накачка %s Гц"
          % (base["перекос калибровки DNa02, Гц"],
             left["перекос калибровки DNa02, Гц"]))
    check("съём стоит на полке с ПЕРВОГО блока управления (20 мс): "
          "переходного процесса у ступени нет",
          (left["съём: 1-й шаг в долях полки"] or 0.0) >= 0.5,
          "1-й шаг %s Гц при полке %s Гц, то есть %.2f полки"
          % (left["съём на 1-м шаге, Гц"], left["съём во 2-й половине, Гц"],
             left["съём: 1-й шаг в долях полки"] or 0.0))
    check("встречный: у ОПОРЫ та же проверка тоже проходит, то есть она "
          "не доказывает действие накачки, а только измеряет задержку",
          (base["съём: 1-й шаг в долях полки"] or 0.0) >= 0.5,
          "опора: 1-й шаг %s Гц при полке %s Гц"
          % (base["съём на 1-м шаге, Гц"],
             base["съём во 2-й половине, Гц"]))

    # ПОТОЛОК ИНЖЕНЕРНОГО СЛОЯ, названный и замеренный.
    note("потолок преобразования", {
        "|cmd_turn| не может превысить": round(1.0 / 1.8, 5),
        "откуда": ("z обрезается до ±1, дальше делится на сумму модулей "
                   "весов TURN_WEIGHTS_V1 (1,0 + 0,5 + 0,3 = 1,8)"),
        "при 200 Гц слева": [left["cmd_turn на полке"], left["на потолке"]],
        "при 200 Гц справа": [right["cmd_turn на полке"],
                              right["на потолке"]],
        "при 50 Гц слева": [weak["cmd_turn на полке"], weak["на потолке"]],
        "следствие": ("при 200 Гц команда стоит на потолке с нулевым "
                      "разбросом: дальше по дозе измерять нечего, и это "
                      "предел ОБЪЯВЛЕННОГО преобразования, а не сети"),
    })
    check("инженерный потолок команды замерен: при 200 Гц команда стоит "
          "на 1/Σ|w| = 0,5556 с нулевым разбросом, при 50 Гц — нет",
          left["на потолке"] and right["на потолке"]
          and not weak["на потолке"]
          and left["cmd_turn разброс (после 3τ)"] == 0.0,
          "200 Гц слева %+.5f (разброс %.8f), справа %+.5f; 50 Гц %+.5f"
          % (left["cmd_turn на полке"], left["cmd_turn разброс (после 3τ)"],
             right["cmd_turn на полке"], weak["cmd_turn на полке"]))

    print("\n9. Отказы заданы так, чтобы вмешательство нельзя было "
          "подать мимо")
    from flybrain import motor

