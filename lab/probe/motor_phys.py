"""Физический отклик в MuJoCo на ПРЯМОЕ вмешательство в названную популяцию.

Чего не хватало до этой пробы
-----------------------------
`MOTOR.md` §10 п. 3 говорит прямо: «куда на самом деле повернёт муха при
активации `DNa02` слева — не проверено ни на чём». И п. 2 объясняет,
почему это не проверялось обычным прогоном: рулевые `DNa02` и `DNa01` на
обонятельный и зрительный раздражитель не отвечают вовсе (0,00 Гц), то
есть дозовую кривую §2 пришлось снимать прямой стимуляцией зонда — но в
ТЕЛЕ такого прогона не было ни одного. Значит физический эффект
нисходящего не был измерен нигде.

Здесь он измеряется, и измеряется строго: у отклика есть
отрицательный и мимо-целевой контроли, а источник назван номерами
нейронов.

Что считается
-------------
Шесть эпизодов одним зерном, декодер `dn_linear` (прямые зонды):

1. **опора** — без вмешательства;
2. **DNa02 слева, 200 Гц** — прямая накачка рулевого нисходящего;
3. **DNa02 справа, 200 Гц** — зеркало. Знак отклика обязан
   перевернуться, иначе измерен не отклик, а дрейф;
4. **DNa02 слева, 50 Гц** — та же накачка слабее: отклик обязан быть
   того же знака и меньше по величине;
5. **ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: DNa02 слева, 200 Гц, и та же DNa02
   заглушена** маской `fire`. Накачка подана, но спайк не выходит:
   съём обязан стать ровно нулевым, команда — постоянной, а траектория
   вернуться к опоре. Без этого контроля пункт 2 доказывал бы только
   «накачка что-то делает», а не «делает это ЧЕРЕЗ названную популяцию»;
6. **МИМО-ЦЕЛЕВОЙ КОНТРОЛЬ: DNp03 слева, 200 Гц** — те же 200 Гц в
   нисходящий, которого в декодере нет ни в одном варианте. Съём
   `DNa02` обязан остаться нулевым, а траектория — у опоры. Без этого
   контроля пункт 2 доказывал бы «200 Гц куда угодно поворачивают
   муху».

Физический эффект мерится двумя величинами, и обе сняты с MuJoCo, а не
с команды: накопленный поворот курса (развёрнутый, радианы) и
знаковый поперечный снос относительно НАЧАЛЬНОГО курса (мм). Команда
(`cmd_turn`) записывается рядом, но доказательством отклика не
является: она инженерная, а вопрос — что сделало тело.

    PYTHONIOENCODING=utf-8 FLYBRAIN_OUT=<свой каталог> \\
        .venv/Scripts/python.exe lab/probe/motor_phys.py
"""

