DNA02_LEFT = 720575940629327659
DNA02_RIGHT = 720575940604737708

fails = []
rep = {"проверки": {}, "замеры": {}}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""))
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def note(key, value):
    rep["замеры"][key] = value


# ----------------------------------------------- источник, по номерам


def part_source(neurons):
    """Назвать нейроны-источники точными номерами и проверить их приписку."""
    print("\n1. Источник: номера нейронов, роли и сторона по столбцу")
    from flybrain import data as D, motor

    rows = []
    for name in ("DNa02", "DNa01", "DNp09", "MDN", "DNp01", "DNp04"):
        p = motor.DN_PROBES[name]
        idx = np.asarray(D.select(neurons, p.sel), np.int64)
        sub = neurons.iloc[idx]
        rows.append({
            "зонд": name, "селектор": p.sel,
            "root_id": [int(v) for v in sub["root_id"].to_numpy()],
            # Сторона берётся СТОЛБЦОМ `side`, а не из имени нейрона:
            # имя ничего про сторону не обещает, и в v783 это уже
            # расходилось с апстримной разметкой (`MOTOR.md` §1).
            "side (столбец)": [str(v) for v in sub["side"].to_numpy()],
            "cell_type": sorted({str(v) for v in sub["cell_type"]}),
            "hemibrain_type": sorted({str(v)
                                      for v in sub["hemibrain_type"]}),
            "роль по литературе": motor.PROBE_ROLES.get(name, ""),
            "вес поворота": motor.TURN_WEIGHTS_V1.get(name),
            "вес тяги": motor.DRIVE_WEIGHTS_V1.get(name),
        })
    note("нейроны-источники", rows)
    for r in rows:
        print("   %-6s %s  side=%s  cell_type=%s"
              % (r["зонд"], r["root_id"], r["side (столбец)"],
                 r["cell_type"]))

    # Имя `DNa01` НЕОДНОЗНАЧНО, и это не описка в данных, а спор двух
    # именующих авторитетов (`BANC_MOTOR.md`): `hemibrain_type = DNa01`
    # стоит у пары с `cell_type = DNae001`, а `cell_type = DNa01` — у
    # пары с `hemibrain_type = VES006`. Обе пары нисходящие,
    # холинергические и лево-право. Поэтому любое упоминание `DNa01`
    # обязано говорить, КАКИМ СТОЛБЦОМ он выбран, и обе пары печатаются
    # рядом — иначе читающий решит, что речь об одной.
    amb = []
    for label, sel in (("наш зонд DNa01 (столбец hemibrain_type)",
                        "hemibrain=DNa01"),
                       ("другая пара (столбец cell_type)",
                        "celltype=DNa01")):
        idx = np.asarray(D.select(neurons, sel), np.int64)
        sub = neurons.iloc[idx]
        amb.append({"что": label, "селектор": sel,
                    "root_id": [int(v) for v in sub["root_id"].to_numpy()],
                    "cell_type": sorted({str(v) for v in sub["cell_type"]}),
                    "hemibrain_type": sorted({str(v)
                                              for v in sub["hemibrain_type"]}),
                    "side": sorted({str(v) for v in sub["side"]})})
    note("неоднозначность имени DNa01", amb)
    l0 = set(amb[0]["root_id"])
    l1 = set(amb[1]["root_id"])
    check("имя DNa01 называет ДВЕ РАЗНЫЕ пары, и наш зонд выбран "
          "столбцом hemibrain_type",
          not (l0 & l1) and len(l0) == 2 and len(l1) == 2,
          "hemibrain=DNa01 → %s (cell_type %s); celltype=DNa01 → %s "
          "(hemibrain_type %s); пересечение %d"
          % (sorted(l0), amb[0]["cell_type"], sorted(l1),
             amb[1]["hemibrain_type"], len(l0 & l1)))

    # Встречный замер к любому ОТРИЦАТЕЛЬНОМУ итогу по выборке: тот же
    # запрос подстрочным селектором. Ловушка замерена на BANC: точное
    # сравнение `cell_type == "tergotrochanter_extensor"` нашло 10
    # нейронов вместо 20, потому что адресаты зовутся `…_TT` и
    # `…_TT_PDMN`, и «пути нет» было бы объявлено там, где просто не так
    # назвали. Поэтому у каждого зонда рядом стоит подстрочное число.
    sub_rows = []
    for name in ("DNa02", "DNa01", "DNp09", "MDN", "DNp01", "DNp04",
                 "DNp03", "DNp10"):
        exact = len(D.select(neurons, "celltype=%s" % name))
        loose = len(D.select(neurons, "type:%s" % name))
        sub_rows.append({"имя": name, "celltype= (столбец)": exact,
                         "type: (подстрока)": loose,
                         "подстрока шире": loose > exact})
    note("столбец против подстроки", sub_rows)
    print("   столбец/подстрока: " + ", ".join(
        "%s %d/%d" % (r["имя"], r["celltype= (столбец)"],
                      r["type: (подстрока)"]) for r in sub_rows))
    check("встречный: подстрочный селектор нигде не даёт МЕНЬШЕ, чем "
          "ключ по столбцу (иначе отрицательный итог по выборке был бы "
          "артефактом точного сравнения)",
          all(r["type: (подстрока)"] >= r["celltype= (столбец)"]
              for r in sub_rows),
          "; ".join("%s %d→%d" % (r["имя"], r["celltype= (столбец)"],
                                  r["type: (подстрока)"])
                    for r in sub_rows if r["подстрока шире"]) or "все равны")

    a02 = [r for r in rows if r["зонд"] == "DNa02"][0]
    sel_l = np.asarray(D.select(neurons, "celltype=DNa02+side:left"), np.int64)
    sel_r = np.asarray(D.select(neurons, "celltype=DNa02+side:right"),
                       np.int64)
    got_l = [int(v) for v in neurons.iloc[sel_l]["root_id"].to_numpy()]
    got_r = [int(v) for v in neurons.iloc[sel_r]["root_id"].to_numpy()]
    check("DNa02 — ровно два нейрона с ожидаемыми номерами, и сторона "
          "каждого взята столбцом `side`",
          got_l == [DNA02_LEFT] and got_r == [DNA02_RIGHT]
          and sorted(a02["side (столбец)"]) == ["left", "right"],
          "слева %s, справа %s, столбец side %s"
          % (got_l, got_r, a02["side (столбец)"]))
    # Встречный замер: номера обязаны отличаться у разных зондов.
    # Проверка «номер тот» ничего не стоит, если бы любой селектор давал
    # те же номера.
    other = [r["root_id"] for r in rows if r["зонд"] == "DNp09"][0]
    check("встречный: у другого зонда номера ДРУГИЕ",
          not (set(other) & {DNA02_LEFT, DNA02_RIGHT}),
          "DNp09 %s против DNa02 %s" % (other, got_l + got_r))
    return rows


# ------------------------------- адресация, подключаемая ДАННЫМИ


def part_map(neurons):
    """Собрать файл адресации из отображения BANC — по НОМЕРАМ, не по именам.

    Зачем вообще. Коэффициенты `dn_linear` объявлены в коде, и это его
    главная инженерная вольность. Лучше определённая адресация может
    прийти из данных — из брюшной цепочки BANC, где у нисходящих есть
    измеренный премоторный выход. Поэтому интерфейс читает адресацию
    ФАЙЛОМ (`motor.load_weight_map`), а здесь этот файл собирается.

    Почему по номерам. Сопоставление идёт по ``fafb_v783_id``, то есть по
    ``root_id`` наших же зондов, а не по совпадению имени. Имя `DNa01`
    неоднозначно (см. §1), и BANC спор не решает: его ярлык получен
    переносом из FAFB через тот же матч. Адресация по имени выбрала бы
    другую пару и выглядела бы обоснованной.

    Что здесь ИНЖЕНЕРНОЕ, и это надо сказать прямо:

    * ЗНАК каждого веса — по-прежнему литература (`motor.PROBE_ROLES`),
      а не BANC: синапс не говорит, в какую сторону повернёт муха;
    * ВЕЛИЧИНА — нормировка премоторного выхода на наибольший среди
      зондов. Нормировка объявлена; шкалы весов двух наборов не
      совпадают (`LC4→DNp01` 805 у нас против 354 в BANC, ×2,27), и
      любой пересчёт был бы инженерным числом;
    * у 37,4 % пар численной меры сходства нет вовсе, 487 пар из 1409
      неоднозначны, у левого Giant Fiber правильной пары нет даже среди
      кандидатов. Поэтому файл — КАНДИДАТ, а не отождествление.
    """
    print("\n2. Адресация из данных: файл по отображению BANC, по номерам")
    from flybrain import data as D, motor

    src = (Path(__file__).resolve().parents[1] / "flybrain" / "assets"
           / "banc_fafb_v888_v783_map.json")
    raw = src.read_bytes()
    m = json.loads(raw.decode("utf-8"))
    by_id = {}
    for p in m["pairs"]:
        by_id.setdefault(str(p["fafb_v783_id"]), []).append(p)

    rows, strength = [], {}
    for name, pr in motor.DN_PROBES.items():
        idx = np.asarray(D.select(neurons, pr.sel), np.int64)
        ids = [str(v) for v in neurons.iloc[idx]["root_id"].to_numpy()]
        hits = [p for i in ids for p in by_id.get(i, [])]
        syn = sum(int(p.get("banc_syn_to_motor_total") or 0) for p in hits)
        best = max([int(p.get("banc_syn_to_motor_strongest_pair") or 0)
                    for p in hits] or [0])
        rows.append({"зонд": name, "селектор": pr.sel,
                     "наших нейронов": len(ids),
                     "нашлось пар в отображении": len(hits),
                     "синапсов к мотонейронам (BANC), сумма": syn,
                     "сильнейшая пара": best,
                     "уверенность пар": sorted({round(float(
                         p.get("confidence") or 0.0), 3) for p in hits})})
        strength[name] = syn
    note("премоторный выход зондов по BANC", rows)
    for r in rows:
        print("   %-6s пар %d, синапсов к мотонейронам %5d, сильнейшая %3d"
              % (r["зонд"], r["нашлось пар в отображении"],
                 r["синапсов к мотонейронам (BANC), сумма"],
                 r["сильнейшая пара"]))
    check("каждый зонд нашёл себе пару в отображении по root_id",
          all(r["нашлось пар в отображении"] > 0 for r in rows),
          "; ".join("%s %d" % (r["зонд"], r["нашлось пар в отображении"])
                    for r in rows))

    # И вот прямое следствие неоднозначности имени, в синапсах. Две пары,
    # которые обе зовутся `DNa01`, сопоставляются по root_id, и у них
    # РАЗНЫЙ премоторный выход. Значит выбор столбца — это не вкус
    # номенклатуры, а разные числа в адресации, и выбирать `DNa01` по
    # имени нельзя не потому, что неаккуратно, а потому что получится
    # другой вес.
    amb_rows = []
    for label, sel in (("наш зонд: hemibrain=DNa01 (cell_type DNae001)",
                        "hemibrain=DNa01"),
                       ("другая пара: celltype=DNa01 (hemibrain_type VES006)",
                        "celltype=DNa01")):
        idx = np.asarray(D.select(neurons, sel), np.int64)
        ids = [str(v) for v in neurons.iloc[idx]["root_id"].to_numpy()]
        hits = [p for i in ids for p in by_id.get(i, [])]
        amb_rows.append({
            "что": label, "селектор": sel, "root_id": ids,
            "пар в отображении": len(hits),
            "синапсов к мотонейронам, сумма":
                sum(int(p.get("banc_syn_to_motor_total") or 0) for p in hits),
            "сильнейшая пара":
                max([int(p.get("banc_syn_to_motor_strongest_pair") or 0)
                     for p in hits] or [0]),
            "nblast": sorted({p.get("nblast_score") for p in hits}),
            "уверенность": sorted({round(float(p.get("confidence") or 0), 3)
                                   for p in hits}),
        })
    note("две пары по имени DNa01: премоторный выход разный", amb_rows)
    a, b = amb_rows
    print("   DNa01 по столбцам: %s → %d синапсов; %s → %d синапсов"
          % (a["селектор"], a["синапсов к мотонейронам, сумма"],
             b["селектор"], b["синапсов к мотонейронам, сумма"]))
    check("две пары, носящие имя DNa01, имеют РАЗНЫЙ премоторный выход "
          "по BANC — значит имя без столбца меняет вес адресации",
          a["синапсов к мотонейронам, сумма"]
          != b["синапсов к мотонейронам, сумма"],
          "%s %d (сильнейшая %d) против %s %d (сильнейшая %d)"
          % (a["селектор"], a["синапсов к мотонейронам, сумма"],
             a["сильнейшая пара"], b["селектор"],
             b["синапсов к мотонейронам, сумма"], b["сильнейшая пара"]))

    # Знаки — литература. Величины — нормированный премоторный выход.
    SIGNS = {"DNa02": +1.0, "DNa01": +1.0, "DNp09": +1.0,
             "MDN": 0.0, "DNp01": 0.0, "DNp04": 0.0}
    top = max([strength[k] for k, s in SIGNS.items() if s] or [1]) or 1
    turn = {k: round(s * strength[k] / top, 4) for k, s in SIGNS.items()}
    out = {
        "версия": 1,
        "вес поворота": turn,
        "вес тяги": dict(motor.DRIVE_WEIGHTS_V1),
        "происхождение": (
            "КАНДИДАТ. Знаки — опубликованные роли нисходящих "
            "(motor.PROBE_ROLES), то есть литература. Величины — сумма "
            "синапсов зонда к мотонейронам в BANC v888, сопоставленная по "
            "root_id через lab/flybrain/assets/banc_fafb_v888_v783_map.json "
            "и НОРМИРОВАННАЯ на наибольшую среди рулевых зондов. "
            "Нормировка объявлена, а не измерена; шкалы весов двух "
            "наборов не совпадают (LC4→DNp01 805 против 354, ×2,27). "
            "Вес тяги оставлен объявленным: премоторного основания для "
            "знака тяги в отображении нет. Отождествлением нейронов это "
            "не является: у 37,4 %% пар численной меры сходства нет, 487 "
            "пар из 1409 неоднозначны, у левого Giant Fiber правильной "
            "пары нет даже среди кандидатов NBLAST."),
        "источник": {
            "файл": str(src),
            "sha256": hashlib.sha256(raw).hexdigest(),
            "наборы": {k: m["datasets"][k].get("name")
                       for k in m["datasets"]},
            "пар всего": m["counts"]["pairs_total"],
        },
        "сила по BANC, синапсов к мотонейронам": strength,
    }
    path = OUT / "motor_map_banc_v1.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1),
                    encoding="utf-8")
    note("файл адресации", {"путь": str(path), "вес поворота": turn})
    print("   вес поворота из данных: " + ", ".join(
        "%s %+.4f" % (k, v) for k, v in turn.items()))

    # Проверочный файл: тот же формат, но вес DNa02 обнулён. Нужен
    # затем, что иначе «ручка читает файл» проверялась бы только тем,
    # что файл прочитался. Здесь она проверяется ЧИСЛОМ: накачка DNa02
    # перестаёт поворачивать тело, хотя сама накачка та же.
    zero = {"версия": 1,
            "вес поворота": {k: (0.0 if k == "DNa02"
                                 else motor.TURN_WEIGHTS_V1[k])
                             for k in motor.TURN_WEIGHTS_V1},
            "вес тяги": dict(motor.DRIVE_WEIGHTS_V1),
            "происхождение": (
                "ПРОВЕРОЧНЫЙ файл пробы, НЕ научная адресация: вес DNa02 "
                "обнулён нарочно, чтобы проверить числом, что ручка "
                "motor_map доходит до команды")}
    zpath = OUT / "motor_map_zero_dna02.json"
    zpath.write_text(json.dumps(zero, ensure_ascii=False, indent=1),
                     encoding="utf-8")

    for p, why in ((path, "кандидат по BANC"), (zpath, "проверочный")):
        w = motor.load_weight_map(p)
        check("файл адресации читается и несёт происхождение и sha256 "
              "(%s)" % why,
              bool(w["происхождение"]) and len(w["sha256"]) == 64
              and len(w["вес поворота"]) == len(motor.DN_PROBES),
              "sha256 %s…, зондов %d" % (w["sha256"][:12],
                                         len(w["вес поворота"])))
    # Встречный замер: файл без происхождения и файл с незнакомым
    # зондом обязаны быть отвергнуты, иначе проверка выше не значит
    # ничего.
    bad1 = OUT / "_motor_map_bad_no_src.json"
    bad1.write_text(json.dumps({"вес поворота": turn,
                                "вес тяги": dict(motor.DRIVE_WEIGHTS_V1)},
                               ensure_ascii=False), encoding="utf-8")
    bad2 = OUT / "_motor_map_bad_name.json"
    bad2.write_text(json.dumps(
        {"вес поворота": {**turn, "НЕТТАКОГО": 1.0},
         "вес тяги": dict(motor.DRIVE_WEIGHTS_V1),
         "происхождение": "проверка отказа"}, ensure_ascii=False),
        encoding="utf-8")
    for p, why in ((bad1, "без происхождения"), (bad2, "с незнакомым зондом")):
        try:
            motor.load_weight_map(p)
            ok, msg = False, "ошибки не было"
        except ValueError as e:
            ok, msg = True, str(e)[:70]
        check("отказ файла адресации: %s" % why, ok, msg)
        p.unlink(missing_ok=True)
    return path, zpath


