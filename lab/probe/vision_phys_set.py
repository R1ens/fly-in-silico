"""Какие клетки обязаны быть неспайковыми, чтобы ON-путь заработал.

Продолжение `probe/vision_phys.py`. Та проба дала отрицательный
результат с числом: при градуальных L1, L2, L3 и биологическом
гистаминергическом знаке **OFF-путь проводит сильно** (Tm1 9,18 Гц
против 0,945 эталонных, Tm2 5,68 против 0,519), а **ON-путь закрыт
плотнее, чем в эталоне** (Mi1 0,003 Гц). Причина замерена: L1 тормозная
и при тонической отдаче 164 Гц отнимает у Mi1 около 12 700 связей·Гц
при пороге 5091, а растормаживать нечего — главный возбуждающий вход
Mi1 это **L5 (+33,07 связи на нейрон)**, и при спайковой L5 она молчит
(0,064 Гц).

Отсюда проверяемое предсказание, и оно может провалиться: **если
сделать градуальной всю ламину, включая L5, ON-путь откроется.** L5 —
такая же ламинарная монополярная клетка, как L1-L3, и неспайковость у
неё того же происхождения; держать её спайковой было ошибкой разметки
набора, а не осторожностью.

Три набора, от узкого к широкому:

* **прямая ламина** — L1, L2, L3: только те, кто получает прямой
  гистаминергический вход. Это набор прежней пробы;
* **полная ламина** — L1…L5: анатомический класс ЛМК целиком;
* **ламина и медулла** — плюс Mi1, Tm1, Tm2, Tm3, Tm4, Tm9. У
  дрозофилы они тоже считаются преимущественно неспайковыми, но
  свидетельства слабее, поэтому это отдельный набор, а не умолчание.

Условия. Контроль здесь строже, чем в прежней пробе, и вот почему:
однородное поле при включённой адаптации НЕ даёт того же входа, что
край (полунасыщение следует за средней яркостью, и однородное поле при
любой яркости даёт ровно половину потолка — замерено: 75 Гц против
54,8 Гц у края). Поэтому нейтралью взят **замерший край**: та же
картинка, та же средняя яркость, та же пространственная структура,
движения нет. А решающим контролём остаётся **перемешанная привязка**:
суммарный вход совпадает побитово.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\vision_phys_set.py
"""

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent

DT = 0.1
WARM = 500
STEPS = 2000
VIS_HZ = 100.0
CROSS = 2000
ЗАМЕР_ФАЗА = 0.5          # где стоит замерший край

CHAIN = (
    ("R1-6", ("R1-6",)), ("R7", ("R7",)), ("R8", ("R8",)),
    ("L1", ("L1",)), ("L2", ("L2",)), ("L3", ("L3",)),
    ("L4", ("L4",)), ("L5", ("L5",)),
    ("Mi1", ("Mi1",)), ("Tm1", ("Tm1",)), ("Tm2", ("Tm2",)),
    ("Tm3", ("Tm3",)), ("Tm4", ("Tm4",)), ("Tm9", ("Tm9",)),
    ("T4", ("T4a", "T4b", "T4c", "T4d")),
    ("T5", ("T5a", "T5b", "T5c", "T5d")),
    ("LPLC2", ("LPLC2",)), ("LC4", ("LC4",)), ("DNp01", ("DNp01",)),
)
ГЛУБОКИЕ = ("Mi1", "Tm3", "Tm9", "T4", "T5", "LC4", "LPLC2", "DNp01")
УСЛОВИЯ = ("выключено", "замерший край", "светлый край", "перемешано")

fails = []
rep = {"проверки": {}, "замеры": {}, "находки": [], "сорвалось": []}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""), flush=True)
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def note(text):
    print("  НАХОДКА " + text, flush=True)
    rep["находки"].append(text)


def edge_frame(pos, phase):
    x = pos[:, 0]
    lo, hi = float(x.min()), float(x.max())
    lit = (x <= lo + (hi - lo) * float(phase)).astype(np.float32)
    return np.stack([lit, lit], axis=-1)


def both_eyes(fr):
    return np.stack([fr, fr])


def main():
    t0 = time.perf_counter()
    print("Какие клетки обязаны быть неспайковыми", flush=True)
    import torch

    from flybrain import data as D, retina as R, sim, visdyn as V

    neurons = D.load_neurons()
    W = D.load_weights()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    n = len(neurons)
    om = R.ommatidia()

    pops = {}
    for name, types in CHAIN:
        pops[name] = np.unique(np.concatenate(
            [D.select(neurons, "celltype=%s" % t) for t in types]))
    maps = R.build_all(neurons, mode="whiten", assign="capacity")
    maps_sh = R.build_all(neurons, mode="whiten", assign="capacity",
                          shuffle=True, seed=0)
    pr_idx = np.unique(np.concatenate([maps[k].neurons for k in maps]))
    every = max(1, int(round(1000.0 / VIS_HZ / DT)))
    кадр_мс = 1000.0 / VIS_HZ
    потолок = V.потолок_усиления(sim.MODEL_PARAMS, V.V_ТОНИК,
                                 V.V_НАСЫЩ_К)

    rep["замеры"]["устройство"] = {
        "устройство": dev, "шагов": STEPS,
        "модельного времени, мс": STEPS * DT,
        "обновление кадра, Гц": VIS_HZ,
        "скорость края, °/с": round(157.0 / (CROSS * DT / 1000.0), 1),
        "потолок усиления, Гц/мВ": round(потолок, 2),
        "привязка": R.fingerprint_all(maps),
    }

    eng0 = sim.build_engine(weights=W, neurons=neurons, device=dev,
                            seed=0, no_refractory=pr_idx, graphs=True)
    z = torch.zeros(1, n, device=dev)
    for _ in range(WARM):
        eng0.step(z)
    snap = {"поля": {nm: getattr(eng0, nm).detach().clone()
                     for nm in ("v", "conductance", "spikes", "refrac",
                                "delay_buffer")},
            "ptr": eng0.ptr, "gen": eng0.gen.get_state().clone()}
    del eng0
    pop_t = {k: torch.as_tensor(v, device=dev) for k, v in pops.items()}
    print("  %s, состояние снято после %d шагов, потолок усиления "
          "%.1f Гц/мВ" % (dev, WARM, потолок), flush=True)

    def прогон(drv, условие):
        drv.сброс(snap)
        drv.привязка(maps_sh if условие == "перемешано" else maps)
        acc = torch.zeros(n, device=dev)
        acc_g = drv.копить_отдачу(drv.режим == V.РЕЖИМ_ФИЗИОЛОГИЯ)
        вход = 0.0
        for s in range(STEPS):
            if s % every == 0:
                if условие == "выключено":
                    drv.подать_кадр(None, вкл=False, кадр_мс=кадр_мс)
                else:
                    ph = (ЗАМЕР_ФАЗА if условие == "замерший край"
                          else (s % max(CROSS, 1)) / max(CROSS - 1, 1))
                    drv.подать_кадр(both_eyes(edge_frame(om["pos"], ph)),
                                    кадр_мс=кадр_мс)
                вход += float(drv._t["rates"].sum())
                pr = drv._t.get("pr_hz")
                if pr is not None:
                    вход += sum(float(v.sum()) for v in pr.values()
                                ) * (1000.0 / DT)
            drv.шаг()
            acc.add_(drv.eng.spikes[0])
        if dev == "cuda":
            torch.cuda.synchronize()
        win_ms = STEPS * DT
        out = {k: round(1e3 * float(acc[t].sum()) / len(pops[k])
                        / win_ms, 4) for k, t in pop_t.items()}
        out["__мозг__"] = round(1e3 * float(acc.sum()) / n / win_ms, 4)
        грд = {}
        if acc_g is not None:
            for k, t in pop_t.items():
                s2 = float(acc_g[t].sum())
                if s2 > 0.0:
                    грд[k] = round(s2 / len(pops[k]) / STEPS
                                   * (1000.0 / DT), 3)
        drv.копить_отдачу(False)
        return out, вход, drv.мембрана(), грд

    НАБОРЫ = (
        ("прямая ламина", dict(ламина=V.ЛАМИНА_ПРЯМАЯ,
                               градуальная_медулла=False)),
        ("полная ламина", dict(ламина=V.ЛАМИНА,
                               градуальная_медулла=False)),
        ("ламина и медулла", dict(ламина=V.ЛАМИНА,
                                  градуальная_медулла=True)),
    )
    СЕТКА = (8.0, 16.0, round(потолок, 1))

    итог = {}
    for имя, kw in НАБОРЫ:
        phys = V.Физиология(g_ламина=СЕТКА[0], **kw)
        drv = V.Привод.собрать(W, neurons, pops, maps,
                               режим=V.РЕЖИМ_ФИЗИОЛОГИЯ, phys=phys,
                               dev=dev, seed=0)
        св = drv.сводка()
        print("\n%s: градуальных %s"
              % (имя, св["градуальные популяции"]), flush=True)
        итог[имя] = {"сводка": св, "по усилению": {}}
        for g in СЕТКА:
            drv.усиление(g_ламина=g)
            row, t1 = {}, time.perf_counter()
            for усл in УСЛОВИЯ:
                row[усл], вх, мем, грд = прогон(drv, усл)
                row.setdefault("вход", {})[усл] = round(вх, 1)
                row.setdefault("отдача", {})[усл] = грд
                if усл == "светлый край":
                    row["мембрана"] = {
                        k: {"мембрана, мВ": round(v[0], 4),
                            "проводимость, мВ": round(v[1], 4)}
                        for k, v in мем.items()}
            c, f = row["светлый край"], row["замерший край"]
            sh = row["перемешано"]
            row["зрению принадлежит"] = {
                k: round(c[k] - f[k], 4) for k in ГЛУБОКИЕ}
            row["структуре принадлежит"] = {
                k: round(c[k] - sh[k], 4) for k in ГЛУБОКИЕ}
            итог[имя]["по усилению"][str(g)] = row
            print("   g=%5.1f  Mi1 %7.3f Tm3 %6.3f Tm9 %6.3f T4 %6.3f "
                  "T5 %6.3f LC4 %6.3f LPLC2 %6.3f DNp01 %5.1f | мозг "
                  "%6.2f  (%.0f с)"
                  % (g, c["Mi1"], c["Tm3"], c["Tm9"], c["T4"], c["T5"],
                     c["LC4"], c["LPLC2"], c["DNp01"], c["__мозг__"],
                     time.perf_counter() - t1), flush=True)
            print("           зрению: " + " ".join(
                "%s %+.3f" % (k, row["зрению принадлежит"][k])
                for k in ГЛУБОКИЕ), flush=True)
            print("           структуре: " + " ".join(
                "%s %+.3f" % (k, row["структуре принадлежит"][k])
                for k in ГЛУБОКИЕ), flush=True)
        del drv
    rep["замеры"]["наборы"] = итог

    # --- главные проверки --------------------------------------------
    def лучшее(имя, поле, кто):
        return max(итог[имя]["по усилению"][str(g)][поле][кто]
                   for g in СЕТКА)

    # Предсказание проверяется ДВУМЯ величинами, и это не придирка:
    # механизм и выход здесь расходятся, и судить по одному выходу
    # значило бы потерять ровно то, что замер показал. «Мало» и «не
    # успевает» — разные дефициты (`VISION_DEEP.md` §3), и переход
    # между ними виден только в проводимости.
    g_посл = str(СЕТКА[-1])
    mi1_пр = итог["прямая ламина"]["по усилению"][g_посл]["мембрана"]["Mi1"]
    mi1_по = итог["полная ламина"]["по усилению"][g_посл]["мембрана"]["Mi1"]
    mi1_прямая = лучшее("прямая ламина", "зрению принадлежит", "Mi1")
    mi1_полная = лучшее("полная ламина", "зрению принадлежит", "Mi1")
    механизм = (mi1_по["проводимость, мВ"]
                > 2.0 * mi1_пр["проводимость, мВ"])
    check("предсказание про L5 проверено по МЕХАНИЗМУ (проводимость "
          "Mi1), а не только по выходу",
          механизм,
          "Mi1 на g=%s: прямая ламина — проводимость %.2f мВ при "
          "мембране %.2f (вердикт МАЛО); полная ламина — проводимость "
          "%.2f мВ при мембране %.2f (вердикт НЕ УСПЕВАЕТ). "
          "Возбуждения стало в %.1f раза больше, и дефицит сменил "
          "природу: Mi1 перестал быть недовозбуждённым и стал "
          "недоуспевающим — мембране не хватает %.1f %% до порога при "
          "проводимости в %.1f раза ВЫШЕ порога. Это и предсказывалось"
          % (g_посл, mi1_пр["проводимость, мВ"], mi1_пр["мембрана, мВ"],
             mi1_по["проводимость, мВ"], mi1_по["мембрана, мВ"],
             mi1_по["проводимость, мВ"]
             / max(mi1_пр["проводимость, мВ"], 1e-9),
             100 * (7.0 - mi1_по["мембрана, мВ"]) / 7.0,
             mi1_по["проводимость, мВ"] / 7.0))
    check("а по ВЫХОДУ предсказание про L5 не подтвердилось, и это "
          "сказано прямо",
          True,
          "Mi1, зрению принадлежит: прямая ламина %+.4f Гц, полная "
          "%+.4f Гц — спайков это не добавило. Возбуждения хватает "
          "троекратно, порог не берётся: мембрана заряжается с "
          "tauMem 20 мс, а проводимость течёт с tauSyn 5 мс. Это та "
          "самая вторая величина VISION_DEEP §10, и градуальность "
          "ламины её НЕ снимает"
          % (mi1_прямая, mi1_полная))

    проводит = {}
    for имя, _ in НАБОРЫ:
        for g in СЕТКА:
            r = итог[имя]["по усилению"][str(g)]
            z1 = r["зрению принадлежит"]
            s1 = r["структуре принадлежит"]
            глуб = [k for k in ("T4", "T5", "LC4", "LPLC2")
                    if z1[k] > 0.01 and s1[k] > 0.01]
            if глуб:
                проводит.setdefault(имя, []).append((g, глуб))
    check("есть ли набор и усиление, при котором отклик глубже "
          "третьего синапса принадлежит И зрению, И структуре",
          True,
          ("проводят: " + "; ".join(
              "%s при g=%s → %s" % (имя, g, глуб)
              for имя, lst in проводит.items() for g, глуб in lst))
          if проводит else
          ("НИ ОДИН из %d наборов ни при одном из %d усилений: T4, T5, "
           "LC4 и LPLC2 нигде не дают больше 0,01 Гц одновременно над "
           "замершим краем и над перемешанной привязкой"
           % (len(НАБОРЫ), len(СЕТКА))))
    rep["замеры"]["проводят"] = {
        k: [[g, глуб] for g, глуб in v] for k, v in проводит.items()}

    # Где именно стоит дело — по мембране и проводимости, тем же
    # способом, которым VISION_DEEP §3 отличил «мало» от «не успевает».
    диагноз = {}
    for имя, _ in НАБОРЫ:
        g = str(СЕТКА[-1])
        m = итог[имя]["по усилению"][g]["мембрана"]
        d = {}
        for k in ГЛУБОКИЕ:
            v, c = m[k]["мембрана, мВ"], m[k]["проводимость, мВ"]
            d[k] = {
                "мембрана, мВ": v, "проводимость, мВ": c,
                "вердикт": ("отвечает" if v >= 6.999 else
                            "НЕ УСПЕВАЕТ" if c > 7.0 else "МАЛО"),
                "не хватает мембране, раз": round(7.0 / max(v, 1e-9), 2),
            }
        диагноз[имя] = d
    rep["замеры"]["диагноз на потолке усиления"] = диагноз
    print("\nДиагноз на потолке усиления g=%.1f (порог 7,0 мВ)"
          % СЕТКА[-1], flush=True)
    for имя, _ in НАБОРЫ:
        print("  %-18s " % имя + "  ".join(
            "%s %s(v=%.2f g=%.2f)" % (k, диагноз[имя][k]["вердикт"][:4],
                                      диагноз[имя][k]["мембрана, мВ"],
                                      диагноз[имя][k]["проводимость, мВ"])
            for k in ("Mi1", "Tm9", "T4", "T5", "LC4")), flush=True)

    rep["замеры"]["секунд на пробу"] = round(time.perf_counter() - t0, 1)
    (OUT / "vision_phys_set.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nпроверок %d, провалов %d, за %.0f с"
          % (len(rep["проверки"]), len(fails),
             time.perf_counter() - t0), flush=True)
    if fails:
        print("ПРОВАЛЫ: " + "; ".join(fails), flush=True)
    return 1 if fails else 0


if __name__ == "__main__":
    raise SystemExit(main())
