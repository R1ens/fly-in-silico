def one_synapse(params):
    """Пересчитать объявленные допущения из параметров движка.

    Считается тем же уравнением, каким считает :meth:`sim.Engine._core`:
    проводимость спадает с ``tauSyn``, мембрана берёт от неё долю
    ``DT/tauMem`` и сама течёт к ``vRest``. Ни одно число ниже не взято
    из текста отчёта — все выведены отсюда.
    """
    dt = DT
    g_dec = 1.0 - dt / params["tauSyn"]
    m_f = dt / params["tauMem"]
    # Один синапс, один синхронный залп: проводимость получает wScale и
    # дальше спадает; мембрана интегрирует.
    g = params["wScale"]
    dv, peak = 0.0, 0.0
    for _ in range(2000):
        dv += m_f * (g - dv)
        peak = max(peak, dv)
        g *= g_dec
    need = params["vThreshold"] - params["vRest"]
    # Установившийся режим при постоянной подаче: g_ss = wScale · s · r ·
    # dt_s / (dt/tauSyn), и мембрана в установившемся состоянии равна g.
    syn_hz = need / (params["wScale"] * (dt * 1e-3) / (dt / params["tauSyn"]))
    return {
        "один синапс в пике, мВ": round(peak, 6),
        "до порога, мВ": round(need, 4),
        "синапсов в шаг до порога": round(need / peak, 1),
        "синапс·герц до порога": round(syn_hz, 0),
        "wScale, мВ на синапс": params["wScale"],
        "tauSyn, мс": params["tauSyn"],
        "tauMem, мс": params["tauMem"],
    }


