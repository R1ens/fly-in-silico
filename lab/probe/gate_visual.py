def r_reach(m):
    t = m["таблица"]
    дошло = [k for k in TARGETS if t[k]["зрению принадлежит, Гц"] > EPS]
    ok = len(дошло) == len(TARGETS)
    return ok, ("намеченные цели и что им принадлежит от зрения: %s. "
                "Порог %.2f Гц на нейрон. Дошло до %d из %d"
                % ("; ".join("%s %.4f Гц" % (k, t[k]["зрению принадлежит, Гц"])
                             for k in TARGETS),
                   EPS, len(дошло), len(TARGETS)))


def r_causal(m):
    """Частота у цели обязана УМИРАТЬ от обрыва её зрительного входа."""
    p = m["путь"]
    живые = [k for k in TARGETS if p[k]["зрение, Гц"] > EPS]
    if not живые:
        return False, ("ни у одной цели нет частоты, которую можно было бы "
                       "оборвать: %s. Причинность проверять нечего, и "
                       "«сигнал дошёл» утверждать нельзя"
                       % "; ".join("%s %.4f Гц" % (k, p[k]["зрение, Гц"])
                                   for k in TARGETS))
    плохие = [k for k in живые if p[k]["доля, снятая обрывом"] < 0.5]
    ok = not плохие
    return ok, ("обрыв объявленного зрительного входа (маска `out` на "
                "пресинаптические нейроны цели из оптических долей): %s. "
                "Нужно, чтобы обрыв снимал не меньше половины частоты. "
                "Не выдержали: %s"
                % ("; ".join("%s %.4f → %.4f Гц, снято %.3f (оборвано "
                             "%d нейронов)"
                             % (k, p[k]["зрение, Гц"], p[k]["обрыв, Гц"],
                                p[k]["доля, снятая обрывом"],
                                p[k]["оборвано нейронов"]) for k in живые),
                   ", ".join(плохие) or "нет"))


def r_hybrid(m):
    """Инженерная граница обязана быть объявлена, если она включена."""
    bio = m["биологическая точка"]
    гр = m["гибридная граница"]
    отклонения = [k for k, v in bio.items() if v["использовано"] != v["биология"]]
    ok = (not отклонения) or bool(гр)
    return ok, ("подача %s Гц (биологическая точка %s), фон %s Гц "
                "(биология %s), мост GF %r (биология %r). Отклонений от "
                "биологической точки: %d (%s). Объявленная гибридная "
                "граница: %r"
                % (bio["подача, Гц"]["использовано"],
                   bio["подача, Гц"]["биология"],
                   bio["фон, Гц"]["использовано"], bio["фон, Гц"]["биология"],
                   bio["мост GF"]["использовано"], bio["мост GF"]["биология"],
                   len(отклонения), ", ".join(отклонения) or "нет", гр))


