def f_unmatched(m):
    """Контроль не сопоставлен: у перемешанной привязки меньше входа."""
    m = dict(m)
    m["вход: перемешано"] = m["вход: зрение"] * 0.5
    return m


def f_no_stimulus(m):
    """Раздражителя нет: зрение равно выключенному."""
    m = dict(m)
    t = {k: dict(v, **{"зрение, Гц": v["выключено, Гц"],
                       "зрению принадлежит, Гц": 0.0})
         for k, v in m["таблица"].items()}
    m["таблица"] = t
    return m


def f_noise_structure(m):
    """Структура не сильнее шума: отход равен нулевой полосе."""
    m = dict(m)
    s = dict(m["структура"])
    s["отход настоящей, Гц"] = s["нулевая полоса, Гц"]
    s["лучшее отношение к нулевой полосе"] = 1.0
    m["структура"] = s
    return m


def f_wscale(m):
    """Допущение подменено: wScale вдвое меньше, объявленное — прежнее.

    Если правило это пропустит, значит «объявленные допущения» были
    строкой в отчёте, а не свойством движка.
    """
    m = dict(m)
    from flybrain import sim as S

    p = dict(S.MODEL_PARAMS)
    p["wScale"] = p["wScale"] / 2.0
    d = dict(m["допущения"])
    d.update(one_synapse(p))
    m["допущения"] = d
    return m


def f_undeclared(m):
    """Инженерная граница включена и НЕ объявлена."""
    m = dict(m)
    bio = {k: dict(v) for k, v in m["биологическая точка"].items()}
    bio["фон, Гц"]["использовано"] = 40.0
    m["биологическая точка"] = bio
    m["гибридная граница"] = None
    return m


def main():
    rep = Report("ШЛЮЗЫ B и C. Зрительная динамика и глубокая передача",
                 OUT / "gate_visual.json")
    import torch

    from flybrain import data as D, retina as R, sim as S

    neurons = D.load_neurons()
    W = D.load_weights()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    n = len(neurons)
    om = R.ommatidia()

    pops = {}
    for name, types in CHAIN:
        idx = np.unique(np.concatenate(
            [D.select(neurons, "celltype=%s" % t) for t in types]))
        if not len(idx):
            raise SystemExit("нет в v783: " + name)
        pops[name] = idx
    t_pop = {k: torch.as_tensor(v, device=dev) for k, v in pops.items()}
    rep.measure("популяции", {k: int(len(v)) for k, v in pops.items()})

    maps = R.build_all(neurons, mode="whiten", assign="capacity")
    # ЧЕТЫРЕ перемешивания, а не одно. Одно даёт ОДНУ точку и никакой
    # оценки разброса: разные зёрна меняют, какой нейрон получит какой
    # омматидий, то есть и сам пуассоновский розыгрыш, и два прогона
    # расходятся без всякой структуры. Нулевая полоса — расхождение
    # перемешиваний МЕЖДУ СОБОЙ, и мерить структуру без неё нечем.
    SHUF = 5
    shuf = [R.build_all(neurons, mode="whiten", assign="capacity",
                        shuffle=True, seed=s) for s in range(SHUF)]
    pr_idx = np.unique(np.concatenate([maps[k].neurons for k in maps]))
    t_map = {k: torch.as_tensor(m.neurons, device=dev)
             for k, m in maps.items()}

    # --- раздражитель: настоящие кадры нависания или посчитанный край ---
    путь = probe._isolate.OUT / "gate_frames.npy"
    if путь.exists():
        frames = np.load(путь)
        источник = ("настоящие кадры MuJoCo из probe/gate_retina.py "
                    "(нависание, %d кадров)" % len(frames))
    else:
        x = om["pos"][:, 0]
        lo, hi = float(x.min()), float(x.max())
        frames = []
        for i in range(8):
            cut = lo + (hi - lo) * i / 7.0
            lit = (x <= cut).astype(np.float32)
            fr = np.stack([lit, lit], axis=-1)
            frames.append(np.stack([fr, fr]))
        frames = np.stack(frames)
        источник = ("ПОСЧИТАННЫЙ край по положениям омматидиев: настоящих "
                    "кадров не нашлось (%s)" % путь)
    print("  раздражитель: " + источник, flush=True)
    rep.measure("раздражитель", {
        "источник": источник, "кадров": int(len(frames)),
        "средняя яркость": round(float(frames.mean()), 5),
        "доля насыщенных выше %.2f" % VIS_REF:
            round(float((frames > VIS_REF).mean()), 5),
    })

    every = max(1, int(round(1000.0 / VIS_HZ / DT)))

    # --- общее состояние после разогрева ---
    eng0 = S.build_engine(weights=W, neurons=neurons, device=dev, seed=0,
                          no_refractory=pr_idx, graphs=True)
    z = torch.zeros(1, n, device=dev)
    for _ in range(WARM):
        eng0.step(z)
    snap = {"поля": {nm: getattr(eng0, nm).detach().clone()
                     for nm in ("v", "conductance", "spikes", "refrac",
                                "delay_buffer")},
            "ptr": eng0.ptr, "gen": eng0.gen.get_state().clone()}
    del eng0
    print("  состояние снято после %d шагов разогрева" % WARM, flush=True)

    def run(mode, mm=None, pr_hz=PR_MAX_HZ, tonic_hz=0.0, tonic_idx=None,
            out_mask=None):
        """Один прогон условия с одного и того же состояния."""
        eng = S.build_engine(weights=W, neurons=neurons, device=dev, seed=0,
                             no_refractory=pr_idx, graphs=True)
        for nm, val in snap["поля"].items():
            getattr(eng, nm).copy_(val)
        eng.ptr = snap["ptr"]
        eng.gen.set_state(snap["gen"].clone())
        if out_mask is not None and len(out_mask):
            eng.set_masks(out=out_mask)
        rates = torch.zeros(1, n, device=dev)
        acc = torch.zeros(n, device=dev)
        total_in = 0.0
        mm = mm if mm is not None else maps
        for s in range(STEPS):
            if s % every == 0:
                rates.zero_()
                if mode != "выключено":
                    fr = frames[(s // every) % len(frames)]
                    hz = R.rates(mm, fr, max_hz=pr_hz, ref=VIS_REF)
                    for key, v in hz.items():
                        rates[0, t_map[key]] = torch.as_tensor(
                            np.asarray(v, dtype=np.float32), device=dev)
                if tonic_hz > 0.0 and tonic_idx is not None:
                    cur = rates[0, tonic_idx]
                    rates[0, tonic_idx] = torch.clamp(cur, min=tonic_hz)
                total_in += float(rates.sum().item())
            acc += eng.step(rates)[0]
        if dev == "cuda":
            torch.cuda.synchronize()
        win_ms = STEPS * DT
        out = {k: round(1e3 * float(acc[t].sum().item()) / len(pops[k])
                        / win_ms, 5) for k, t in t_pop.items()}
        del eng
        return out, total_in

    # --- четыре сопоставленных условия ---
    res, tin = {}, {}
    for tag, mm in ([("выключено", None), ("зрение", maps)]
                    + [("перемешано %d" % s, shuf[s]) for s in range(SHUF)]):
        res[tag], tin[tag] = run(
            "выключено" if tag == "выключено" else "зрение", mm=mm)
        print("  %-13s суммарный вход %.4f Гц·кадров" % (tag, tin[tag]),
              flush=True)

    таблица = {}
    for name, _ in CHAIN:
        off = res["выключено"][name]
        vis = res["зрение"][name]
        sh = [res["перемешано %d" % s][name] for s in range(SHUF)]
        таблица[name] = {
            "нейронов": int(len(pops[name])),
            "выключено, Гц": off, "зрение, Гц": vis,
            "перемешанные, Гц": sh,
            "среднее перемешанных, Гц": round(float(np.mean(sh)), 5),
            "зрению принадлежит, Гц": round(vis - off, 5),
        }
    rep.measure("отклик по цепочке", таблица)
    print("\n  %-7s %8s %9s %11s %11s %11s"
          % ("", "выкл", "зрение", "перем.среднее", "зрению", "полоса СО"),
          flush=True)

    # --- структура против нулевой полосы ---
    лучш, луч_отн, луч_d, луч_null = None, -1.0, 0.0, 0.0
    стр = {}
    for name, _ in CHAIN:
        t = таблица[name]
        sh = np.asarray(t["перемешанные, Гц"], dtype=float)
        # Нулевая полоса — СО по перемешиваниям, а не их размах: размах
        # растёт с числом прогонов и порог по нему зависел бы от того,
        # сколько перемешиваний посчитали. Отношение ниже — это z-оценка:
        # на сколько СО настоящая привязка отходит от среднего
        # перемешанных.
        null = float(sh.std(ddof=1)) if len(sh) > 1 else 0.0
        d = abs(t["зрение, Гц"] - float(sh.mean()))
        отн = (d / null) if null > 0 else (float("inf") if d > 0 else 0.0)
        стр[name] = {"отход настоящей, Гц": round(d, 5),
                     "нулевая полоса, Гц": round(null, 5),
                     "отношение": (round(отн, 3) if np.isfinite(отн)
                                   else "бесконечно")}
        print("  %-7s %8.4f %9.4f %11.4f %11.4f %11.4f"
              % (name, t["выключено, Гц"], t["зрение, Гц"],
                 t["среднее перемешанных, Гц"],
                 t["зрению принадлежит, Гц"], null), flush=True)
        if name in ("R1-6", "R7", "R8"):
            continue                 # фоторецепторы структуры не несут
        кон = отн if np.isfinite(отн) else 1e9
        if кон > луч_отн and d > 0:
            лучш, луч_отн, луч_d, луч_null = name, кон, d, null
    структура = {
        "перемешиваний": SHUF,
        "по популяциям": стр,
        "лучшая популяция": лучш,
        "отход настоящей, Гц": round(луч_d, 5),
        "нулевая полоса, Гц": round(луч_null, 5),
        "лучшее отношение к нулевой полосе": round(луч_отн, 3),
    }
    rep.measure("структура против нулевой полосы", структура)
    print("\n  структура: лучшее у %s — отход %.5f Гц при полосе %.5f Гц, "
          "отношение %.2f" % (лучш, луч_d, луч_null, луч_отн), flush=True)

    # --- объявленные допущения, пересчитанные из параметров движка ---
    доп = one_synapse(S.MODEL_PARAMS)
    pre = W.indices()[1].cpu().numpy()
    val = W.values().cpu().numpy()
    знак = np.sign(val)
    order = np.argsort(pre, kind="stable")
    p_s, z_s = pre[order], знак[order]
    bounds = np.flatnonzero(np.diff(p_s)) + 1
    starts = np.concatenate([[0], bounds])
    ends = np.concatenate([bounds, [len(p_s)]])
    нарушителей = 0
    for a, b in zip(starts, ends):
        seg = z_s[a:b]
        if seg.min() < 0 < seg.max():
            нарушителей += 1
    доп["нарушителей закона Дейла"] = int(нарушителей)
    доп["пресинаптических всего"] = int(len(starts))
    # Полнота: сколько фоторецепторов набора получили место в привязке.
    все_pr = np.unique(np.concatenate(
        [D.select(neurons, "celltype=%s" % t) for t in ("R1-6", "R7", "R8")]))
    доп["полнота набора фоторецепторов"] = round(
        float(len(np.intersect1d(все_pr, pr_idx)) / max(len(все_pr), 1)), 6)
    доп["фоторецепторов в наборе"] = int(len(все_pr))
    доп["фоторецепторов в привязке"] = int(len(pr_idx))
    rep.measure("допущения модели", доп)
    print("  допущения: один синапс %.6f мВ, %.1f синапса в шаг, "
          "%.0f синапс·герц; нарушителей Дейла %d из %d; полнота %.4f"
          % (доп["один синапс в пике, мВ"], доп["синапсов в шаг до порога"],
             доп["синапс·герц до порога"], нарушителей, len(starts),
             доп["полнота набора фоторецепторов"]), flush=True)

    m_b = {
        "вход: зрение": round(tin["зрение"], 6),
        "вход: перемешано": round(tin["перемешано 0"], 6),
        "вход: все перемешивания": [round(tin["перемешано %d" % s], 6)
                                    for s in range(SHUF)],
        "таблица": таблица,
        "структура": структура,
        "допущения": доп,
        # Объявлено в отчётах проекта (`VISION.md` §3). Правило сверяет
        # ПЕРЕСЧЁТ с этими числами, а не доверяет им.
        "объявлено в отчётах": {
            "один синапс в пике, мВ": 0.043512,
            "синапсов в шаг до порога": 160.9,
            "синапс·герц до порога": 5091.0,
        },
    }
    rep.measure("замер шлюза B", m_b)

    rep.gate(
        "B", "зрительная динамика: отклик зависит от раздражителя при "
             "сопоставленных контролях и подчиняется объявленным "
             "допущениям", m_b,
        rules=(
            rule("контроль сопоставлен: суммарный вход совпадает",
                 r_matched, "расхождение входа ≤ 1e-6 в долях"),
            rule("отклик зависит от раздражителя", r_stimulus_dep,
                 "зрению принадлежит > %.2f Гц хотя бы у двух популяций"
                 % EPS),
            rule("отклик зависит от структуры сильнее, чем от зерна "
                 "перемешивания", r_structure,
                 "отход ≥ 3 СО нулевой полосы"),
            rule("объявленные допущения модели пересчитаны и держатся",
                 r_assumptions,
                 "пересчёт совпал с объявленным; Дейл без нарушителей"),
        ),
        forgeries=(
            forge("контроль не сопоставлен (вход вдвое меньше)",
                  f_unmatched, "контроль сопоставлен: суммарный вход "
                               "совпадает",
                  "ровно эта ошибка уже была в проекте: портились "
                  "таблицы, общие для обеих сравниваемых дорог"),
            forge("раздражителя нет вовсе", f_no_stimulus,
                  "отклик зависит от раздражителя",
                  "проба этого проекта один раз отчиталась «ок», идя "
                  "вообще без стимула"),
            forge("структура не сильнее шума", f_noise_structure,
                  "отклик зависит от структуры сильнее, чем от зерна "
                  "перемешивания",
                  "разница настоящей и перемешанной равна разнице двух "
                  "перемешиваний: структуры нет, разброс есть"),
            forge("допущение подменено: wScale вдвое меньше", f_wscale,
                  "объявленные допущения модели пересчитаны и держатся",
                  "если правило пропустит, «объявленное допущение» было "
                  "строкой в отчёте, а не свойством движка"),
        ))

    # ------------------------------------------------------------ шлюз C
    print("\n  Шлюз C: причинность пути к намеченным целям", flush=True)
    # ЧТО СЧИТАЕТСЯ ЗРИТЕЛЬНЫМ ВХОДОМ, и почему одного `super:optic` мало.
    # Первая редакция этой пробы брала только `super:optic` и получила,
    # что у DNp01 ноль зрительных входов из 862 — а это неверно: LC4 и
    # LPLC2 в v783 лежат в `super_class = visual_projection`, не в
    # `optic`, и именно они кормят DNp01. На том же недосмотре сломался
    # бы и подлог: «невизуальные входы DNp01» включили бы LC4 и LPLC2, и
    # ловушка разожгла бы ровно те популяции, которые обязана держать в
    # нуле (замерено: LC4 36,35 Гц, LPLC2 35,26 Гц вместо ровных нулей).
    # Поэтому зрительным считается объединение трёх надклассов, и состав
    # его записан в отчёт числом.
    зрит_классы = ("optic", "visual_projection", "visual_centrifugal")
    optic = np.unique(np.concatenate(
        [D.select(neurons, "super:%s" % c) for c in зрит_классы]))
    rep.measure("что считается зрительным входом", {
        "надклассы": list(зрит_классы),
        "нейронов": int(len(optic)),
        "по надклассам": {c: int(len(D.select(neurons, "super:%s" % c)))
                          for c in зрит_классы},
    })
    post = W.indices()[0].cpu().numpy()
    путь_зам = {}
    for name in TARGETS:
        цель = pops[name]
        # Объявленный зрительный вход цели: её пресинаптические нейроны,
        # лежащие в оптических долях. Считается по коннектому, а не
        # предполагается по учебнику.
        mask = np.isin(post, цель)
        src = np.unique(pre[mask])
        vis_src = np.intersect1d(src, optic)
        got, _ = run("зрение", out_mask=vis_src)
        путь_зам[name] = {
            "зрение, Гц": таблица[name]["зрение, Гц"],
            "обрыв, Гц": got[name],
            "оборвано нейронов": int(len(vis_src)),
            "пресинаптических всего": int(len(src)),
            "доля зрительных среди входов": round(
                float(len(vis_src) / max(len(src), 1)), 4),
            "доля, снятая обрывом": (
                round(1.0 - got[name] / таблица[name]["зрение, Гц"], 4)
                if таблица[name]["зрение, Гц"] > 0 else None),
        }
        print("    %-6s зрение %.4f → обрыв %.4f Гц; оборвано %d из %d "
              "входов (%.1f %% зрительных)"
              % (name, путь_зам[name]["зрение, Гц"],
                 путь_зам[name]["обрыв, Гц"],
                 len(vis_src), len(src),
                 100 * путь_зам[name]["доля зрительных среди входов"]),
              flush=True)
    rep.measure("причинность пути", путь_зам)

    bio = {
        "подача, Гц": {"использовано": PR_MAX_HZ, "биология": PR_MAX_HZ},
        "фон, Гц": {"использовано": 0.0, "биология": 0.0},
        "мост GF": {"использовано": "none", "биология": "none"},
    }
    m_c = {
        "таблица": таблица,
        "путь": путь_зам,
        "биологическая точка": bio,
        "гибридная граница": None,
    }
    rep.measure("замер шлюза C", m_c)

    # --- настоящий подлог к правилу причинности: DNp01 мимо пути ---
    # Разжигаем DNp01 его НЕвизуальными возбуждающими входами. Это и есть
    # та ловушка, на которой проект уже один раз поймал себя: 5 Гц у
    # DNp01 при РОВНО нулевых LC4 и LPLC2.
    dn = pops["DNp01"]
    mask = np.isin(post, dn)
    src_dn = np.unique(pre[mask])
    exc = np.unique(pre[mask][val[mask] > 0])
    non_vis = np.setdiff1d(exc, optic)
    syn_exc = float(val[mask][val[mask] > 0].sum())
    vis_edges = mask.copy()
    vis_edges[mask] = (val[mask] > 0) & np.isin(pre[mask], optic)
    syn_vis = float(val[vis_edges].sum())
    t_nv = torch.as_tensor(non_vis, device=dev)
    trap, _ = run("выключено", tonic_hz=40.0, tonic_idx=t_nv)
    vis_src_dn = np.intersect1d(src_dn, optic)
    trap_cut, _ = run("выключено", tonic_hz=40.0, tonic_idx=t_nv,
                      out_mask=vis_src_dn)
    ловушка = {
        "чем разожгли": ("фон 40 Гц на %d НЕвизуальных возбуждающих "
                         "входов DNp01" % len(non_vis)),
        "DNp01, Гц": trap["DNp01"],
        "DNp01 при обрыве зрительного входа, Гц": trap_cut["DNp01"],
        "LC4, Гц": trap["LC4"],
        "LPLC2, Гц": trap["LPLC2"],
        "T4, Гц": trap["T4"],
        "доля, снятая обрывом": (
            round(1.0 - trap_cut["DNp01"] / trap["DNp01"], 4)
            if trap["DNp01"] > 0 else None),
        "возбуждающих входов всего, нейронов": int(len(exc)),
        "из них зрительных, нейронов": int(len(np.intersect1d(exc, optic))),
        "возбуждающих синапсов на нейрон DNp01":
            round(syn_exc / len(dn), 1),
        "из них зрительных, доля": round(syn_vis / max(syn_exc, 1.0), 4),
    }
    rep.measure("ловушка DNp01", ловушка)
    print("    ЛОВУШКА: DNp01 %.4f Гц при LC4 %.4f и LPLC2 %.4f; обрыв "
          "зрительного входа оставил %.4f Гц (снято %s)"
          % (trap["DNp01"], trap["LC4"], trap["LPLC2"], trap_cut["DNp01"],
             ловушка["доля, снятая обрывом"]), flush=True)

    def f_dnp01_trap(m):
        """Настоящий замер, на котором наивный судья бы прошёл."""
        m = dict(m)
        p = {k: dict(v) for k, v in m["путь"].items()}
        p["DNp01"]["зрение, Гц"] = ловушка["DNp01, Гц"]
        p["DNp01"]["обрыв, Гц"] = ловушка["DNp01 при обрыве зрительного "
                                          "входа, Гц"]
        p["DNp01"]["доля, снятая обрывом"] = ловушка["доля, снятая обрывом"]
        m["путь"] = p
        return m

    rep.gate(
        "C", "глубокая зрительная передача: сигнал доходит до намеченных "
             "целей ПО ЗАЯВЛЕННОМУ ПУТИ, гибридная граница объявлена",
        m_c,
        rules=(
            rule("сигнал дошёл до намеченных целей", r_reach,
                 "зрению принадлежит > %.2f Гц у всех целей" % EPS),
            rule("частота у цели приходит ПО ПУТИ: обрыв зрительного "
                 "входа её убивает", r_causal,
                 "обрыв снимает ≥ 0,5 частоты"),
            rule("гибридная граница объявлена, если включена", r_hybrid,
                 "отклонение от биологической точки названо"),
        ),
        forgeries=(
            forge("DNp01 разожжён мимо пути (НАСТОЯЩИЙ замер)",
                  f_dnp01_trap,
                  "частота у цели приходит ПО ПУТИ: обрыв зрительного "
                  "входа её убивает",
                  "DNp01 даёт %.4f Гц при РОВНО нулевых LC4 и LPLC2, и "
                  "обрыв зрительного входа снимает %s. Наивный судья "
                  "«DNp01 > 0 ⇒ дошло» здесь проходит; этот — обязан "
                  "отвергнуть"
                  % (ловушка["DNp01, Гц"], ловушка["доля, снятая обрывом"])),
            forge("инженерная граница включена и не объявлена",
                  f_undeclared, "гибридная граница объявлена, если включена",
                  "фон 40 Гц подан, в отчёте не назван — ровно так "
                  "«фоновая активность» однажды подменила зрительный путь"),
        ))

    rep.note("шлюз C на нынешнем v2 не пройден, и это не дефект пробы. "
             "Глубже Tm1/Tm2 зрению не принадлежит ничего: LC4 %.4f Гц, "
             "LPLC2 %.4f, DNp01 %.4f, DNp04 %.4f. Причина посчитана и "
             "названа в `VISION.md` §3: один синапс даёт в пике %.6f мВ, "
             "до порога нужно %.1f синапса в шаг, на первом синапсе "
             "приходит 2272, то есть 45 %% порога. Это предел МОДЕЛИ, а "
             "не данных."
             % (таблица["LC4"]["зрению принадлежит, Гц"],
                таблица["LPLC2"]["зрению принадлежит, Гц"],
                таблица["DNp01"]["зрению принадлежит, Гц"],
                таблица["DNp04"]["зрению принадлежит, Гц"],
                доп["один синапс в пике, мВ"],
                доп["синапсов в шаг до порога"]))
    rep.note("мост Giant Fiber остаётся ВЫКЛЮЧЕННЫМ, и шлюз C его не "
             "требует: главный канал GF→TTMn и GF→PSI электрический, а "
             "ЭМ считает только хемический, то есть вес из коннектома не "
             "выводится в принципе (`BANC_MOTOR.md`). Прыжок по этому "
             "пути обосновать нельзя.")
    return rep.finish()


