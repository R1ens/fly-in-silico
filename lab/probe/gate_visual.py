def r_matched(m):
    a, b = m["вход: зрение"], m["вход: перемешано"]
    rel = abs(a - b) / max(a, 1.0)
    ok = rel <= 1e-6
    return ok, ("подано %.4f против %.4f Гц·кадров, расхождение %.2e в "
                "долях (порог 1e-6). Перемешивание сохраняет число "
                "нейронов на омматидий, поэтому сила входа та же до "
                "разрядности float32, и сравнивается ТОЛЬКО "
                "пространственная структура. Без этого равенства "
                "сравнение не измеряет структуру — ровно так в этом "
                "проекте уже портили таблицы, общие для обеих дорог"
                % (a, b, rel))


def r_stimulus_dep(m):
    t = m["таблица"]
    дошло = [k for k in t
             if k not in ("R1-6", "R7", "R8")
             and t[k]["зрению принадлежит, Гц"] > EPS]
    ok = len(дошло) >= 2
    return ok, ("зрению принадлежит (зрение минус выключенное при том же "
                "фоне, порог %.2f Гц): %s. Фоторецепторы %.2f Гц при "
                "зрении против %.4f при выключенном. Непрошедших "
                "популяций %d"
                % (EPS, ", ".join(дошло) or "НИ ОДНОЙ",
                   t["R1-6"]["зрение, Гц"], t["R1-6"]["выключено, Гц"],
                   sum(1 for k in t
                       if t[k]["зрению принадлежит, Гц"] <= EPS)))


def r_structure(m):
    s = m["структура"]
    ok = s["лучшее отношение к нулевой полосе"] >= 3.0
    return ok, ("нулевая полоса снята по %d перемешиваниям с разными "
                "зёрнами: для каждой популяции это СО частоты по "
                "перемешиваниям, то есть разброс, который структурой не "
                "объясняется вовсе. Лучшее отношение — у "
                "%s: настоящая привязка отходит от среднего перемешанных "
                "на %.5f Гц при полосе %.5f Гц, то есть %.2f СО (нужно "
                "≥ 3,00). Без этой полосы «отклик зависит от структуры» "
                "проходит на пуассоновском шуме: разные зёрна дают разные "
                "розыгрыши и без всякой структуры"
                % (s["перемешиваний"], s["лучшая популяция"],
                   s["отход настоящей, Гц"],
                   s["нулевая полоса, Гц"],
                   s["лучшее отношение к нулевой полосе"]))


def r_assumptions(m):
    d = m["допущения"]
    объявлено = m["объявлено в отчётах"]
    ok = (abs(d["один синапс в пике, мВ"]
              - объявлено["один синапс в пике, мВ"]) < 5e-6
          and abs(d["синапсов в шаг до порога"]
                  - объявлено["синапсов в шаг до порога"]) < 0.05
          and abs(d["синапс·герц до порога"]
                  - объявлено["синапс·герц до порога"]) < 1.0
          and d["нарушителей закона Дейла"] == 0
          and d["полнота набора фоторецепторов"] >= 0.9999)
    return ok, ("пересчитано из параметров движка: один синапс в пике "
                "%.6f мВ (объявлено %.6f), %.1f синапса в шаг "
                "(объявлено %.1f), %.0f синапс·герц (объявлено %.0f). "
                "Нарушителей закона Дейла %d из %d пресинаптических. "
                "Полнота набора фоторецепторов %.4f. Ни одно из этих "
                "чисел не взято из текста: все выведены из `MODEL_PARAMS` "
                "тем же уравнением, каким считает движок"
                % (d["один синапс в пике, мВ"],
                   объявлено["один синапс в пике, мВ"],
                   d["синапсов в шаг до порога"],
                   объявлено["синапсов в шаг до порога"],
                   d["синапс·герц до порога"],
                   объявлено["синапс·герц до порога"],
                   d["нарушителей закона Дейла"],
                   d["пресинаптических всего"],
                   d["полнота набора фоторецепторов"]))


