"""«Стоп» на эпизоде арены не должен ждать локальную модель три минуты.

Что было замерено
-----------------

`loop.Commentator.finish` ждал, пока очередь к локальной модели
опустеет, с запасом до **180 секунд**, и звался он на оборванном эпизоде
тоже. То есть пользователь нажимал «Стоп», счёт останавливался, а окно
стояло ещё до трёх минут, дожидаясь реплик, которые уже никому не
нужны. Время после «Стоп» принадлежит пользователю.

Как это починено и что проверяется
----------------------------------

`finish(drop=True)` вычерпывает очередь без обращения к модели и
**считает брошенное** (`Commentator.dropped`), а число уезжает в
`timing["реплик брошено"]` и в оговорки прогона. Иначе «реплик меньше,
чем шагов» читалось бы как «модель промолчала», а не как «эпизод
оборвали».

Проверки здесь без локальной модели и без карты: модель подменяется
заглушкой, которая СПИТ. Так и воспроизводится то, что делала настоящая
очередь, и время измеряется, а не обсуждается.

* ``drop=True`` возвращается быстро и называет число брошенного;
* **встречный замер**: ``drop=False`` на том же состоянии ждёт заметно
  дольше. Без него «быстро» ничего не значило бы: быстрым оно могло
  оказаться потому, что очередь и так была пуста;
* короткий срок у `drop=True` всё равно нужен: нить может сидеть в уже
  НАЧАТОМ запросе, и его не отменить. Проверяется, что этот срок
  ограничен, а не отсутствует;
* ``enabled=False`` не трогается вовсе: там комментатора нет.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\comment_stop.py

Коды: 0 — всё сошлось; 1 — есть провал.
"""

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

OUT = Path(__file__).parent

fails = []
rep = {"проверки": {}}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""))
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


СОН_С = 1.5          # сколько «думает» подменённая модель над одной репликой
В_ОЧЕРЕДИ = 6        # сколько реплик стоит в очереди на момент «Стоп»


def main():
    from flybrain import llm, loop

    # Модель подменяется заглушкой, которая спит. Подмена именно
    # `llm.chat`, а не `Commentator`: ждёт в нём ровно эта очередь.
    настоящий = llm.chat

    def медленно(msgs, model=None, temperature=0.5):
        time.sleep(СОН_С)
        return "заглушка"

    llm.chat = медленно
    try:
        print("— «Стоп» и очередь к локальной модели —")
        print("  заглушка думает %.1f с над репликой, в очереди %d"
              % (СОН_С, В_ОЧЕРЕДИ))

        # --- брошено: быстро и с числом --------------------------------
        c = loop.Commentator(model="заглушка", enabled=True)
        for i in range(В_ОЧЕРЕДИ):
            c.submit(i * 200.0, {"шаг": i})
        time.sleep(0.1)          # дать нити взять первую
        t0 = time.perf_counter()
        c.finish(drop=True)
        брошено_с = time.perf_counter() - t0
        rep["drop=True, с"] = round(брошено_с, 3)
        rep["брошено"] = int(c.dropped)
        check("drop=True возвращается быстро", брошено_с < СОН_С * 2.0,
              "%.3f с при сроке %.1f с" % (брошено_с, min(180.0, 5.0)))
        check("брошенное посчитано, а не потеряно молча",
              c.dropped >= В_ОЧЕРЕДИ - 2,
              "%d из %d (одну-две нить успевает взять)"
              % (c.dropped, В_ОЧЕРЕДИ))
        check("срок у drop=True ограничен, а не отсутствует",
              брошено_с <= 5.0 + СОН_С, "%.3f с" % брошено_с)

        # --- ВСТРЕЧНЫЙ ЗАМЕР: без drop ждёт заметно дольше ------------
        c2 = loop.Commentator(model="заглушка", enabled=True)
        for i in range(В_ОЧЕРЕДИ):
            c2.submit(i * 200.0, {"шаг": i})
        time.sleep(0.1)
        t0 = time.perf_counter()
        c2.finish(drop=False, timeout=180)
        ждал_с = time.perf_counter() - t0
        rep["drop=False, с"] = round(ждал_с, 3)
        check("без drop та же очередь ждётся заметно дольше",
              ждал_с > брошено_с * 2.0 and ждал_с > СОН_С,
              "%.3f с против %.3f с — в %.1f раза"
              % (ждал_с, брошено_с, ждал_с / max(брошено_с, 1e-9)))
        check("и без drop реплики ДОЖДАЛИСЬ, то есть ждал он не впустую",
              len(c2.out) >= В_ОЧЕРЕДИ - 1 and c2.dropped == 0,
              "%d реплик, брошено %d" % (len(c2.out), c2.dropped))

        # --- выключенный комментатор не трогается --------------------
        c3 = loop.Commentator(enabled=False)
        t0 = time.perf_counter()
        пусто = c3.finish(drop=True)
        check("у выключенного комментатора finish мгновенный и пустой",
              пусто == [] and (time.perf_counter() - t0) < 0.1,
              "%.4f с" % (time.perf_counter() - t0))
    finally:
        llm.chat = настоящий

    (OUT / "comment_stop.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print()
    if fails:
        print("ПРОВАЛЫ: %s" % ", ".join(fails))
        return 1
    print("«Стоп» больше не ждёт модель, и брошенное сосчитано")
    return 0


if __name__ == "__main__":
    sys.exit(main())
