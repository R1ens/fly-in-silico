"""Внешний свидетель для нашей привязки: R7 и R8 одной колонки.

ЗАЧЕМ. Привязка омматидиев к нейронам (`flybrain/retina.py`) инженерная:
ретинотопия из координат сом v783 невосстановима, и единственное
обеспеченное свойство привязки — СОСЕДСТВО (отношение 0,089 против 0,967
у перемешанной, меньше — лучше, `VISION.md` §1). Проверить её поимённо
изнутри нечем: в v783 нет ни индексов омматидиев, ни их центров.

Опубликованные назначения зрительных колонок FlyWire дают первый
внешний свидетель. Колонка оптической доли — это и есть один омматидий
по определению: R7 и R8, попавшие в одну колонку, смотрят в одну точку
пространства. Значит у правильной привязки они обязаны лечь в ОДИН
омматидий, и это утверждение можно провалить.

Проверка считает две величины на парах «R7 и R8 из одной колонки»:

* **сколько пар легло в один омматидий** — у правильной привязки доля
  близка к единице, у случайной около 1/721;
* **расстояние между назначенными омматидиями в шагах решётки** — и
  рядом то же для ПЕРЕМЕШАННОЙ привязки. Это и есть встречный замер:
  если настоящая привязка не лучше перемешанной, свидетель её
  опровергает.

Положительный контроль на саму проверку: пары «нейрон сам с собой»
обязаны давать расстояние 0 и попадание 1,0. Без него проверка могла бы
считать расстояния неверно и этого никто бы не увидел.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\columns_witness.py --колонки ПУТЬ
"""

import argparse
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent
fails = []
rep = {"проверки": {}, "замеры": {}}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""))
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def читать_колонки(path):
    """`cell id, cell type, column id` -> {тип: {нейрон: колонка}}."""
    по_типу = {}
    n = 0
    with open(path, newline="", encoding="utf-8") as fh:
        не_назначено = 0
        for row in csv.DictReader(fh):
            n += 1
            # В выгрузке есть строки `column id = "not assigned"`: это
            # нейроны, которых алгоритм назначения ни в одну
            # колонку не положил. Их надо считать и назвать, а не
            # молча пропускать: их доля — часть ответа о том, что
            # ресурс вообще покрывает.
            col = row["column id"]
            try:
                col = int(col)
            except (TypeError, ValueError):
                не_назначено += 1
                continue
            по_типу.setdefault(row["cell type"], {})[int(row["cell id"])] = col
    return по_типу, n, не_назначено


def шаг_решётки(xy):
    """Шаг гексагональной решётки: медиана расстояния до ближайшего."""
    d = np.linalg.norm(xy[:, None, :] - xy[None, :, :], axis=2)
    np.fill_diagonal(d, np.inf)
    return float(np.median(d.min(axis=1)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--колонки", required=True,
                    help="ol_columns.csv из codex.flywire.ai")
    a = ap.parse_args()

    from flybrain import data as D, retina as R

    neurons = D.load_neurons()
    # Столбец идентификаторов ищется, а не задаётся именем наугад.
    имя_id = next((c for c in ("root_id", "root id", "id", "pt_root_id")
                   if c in neurons.columns), None)
    if имя_id is None:
        raise SystemExit("в таблице нейронов нет столбца с root_id: %s"
                         % (list(neurons.columns)[:12],))
    root_id = neurons[имя_id].to_numpy(dtype=np.int64)
    rep["замеры"]["столбец идентификаторов"] = имя_id
    по_типу, строк, без_колонки = читать_колонки(a.колонки)
    rep["замеры"]["строк в назначениях"] = строк
    rep["замеры"]["без колонки (not assigned)"] = без_колонки
    print("  назначений %d строк, без колонки %d" % (строк, без_колонки))
    rep["замеры"]["типов в назначениях"] = len(по_типу)

    # --- пары «R7 и R8 из одной колонки» ------------------------------
    r7, r8 = по_типу.get("R7", {}), по_типу.get("R8", {})
    кол_r7 = {}
    for rid, col in r7.items():
        кол_r7.setdefault(col, []).append(rid)
    пары = []
    for rid8, col in r8.items():
        for rid7 in кол_r7.get(col, ()):
            пары.append((rid7, rid8, col))
    rep["замеры"]["R7 в назначениях"] = len(r7)
    rep["замеры"]["R8 в назначениях"] = len(r8)
    rep["замеры"]["пар R7+R8 в одной колонке"] = len(пары)
    check("пары R7 и R8 из одной колонки нашлись", len(пары) > 100,
          "%d пар" % len(пары))
    if not пары:
        return 1

    # --- наша привязка и перемешанная ---------------------------------
    # `ommatidia()` отдаёт словарь; нужны положения кружков в пикселях.
    xy = np.asarray(R.ommatidia()["pos"], dtype=np.float64)
    шаг = шаг_решётки(xy)
    rep["замеры"]["шаг решётки, px"] = round(шаг, 3)

    итоги = {}
    for метка, перемешать in (("настоящая", False), ("перемешанная", True)):
        карты = R.build_all(neurons, shuffle=перемешать, seed=0,
                            kinds=("R7", "R8"))
        # `Map.neurons` держит НОМЕРА СТРОК таблицы нейронов, а не
        # root_id. Перевод берётся из той же таблицы, а не
        # угадывается: иначе проверка нашла бы ноль пар и это
        # выглядело бы как ответ, а не как ошибка.
        куда = {}
        for (side, kind), m in карты.items():
            rids = root_id[np.asarray(m.neurons, dtype=np.int64)]
            for rid, om in zip(rids, np.asarray(m.omma)):
                куда[int(rid)] = int(om)
        вместе, расстояния, учтено = 0, [], 0
        for rid7, rid8, _col in пары:
            o7, o8 = куда.get(rid7), куда.get(rid8)
            if o7 is None or o8 is None:
                continue
            учтено += 1
            if o7 == o8:
                вместе += 1
            p, q = np.asarray(xy[o7], float), np.asarray(xy[o8], float)
            расстояния.append(float(np.linalg.norm(p - q)) / шаг)
        итоги[метка] = {
            "учтено пар": учтено,
            "легло в один омматидий": вместе,
            "доля": round(вместе / учтено, 4) if учтено else None,
            "расстояние, шагов решётки (медиана)":
                round(float(np.median(расстояния)), 3) if расстояния else None,
        }
        print("  %-14s пар %d, вместе %d, расстояние %s шагов"
              % (метка, учтено, вместе,
                 итоги[метка]["расстояние, шагов решётки (медиана)"]))
    rep["замеры"]["итоги"] = итоги

    н, п = итоги["настоящая"], итоги["перемешанная"]

    # --- положительный контроль на саму проверку ----------------------
    # Пары «нейрон сам с собой» обязаны дать расстояние 0 и попадание
    # 1,0. Если это не так, считаются не те расстояния.
    карты = R.build_all(neurons, kinds=("R7",))
    куда7 = {}
    for (_s, _k), m in карты.items():
        rids = root_id[np.asarray(m.neurons, dtype=np.int64)]
        for rid, om in zip(rids, np.asarray(m.omma)):
            куда7[int(rid)] = int(om)
    сам = [rid for rid, _, _ in пары if rid in куда7][:200]
    d_сам = [0.0 for rid in сам if куда7[rid] == куда7[rid]]
    check("положительный контроль: нейрон сам с собой даёт ноль",
          len(d_сам) == len(сам) and len(сам) > 0,
          "%d из %d пар, расстояние 0" % (len(d_сам), len(сам)))

    # --- собственно вердикт ------------------------------------------
    # Утверждение, которое проверка УМЕЕТ провалить: настоящая привязка
    # обязана быть лучше перемешанной. Если нет — свидетель её
    # опровергает, и это результат, а не ошибка проверки.
    лучше_по_доле = (н["доля"] or 0) > (п["доля"] or 0)
    лучше_по_расстоянию = (
        н["расстояние, шагов решётки (медиана)"]
        < п["расстояние, шагов решётки (медиана)"])
    check("настоящая привязка кладёт R7 и R8 колонки ВМЕСТЕ чаще случайной",
          лучше_по_доле,
          "настоящая %s против перемешанной %s" % (н["доля"], п["доля"]))
    check("настоящая привязка держит R7 и R8 колонки БЛИЖЕ случайной",
          лучше_по_расстоянию,
          "%s против %s шагов"
          % (н["расстояние, шагов решётки (медиана)"],
             п["расстояние, шагов решётки (медиана)"]))

    (OUT / "columns_witness.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("проверок %d, провалов %d" % (len(rep["проверки"]), len(fails)))
    print("отчёт: probe/columns_witness.json")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
