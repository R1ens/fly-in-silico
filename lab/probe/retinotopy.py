def profile(pts, k=10):
    """Медианное расстояние до k-го соседа и прирост по соседям.

    Пучок из шести даёт разрыв между пятым и шестым соседом: пятый ещё
    свой, шестой уже чужой. Разрыв ищется не на глаз, а числом —
    отношением медиан и приростом.
    """
    from scipy.spatial import cKDTree

    d, _ = cKDTree(pts).query(pts, k=k)
    med = [float(np.median(d[:, i])) for i in range(1, k)]
    grow = [(med[i] - med[i - 1]) / med[i - 1] for i in range(1, len(med))]
    return {
        "медиана до соседа, мкм": [round(v, 2) for v in med],
        "прирост по соседям, доля": [round(v, 4) for v in grow],
        "шестой к пятому": round(med[5] / med[4], 4),
        "прирост на шестом": round(grow[4], 4),
        "прирост на четвёртом": round(grow[2], 4),
    }


def bundled(pts, per=6, spread=1.0, seed=0):
    """Искусственный контроль: та же поверхность, но пучки по шесть.

    Берутся настоящие положения R7 — то есть настоящая решётка
    омматидиев, — и вокруг каждого рассыпается шесть точек в пределах
    `spread` мкм. Это и есть то, как выглядели бы координаты сом, если
    бы фоторецепторы одного омматидия лежали вместе.
    """
    g = np.random.default_rng(seed)
    out = np.repeat(pts, per, axis=0)
    return out + g.normal(0.0, spread / 3.0, out.shape)


def part_sheet(ctx):
    """Поверхность сом двумерна — значит плоская параметризация законна."""
    print("\nФорма облака сом", flush=True)
    res = {}
    for side in SIDES:
        p = ctx["R1-6"][side]
        c = p - p.mean(0)
        _, s, vt = np.linalg.svd(c, full_matrices=False)
        var = s ** 2 / (s ** 2).sum()
        res[side] = {
            "нейронов": int(len(p)),
            "доля дисперсии по осям": [round(float(v), 5) for v in var],
            "толщина по третьей оси, СО мкм": round(
                float(np.std(c @ vt[2])), 2),
            "размах по осям, мкм": [round(float(v), 1)
                                    for v in (p.max(0) - p.min(0))],
        }
        print("  %-6s дисперсия по осям %s, толщина %s мкм"
              % (side, res[side]["доля дисперсии по осям"],
                 res[side]["толщина по третьей оси, СО мкм"]), flush=True)
    # Толщина листа в ШАГАХ РЕШЁТКИ омматидиев, а не в долях дисперсии:
    # доля дисперсии зависит от размаха глаза и сама по себе ничего не
    # говорит о том, разрешимы ли соседние омматидии. Первая редакция
    # этой проверки сравнивала третью ось с порогом 1 % «на глаз» и
    # провалилась на правом глазе — правильно провалилась.
    from scipy.spatial import cKDTree

    for side in SIDES:
        r7 = ctx["R7"][side]
        step = float(np.median(cKDTree(r7).query(r7, k=2)[0][:, 1]))
        res[side]["шаг решётки омматидиев, мкм"] = round(step, 2)
        res[side]["толщина листа в шагах решётки"] = round(
            res[side]["толщина по третьей оси, СО мкм"] / step, 2)
    rep["замеры"]["форма облака сом"] = res
    flat = min(sum(res[s]["доля дисперсии по осям"][:2]) for s in SIDES)
    thick = max(res[s]["толщина листа в шагах решётки"] for s in SIDES)
    check("облако сом — лист, но толщина его сравнима с шагом решётки "
          "омматидиев, и это уже само по себе мешает назначению",
          flat >= 0.95,
          "две главные оси держат от %.1f %% дисперсии, то есть это "
          "лист. Но толщина листа %s мкм при шаге решётки омматидиев %s "
          "мкм — то есть %s шага. На правом глазе лист толще двух шагов, "
          "и значит ближайший сосед в трёхмерном пространстве может "
          "принадлежать соседнему омматидию просто из-за глубины. "
          "Двумерная координата законна (лист), привязка по трёхмерной "
          "близости — нет"
          % (100 * flat,
             [res[s]["толщина по третьей оси, СО мкм"] for s in SIDES],
             [res[s]["шаг решётки омматидиев, мкм"] for s in SIDES],
             [res[s]["толщина листа в шагах решётки"] for s in SIDES]))
    return res


