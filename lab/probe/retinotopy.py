def assign(src, dst):
    """Назначить каждую точку `src` ближайшей точке `dst`."""
    from scipy.spatial import cKDTree

    tree = cKDTree(dst)
    d, who = tree.query(src, k=1)
    cnt = np.bincount(who, minlength=len(dst))
    step = float(np.median(tree.query(dst, k=2)[0][:, 1]))
    h = np.bincount(cnt)
    return {
        "медиана на приёмник": float(np.median(cnt)),
        "среднее на приёмник": round(float(cnt.mean()), 3),
        "мода": int(h.argmax()),
        "доля приёмников ровно с шестью": round(float((cnt == 6).mean()), 4),
        "доля приёмников ровно с одним": round(float((cnt == 1).mean()), 4),
        "доля с пятью-семью":
            round(float(((cnt >= 5) & (cnt <= 7)).mean()), 4),
        "пустых приёмников": int((cnt == 0).sum()),
        "приёмников всего": int(len(dst)),
        "наибольшее на один приёмник": int(cnt.max()),
        "расстояние до своего, медиана": round(float(np.median(d)), 3),
        "расстояние до своего, 95-й": round(float(np.percentile(d, 95)), 3),
        "шаг решётки приёмников, медиана": round(step, 3),
        "отношение расстояния к шагу решётки":
            round(float(np.median(d)) / max(step, 1e-9), 3),
    }


