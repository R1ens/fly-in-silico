         "шесть нет, ближайший R7 лежит в двух с половиной шагах решётки, "
         "а по направлению расстояние до «своего» узла больше углового "
         "шага решётки. Все три способа проверены встречными замерами: на "
         "искусственных данных с заложенными пучками те же способы "
         "работают, а пара R7–R8 находится и в настоящих данных, то есть "
         "координаты достаточно точны. Значит дело в данных. Следствие "
         "для проекта: любая привязка омматидиев к нейронам будет "
         "ИНЖЕНЕРНОЙ КОНСТРУКЦИЕЙ, а не восстановленной анатомией, и "
