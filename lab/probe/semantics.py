def context():
    import torch

    from flybrain import data as D

    dev = "cuda" if torch.cuda.is_available() else "cpu"
    neurons = D.load_neurons()
    W = D.load_weights(device=dev)
    n = len(neurons)
    src = D.select(neurons, Q_IN)
    pop = D.select(neurons, Q_POP)
    rest = np.setdiff1d(np.arange(n), pop)
    rates = torch.zeros(1, n, device=dev)
    rates[0, torch.as_tensor(src, device=dev)] = HZ

    # Какую долю входящего веса популяция получает ОТ СЕБЯ. Это не
    # любопытство: `out` на популяции режет и её связи внутрь себя, и
    # без этого числа падение её собственной активности выглядело бы
    # как ошибка места маски.
    m = np.zeros(n, bool)
    m[pop] = True
    w = W.coalesce()
    idx = w.indices().cpu().numpy()
    val = w.values().cpu().numpy()
    post, pre = idx[0], idx[1]
    inner = m[post] & m[pre]
    inner_n = int(inner.sum())
    all_n = int(m[post].sum())
    w_inner = float(val[inner].sum())
    w_all = float(val[m[post]].sum())
    del w, idx, val, post, pre, inner, m
    return {
        "dev": dev, "neurons": neurons, "W": W, "n": n,
        "src": src, "pop": pop,
        "tpop": torch.as_tensor(pop, device=dev),
        "trest": torch.as_tensor(rest, device=dev),
        "rates": rates,
        "связей внутри популяции": int(inner_n),
        "входящих связей популяции": int(all_n),
        "вес внутри популяции": round(w_inner, 1),
        "весь входящий вес популяции": round(w_all, 1),
        "доля веса от себя": round(w_inner / max(w_all, 1e-9), 4),
    }


def engine_of(ctx):
    from flybrain import sim

    return sim.build_engine(weights=ctx["W"], neurons=ctx["neurons"],
                            device=ctx["dev"], seed=0,
                            no_refractory=ctx["src"], graphs=True)


STATE = ("v", "conductance", "spikes", "refrac", "delay_buffer")


def snapshot(eng):
    """Полное состояние движка: всё, что переносит прогон вперёд."""
    return {
        "поля": {nm: getattr(eng, nm).detach().clone() for nm in STATE},
        "ptr": eng.ptr,
        "gen": eng.gen.get_state().clone(),
    }


def restore(eng, snap):
    for nm, val in snap["поля"].items():
        getattr(eng, nm).copy_(val)
    eng.ptr = snap["ptr"]
    eng.gen.set_state(snap["gen"].clone())
    eng.set_masks(fire=[], out=[], inc=[], hold=[])


def run(ctx, eng, steps):
    """Прогнать шаги и снять по-шаговые ряды для цели и остального мозга."""
    import torch

    tp, tr = ctx["tpop"], ctx["trest"]
    r = ctx["rates"]
    sp_pop = torch.zeros(steps, device=ctx["dev"])
    sp_rest = torch.zeros(steps, device=ctx["dev"])
    for s in range(steps):
        sp = eng.step(r)
        sp_pop[s] = sp[0, tp].sum()
        sp_rest[s] = sp[0, tr].sum()
    if ctx["dev"] == "cuda":
        torch.cuda.synchronize()
    return {
        "цель по шагам": sp_pop.cpu().numpy(),
        "остальные по шагам": sp_rest.cpu().numpy(),
    }


def membrane(ctx, eng):
    """Мембрана, проводимость и число нейронов выше порога — у цели."""
    import torch

    tp = ctx["tpop"]
    v = eng.v[0, tp]
    c = eng.conductance[0, tp]
    return {
        "v среднее, мВ": round(float(v.mean()), 3),
        "v максимум, мВ": round(float(v.max()), 3),
        "v минимум, мВ": round(float(v.min()), 3),
        "v размах, мВ": round(float(v.max() - v.min()), 6),
        "проводимость средняя, мВ": round(float(c.mean()), 3),
        "проводимость максимум, мВ": round(float(c.max()), 3),
        "v покоя плюс проводимость максимум, мВ":
            round(float(eng.v_rest + c.max()), 3),
        "выше порога, нейронов": int((v > eng.v_th).sum()),
        "отпечаток v": fp(v.detach().cpu().numpy()),
    }


def mask_of(ctx, kind):
    """Индексы для `set_masks` по имени условия."""
    pop = ctx["pop"]
    z = {"fire": EMPTY, "out": EMPTY, "inc": EMPTY, "hold": EMPTY}
    for part in kind.split("+"):
        if part == "контроль":
            continue
        z["inc" if part == "in" else part] = pop
    return z


# --------------------------------------------------------- семь условий

CONDS = ("контроль", "fire", "hold", "out", "in", "fire+out", "hold+in")


def one_cond(ctx, eng, snap, kind, sup=SUP, aft=AFT):
    """Одно условие от перенесённого состояния: под маской и после снятия."""
    restore(eng, snap)
    eng.set_masks(**mask_of(ctx, kind))
    counts = eng.mask_counts()
    during = run(ctx, eng, sup)
    mem = membrane(ctx, eng)
    eng.set_masks(fire=[], out=[], inc=[], hold=[])
    after = run(ctx, eng, aft)
    return {
        "маски": counts,
        "цель под маской, спайков": int(during["цель по шагам"].sum()),
        "остальные под маской, спайков":
            int(during["остальные по шагам"].sum()),
        "мембрана перед снятием": mem,
        "после снятия по шагам":
            [int(x) for x in after["цель по шагам"][:5]],
        "после снятия, всего за %d шагов" % aft:
            int(after["цель по шагам"].sum()),
        "_ряд под маской": during["цель по шагам"],
        "_ряд после": after["цель по шагам"],
        "_ряд остальные": during["остальные по шагам"],
    }


def part_table(ctx, eng, snap):
    """Сводная таблица по семи условиям и проверки их различий."""
    stage("\nСемь условий на одной популяции, одинаковые начальные "
          "условия (%d нейронов, %d шагов под маской)"
          % (len(ctx["pop"]), SUP))
    res = {}
    for kind in CONDS:
        t0 = time.perf_counter()
        res[kind] = one_cond(ctx, eng, snap, kind)
        print("  условие %-9s цель %7d, остальные %8d, v максимум "
              "%9.2f мВ, после снятия %s  (%.1f с)"
              % (kind, res[kind]["цель под маской, спайков"],
                 res[kind]["остальные под маской, спайков"],
                 res[kind]["мембрана перед снятием"]["v максимум, мВ"],
                 res[kind]["после снятия по шагам"][:3],
                 time.perf_counter() - t0), flush=True)

    ctl = res["контроль"]
    base = float(ctl["_ряд после"][:AFT].mean())
    base_sup = float(ctl["_ряд под маской"].mean())

    # Повтор контроля от того же состояния — побитово, иначе сравнивать
    # нечего: расхождение контроля с самим собой означало бы, что
    # перенос состояния неполон и различия между условиями ничего не
    # значат.
    again = one_cond(ctx, eng, snap, "контроль")
    same = (fp(again["_ряд под маской"]) == fp(ctl["_ряд под маской"])
            and fp(again["_ряд после"]) == fp(ctl["_ряд после"])
            and (again["мембрана перед снятием"]["отпечаток v"]
                 == ctl["мембрана перед снятием"]["отпечаток v"]))
    check("перенос состояния полон: контроль повторяется побитово",
          same,
          "отпечатки ряда и мембраны совпали; спайков цели %d оба раза"
          % ctl["цель под маской, спайков"])

    table = {}
    for kind in CONDS:
        d = res[kind]
        m = d["мембрана перед снятием"]
        burst = d["после снятия по шагам"][0]
        table[kind] = {
            "цель под маской, спайков": d["цель под маской, спайков"],
            "цель, доля от контроля":
                round(d["цель под маской, спайков"]
                      / max(ctl["цель под маской, спайков"], 1), 4),
            "остальные под маской, спайков":
                d["остальные под маской, спайков"],
            "остальные, доля от контроля":
                round(d["остальные под маской, спайков"]
                      / max(ctl["остальные под маской, спайков"], 1), 4),
            "v среднее перед снятием, мВ": m["v среднее, мВ"],
            "v максимум перед снятием, мВ": m["v максимум, мВ"],
            "размах v по популяции, мВ": m["v размах, мВ"],
            "выше порога перед снятием": m["выше порога, нейронов"],
            "спайков в первом шаге после снятия": burst,
            "во сколько раз больше обычного шага":
                round(burst / max(base, 1e-9), 1),
            "спайков во втором и третьем шаге":
                d["после снятия по шагам"][1:3],
            "масок поставлено": d["маски"],
        }
    table["обычно спайков цели на шаг"] = round(base, 2)
    table["обычно спайков цели на шаг под маской (контроль)"] = \
        round(base_sup, 2)
    rep["замеры"]["таблица семи условий"] = table

    # --- что именно отличает семантики ---
    f, h, o, i = res["fire"], res["hold"], res["out"], res["in"]

    check("молчание у `fire` и `hold` полное, и это НЕ отличает их друг "
          "от друга",
          f["цель под маской, спайков"] == 0
          and h["цель под маской, спайков"] == 0
          and ctl["цель под маской, спайков"] > 0,
          "по нулю спайков у обоих за %d шагов против %d у контроля — "
          "по этому числу семантики неразличимы, поэтому дальше "
          "сравнивается не молчание, а мембрана и то, что остаётся "
          "после снятия" % (SUP, ctl["цель под маской, спайков"]))

    fv = f["мембрана перед снятием"]["v максимум, мВ"]
    hv = h["мембрана перед снятием"]["v максимум, мВ"]
    hsp = h["мембрана перед снятием"]["v размах, мВ"]
    check("`hold` держит мембрану ровно на v_clamp, `fire` пускает её "
          "на три порядка выше порога",
          hsp < 1e-3 and hv < -45.0 and fv > 100.0,
          "`hold`: v у всех %d нейронов равна %.3f мВ, размах по "
          "популяции %.2e мВ (это и есть v_clamp = vReset); `fire`: "
          "максимум %.1f мВ при пороге %.1f мВ — выше порога на %.0f мВ"
          % (len(ctx["pop"]), hv, hsp, fv, -45.0, fv + 45.0))

    # `out` на популяции режет и её связи ВНУТРЬ СЕБЯ, поэтому её
    # собственная активность тоже падает. Это не ошибка места маски, и
    # проверяется это не порогом «на вид», а совпадением падения с
    # долей веса, которую популяция получает от себя: доля считана по
    # матрице независимо от прогона.
    drop = (1.0 - o["цель под маской, спайков"]
            / max(ctl["цель под маской, спайков"], 1))
    share = ctx["доля веса от себя"]
    rep["замеры"]["почему `out` снижает и саму популяцию"] = {
        "связей внутри популяции": ctx["связей внутри популяции"],
        "входящих связей популяции": ctx["входящих связей популяции"],
        "вес внутри популяции": ctx["вес внутри популяции"],
        "весь входящий вес популяции": ctx["весь входящий вес популяции"],
        "доля входящего веса от себя": share,
        "падение собственной активности под `out`": round(drop, 4),
        "расхождение доли и падения": round(abs(drop - share), 4),
    }
    check("`out` не глушит саму популяцию, а её падение на %.1f %% "
          "объяснено весом, который она получает от себя" % (100 * drop),
          o["цель под маской, спайков"]
          > 0.5 * ctl["цель под маской, спайков"]
          and abs(drop - share) <= 0.3 * share
          and o["остальные под маской, спайков"]
          < ctl["остальные под маской, спайков"],
          "цель выдала %d спайков против %d у контроля — падение "
          "%.2f %% при доле входящего веса от себя %.2f %% (%d связей "
          "внутри популяции из %d входящих), расхождение %.2f п.п.; "
          "остальной мозг %d против %d (%.1f %% от контроля). Стой маска "
          "не на исходящих, а на выдаче спайка, спайков цели было бы "
          "ноль, как у `fire`"
          % (o["цель под маской, спайков"],
             ctl["цель под маской, спайков"], 100 * drop, 100 * share,
             ctx["связей внутри популяции"],
             ctx["входящих связей популяции"],
             100 * abs(drop - share),
             o["остальные под маской, спайков"],
             ctl["остальные под маской, спайков"],
             100.0 * o["остальные под маской, спайков"]
             / max(ctl["остальные под маской, спайков"], 1)))

    iv = i["мембрана перед снятием"]["v среднее, мВ"]
    check("`in` глушит голодом: мембрана ПАДАЕТ к покою, а не растёт "
          "(встречный замер против `fire`)",
          iv < -45.0 and iv < f["мембрана перед снятием"]["v среднее, мВ"],
          "у `in` v в среднем %.2f мВ (покой −52,0 мВ, порог −45,0 мВ), "
          "у `fire` %.1f мВ. Молчание похожее, мембрана — "
          "противоположная"
          % (iv, f["мембрана перед снятием"]["v среднее, мВ"]))

    fb = f["после снятия по шагам"][0]
    hb = h["после снятия по шагам"][0]
    ib = i["после снятия по шагам"][0]
    check("залп при снятии есть только у `fire`",
          fb / max(base, 1e-9) >= 10.0
          and hb <= max(3.0 * base, 5.0)
          and ib <= max(3.0 * base, 5.0),
          "в первом шаге после снятия: `fire` %d спайков (%.0f-кратно "
          "обычного шага %.2f), `hold` %d, `in` %d. Залп — свойство "
          "накопления в уравнении, а не сети"
          % (fb, fb / max(base, 1e-9), base, hb, ib))

    # Комбинации: маски складываются, и несовместимых среди них нет.
    fo = res["fire+out"]
    hi = res["hold+in"]
    pop_n = len(ctx["pop"])
    check("совместимые вмешательства складываются: `fire+out`",
          fo["цель под маской, спайков"] == 0
          and fo["остальные под маской, спайков"]
          < ctl["остальные под маской, спайков"]
          and sorted(v for v in fo["маски"].values() if v) == [pop_n] * 2,
          "цель молчит, остальной мозг %d против %d у контроля, масок "
          "поставлено %s"
          % (fo["остальные под маской, спайков"],
             ctl["остальные под маской, спайков"], fo["маски"]))
    check("совместимые вмешательства складываются: `hold+in`",
          hi["цель под маской, спайков"] == 0
          and hi["мембрана перед снятием"]["v размах, мВ"] < 1e-3
          and sorted(v for v in hi["маски"].values() if v) == [pop_n] * 2,
          "цель молчит, мембрана держится ровно (размах %.2e мВ), масок "
          "поставлено %s"
          % (hi["мембрана перед снятием"]["v размах, мВ"], hi["маски"]))

    # Стоимость для сети: три семантики глушат получателей, одна — нет.
    rows = {k: table[k]["остальные, доля от контроля"] for k in CONDS}
    check("`in` на цели почти не затрагивает остальной мозг, а три "
          "остальные семантики затрагивают",
          rows["in"] > rows["fire"] and rows["in"] > rows["hold"]
          and rows["in"] > rows["out"],
          "доля спайков остального мозга от контроля: in %.4f, out "
          "%.4f, fire %.4f, hold %.4f"
          % (rows["in"], rows["out"], rows["fire"], rows["hold"]))
    return res, base


# ------------------------------------- развёртка по длительности залпа

def part_growth(ctx, eng, snap, base):
    """Залп растёт с длительностью подавления у `fire` и не растёт у `hold`.

    Это и есть доказательство, что разряд после снятия исторического
    `fire` — вычислительный артефакт. Биологический rebound ограничен
    ёмкостью мембраны и рефрактерностью; здесь предела нет ни в одном
    месте кода, и зависимость от длительности это показывает прямо.
    """
    stage("\nРазвёртка по длительности подавления")
    g = {}
    for kind in ("fire", "hold"):
        g[kind] = {}
        for d in DURS:
            r = one_cond(ctx, eng, snap, kind, sup=d, aft=10)
            m = r["мембрана перед снятием"]
            g[kind][d] = {
                "v максимум перед снятием, мВ": m["v максимум, мВ"],
                "v среднее перед снятием, мВ": m["v среднее, мВ"],
                "проводимость максимум, мВ": m["проводимость максимум, мВ"],
                "предел уравнения, v покоя + проводимость, мВ":
                    m["v покоя плюс проводимость максимум, мВ"],
                "выше порога перед снятием": m["выше порога, нейронов"],
                "спайков в первом шаге после снятия":
                    r["после снятия по шагам"][0],
                "кратность обычного шага":
                    round(r["после снятия по шагам"][0]
                          / max(base, 1e-9), 1),
            }
            print("  %-5s %4d шагов: v максимум %9.2f мВ, выше порога "
                  "%4d, залп %4d (%.0f-кратно)"
                  % (kind, d, m["v максимум, мВ"],
                     m["выше порога, нейронов"],
                     r["после снятия по шагам"][0],
                     r["после снятия по шагам"][0] / max(base, 1e-9)),
                  flush=True)
    rep["замеры"]["развёртка по длительности"] = g

    fv = [g["fire"][d]["v максимум перед снятием, мВ"] for d in DURS]
    fb = [g["fire"][d]["спайков в первом шаге после снятия"] for d in DURS]
    hv = [g["hold"][d]["v максимум перед снятием, мВ"] for d in DURS]
    hb = [g["hold"][d]["спайков в первом шаге после снятия"] for d in DURS]

    # Мембрана под `fire` НЕ беспредельна, и это пришлось измерить,
    # чтобы не повторить прежнее неверное утверждение. Уравнение
    # мембраны — утечка к `v_rest + conductance`:
    #
    #     v += tau * (conductance - (v - v_rest)),
    #
    # и его неподвижная точка v = v_rest + conductance. Значит рост
    # останавливается не произвольно, а на уровне, который задаёт
    # входная проводимость. Предел есть, он просто на три порядка выше
    # порога и ничем в коде не ОГРАНИЧЕН СПЕЦИАЛЬНО.
    lim = [g["fire"][d]["предел уравнения, v покоя + проводимость, мВ"]
           for d in DURS]
    grows = fv[1] > fv[0] and fv[2] > fv[1]
    plateau = abs(fv[-1] - fv[-2]) < 0.1 * abs(fv[-2])
    at_lim = abs(fv[-1] - lim[-1]) <= 0.02 * abs(lim[-1])
    check("мембрана под `fire` растёт с длительностью, но выходит на "
          "полку, и полку задаёт уравнение, а не ограничитель",
          grows and plateau and at_lim,
          "по длительностям %s: %s мВ. Рост от %.0f до %.0f мВ, дальше "
          "полка (%d→%d шагов добавили %.1f %%). Полка совпала с "
          "неподвижной точкой уравнения v = v_покоя + проводимость = "
          "%.0f мВ с расхождением %.2f %%: ограничителя напряжения в "
          "коде нет, рост останавливает сама утечка к входной "
          "проводимости. Порог −45 мВ, то есть полка выше порога на "
          "%.0f мВ"
          % (list(DURS), [round(x, 1) for x in fv], fv[0], fv[-2],
             DURS[-2], DURS[-1],
             100 * abs(fv[-1] - fv[-2]) / max(abs(fv[-2]), 1e-9),
             lim[-1], 100 * abs(fv[-1] - lim[-1]) / max(abs(lim[-1]), 1e-9),
             fv[-1] + 45.0))
    check("залп под `fire` растёт вместе с длительностью и тоже выходит "
          "на полку",
          fb[1] >= fb[0] and fb[-1] >= fb[-2]
          and fb[-1] > 1.5 * max(base, 1.0),
          "залп по длительностям %s: %s спайков при обычном уровне %.2f "
          "на шаг; полка — это те %d нейронов из %d, у которых "
          "установившаяся мембрана выше порога, остальным входа не "
          "хватает ни при какой длительности"
          % (list(DURS), fb, base, fb[-1], len(ctx["pop"])))
    check("у `hold` ни мембрана, ни залп от длительности не зависят "
          "(встречный замер)",
          max(hv) - min(hv) < 1e-3 and max(hb) <= max(3.0 * base, 5.0),
          "v максимум %s мВ при любой длительности, залп %s — против "
          "роста %s мВ и %s у `fire`"
          % ([round(x, 2) for x in hv], hb,
             [round(x, 1) for x in fv], fb))

    note("flybrain/LESION.md и probe/lesion.py утверждали, что у "
         "накопления мембраны под `fire` «предела в коде нет» и что "
         "«чем дольше подавление, тем выше залп». Развёртка показала, "
         "что это НЕВЕРНО: v растёт с %.0f мВ за %d шагов до %.0f мВ за "
         "%d и дальше стоит на полке (%d шагов дали те же %.0f мВ, "
         "+%.1f %%), а залп — с %d до %d спайков и дальше тоже стоит. "
         "Предел есть, и он не произволен: уравнение мембраны есть "
         "утечка к v_покоя + проводимость, и полка совпала с этой "
         "неподвижной точкой (%.0f мВ) с расхождением %.2f %%. То есть "
         "рост останавливает входная проводимость, а не ограничитель "
         "напряжения — его в коде действительно нет. Текст исправлен: "
         "прежняя формулировка преувеличивала. Вывод о природе залпа от "
         "этого не меняется — он остаётся ВЫЧИСЛИТЕЛЬНЫМ АРТЕФАКТОМ "
         "способа подавления, потому что его величину задаёт "
         "накопленная за время маски проводимость, а не состояние сети, "
         "и ни рефрактерность, ни ёмкость мембраны его не ограничивают. "
         "Трактовать залп как естественный нейронный rebound нельзя. "
         "Историческая семантика оставлена нетронутой ради "
         "воспроизводимости прежних прогонов; для опытов, где "
         "выключение и обратное включение важны, предназначен `hold`."
         % (fv[0], DURS[0], fv[-2], DURS[-2], DURS[-1], fv[-1],
            100 * abs(fv[-1] - fv[-2]) / max(abs(fv[-2]), 1e-9),
            fb[0], fb[-1], lim[-1],
            100 * abs(fv[-1] - lim[-1]) / max(abs(lim[-1]), 1e-9)))
    return g


# ----------------------------------------------- возврат к обычной работе

def part_recovery(ctx, eng, snap, res, base):
    """Через сколько шагов после снятия активность цели обычная."""
    stage("\nВозврат к обычной работе после снятия")
    rec = {}
    for kind in ("fire", "hold", "out", "in"):
        row = res[kind]["_ряд после"]
        back = None
        for s in range(len(row) - 2):
            if all(row[s + k] <= 3.0 * max(base, 1.0) for k in range(3)):
                back = s
                break
        rec[kind] = {
            "шагов до обычного уровня": back,
            "первые пять шагов": [int(x) for x in row[:5]],
            "среднее за 60 шагов после снятия": round(float(row.mean()), 2),
        }
        print("  %-5s обычный уровень через %s шагов, в среднем %.2f "
              "против %.2f у контроля"
              % (kind, back, float(row.mean()), base), flush=True)
    rec["обычно спайков на шаг"] = round(base, 2)
    rep["замеры"]["возврат к обычной работе"] = rec

    check("после снятия любой семантики активность возвращается к "
          "обычному уровню за единицы шагов",
          all(rec[k]["шагов до обычного уровня"] is not None
              and rec[k]["шагов до обычного уровня"] <= 5
              for k in ("fire", "hold", "out", "in")),
          "шагов до обычного уровня: " + ", ".join(
              "%s %s" % (k, rec[k]["шагов до обычного уровня"])
              for k in ("fire", "hold", "out", "in")))
    return rec


# -------------------------------------------------------------------- ход

def guarded(name, fn, *args):
    try:
        return fn(*args)
    except Exception:
        print("  СОРВАЛОСЬ %s" % name, flush=True)
        traceback.print_exc()
        rep["сорвалось"].append({"часть": name,
                                 "след": traceback.format_exc()})
        fails.append("сорвалось: " + name)
        return None


def main():
    t0 = time.perf_counter()
    stage("Научное сравнение семантик вмешательства (этап 1.3)")
    ctx = context()
    rep["замеры"]["устройство"] = {
        "нейронов": ctx["n"],
        "вход": "%s, %d нейронов, %.0f Гц" % (Q_IN, len(ctx["src"]), HZ),
        "цель вмешательства": "%s, %d нейронов"
                              % (Q_POP, len(ctx["pop"])),
        "шагов разогрева": WARM,
        "шагов под маской": SUP,
        "шагов после снятия": AFT,
        "развёртка по длительности": list(DURS),
        "устройство": ctx["dev"],
    }
    stage("  вход %s (%d), цель %s (%d), устройство %s"
          % (Q_IN, len(ctx["src"]), Q_POP, len(ctx["pop"]), ctx["dev"]))

    eng = engine_of(ctx)
    rep["замеры"]["устройство"]["графы"] = eng._graphs is not None
    run(ctx, eng, WARM)
    snap = snapshot(eng)
    stage("  состояние снято после %d шагов разогрева" % WARM)

    out = guarded("таблица", part_table, ctx, eng, snap)
    if out:
        res, base = out
        guarded("развёртка", part_growth, ctx, eng, snap, base)
        guarded("возврат", part_recovery, ctx, eng, snap, res, base)

    del eng
    gc.collect()

    rep["замеры"]["проба заняла, с"] = round(time.perf_counter() - t0, 1)
    for d in (rep["замеры"].get("таблица семи условий") or {}).values():
        if isinstance(d, dict):
            d.pop("_ряд под маской", None)
    (OUT / "semantics.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    n_ok = sum(1 for v in rep["проверки"].values() if v["пройдено"])
    stage("\nпроверок %d, провалов %d, находок %d, за %.0f с"
          % (len(rep["проверки"]), len(fails), len(rep["находки"]),
             time.perf_counter() - t0))
    if fails:
        stage("ПРОВАЛЫ:")
        for f in fails:
            stage("  " + f)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
