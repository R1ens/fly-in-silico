"""Научное сравнение всех семантик вмешательства на одинаковых условиях.

Этап 1.3 единого плана. Четыре семантики масок (`fire`, `hold`, `out`,
`in`) по отдельности уже проверены пробой `probe/lesion.py`. Здесь они
сравниваются МЕЖДУ СОБОЙ, и это другой вопрос: не «работает ли каждая»,
а «чем они отличаются и что остаётся после снятия».

Сравнение честно только при одинаковых начальных условиях, поэтому
состояние движка снимается ОДИН раз после разогрева и переносится в
каждое условие целиком — мембрана, проводимость, спайки, рефрактерность,
кольцо задержек, указатель кольца и состояние генератора случайных
чисел. Движок при этом один и тот же: различия в числах принадлежат
семантике, а не зерну и не порядку запуска.

Семь условий на одной популяции (`class:ALPN+side:left`, 341 нейрон):

    контроль, fire, hold, out, in, fire+out, hold+in

и отдельно — развёртка по длительности подавления (100, 250, 500, 1000
шагов) для `fire` и `hold`. Развёртка нужна ровно для одного
утверждения, которое владелец проекта потребовал сделать явно:
**синхронный разряд после снятия исторического `fire` — вычислительный
артефакт способа подавления, а не нейронный rebound.** Доказывается это
не словами, а тем, что залп растёт вместе с длительностью подавления
без всякого предела, тогда как у `hold` он не растёт вовсе. У
биологического rebound такой зависимости от длительности выключения
быть не может: он ограничен ёмкостью мембраны и рефрактерностью, а
здесь ограничения нет нигде в коде.

ВСТРЕЧНЫЕ ЗАМЕРЫ. Проверка «популяция замолчала» проходит у трёх
семантик из четырёх, и по ней их не различить. Поэтому у каждой
проверки стоит замер, который показал бы подмену:

* `out` НЕ должен глушить саму популяцию — она продолжает выдавать
  спайки, молчат её получатели. Если бы `out` оказался ещё одним
  глушителем, это значило бы, что маска стоит не в том месте цепочки;
* `in` глушит голодом, и мембрана при этом ПАДАЕТ к покою, а не растёт;
  у `fire` она растёт. Одинаковое молчание — разная мембрана;
* `hold` держит мембрану на `v_clamp` ровно, до последнего разряда
  float32; у `fire` она уходит на три порядка выше порога;
* контроль прогоняется дважды и обязан совпасть побитово, иначе
  сравнивать нечего.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\semantics.py
"""

