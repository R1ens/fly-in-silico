r"""Веса адресации нисходящих на моторный выход — из связности BANC.

Зачем. Веса `TURN_WEIGHTS_V1` в `motor.py` ОБЪЯВЛЕНЫ: 1,0 на `DNa02`,
0,5 на `DNa01`, 0,3 на `DNp09` — порядок взят из литературы, а числа
назначены. `BANC_MOTOR.md` принёс то, чего для них не хватало:
премоторный выход каждого зонда, посчитанный по брюшной цепочке BANC.
Этот скрипт переводит его в файл адресации, который `motor.py` уже
умеет читать (`load_weight_map`), — то есть подключает обоснование
ДАННЫМИ, а не правкой кода.

Что здесь считается и чего здесь НЕТ:

* считается СИЛА премоторного выхода — сильнейшая пара «нисходящий →
  мотонейрон» в BANC, по сторонам, с опорой на `root_id`, а не на имя
  (решение владельца №3: `DNa01`, `DNa04`, `DNa05` по одному имени не
  выбирать — два авторитета называют этим именем разные клетки);
* НЕ считается ЗНАК и НЕ считается РОЛЬ. Куда поворачивает рост
  `DNa02` и почему `MDN` — задний ход, из таблицы соответствий не
  следует: в ней нет латеральности мишеней. Знаки и роли остаются из
  объявленной версии, и в происхождении это записано прямо;
* `DNp01` исключён решением владельца №1: мост Giant Fiber остаётся
  выключенным, его моторный выход в BANC — 41-й и 55-й процентиль, то
  есть ниже середины популяции.

    cd D:\fly-brain\lab
    set PYTHONIOENCODING=utf-8
    ..\.venv\Scripts\python.exe probe\banc_weights.py          # показать
    ..\.venv\Scripts\python.exe probe\banc_weights.py --писать  # записать файл
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from flybrain import data as D, motor  # noqa: E402

КАРТА = (Path(__file__).resolve().parents[1] / "flybrain" / "assets"
         / "banc_fafb_v888_v783_map.parquet")
ЦЕЛЬ = (Path(__file__).resolve().parents[1] / "flybrain" / "assets"
        / "motor_map_banc_v888.json")

# Кому веса поворота пересчитываются по BANC. Остальные три зонда
# рулёжкой не занимаются ни в объявленной версии, ни по смыслу:
# `MDN` — задний ход, `DNp04` — ответ на надвигание, `DNp01` исключён
# решением владельца.
РУЛЕВЫЕ = ("DNa02", "DNa01", "DNp09")
ОПОРНЫЙ = "DNa02"


def стороны(neurons, зонд):
    """`root_id` зонда по сторонам, через тот же селектор, что в модели."""
    из = {}
    for сторона in ("left", "right"):
        idx = np.asarray(D.select(neurons, "%s+side:%s" % (зонд.sel, сторона)),
                         dtype=np.int64)
        из[сторона] = neurons.root_id.to_numpy()[idx]
    return из


def главное(карта, ids):
    """Сводка BANC по набору `root_id`: пары, синапсы, сильнейшая пара."""
    d = карта[карта.fafb_v783_id.isin([str(i) for i in ids])]
    if d.empty:
        return {"пар": 0, "синапсов": 0, "сильнейшая": 0, "порог, Гц": None,
                "подтверждено вручную": 0}
    силь = pd.to_numeric(d.banc_syn_to_motor_strongest_pair,
                         errors="coerce").fillna(0)
    всего = pd.to_numeric(d.banc_syn_to_motor_total,
                          errors="coerce").fillna(0)
    порог = pd.to_numeric(d.hz_needed_strongest, errors="coerce")
    return {"пар": int(len(d)), "синапсов": int(всего.sum()),
            "сильнейшая": int(силь.max()),
            "порог, Гц": (None if порог.dropna().empty
                          else round(float(порог.min()), 1)),
            "подтверждено вручную": int(d.manually_checked.astype(bool).sum())}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--писать", action="store_true",
                    help="записать файл адресации в assets/")
    args = ap.parse_args()

    сырое = КАРТА.read_bytes()
    карта = pd.read_parquet(КАРТА)
    карта["fafb_v783_id"] = карта.fafb_v783_id.astype(str)
    neurons = D.load_neurons()
    # Зонды проверяются теми же отпечатками, что и в модели: выборка
    # того же размера из других нейронов проверку по числу проходит.
    motor.verify_probes(neurons, strict=True)

    # Опора популяции: по ней видно, что 91 синапс — это много.
    нисх = карта[карта.banc_super_class.astype(str) == "descending"]
    силь_все = pd.to_numeric(нисх.banc_syn_to_motor_strongest_pair,
                             errors="coerce").dropna()
    print("нисходящих в отображении: %d, сильнейшая пара — медиана %.0f, "
          "90%% %.0f, 95%% %.0f"
          % (len(нисх), силь_все.median(),
             силь_все.quantile(0.90), силь_все.quantile(0.95)), flush=True)

    свод = {}
    print("\n%-7s %-6s %4s %8s %10s %9s %8s"
          % ("зонд", "сторона", "пар", "синапсов", "сильнейшая",
             "порог Гц", "вручную"))
    for имя, зонд in motor.DN_PROBES.items():
        свод[имя] = {}
        for сторона, ids in стороны(neurons, зонд).items():
            s = главное(карта, ids)
            свод[имя][сторона] = s
            print("%-7s %-6s %4d %8d %10d %9s %8d"
                  % (имя, сторона, s["пар"], s["синапсов"], s["сильнейшая"],
                     "—" if s["порог, Гц"] is None else "%.1f" % s["порог, Гц"],
                     s["подтверждено вручную"]))

    # Вес поворота: сила премоторного выхода относительно опорного
    # зонда. Берётся НАИБОЛЬШАЯ из двух сторон — вес в декодере один на
    # зонд, а стороны входят в него разностью частот.
    def сила(имя):
        return max(свод[имя]["left"]["сильнейшая"],
                   свод[имя]["right"]["сильнейшая"])

    опора = сила(ОПОРНЫЙ)
    if not опора:
        raise SystemExit("у опорного зонда %s нет моторного выхода в BANC "
                         "— дальше считать нечего" % ОПОРНЫЙ)
    поворот = {имя: 0.0 for имя in motor.DN_PROBES}
    for имя in РУЛЕВЫЕ:
        поворот[имя] = round(сила(имя) / опора, 3)

    print("\nвес поворота: объявленный -> по BANC")
    for имя in motor.DN_PROBES:
        было = motor.TURN_WEIGHTS_V1.get(имя, 0.0)
        знак = "" if abs(поворот[имя] - было) < 1e-9 else "  <-- меняется"
        print("  %-7s %5.2f -> %5.3f%s" % (имя, было, поворот[имя], знак))

    происхождение = (
        "Сила премоторного выхода по BANC v888. Вес поворота зонда = "
        "его сильнейшая пара «нисходящий -> мотонейрон» (наибольшая из "
        "двух сторон), делённая на ту же величину у %s: %s. Источник — "
        "assets/banc_fafb_v888_v783_map.parquet, sha256 %s, "
        "1409 пар соответствия FAFB v783 <-> BANC v888 (BANC_MOTOR.md). "
        "Зонды адресованы root_id через те же селекторы и отпечатки, что "
        "в модели (решение владельца 3: DNa01/DNa04/DNa05 по одному "
        "имени не выбирать). DNp01 исключён решением владельца 1: мост "
        "Giant Fiber выключен, его моторный выход в BANC ниже медианы "
        "популяции. ЗНАКИ И РОЛИ взяты из объявленной версии "
        "TURN_WEIGHTS_V1 / DRIVE_WEIGHTS_V1 и по BANC НЕ выводятся: "
        "латеральности мишеней в таблице соответствий нет, поэтому "
        "куда поворачивает рост зонда и почему MDN — задний ход, "
        "отсюда не следует. Вес тяги не трогался вовсе. Это инженерный "
        "интерфейс, обоснованный анатомией, а не восстановленная "
        "связность."
        % (ОПОРНЫЙ,
           ", ".join("%s %d" % (и, сила(и)) for и in РУЛЕВЫЕ),
           hashlib.sha256(сырое).hexdigest()[:16]))

    файл = {
        "версия": 1,
        "имя": "banc-v888",
        "вес поворота": поворот,
        "вес тяги": dict(motor.DRIVE_WEIGHTS_V1),
        "происхождение": происхождение,
        "вывод": {имя: {с: свод[имя][с] for с in ("left", "right")}
                  for имя in motor.DN_PROBES},
        "опора популяции": {
            "нисходящих в отображении": int(len(нисх)),
            "сильнейшая пара, медиана": float(силь_все.median()),
            "сильнейшая пара, 95%": float(силь_все.quantile(0.95))},
    }
    if args.писать:
        ЦЕЛЬ.write_text(json.dumps(файл, ensure_ascii=False, indent=1),
                        encoding="utf-8")
        # Читаем своим же загрузчиком: он и есть приёмка формата.
        прочитано = motor.load_weight_map(ЦЕЛЬ)
        print("\nзаписано %s" % ЦЕЛЬ.name)
        print("  sha256 %s" % прочитано["sha256"][:16])
        print("  загрузчик принял, вес поворота: %s"
              % прочитано["вес поворота"])
    else:
        print("\n(файл не записан, нужен --писать)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
