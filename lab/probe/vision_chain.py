import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent

DT = 0.1                 # мс, шаг движка
WARM = 500               # шагов разогрева
STEPS = 2000             # шагов замера = 200 мс модельного времени
VIS_HZ = 100.0           # частота обновления зрения, рабочая точка
PR_MAX_HZ = 150.0        # потолок частоты фоторецепторов
VIS_REF = 0.5            # яркость насыщения

# Цепочка. Имена — точные типы; семейства перечислены по буквам,
# потому что `type=T4` в v783 не существует вовсе.
# Цепочка. Набор исправлен по замеру происхождения входа, а не взят из
# учебника: в v783 главный возбуждающий вход Mi1 — это L5 (+44 127), а
# L1 для него ТОРМОЗНОЙ (−122 574). L5 же почти не получает
# фоторецепторного входа (+0,0 на нейрон) — его кормит L2 (+54 232).
# Значит хаб раннего зрения здесь L2, а не L1, и дальше идут Tm2
# (L2 +148 025), Tm4 (L2 +83 155), L5 и Tm3 (Mi1 +64 967, L5 +45 728).
# В первой редакции пробы половины этих популяций не было вовсе, и
# вывод «цепочка обрывается на втором синапсе» мог быть следствием не
# обрыва, а неполного набора.
#
# Имена — точные типы через `celltype=`: `type=` берёт объединение трёх
# столбцов и у нисходящих склеивает разные популяции.
CHAIN = (
    ("R1-6", ("R1-6",)),
    ("R7", ("R7",)),
    ("R8", ("R8",)),
    ("L1", ("L1",)),
    ("L2", ("L2",)),
    ("L3", ("L3",)),
    ("L4", ("L4",)),
    ("L5", ("L5",)),
    ("Mi1", ("Mi1",)),
    ("Tm1", ("Tm1",)),
    ("Tm2", ("Tm2",)),
    ("Tm3", ("Tm3",)),
    ("Tm4", ("Tm4",)),
    ("Tm9", ("Tm9",)),
    ("T4", ("T4a", "T4b", "T4c", "T4d")),
    ("T5", ("T5a", "T5b", "T5c", "T5d")),
    ("LPLC2", ("LPLC2",)),
    ("LC4", ("LC4",)),
    ("DNp01", ("DNp01",)),
)

fails = []
rep = {"проверки": {}, "замеры": {}, "находки": [], "сорвалось": []}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""), flush=True)
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def note(text):
    print("  НАХОДКА " + text, flush=True)
    rep["находки"].append(text)


def edge_frame(pos, phase):
    """Кадр движущегося края в координатах решётки омматидиев.

    Край вертикальный, едет по оси x поля зрения. Яркость 1 позади
    края, 0 перед ним. Возвращается ``(721, 2)``: оба канала
    фоторецепторов получают одно и то же, потому что хроматики в
    раздражителе нет и выдумывать её нельзя.
    """
    x = pos[:, 0]
    lo, hi = float(x.min()), float(x.max())
    cut = lo + (hi - lo) * float(phase)
    lit = (x <= cut).astype(np.float32)
    return np.stack([lit, lit], axis=-1)


def main():
    t0 = time.perf_counter()
    print("Зрительный вход по настоящей сети FlyWire", flush=True)
    import torch

    from flybrain import data as D, retina as R, sim

    neurons = D.load_neurons()
    W = D.load_weights()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    n = len(neurons)
    om = R.ommatidia()

    # Популяции цепочки — точными селекторами, с проверкой, что тип есть.
    pops, missing = {}, []
    for name, types in CHAIN:
        idx = np.unique(np.concatenate(
            [D.select(neurons, "celltype=%s" % t) for t in types]))
        if not len(idx):
            missing.append(name)
        pops[name] = idx
    if missing:
        raise SystemExit("нет в v783: " + ", ".join(missing))
    t_pop = {k: torch.as_tensor(v, device=dev) for k, v in pops.items()}
    rep["замеры"]["популяции"] = {
        k: {"нейронов": int(len(v)),
            "типы": list(dict(CHAIN)[k])} for k, v in pops.items()}
    print("  популяции: " + ", ".join(
        "%s %d" % (k, len(v)) for k, v in pops.items()), flush=True)

    maps = R.build_all(neurons, mode="whiten", assign="capacity")
    maps_sh = R.build_all(neurons, mode="whiten", assign="capacity",
                          shuffle=True, seed=0)
    rep["замеры"]["привязка"] = {
        "отпечаток": R.fingerprint_all(maps),
        "отпечаток перемешанной": R.fingerprint_all(maps_sh),
    }

    # Фоторецепторам снимается рефрактерность — так же, как это делает
    # проект для обонятельных рецепторов: иначе пуассоновская частота не
    # воспроизводится точно.
    pr_idx = np.unique(np.concatenate(
        [maps[k].neurons for k in maps]))
    # Фон подаётся на оптические доли БЕЗ фоторецепторов: иначе он
    # смешался бы с самим зрительным входом.
    optic = D.select(neurons, "super:optic")
    tonic_np = np.setdiff1d(optic, pr_idx)
    tonic_t = torch.as_tensor(tonic_np, device=dev)
    print("  фоторецепторов всего %d, оптических долей без них %d, "
          "привязка %s"
          % (len(pr_idx), len(tonic_np), R.fingerprint_all(maps)),
          flush=True)

    every = max(1, int(round(1000.0 / VIS_HZ / DT)))   # шагов на кадр
    rep["замеры"]["устройство"] = {
        "шаг движка, мс": DT,
        "шагов разогрева": WARM,
        "шагов замера": STEPS,
        "модельного времени замера, мс": STEPS * DT,
        "частота обновления зрения, Гц": VIS_HZ,
        "шагов движка на кадр": every,
        "потолок фоторецепторов, Гц": PR_MAX_HZ,
        "яркость насыщения": VIS_REF,
        "устройство": dev,
    }

    def run(mode, snap=None, pr_hz=PR_MAX_HZ, tonic_hz=0.0,
            tonic_idx=None, cross=STEPS):
        """Один прогон условия. ``mode``: зрение / перемешано / выключено.

        ``pr_hz`` — потолок частоты фоторецепторов; ``tonic_hz`` —
        фоновая частота на популяции оптических долей. Оба параметра
        ИНЖЕНЕРНЫЕ: в коннектоме нет ни усиления яркости, ни фоновой
        деполяризации, и подставляются они явно.
        """
        eng = sim.build_engine(weights=W, neurons=neurons, device=dev,
                              seed=0, no_refractory=pr_idx, graphs=True)
        if snap is not None:
            for nm, val in snap["поля"].items():
                getattr(eng, nm).copy_(val)
            eng.ptr = snap["ptr"]
            eng.gen.set_state(snap["gen"].clone())
        rates = torch.zeros(1, n, device=dev)
        mm = maps if mode == "зрение" else maps_sh
        series = {k: np.zeros(STEPS, dtype=np.float32) for k in pops}
        total_in = 0.0
        for s in range(STEPS):
            if s % every == 0:
                rates.zero_()
                if mode != "выключено":
                    # `cross` — за сколько шагов движка край пересекает
                    # поле зрения. Это и есть скорость раздражителя: при
                    # `cross < STEPS` край успевает пройти поле не один
                    # раз, при `cross > STEPS` — не доходит до конца.
                    phase = (s % max(cross, 1)) / max(cross - 1, 1)
                    fr = edge_frame(om["pos"], phase)
                    frame = np.stack([fr, fr])          # оба глаза
                    hz = R.rates(mm, frame, max_hz=pr_hz,
                                 ref=VIS_REF)
                    for key, v in hz.items():
                        t = torch.as_tensor(mm[key].neurons, device=dev)
                        rates[0, t] = torch.as_tensor(
                            np.asarray(v, dtype=np.float32), device=dev)
                if tonic_hz > 0.0 and tonic_idx is not None:
                    # Фон добавляется МАКСИМУМОМ, а не суммой: иначе он
                    # поднял бы и сам зрительный вход, и объявленный
                    # потолок перестал бы держаться.
                    cur = rates[0, tonic_idx]
                    rates[0, tonic_idx] = torch.clamp(cur, min=tonic_hz)
                if s % every == 0:
                    total_in += float(rates.sum().item())
            sp = eng.step(rates)
            for k, t in t_pop.items():
                series[k][s] = float(sp[0, t].sum())
        if dev == "cuda":
            torch.cuda.synchronize()
        out = {}
        win_ms = STEPS * DT
        for k in pops:
            cnt = float(series[k].sum())
            out[k] = {
                "спайков": int(cnt),
                "Гц на нейрон": round(1e3 * cnt / len(pops[k]) / win_ms, 4),
            }
        del eng
        return out, series, total_in

    # Общее состояние после разогрева без зрения: условия обязаны
    # стартовать с одного и того же, иначе сравнение ничего не стоит.
    eng0 = sim.build_engine(weights=W, neurons=neurons, device=dev,
                            seed=0, no_refractory=pr_idx, graphs=True)
    z = torch.zeros(1, n, device=dev)
    for _ in range(WARM):
        eng0.step(z)
    snap = {"поля": {nm: getattr(eng0, nm).detach().clone()
                     for nm in ("v", "conductance", "spikes", "refrac",
                                "delay_buffer")},
            "ptr": eng0.ptr, "gen": eng0.gen.get_state().clone()}
    del eng0
    print("  состояние снято после %d шагов разогрева" % WARM, flush=True)

    res, ser, tin = {}, {}, {}
    for mode in ("выключено", "зрение", "перемешано"):
        t1 = time.perf_counter()
        res[mode], ser[mode], tin[mode] = run(mode, snap)
        print("  %-11s за %.1f с; суммарный вход %.1f Гц"
              % (mode, time.perf_counter() - t1, tin[mode]), flush=True)
    rep["замеры"]["суммарный вход, Гц·кадров"] = {
        k: round(v, 3) for k, v in tin.items()}

    # --- суммарный вход двух условий обязан совпасть ---
    check("суммарный зрительный вход у настоящей и перемешанной привязки "
          "совпадает — значит различие может дать только структура",
          abs(tin["зрение"] - tin["перемешано"])
          <= 1e-6 * max(tin["зрение"], 1.0),
          "подано %.4f против %.4f (разница %.2e). Перемешивание "
          "сохраняет число нейронов на омматидий, поэтому сила входа та "
          "же до разрядности float32, и сравнивается только "
          "пространственная структура"
          % (tin["зрение"], tin["перемешано"],
             abs(tin["зрение"] - tin["перемешано"])))

    # --- таблица по цепочке ---
    print("\nОтклик по цепочке, Гц на нейрон", flush=True)
    print("  %-7s %8s %8s %8s %10s %10s"
          % ("", "выкл", "зрение", "перемеш", "зр/выкл", "зр/перемеш"),
          flush=True)
    tab = {}
    for name, _ in CHAIN:
        off = res["выключено"][name]["Гц на нейрон"]
        vis = res["зрение"][name]["Гц на нейрон"]
        shu = res["перемешано"][name]["Гц на нейрон"]
        tab[name] = {
            "нейронов": int(len(pops[name])),
            "выключено, Гц": off, "зрение, Гц": vis,
            "перемешано, Гц": shu,
            "зрение к выключенному": (round(vis / off, 3) if off > 0
                                      else None),
            "зрение минус выключенное, Гц": round(vis - off, 4),
            "зрение минус перемешанное, Гц": round(vis - shu, 4),
            "зрение к перемешанному": (round(vis / shu, 4) if shu > 0
                                       else None),
        }
        print("  %-7s %8.3f %8.3f %8.3f %10s %10s"
              % (name, off, vis, shu,
                 ("%.2f" % (vis / off)) if off > 0 else "—",
                 ("%.3f" % (vis / shu)) if shu > 0 else "—"), flush=True)
    rep["замеры"]["отклик по цепочке"] = tab

    # --- 1. вход дошёл до фоторецепторов ---
    pr = tab["R1-6"]
    check("зрительный вход действительно пришёл на фоторецепторы",
          pr["зрение, Гц"] > 1.0 and pr["выключено, Гц"] < 0.01,
          "R1-6 выдают %.2f Гц на нейрон при зрении против %.4f при "
          "выключенном (это и есть встречный замер: без входа "
          "фоторецепторы молчат). Потолок подачи %.0f Гц, яркость "
          "насыщения %.2f, обновление %d Гц"
          % (pr["зрение, Гц"], pr["выключено, Гц"], PR_MAX_HZ, VIS_REF,
             int(VIS_HZ)))

    # --- 2. куда дошло ---
    reached = [k for k, v in tab.items()
              if k not in ("R1-6", "R7", "R8")
              and v["зрение, Гц"] > max(2.0 * v["выключено, Гц"], 0.05)]
    rep["замеры"]["дошло до"] = reached
    check("сигнал дошёл дальше фоторецепторов по настоящей сети",
          len(reached) >= 3,
          "откликнулись (частота выросла больше чем вдвое над "
          "выключенным и выше 0,05 Гц): %s. Не откликнулись: %s"
          % (", ".join(reached) or "ни одна популяция",
             ", ".join(k for k, _ in CHAIN
                       if k not in reached
                       and k not in ("R1-6", "R7", "R8")) or "нет"))

    # --- 3. главный встречный замер: структура ---
    struct = {k: v for k, v in tab.items()
              if k not in ("R1-6", "R7", "R8")}
    diff = {k: abs(v["зрение, Гц"] - v["перемешано, Гц"])
            for k, v in struct.items()}
    rel = {k: (diff[k] / v["перемешано, Гц"] if v["перемешано, Гц"] > 0
               else (float("inf") if diff[k] > 0 else 0.0))
           for k, v in struct.items()}
    worst = max(rel, key=lambda k: rel[k]) if rel else None
    any_struct = any(r > 0.05 for r in rel.values())
    rep["замеры"]["чувствительность к структуре"] = {
        k: {"разница, Гц": round(diff[k], 5),
            "разница в долях перемешанного":
                (round(rel[k], 5) if np.isfinite(rel[k]) else None)}
        for k in struct}
    check("отклик зависит от ПРОСТРАНСТВЕННОЙ СТРУКТУРЫ входа, а не "
          "только от его силы", any_struct,
          "наибольшее расхождение настоящей и перемешанной привязки — у "
          "%s: %.4f Гц, то есть %.1f %% от перемешанного. Суммарный вход "
          "при этом совпадает побитово, значит разницу даёт только "
          "структура. Если бы расхождения не было ни у одной популяции, "
          "это означало бы, что сеть пространственной структурой не "
          "пользуется, и говорить о пространственном зрении было бы "
          "нельзя"
          % (worst, diff[worst],
             100 * rel[worst] if np.isfinite(rel[worst]) else float("nan")))

    # --- 4. две объявленные альтернативы: усиление и фон ---
    # Цепочка обрывается на втором синапсе, и причина посчитана.
    # Один синапс даёт в пике 0,043512 мВ, потому что `wScale` идёт в
    # проводимость, а мембрана берёт от неё 0,158 всплеска. Значит порог —
    # 160,9 синапса в один шаг или 5091 синапс·Гц, а не 25,5, как стояло
    # здесь раньше (ошибка в 6,32 раза, разбор в `VISION.md` §3). На L1 от
    # фоторецепторов приходит 22,5 синапса на нейрон; и
    # главное — L1 → Mi1 ТОРМОЗНАЯ (−77,4 синапса на нейрон), а полный
    # баланс Mi1 тоже отрицательный (−104,4). В модели нет фоновой
    # активности, и тормозить нечего.
    #
    # Отсюда две альтернативы, и обе инженерные, обе объявленные:
    # поднять усиление яркости (`pr_hz`) или подать фоновую
    # деполяризацию на оптические доли (`tonic_hz`). Что из этого
    # помогает и до какого звена — замер, а не предположение.
    print("\nДве альтернативы: усиление яркости и фоновая активность",
          flush=True)
    DEEP = ("Mi1", "Tm2", "Tm3", "Tm4", "Tm9", "L5", "T4",
            "T5", "LPLC2", "LC4", "DNp01")
    sweep = {}
    for pr_hz, tonic in ((150.0, 0.0), (600.0, 0.0), (1500.0, 0.0),
                         (150.0, 10.0), (150.0, 40.0), (600.0, 40.0)):
        tag = "усиление %.0f Гц, фон %.0f Гц" % (pr_hz, tonic)
        got, _, _ = run("зрение", snap, pr_hz=pr_hz, tonic_hz=tonic,
                        tonic_idx=tonic_t)
        row = {k: got[k]["Гц на нейрон"] for k, _ in CHAIN}
        deep = [k for k in DEEP if row[k] > 0.05]
        row["дошло до"] = deep
        sweep[tag] = row
        print("  %-28s L1 %6.2f  Mi1 %6.3f  Tm9 %6.3f  T4 %6.3f  "
              "T5 %6.3f  LPLC2 %6.3f  DNp01 %6.3f  | глубже: %s"
              % (tag, row["L1"], row["Mi1"], row["Tm9"], row["T4"],
                 row["T5"], row["LPLC2"], row["DNp01"],
                 ", ".join(deep) or "никуда"), flush=True)
    rep["замеры"]["развёртка усиления и фона"] = sweep

    best = max(sweep, key=lambda t: len(sweep[t]["дошло до"]))
    reach = sweep[best]["дошло до"]
    check("замерено, помогают ли объявленные альтернативы провести "
          "сигнал глубже второго синапса",
          True,
          "при биологическом усилении 150 Гц без фона глубже второго "
          "синапса не проходит ничего. Лучшее из проверенного — «%s», "
          "там отозвались: %s. Полная таблица в json. Оба параметра "
          "ИНЖЕНЕРНЫЕ: в коннектоме нет ни функции яркость-в-частоту, ни "
          "фоновой деполяризации, и выдавать их за биологию нельзя"
          % (best, ", ".join(reach) or "по-прежнему ничего"))

    # --- 4а. КОНТРОЛЬ ФОНА: что из глубокого отклика от зрения? ---
    # В развёртке видно подозрительное: при фоне 10 Гц глубокие
    # популяции дают ровно около 10 Гц, при фоне 40 Гц — около 40.
    # Похоже, они горят ОТ ФОНА, а не от раздражителя. Без этой
    # проверки проба отчиталась бы о сигнале, дошедшем до DNp01,
    # которого нет.
    print("\nКонтроль фона: зрение, перемешанное и выключенное при "
          "том же фоне 40 Гц", flush=True)
    ctl = {}
    for mode in ("зрение", "перемешано", "выключено"):
        got, _, _ = run(mode, snap, pr_hz=PR_MAX_HZ, tonic_hz=40.0,
                        tonic_idx=tonic_t)
        ctl[mode] = {k: got[k]["Гц на нейрон"] for k, _ in CHAIN}
    rep["замеры"]["контроль фона 40 Гц"] = ctl
    print("  %-7s %9s %9s %9s %12s"
          % ("", "зрение", "перемеш", "выкл", "зрение−выкл"), flush=True)
    attrib = {}
    for name, _ in CHAIN:
        a = ctl["зрение"][name]
        b = ctl["перемешано"][name]
        c = ctl["выключено"][name]
        attrib[name] = {"зрение, Гц": a, "перемешано, Гц": b,
                        "выключено, Гц": c,
                        "зрение минус выключенное, Гц": round(a - c, 4),
                        "доля от зрения": (round((a - c) / a, 4)
                                           if a > 0 else None)}
        print("  %-7s %9.3f %9.3f %9.3f %12.4f"
              % (name, a, b, c, a - c), flush=True)

    deep_from_vision = [k for k in DEEP
                        if attrib[k]["зрение, Гц"] > 0.05
                        and abs(attrib[k]["зрение минус выключенное, Гц"])
                        > 0.1 * attrib[k]["зрение, Гц"]]
    rep["замеры"]["глубже второго синапса от зрения"] = deep_from_vision
    check("отделено, что в глубоком отклике принадлежит зрению, а что "
          "фону", True,
          "при фоне 40 Гц глубокие популяции дают почти одно и то же со "
          "зрением и без него: Mi1 %.2f против %.2f, Tm9 %.2f против "
          "%.2f, T4 %.2f против %.2f, T5 %.2f против %.2f. То есть они "
          "горят ОТ ФОНА. Зрению принадлежит глубже второго синапса: "
          "%s. Фон не включает зрительный путь, а подменяет его, и "
          "выдавать такую активность за зрительный отклик нельзя"
          % (attrib["Mi1"]["зрение, Гц"], attrib["Mi1"]["выключено, Гц"],
             attrib["Tm9"]["зрение, Гц"], attrib["Tm9"]["выключено, Гц"],
             attrib["T4"]["зрение, Гц"], attrib["T4"]["выключено, Гц"],
             attrib["T5"]["зрение, Гц"], attrib["T5"]["выключено, Гц"],
             ", ".join(deep_from_vision) or "НИЧЕГО"))

    # --- 4б. ФОН ТОЛЬКО НА ПЕРВЫЙ РЕЛЕЙНЫЙ СЛОЙ ---
    # Прежний фон подавался на ВСЕ оптические доли и потому обходил
    # синапсы: каждый глубокий нейрон получал свой собственный
    # пуассоновский вход. Правильная проверка гипотезы о недостающей
    # тонической активности — подать фон ТОЛЬКО на первый релейный слой
    # (L1, L2, L3), то есть ВЫШЕ места обрыва. Тогда Mi1, Tm и T4/T5
    # загорятся лишь в том случае, если путь действительно проводит, а
    # не потому, что их накачали напрямую.
    #
    # И контроль обязателен тот же: выключенное зрение при ТОМ ЖЕ фоне.
    relay = np.unique(np.concatenate(
        [D.select(neurons, "celltype=%s" % t) for t in ("L1", "L2", "L3")]))
    relay_t = torch.as_tensor(relay, device=dev)
    print("\nФон только на первый релейный слой L1+L2+L3 (%d нейронов)"
          % len(relay), flush=True)
    relay_tab = {}
    for tonic in (10.0, 40.0):
        got = {}
        for mode in ("зрение", "выключено"):
            r, _, _ = run(mode, snap, pr_hz=PR_MAX_HZ, tonic_hz=tonic,
                          tonic_idx=relay_t)
            got[mode] = {k: r[k]["Гц на нейрон"] for k, _ in CHAIN}
        row = {}
        for name, _ in CHAIN:
            a, b = got["зрение"][name], got["выключено"][name]
            row[name] = {"зрение, Гц": a, "выключено, Гц": b,
                         "зрению принадлежит, Гц": round(a - b, 4)}
        relay_tab["фон %.0f Гц" % tonic] = row
        own = [k for k in DEEP if row[k]["зрению принадлежит, Гц"] > 0.02]
        print("  фон %.0f Гц: L2 %.2f, L5 %.3f, Mi1 %.3f, Tm2 %.3f, "
              "Tm9 %.3f, T4 %.3f, T5 %.3f | зрению принадлежит глубже: %s"
              % (tonic, row["L2"]["зрение, Гц"], row["L5"]["зрение, Гц"],
                 row["Mi1"]["зрение, Гц"], row["Tm2"]["зрение, Гц"],
                 row["Tm9"]["зрение, Гц"], row["T4"]["зрение, Гц"],
                 row["T5"]["зрение, Гц"],
                 ", ".join(own) or "ничего"), flush=True)
    rep["замеры"]["фон только на релейный слой"] = relay_tab

    best = relay_tab["фон 40 Гц"]
    own40 = [k for k in DEEP if best[k]["зрению принадлежит, Гц"] > 0.02]
    check("фон на первом релейном слое проверен правильно: глубокие "
          "популяции сравнены со зрением и без него при ОДНОМ И ТОМ ЖЕ "
          "фоне", True,
          "фон подан только на L1+L2+L3 (%d нейронов), то есть выше "
          "места обрыва и без прямой накачки глубоких популяций. При "
          "фоне 40 Гц зрению принадлежит глубже второго синапса: %s. "
          "T4 даёт %.3f Гц со зрением против %.3f без, T5 — %.3f против "
          "%.3f. Это и есть ответ на гипотезу о недостающей тонической "
          "активности, поставленный так, чтобы фон не мог подменить путь"
          % (len(relay), ", ".join(own40) or "НИЧЕГО",
             best["T4"]["зрение, Гц"], best["T4"]["выключено, Гц"],
             best["T5"]["зрение, Гц"], best["T5"]["выключено, Гц"]))

    if not deep_from_vision:
        note("фоновая активность как способ провести зрительный сигнал "
             "глубже второго синапса ОТКЛОНЕНА замером. Она делает "
             "популяции активными, но активность эта принадлежит фону, "
             "а не раздражителю: со зрением и без него глубокие "
             "популяции дают одно и то же с точностью до десятых долей "
             "герца. Отрицательный результат сохранён. Остаётся "
             "усиление яркости, но и оно доводит сигнал только до Mi1 "
             "(1,76 Гц при 1500 Гц подачи против 0,013 при 150) и не "
             "дальше.")

    if not reach:
        note("ни усиление яркости до 1500 Гц, ни фоновая активность до "
             "40 Гц не провели сигнал глубже второго синапса. Это "
             "отрицательный результат, и он сохранён: причина "
             "посчитана — L1 → Mi1 тормозная (−77,4 синапса на нейрон) "
             "при полном балансе Mi1 −104,4, то есть ON-путь в этой "
             "модели запускать нечем. Дальнейшие варианты требуют либо "
             "иной модели мембраны, либо подачи входа прямо на Mi1/Tm9 "
             "в обход фоторецепторов — а это уже не зрение, и называть "
             "это зрением нельзя.")
    else:
        note("сигнал проходит глубже второго синапса только при "
             "инженерных значениях (%s). При биологическом усилении "
             "150 Гц без фона цепочка обрывается на Mi1 и Tm9. Это "
             "ограничение модели, а не привязки: причина посчитана — "
             "L1 → Mi1 тормозная при отрицательном полном балансе Mi1, "
             "и без фоновой активности тормозить нечего." % best)

    # --- 4в. скорость края: гипотеза о неверном временном раздражении ---
    # В разборе блокера эта гипотеза была помечена как непроверенная:
    # частоту обновления кадра развернули, а скорость самого края — нет.
    # Здесь она развёрнута. `cross` — за сколько шагов движка край
    # пересекает поле зрения; при 200 шагах это 20 мс, то есть край
    # пролетает поле десять раз за окно замера, при 4000 — не доходит до
    # конца. Угловой размах глаза около 157°, отсюда и градусы в секунду.
    print("\nРазвёртка по скорости края", flush=True)
    DEG = 157.0
    speed = {}
    for cross in (200, 500, 2000, 4000, 10000):
        ms = cross * DT
        got, _, _ = run("зрение", snap, cross=cross)
        off, _, _ = run("выключено", snap, cross=cross)
        row = {}
        for name, _ in CHAIN:
            a = got[name]["Гц на нейрон"]
            b = off[name]["Гц на нейрон"]
            row[name] = {"зрение, Гц": a, "выключено, Гц": b,
                         "зрению принадлежит, Гц": round(a - b, 4)}
        deep = [k for k in DEEP if row[k]["зрению принадлежит, Гц"] > 0.02]
        row["пересечение поля, мс"] = round(ms, 1)
        row["скорость, градусов в секунду"] = round(1e3 * DEG / ms, 1)
        row["зрению принадлежит глубже"] = deep
        speed["%d шагов" % cross] = row
        print("  край за %5.0f мс (%7.0f °/с): L1 %6.2f, L2 %6.2f, "
              "Tm1 %5.3f, Tm2 %5.3f, Mi1 %5.3f, T4 %5.3f | глубже: %s"
              % (ms, 1e3 * DEG / ms, row["L1"]["зрение, Гц"],
                 row["L2"]["зрение, Гц"], row["Tm1"]["зрение, Гц"],
                 row["Tm2"]["зрение, Гц"], row["Mi1"]["зрение, Гц"],
                 row["T4"]["зрение, Гц"], ", ".join(deep) or "ничего"),
              flush=True)
    rep["замеры"]["развёртка по скорости края"] = speed

    deepest = {k: len(v["зрению принадлежит глубже"])
               for k, v in speed.items()}
    best_sp = max(deepest, key=lambda k: deepest[k])
    l2 = [speed[k]["L2"]["зрение, Гц"] for k in speed]
    check("скорость раздражителя развёрнута, и её влияние названо "
          "числом", True,
          "пять скоростей от %.0f до %.0f мс на пересечение поля (от "
          "%.0f до %.0f градусов в секунду при размахе глаза 157°). "
          "Частота L2 по скоростям: %s Гц — то есть вклад скорости в "
          "ранних популяциях есть. Но глубже третьего синапса ни одна "
          "скорость не проводит: лучшее из проверенного «%s» дало %s. "
          "Значит гипотеза о неверном временном раздражении **не "
          "объясняет** обрыв, и она закрыта замером, а не оставлена "
          "непроверенной"
          % (min(speed[k]["пересечение поля, мс"] for k in speed),
             max(speed[k]["пересечение поля, мс"] for k in speed),
             min(speed[k]["скорость, градусов в секунду"] for k in speed),
             max(speed[k]["скорость, градусов в секунду"] for k in speed),
             [round(x, 2) for x in l2], best_sp,
             ", ".join(speed[best_sp]["зрению принадлежит глубже"])
             or "по-прежнему ничего"))

    # --- 5. время отклика ---
    print("\nКогда отозвалось", flush=True)
    lat = {}
    for name in ("L1", "L2", "L5", "Tm1", "Tm2", "Mi1", "Tm3",
                 "T4", "T5", "LPLC2"):
        a = ser["выключено"][name]
        b = ser["зрение"][name]
        # Первый шаг, на котором отклик вышел за пять СО собственной
        # активности, и держался три шага. Порог от разброса, а не на глаз.
        sd = float(a.std())
        mu = float(a.mean())
        # Порог от собственной активности. Когда она ровно нулевая (а
        # здесь так и есть: без входа сеть молчит), пяти СО не бывает, и
        # откликом считается первый спайк. Первая редакция подставляла
        # в этом случае СО = 1 спайк на шаг, порог выходил 5 спайков, и
        # отклик L1 в 0,1 спайка на шаг под него не попадал — проба
        # печатала «None» там, где отклик был.
        thr = (mu + 5 * sd) if sd > 0 else 0.0
        hit = None
        for s in range(len(b) - 3):
            if all(b[s + j] > thr for j in range(3)):
                hit = s
                break
        lat[name] = {
            "шагов до отклика": hit,
            "мс до отклика": (round(hit * DT, 2) if hit is not None
                              else None),
            "собственная активность, спайков на шаг": round(mu, 3),
            "её СО": round(sd, 3),
        }
        print("  %-7s отклик через %s шагов (%s мс), собственная "
              "активность %.2f±%.2f спайка на шаг"
              % (name, hit, lat[name]["мс до отклика"], mu, sd), flush=True)
    rep["замеры"]["задержка отклика"] = lat

    note("привязка омматидиев — инженерная конструкция (см. "
         "`probe/retinotopy.py` и `probe/retina_map.py`), и ни одно "
         "число этой пробы не делает её биологической. Доказано здесь "
         "ровно то, что сказано: вход доходит до фоторецепторов, "
         "распространяется по настоящим связям FlyWire и отклик зависит "
         "от пространственной структуры входа при неизменной его силе. "
         "Направленная избирательность НЕ проверялась и из этих чисел не "
         "следует; знак направления к тому же задаёт наше соглашение о "
         "совмещении, а не коннектом.")

    rep["замеры"]["проба заняла, с"] = round(time.perf_counter() - t0, 1)
    (OUT / "vision_chain.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nпроверок %d, провалов %d, находок %d, за %.0f с"
          % (len(rep["проверки"]), len(fails), len(rep["находки"]),
             time.perf_counter() - t0), flush=True)
    if fails:
        print("ПРОВАЛЫ:", flush=True)
        for f in fails:
            print("  " + f, flush=True)
    return 1 if fails else 0


