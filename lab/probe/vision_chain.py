"""Доходит ли зрительный вход по настоящей сети FlyWire и куда именно.

Главный вопрос этапа, и он решается до всякой доводки привязки: **даёт
ли сеть структурный отклик на зрительный вход вообще?** Если оптические
доли не отвечают, точность привязки омматидиев не имеет значения.

Три условия на одном и том же состоянии движка:

* **зрение** — настоящая привязка (`retina.build_all`), движущийся край
  в поле зрения;
* **перемешано** — та же привязка, перемешанная с сохранением числа
  нейронов на омматидий. **Суммарный вход совпадает до последнего
  разряда**, разрушена только пространственная структура. Это главный
  встречный замер: если отклик не отличается, сеть структурой не
  пользуется, и говорить о пространственном зрении нельзя;
* **выключено** — нулевой вход. Нужен, чтобы отличить отклик от
  собственной активности сети.

Что замеряется: частота по каждой популяции цепочки — фоторецепторы,
L1, L2, L3, Mi1, Tm1, Tm9, T4a-d, T5a-d, LPLC2, LC4, DNp01 — и по
шагам, чтобы видеть не только «отозвалось», но и когда.

**Все выборки точным селектором `type=X`.** Свободный `type:X` значит
«cell_type или hemibrain_type СОДЕРЖИТ X» и даёт, например, 6400
нейронов на `type:T4`, среди которых ни одного T4; настоящие типы —
`T4a`…`T4d`. На этом уже ошиблись трое, считая меня.

Раздражитель — движущийся край, посчитанный прямо по положениям
омматидиев: яркость 1 с одной стороны от края и 0 с другой, край едет
через поле зрения. Это не «похоже на край», а именно край в координатах
той самой решётки, по которой тело считает `obs["vision"]`.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\vision_chain.py
"""

