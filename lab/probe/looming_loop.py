"""Сквозной опыт с нависанием: от сцены до движения тела, с контролями.

Что здесь делается
------------------

Один и тот же эпизод в ТЕЛЕ прогоняется в нескольких условиях, и на
каждом шаге записывается вся цепочка: сцена → кадр глаза →
фоторецепторы → переходник → настоящие связи FlyWire → нисходящие →
декодер → команда ногам → положение и курс тела. Ничего не
сценировано: порог, выбор действия и «реакция по факту появления
объекта» в коде отсутствуют. Если команда меняется — она меняется
потому, что изменилась активность, а не потому, что кто-то её написал.

ЧТО ЭТО НЕ ЕСТЬ
---------------

Подача на T4/T5 — **инженерный переходник** (`flybrain.vislink`), и за
границей стоят три посчитанные ВНЕ сети величины: сами направленные
сигналы, соответствие «подтип — направление» и наведённый омматидий.
**Это не передача по глубокому зрительному пути оригинальной сети
FlyWire.** Настоящим связям принадлежит только то, что за границей:
T4/T5 → LPLC2, LC4 → DNp01 и глубже. Без переходника за третьим
синапсом ровно 0,000 Гц, и это замеренное состояние продуктового
зрения, а не недоделка.

Контроли — СОПОСТАВИМЫЕ
-----------------------

Каждый контроль отличается от опыта ровно одной вещью, и список
объявлен заранее, а не подобран по итогу:

* ``без предмета`` — слот в сцене есть, объект выключен. Сцена та же,
  угроза отсутствует;
* ``неподвижный`` — объект стоит там, где нависающий оказывается на
  середине пути. Отличает ответ на расширение от ответа на наличие;
* ``поперёк`` — объект идёт поперёк курса на постоянном удалении:
  угловой размер держится, место в поле зрения едет;
* ``зрение выключено`` — ни кадра, ни подачи;
* ``переходник выключен`` — зрение есть, подачи на T4/T5 нет. Это
  контроль на сам переходник: за третьим синапсом обязан быть ноль;
* ``тасовка подачи`` — те же числа тем же популяциям, но нейронам в
  случайном порядке. Суммарный вход сохраняется, разрушена только
  пространственная структура;
* ``заглушены T4/T5`` — маска `fire` на подаваемые популяции. Если
  отклик за границей сохраняется, он идёт не из подачи;
* ``заглушён DNp01`` — заглушение нисходящего. Выше по пути всё
  обязано остаться на месте;
* ``мимо цели`` — заглушена популяция, которой в этом пути нет
  (`DNp03`). Отличает последствие вмешательства от последствия
  вмешательства вообще;
* ``тело заморожено`` — нулевая амплитуда походки. Зрительный вход
  тогда идёт только от объекта, а не от собственного хода;
* ``слева`` и ``справа`` — объект подходит со смещением по +y и −y.
  Знак асимметрии обязан поменяться.

Что меряется
------------

Частоты популяций считаются из растра прогона (`run.bins`), то есть из
того же, что уезжает в сохранённый прогон. Задержки — номер первого
шага, на котором величина выходит за полосу, снятую ДО начала
нависания на том же прогоне, а не за порог из головы.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\looming_loop.py
    ..\\.venv\\Scripts\\python.exe probe\\looming_loop.py --длина 0.8 --только нависание

Коды: 0 — все проверки сошлись; 1 — есть провал.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent

# Популяции цепочки. Селекторы — ТОЧНЫЕ однополевые: `type:T4` даёт
# 6400 нейронов, среди которых нет ни одного T4, а `type=` сравнивает с
# тремя столбцами и объединяет. Нисходящие берутся теми же зондами, что
# и в моторном пути, то есть с записанным отпечатком `root_id`.
ЗВЕНЬЯ = [
    ("R1-6", "celltype=R1-6", "фоторецепторы: вход, посчитан продуктом"),
    ("T4", ("celltype=T4a", "celltype=T4b", "celltype=T4c", "celltype=T4d"),
     "ГРАНИЦА: подано переходником, вне сети"),
    ("T5", ("celltype=T5a", "celltype=T5b", "celltype=T5c", "celltype=T5d"),
     "ГРАНИЦА: подано переходником, вне сети"),
    ("LPLC2", "celltype=LPLC2", "за границей: связи FlyWire"),
    ("LC4", "celltype=LC4", "за границей: связи FlyWire"),
]
НИСХОДЯЩИЕ = ("DNp01", "DNp04", "DNa02", "DNa01")
# Мимо-целевая популяция: нисходящий, которого в этом пути нет.
МИМО = "DNp03"

fails = []
rep = {"проверки": {}, "условия": {}}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""))
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def note(text):
    print("  — " + text)
    rep.setdefault("оговорки", []).append(text)


def полоса(x):
    """Полоса величины до начала нависания: середина и размах."""
    a = np.asarray(x, dtype=np.float64)
    if a.size == 0:
        return 0.0, 0.0
    return float(np.median(a)), float(a.max() - a.min())


def первый_выход(x, лоу, хай, с_шага):
    """Номер первого шага от `с_шага`, где величина вышла за полосу."""
    a = np.asarray(x, dtype=np.float64)
    for i in range(с_шага, len(a)):
        if a[i] < лоу or a[i] > хай:
            return i
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--длина", type=float, default=1.4,
                    help="длительность эпизода, с модельного времени")
    ap.add_argument("--только", default=None,
                    help="прогнать одно условие по имени")
    # Рабочая точка усиления выбрана РАЗВЁРТКОЙ, а не подгонкой, и вся
    # кривая публикуется целиком — иначе выбор точки был бы подгонкой
    # под желаемый ответ. Замерено на эпизоде 1,4 с при объявленном
    # потолке 1000 Гц (средние частоты по эпизоду, Гц):
    #
    #   усиление  подача   в потолке     T4      T5   LPLC2    LC4  DNp04
    #      2e3     0,815    0,00059   0,696   0,871   0,027  0,000  0,000
    #      2e4     5,276    0,01040   5,048   5,143   0,691  0,069  0,000
    #      2e5    19,873    0,02536  19,697  18,653   4,551  0,247  0,357
    #      2e6    35,675    0,05199  35,434  33,388  10,119  0,673  1,429
    #
    # Кривая монотонна, насыщение подачи остаётся малым (до 5,2 %), то
    # есть потолок сигнал не вырождает. `DNp01` при ВСЯКОМ усилении
    # ровно 0,000 — это согласуется с неустранимым обрывом Giant Fiber
    # (главный его канал электрический, а ЭМ считает только химические
    # синапсы), и ослаблять этот ноль нечем.
    #
    # Рабочей точкой взято 2e6: это наименьшее развёрнутое усиление, при
    # котором отклик нисходящего измерим не единицами спайков. При 2e5
    # он есть (0,357 Гц), но это около одного спайка на двух нейронах за
    # эпизод, и отличить на нём условия друг от друга нечем.
    ap.add_argument("--усиление", type=float, default=2000000.0,
                    help="усиление подачи переходника, Гц")
    a = ap.parse_args()

    import torch
    from flybrain import (body as B, data as D, motor as M, objects as O)

    dev = "cuda" if torch.cuda.is_available() else "cpu"
    print("— сквозной опыт с нависанием —")
    print("  устройство %s, эпизод %.2f с модельного" % (dev, a.длина))
    neurons = D.load_neurons()
    weights = D.load_weights(device=dev)

    # --- кто есть кто ------------------------------------------------
    idx = {}
    for имя, сел, _ in ЗВЕНЬЯ:
        части = (сел,) if isinstance(сел, str) else сел
        idx[имя] = np.unique(np.concatenate(
            [D.select(neurons, s) for s in части]))
    for имя in НИСХОДЯЩИЕ:
        p = M.DN_PROBES[имя]
        idx[имя] = D.select(neurons, p.sel)
    side = np.asarray(neurons["side"]).astype(str)
    бок = {}
    for имя in ("DNa02", "DNa01", "DNp01"):
        бок[имя] = {с: idx[имя][side[idx[имя]] == с]
                    for с in ("left", "right")}
    print("  нейронов: " + ", ".join(
        "%s %d" % (k, len(idx[k])) for k, _, _ in ЗВЕНЬЯ))
    print("  нисходящие: " + ", ".join(
        "%s %d" % (k, len(idx[k])) for k in НИСХОДЯЩИЕ))

    # Тёмное нависание со смещением по стороне: тот же отрезок, что в
    # `objects.PRESETS["loom_dark"]`, сдвинутый по y. Числа берутся у
    # пресета, а не переписываются.
    база = O.preset("loom_dark")[0]

    def трек_сбоку(y):
        d = dict(база)
        d["from"] = (база["from"][0], y, база["from"][2])
        d["to"] = (база["to"][0], y * 0.3, база["to"][2])
        return [d]

    УСЛОВИЯ = {
        "нависание": dict(vis_track=O.preset("loom_dark"), vision_bridge="гибрид"),
        "без предмета": dict(vis_track=None, vision_bridge="гибрид"),
        "неподвижный": dict(vis_track=O.preset("still"), vision_bridge="гибрид"),
        "поперёк": dict(vis_track=O.preset("sweep"), vision_bridge="гибрид"),
        "зрение выключено": dict(vision=False, vis_objects=0,
                                 vis_track=None, vision_bridge=None),
        "переходник выключен": dict(vis_track=O.preset("loom_dark"),
                                    vision_bridge=None),
        "тасовка подачи": dict(vis_track=O.preset("loom_dark"),
                               vision_bridge="гибрид",
                               vision_bridge_shuffle=True),
        "заглушены T4/T5": dict(
            vis_track=O.preset("loom_dark"), vision_bridge="гибрид",
            # `DnIntervention` делит строку по запятой и разбирает
            # КАЖДОЕ слагаемое отдельно, поэтому `sel:` нужен каждому.
            # Поймано прогоном: без него отказ «нет популяции
            # celltype=T4b».
            dn_silence=",".join(
                "sel:celltype=%s" % t for t in
                ("T4a", "T4b", "T4c", "T4d",
                 "T5a", "T5b", "T5c", "T5d"))),
        "заглушён DNp04": dict(vis_track=O.preset("loom_dark"),
                               vision_bridge="гибрид",
                               dn_silence="DNp04"),
        "мимо цели": dict(vis_track=O.preset("loom_dark"), vision_bridge="гибрид",
                          dn_silence="sel:celltype=%s" % МИМО),
        # РЕШАЮЩАЯ ПАРА. Замерено на идущей мухе: без предмета в сцене
        # переходник всё равно подаёт 32,3 Гц — это оптический поток от
        # СОБСТВЕННОГО ХОДА, и на нём вклад предмета (37,4 Гц) тонет.
        # На замороженном теле единственное движение в поле зрения —
        # предмет, поэтому сравнивать надо здесь.
        "тело заморожено": dict(vis_track=O.preset("loom_dark"),
                                vision_bridge="гибрид",
                                amp_base=0.0, amp_span=0.0,
                                amp_min=0.0, amp_max=0.0),
        "тело заморожено, без предмета": dict(
            vis_track=None, vision_bridge="гибрид",
            amp_base=0.0, amp_span=0.0, amp_min=0.0, amp_max=0.0),
        "слева": dict(vis_track=трек_сбоку(+8.0),
                      vision_bridge="гибрид"),
        "справа": dict(vis_track=трек_сбоку(-8.0),
                       vision_bridge="гибрид"),
    }
    if a.только:
        if a.только not in УСЛОВИЯ:
            print("нет такого условия: %r; есть: %s"
                  % (a.только, ", ".join(УСЛОВИЯ)))
            return 1
        УСЛОВИЯ = {a.только: УСЛОВИЯ[a.только]}

    итоги = {}
    for имя, ручки in УСЛОВИЯ.items():
        ручки = dict(ручки)
        cfg_kw = dict(duration_s=a.длина, control_ms=20.0, seed=0,
                      device=dev, readout="ALPN",
                      vision=True, vis_objects=1, vision_hz=100.0,
                      vision_bridge_gain=a.усиление)
        cfg_kw.update(ручки)
        print("\n== %s ==" % имя)
        cfg = B.BodyConfig(**cfg_kw)
        run = B.run_episode(cfg=cfg, neurons=neurons, weights=weights,
                            progress=False)
        recs = run.records
        bins = run.bins.cpu().numpy() if hasattr(run.bins, "cpu") \
            else np.asarray(run.bins)
        шаг_с = cfg.control_ms / 1000.0
        hz = {}
        for k, v in idx.items():
            hz[k] = (bins[:, v].sum(1) / max(len(v), 1) / шаг_с
                     if len(v) else np.zeros(len(bins)))
        для_сторон = {}
        for к, пара in бок.items():
            для_сторон[к] = {с: (bins[:, v].sum(1) / max(len(v), 1) / шаг_с
                                 if len(v) else np.zeros(len(bins)))
                             for с, v in пара.items()}

        def кол(ключ):
            return np.array([r.get(ключ, np.nan) for r in recs],
                            dtype=np.float64)

        дан = {
            "шагов": len(recs),
            "частоты, Гц": {k: round(float(np.mean(v)), 4)
                            for k, v in hz.items()},
            # Спайки СЧЁТОМ, а не только частотой: у зондов по два
            # нейрона, и 0,357 Гц за 1,4 с — это около одного спайка.
            # Частота такую малость прячет, счёт — нет.
            "спайков всего": {k: (int(bins[:, v].sum()) if len(v) else 0)
                              for k, v in idx.items()},
            "наибольшая частота, Гц": {k: round(float(np.max(v)), 4)
                                       for k, v in hz.items()},
            "переходник, средняя Гц": round(
                float(np.nanmean(кол("vbr_hz"))), 4)
            if not np.all(np.isnan(кол("vbr_hz"))) else None,
            "нависание, сумма": round(float(np.nansum(кол("vbr_loom"))), 6)
            if not np.all(np.isnan(кол("vbr_loom"))) else None,
            "фоторецепторы, средняя Гц": round(
                float(np.nanmean(кол("vis_hz"))), 4)
            if not np.all(np.isnan(кол("vis_hz"))) else None,
            "съём dn_l, Гц": round(float(np.nanmean(кол("dn_l"))), 4),
            "съём dn_r, Гц": round(float(np.nanmean(кол("dn_r"))), 4),
            "команда amp_l": round(float(np.nanmean(кол("amp_l"))), 4),
            "команда amp_r": round(float(np.nanmean(кол("amp_r"))), 4),
            "асимметрия команды": round(
                float(np.nanmean(кол("amp_l") - кол("amp_r"))), 4),
            "путь, мм": round(float(np.hypot(
                recs[-1]["x"] - recs[0]["x"],
                recs[-1]["y"] - recs[0]["y"])), 4),
            "поворот, рад": round(
                float(recs[-1]["theta"] - recs[0]["theta"]), 4),
            "конец": [round(float(recs[-1]["x"]), 4),
                      round(float(recs[-1]["y"]), 4),
                      round(float(recs[-1]["theta"]), 4)],
            "доля реального времени": (run.timing or {}).get(
                "realtime_ratio"),
        }
        # Задержки: полоса снимается по первым 10 шагам ТОГО ЖЕ прогона,
        # а не задаётся порогом из головы.
        n0 = min(10, max(2, len(recs) // 6))
        задержки = {}
        for ключ, ряд in (("переходник", кол("vbr_hz")),
                          ("LPLC2", hz["LPLC2"]),
                          ("DNp04", hz["DNp04"]),
                          ("съём", кол("dn_l") - кол("dn_r")),
                          ("команда", кол("amp_l") - кол("amp_r")),
                          ("курс", кол("theta"))):
            ряд = np.asarray(ряд, dtype=np.float64)
            if np.all(np.isnan(ряд)):
                задержки[ключ] = None
                continue
            мед, разм = полоса(ряд[:n0])
            i = первый_выход(ряд, мед - max(разм, 1e-9) * 1.5,
                             мед + max(разм, 1e-9) * 1.5, n0)
            задержки[ключ] = (None if i is None
                              else round(i * cfg.control_ms, 1))
        дан["задержка, мс от начала"] = задержки
        дан["нисходящие по сторонам, Гц"] = {
            к: {с: round(float(np.mean(v)), 4) for с, v in п.items()}
            for к, п in для_сторон.items()}
        t = run.timing or {}
        if t.get("зрение", {}).get("переходник"):
            дан["происхождение переходника"] = t["зрение"]["переходник"]
        итоги[имя] = дан
        print("  фоторецепторы %s Гц | переходник %s Гц | нависание %s"
              % (дан["фоторецепторы, средняя Гц"],
                 дан["переходник, средняя Гц"], дан["нависание, сумма"]))
        print("  T4 %.4f | T5 %.4f | LPLC2 %.4f | LC4 %.4f | DNp01 %.4f | "
              "DNa02 %.4f Гц"
              % (дан["частоты, Гц"]["T4"], дан["частоты, Гц"]["T5"],
                 дан["частоты, Гц"]["LPLC2"], дан["частоты, Гц"]["LC4"],
                 дан["частоты, Гц"]["DNp01"], дан["частоты, Гц"]["DNa02"]))
        print("  команда l %.4f r %.4f (асимметрия %.4f) | путь %.3f мм | "
              "поворот %.4f рад"
              % (дан["команда amp_l"], дан["команда amp_r"],
                 дан["асимметрия команды"], дан["путь, мм"],
                 дан["поворот, рад"]))

    rep["условия"] = итоги
    (OUT / "looming_loop.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")

    if a.только:
        print("\nодно условие: сверки между условиями пропущены")
        return 0 if not fails else 1

    print("\n— сверки между условиями —")
    О = итоги
    гл = О["нависание"]

    # 1. Без переходника за третьим синапсом обязан быть ноль.
    б = О["переходник выключен"]
    check("без переходника T4 и T5 ровно 0 Гц",
          б["частоты, Гц"]["T4"] == 0.0 and б["частоты, Гц"]["T5"] == 0.0,
          "T4 %.4f, T5 %.4f" % (б["частоты, Гц"]["T4"],
                                б["частоты, Гц"]["T5"]))
    check("без переходника LPLC2, LC4, DNp01 и DNp04 ровно 0 Гц",
          all(б["частоты, Гц"][k] == 0.0
              for k in ("LPLC2", "LC4", "DNp01", "DNp04")),
          ", ".join("%s %.4f" % (k, б["частоты, Гц"][k])
                    for k in ("LPLC2", "LC4", "DNp01", "DNp04")))
    check("без переходника фоторецепторы ВСЁ РАВНО подаются",
          (б["фоторецепторы, средняя Гц"] or 0.0) > 1.0,
          б["фоторецепторы, средняя Гц"])

    # 2. Пустая сцена у ИДУЩЕЙ мухи. Проверка «переходник обязан дать
    #    ноль» стояла здесь и ПРОВАЛИЛАСЬ бы: замерено 32,3 Гц без
    #    единого предмета в сцене. Ноль переходник даёт только на
    #    однородном неподвижном поле (это его собственный встречный
    #    замер, `probe/vision_hybrid.py`), а в теле муха идёт, арена
    #    едет по полю зрения, и коррелятор отвечает на ОПТИЧЕСКИЙ ПОТОК
    #    от собственного хода. Поэтому утверждение здесь другое — и это
    #    замер, а не ослабление: вклад предмета измеряется на
    #    замороженном теле (пункт 7).
    п = О["без предмета"]
    check("у идущей мухи подача не ноль и БЕЗ предмета — оптический "
          "поток от собственного хода",
          (п["переходник, средняя Гц"] or 0.0) > 1.0,
          п["переходник, средняя Гц"])
    check("предмет добавляет к подаче, но на ходу немного",
          (гл["переходник, средняя Гц"] or 0.0)
          > (п["переходник, средняя Гц"] or 0.0),
          "%s против %s, отношение %.4f"
          % (гл["переходник, средняя Гц"], п["переходник, средняя Гц"],
             (гл["переходник, средняя Гц"] or 0.0)
             / max(п["переходник, средняя Гц"] or 1e-9, 1e-9)))

    # 3. Нависание против неподвижного и поперечного.
    check("нависание даёт больше подачи, чем неподвижный объект",
          (гл["переходник, средняя Гц"] or 0.0)
          > (О["неподвижный"]["переходник, средняя Гц"] or 0.0),
          "%s против %s" % (гл["переходник, средняя Гц"],
                            О["неподвижный"]["переходник, средняя Гц"]))
    check("нависание даёт больше, чем движение ПОПЕРЁК курса",
          (гл["нависание, сумма"] or 0.0)
          > (О["поперёк"]["нависание, сумма"] or 0.0),
          "%s против %s" % (гл["нависание, сумма"],
                            О["поперёк"]["нависание, сумма"]))

    # 4. Заглушение подачи: отклик за границей обязан упасть.
    з = О["заглушены T4/T5"]
    check("заглушение T4/T5 роняет LPLC2",
          з["частоты, Гц"]["LPLC2"] < гл["частоты, Гц"]["LPLC2"]
          or гл["частоты, Гц"]["LPLC2"] == 0.0,
          "%.4f против %.4f" % (з["частоты, Гц"]["LPLC2"],
                                гл["частоты, Гц"]["LPLC2"]))

    # 5. Заглушение DNp01: сам он молчит, выше по пути всё на месте.
    d = О["заглушён DNp04"]
    check("заглушённый DNp04 молчит", d["частоты, Гц"]["DNp04"] == 0.0,
          d["частоты, Гц"]["DNp04"])
    check("заглушение DNp04 не трогает LPLC2 выше по пути",
          abs(d["частоты, Гц"]["LPLC2"] - гл["частоты, Гц"]["LPLC2"])
          <= 0.05 * max(гл["частоты, Гц"]["LPLC2"], 1e-9) + 1e-9,
          "%.4f против %.4f" % (d["частоты, Гц"]["LPLC2"],
                                гл["частоты, Гц"]["LPLC2"]))

    # 6. Мимо-целевое вмешательство: путь не должен шевельнуться
    #    сильнее, чем от целевого.
    м = О["мимо цели"]
    check("мимо-целевое заглушение не роняет DNp04",
          м["частоты, Гц"]["DNp04"] >= 0.5 * гл["частоты, Гц"]["DNp04"],
          "%.4f против %.4f" % (м["частоты, Гц"]["DNp04"],
                                гл["частоты, Гц"]["DNp04"]))
    check("DNp01 ровно 0 при любом условии — обрыв Giant Fiber",
          all(v["частоты, Гц"]["DNp01"] == 0.0 for v in О.values()),
          ", ".join("%s %.4f" % (k, v["частоты, Гц"]["DNp01"])
                    for k, v in О.items()
                    if v["частоты, Гц"]["DNp01"]) or "везде ровно 0")

    # 7. Замороженное тело: подача обязана сохраниться (значит отклик
    #    не от собственного хода), а путь — исчезнуть.
    ф = О["тело заморожено"]
    check("замороженное тело почти не едет", ф["путь, мм"] < 0.5,
          ф["путь, мм"])
    check("у замороженного тела подача переходника сохраняется",
          (ф["переходник, средняя Гц"] or 0.0) > 0.0,
          ф["переходник, средняя Гц"])
    # РЕШАЮЩАЯ ПАРА: собственного хода нет ни у той, ни у другой ветви,
    # значит разница между ними — это вклад ПРЕДМЕТА и ничего больше.
    фп = О["тело заморожено, без предмета"]
    check("на замороженном теле БЕЗ предмета подача почти ноль",
          (фп["переходник, средняя Гц"] or 0.0)
          < 0.1 * max(ф["переходник, средняя Гц"] or 1e-9, 1e-9),
          "%s против %s с предметом"
          % (фп["переходник, средняя Гц"], ф["переходник, средняя Гц"]))
    check("на замороженном теле предмет доходит до LPLC2, а без него нет",
          ф["частоты, Гц"]["LPLC2"] > 5.0 * max(
              фп["частоты, Гц"]["LPLC2"], 1e-9),
          "%.4f против %.4f" % (ф["частоты, Гц"]["LPLC2"],
                                фп["частоты, Гц"]["LPLC2"]))
    check("на замороженном теле предмет доходит до DNp04, а без него нет",
          ф["спайков всего"]["DNp04"] > фп["спайков всего"]["DNp04"],
          "%d спайков против %d"
          % (ф["спайков всего"]["DNp04"], фп["спайков всего"]["DNp04"]))

    # 8. Сторона: знак асимметрии обязан поменяться.
    л, пр = О["слева"], О["справа"]
    check("сторона предмета меняет знак асимметрии подачи у нисходящих",
          np.sign(л["нисходящие по сторонам, Гц"]["DNa02"]["left"]
                  - л["нисходящие по сторонам, Гц"]["DNa02"]["right"])
          != np.sign(пр["нисходящие по сторонам, Гц"]["DNa02"]["left"]
                     - пр["нисходящие по сторонам, Гц"]["DNa02"]["right"])
          or (л["нисходящие по сторонам, Гц"]["DNa02"]["left"]
              == л["нисходящие по сторонам, Гц"]["DNa02"]["right"]
              == 0.0),
          "слева %.4f/%.4f, справа %.4f/%.4f"
          % (л["нисходящие по сторонам, Гц"]["DNa02"]["left"],
             л["нисходящие по сторонам, Гц"]["DNa02"]["right"],
             пр["нисходящие по сторонам, Гц"]["DNa02"]["left"],
             пр["нисходящие по сторонам, Гц"]["DNa02"]["right"]))

    # 9. Тасовка подачи. Суммарный вход она сохраняет ПОБИТОВО на
    #    одном и том же кадре, но в теле кадры расходятся: другая
    #    подача -> другие спайки -> другое поведение -> другой кадр.
    #    Поэтому равенство суммарной подачи здесь НЕ утверждается, а
    #    смотрится то, ради чего тасовка и делается: падает ли отклик за
    #    границей при сохранённом порядке величины подачи.
    т = О["тасовка подачи"]
    check("тасовка подачи оставляет подачу того же порядка",
          0.5 < ((т["переходник, средняя Гц"] or 0.0)
                 / max(гл["переходник, средняя Гц"] or 1e-9, 1e-9)) < 2.0,
          "%s против %s" % (т["переходник, средняя Гц"],
                            гл["переходник, средняя Гц"]))
    check("тасовка подачи РОНЯЕТ отклик LPLC2 — он зависит от "
          "пространственной структуры, а не от суммы",
          т["частоты, Гц"]["LPLC2"] < 0.75 * гл["частоты, Гц"]["LPLC2"],
          "%.4f против %.4f" % (т["частоты, Гц"]["LPLC2"],
                                гл["частоты, Гц"]["LPLC2"]))

    # 10. Главное утверждение: дошло ли до движения. Проверка устроена
    #     так, чтобы её МОЖНО было провалить, и провал здесь — это
    #     честный итог, а не поломка пробы.
    дошло = гл["частоты, Гц"]["DNp04"] > 0.0
    rep["дошло до нисходящих"] = bool(дошло)
    rep["дошло до команды"] = bool(
        abs(гл["асимметрия команды"]
            - О["зрение выключено"]["асимметрия команды"]) > 1e-9)
    print()
    if дошло:
        note("нависание ДОШЛО до нисходящего по настоящим связям: DNp04 "
             "%.4f Гц (%d спайков на %d нейронах), LPLC2 %.4f Гц, LC4 "
             "%.4f Гц. DNp01 при этом ровно 0 — обрыв Giant Fiber "
             "неустраним по природе измерения"
             % (гл["частоты, Гц"]["DNp04"], гл["спайков всего"]["DNp04"],
                len(idx["DNp04"]), гл["частоты, Гц"]["LPLC2"],
                гл["частоты, Гц"]["LC4"]))
    else:
        note("нависание НЕ ДОШЛО до нисходящих: DNp04 ровно 0 Гц при "
             "работающем переходнике. Это измеренный итог, а не "
             "поломка пробы: подача на T4/T5 доходит до LPLC2 "
             "(%.4f Гц), а дальше порога не хватает"
             % гл["частоты, Гц"]["LPLC2"])
    note("граница стыковки — %s, и отклики T4/T5 ПОДАНЫ, а не посчитаны "
         "синапсами" % (гл.get("происхождение переходника", {})
                        .get("ГРАНИЦА СТЫКОВКИ", "?")))

    (OUT / "looming_loop.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print()
    if fails:
        print("ПРОВАЛЫ: %s" % ", ".join(fails))
        return 1
    print("все сверки сошлись")
    return 0


if __name__ == "__main__":
    sys.exit(main())
