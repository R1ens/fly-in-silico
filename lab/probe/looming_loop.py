    # позы, ни таймера, ни последовательности. Биологического основания
    # у величин `gf_ref_hz` и `escape_gain` нет, у знака тоже нет, потому
    # что соответствующего пути в данных нет: `DNp01 -> super:motor` —
    # НОЛЬ пар из 110, а исполнители побега (TTMn, PSI) лежат в брюшной
    # нервной цепочке, которой в FlyWire v783 нет вовсе. Включённый мост
    # пишет оговорку в прогон, и такой прогон с эталонными не
    # сравнивается.
    #
