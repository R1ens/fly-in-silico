"""Переходник измерен: что ему принадлежит и где его граница.

Режим `hybrid_visual` — **инженерный переходник**, и владелец требует,
чтобы он был назван переходником и ИЗМЕРЕН, а не выдан за биологию.
Здесь он и измеряется, с его собственными встречными замерами.

Две границы стыковки, и они дают разное:

* **T4/T5** — внешне посчитаны направленные сигналы, дальше сигнал
  идёт по настоящим связям FlyWire (T4/T5 → LPLC2, LC4 → DNp01).
  Откликам LC4, LPLC2 и DNp01 при этой границе принадлежит настоящая
  связность;
* **LC4/LPLC2** — подача прямо на проекционные. Отклик самих LC4 и
  LPLC2 тогда НЕ принадлежит никаким синапсам: он подан. Настоящей
  связности принадлежит только DNp01.

Встречные замеры, каждый умеет провалить утверждение:

* **предмета нет** — однородное поле. Переходник обязан дать ноль;
* **обратное движение** — край едет в другую сторону;
* **перетасованное назначение** — те же частоты тем же популяциям, но
  нейронам в случайном порядке: суммарный вход сохраняется побитово;
* **перетасованные подтипы** — соответствие «подтип T4 — направление»
  перемешано: суммарный вход тот же, разрушена направленная структура.

**Чего эта проба НЕ показывает.** Она не показывает зрение по
коннектому от сетчатки, и ни одно её число этого не даёт: до T4/T5
сигнал здесь не проходит по связям вовсе, он туда подан. Полная
причинная цепь от омматидия до нисходящих в этом режиме НЕ замкнута, и
объявлять её работающей нельзя.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\vision_hybrid.py
"""

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent

DT = 0.1
WARM = 500
STEPS = 2000
VIS_HZ = 100.0
CROSS = 2000

ПОДТИПЫ = ("T4a", "T4b", "T4c", "T4d", "T5a", "T5b", "T5c", "T5d")
ЗАМЕР = ("T4", "T5", "LC4", "LPLC2", "DNp01")

fails = []
rep = {"проверки": {}, "замеры": {}, "находки": [], "сорвалось": []}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""), flush=True)
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def note(text):
    print("  НАХОДКА " + text, flush=True)
    rep["находки"].append(text)


def edge_frame(pos, phase, назад=False):
    x = pos[:, 0]
    lo, hi = float(x.min()), float(x.max())
    ph = (1.0 - phase) if назад else phase
    return (x <= lo + (hi - lo) * float(ph)).astype(np.float64)


def disc_frame(pos, доля):
    c = pos.mean(0)
    d = np.linalg.norm(pos - c, axis=1)
    return (d > float(доля) * float(d.max())).astype(np.float64)


def main():
    t0 = time.perf_counter()
    print("Переходник: измерение и граница", flush=True)
    import scipy.sparse as sp
    import torch

    from flybrain import (data as D, retina as R, sim, visdyn as V,
                          vishybrid as H)

    neurons = D.load_neurons()
    W = D.load_weights()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    n = len(neurons)
    om = R.ommatidia()
    pos = om["pos"]

    ИМЕНА = {t: (t,) for t in ПОДТИПЫ}
    ИМЕНА.update({"LC4": ("LC4",), "LPLC2": ("LPLC2",),
                  "DNp01": ("DNp01",), "Mi1": ("Mi1",),
                  "Tm9": ("Tm9",), "L1": ("L1",), "L2": ("L2",),
                  "L3": ("L3",), "L4": ("L4",), "L5": ("L5",),
                  "R1-6": ("R1-6",), "R7": ("R7",), "R8": ("R8",)})
    pops = {k: np.unique(np.concatenate(
        [D.select(neurons, "celltype=%s" % t) for t in v]))
        for k, v in ИМЕНА.items()}
    maps = R.build_all(neurons, mode="whiten", assign="capacity")
    pr_idx = np.unique(np.concatenate([maps[k].neurons for k in maps]))

    # --- наведённые места T4/T5: инженерная величина, и она объявлена
    #
    # Омматидий есть только у фоторецепторов. Для T4 и T5 он наводится
    # по настоящим возбуждающим связям через ламину и медуллу — тем же
    # способом и тем же кодом замысла, что `probe/vision_phys_rf.py`,
    # где замерено, что такой вход ЛОКАЛЕН (разброс 0,023 размаха поля
    # у T4a против 0,101 у перетасованной привязки). Это и делает
    # подачу на T4/T5 пространственной, а не размазанной.
    w = W.coalesce()
    ii = w.indices().cpu().numpy()
    vv = w.values().cpu().numpy()
    поз = vv > 0
    A = sp.csr_matrix((vv[поз], (ii[0][поз], ii[1][поз])), shape=(n, n))
    xy = np.full((n, 2), np.nan)
    for key, m in maps.items():
        xy[m.neurons] = pos[m.omma]

    def навести(куда, откуда):
        S = A[куда][:, откуда]
        px, py = xy[откуда, 0], xy[откуда, 1]
        ок = np.isfinite(px)
        S, px, py = S[:, ок], px[ок], py[ок]
        вес = np.asarray(S.sum(1)).ravel()
        есть = вес > 0
        xy[куда[есть], 0] = np.asarray(S @ px).ravel()[есть] / вес[есть]
        xy[куда[есть], 1] = np.asarray(S @ py).ravel()[есть] / вес[есть]
        return int(есть.sum()), int(len(куда))

    лам = np.unique(np.concatenate([pops[k] for k in
                                    ("L1", "L2", "L3", "L4")]))
    навести(лам, pr_idx)
    навести(pops["L5"], лам)
    мед = np.unique(np.concatenate([pops[k] for k in ("Mi1", "Tm9")]))
    навести(мед, np.concatenate([лам, pops["L5"]]))
    всего_t, есть_t = 0, 0
    for t in ПОДТИПЫ:
        e, a = навести(pops[t], np.concatenate([мед, лам, pops["L5"]]))
        есть_t += e
        всего_t += a

    # номер ближайшего омматидия для каждого нейрона T4/T5
    from scipy.spatial import cKDTree
    дерево = cKDTree(pos)
    места, тасовка = {}, {}
    g = np.random.default_rng(0)
    for t in ПОДТИПЫ + ("LC4", "LPLC2"):
        p = xy[pops[t]]
        ок = np.isfinite(p[:, 0])
        ном = np.zeros(len(p), dtype=np.int64)
        if ок.any():
            ном[ок] = дерево.query(p[ок], k=1)[1]
        места[t] = ном
        тасовка[t] = g.permutation(ном)      # те же числа, другой адресат
    check("места T4/T5 наведены по настоящим связям, а не выдуманы",
          есть_t > 0.9 * всего_t,
          "место определилось у %d из %d нейронов T4/T5 (%.1f %%). "
          "Наведение — инженерная величина, и она объявлена: омматидий "
          "есть только у фоторецепторов, глубже он средневзвешен по "
          "числу синапсов. Локальность такого входа замерена отдельно "
          "(`vision_phys_rf.py`: разброс 0,023 размаха у T4a против "
          "0,101 у перетасованной привязки)"
          % (есть_t, всего_t, 100.0 * есть_t / max(всего_t, 1)))

    eng0 = sim.build_engine(weights=W, neurons=neurons, device=dev,
                            seed=0, no_refractory=pr_idx, graphs=True)
    z = torch.zeros(1, n, device=dev)
    for _ in range(WARM):
        eng0.step(z)
    snap = {"поля": {nm: getattr(eng0, nm).detach().clone()
                     for nm in ("v", "conductance", "spikes", "refrac",
                                "delay_buffer")},
            "ptr": eng0.ptr, "gen": eng0.gen.get_state().clone()}
    del eng0
    pop_t = {k: torch.as_tensor(v, device=dev) for k, v in pops.items()}
    кадр_мс = 1000.0 / VIS_HZ
    every = max(1, int(round(кадр_мс / DT)))

    def свод(acc):
        out = {}
        ms = STEPS * DT
        for нм, части in (("T4", ПОДТИПЫ[:4]), ("T5", ПОДТИПЫ[4:])):
            c = sum(float(acc[pop_t[p]].sum()) for p in части)
            k = sum(len(pops[p]) for p in части)
            out[нм] = round(1e3 * c / k / ms, 4)
        for нм in ("LC4", "LPLC2", "DNp01"):
            out[нм] = round(1e3 * float(acc[pop_t[нм]].sum())
                            / len(pops[нм]) / ms, 4)
        out["__мозг__"] = round(1e3 * float(acc.sum()) / n / ms, 4)
        return out

    def прогон(граница, условие, кадр_функ, подтипы=None,
               усиление=H.УСИЛЕНИЕ_HZ):
        пер = H.Переходник(pos, граница=граница, кадр_мс=кадр_мс,
                           усиление_hz=усиление)
        if подтипы is not None:
            пер.подтипы(подтипы)
        гр = (ПОДТИПЫ if граница == H.ГРАНИЦА_T4T5
              else ("LC4", "LPLC2"))
        drv = V.Привод.собрать(W, neurons, pops, maps,
                               режим=V.РЕЖИМ_ГИБРИД, граница=гр,
                               dev=dev, seed=0, snap=snap)
        acc = torch.zeros(n, device=dev)
        подано = 0.0
        мм = тасовка if условие == "перетасованное назначение" else места
        for s in range(STEPS):
            if s % every == 0:
                сиг, _ = пер.сигнал(кадр_функ(s), места=мм)
                срез = drv.подать_границу(сиг)
                подано += float(drv._t["rates"].sum())
            drv.шаг()
            acc.add_(drv.eng.spikes[0])
        if dev == "cuda":
            torch.cuda.synchronize()
        out = свод(acc)
        out["подано, Гц·кадров"] = round(подано, 2)
        out["срез канала подачи"] = dict(срез)
        св = пер.сводка()
        del drv
        return out, св

    def край(s, назад=False):
        ph = (s % max(CROSS, 1)) / max(CROSS - 1, 1)
        return edge_frame(pos, ph, назад)

    # =================================================================
    # Граница T4/T5
    # =================================================================
    print("\nГраница %s: внешне посчитаны только направленные сигналы, "
          "дальше настоящие связи" % H.ГРАНИЦА_T4T5, flush=True)
    усл = {}
    усл["движение вперёд"], св_t = прогон(
        H.ГРАНИЦА_T4T5, "движение вперёд", край)
    усл["движение назад"], _ = прогон(
        H.ГРАНИЦА_T4T5, "движение назад", lambda s: край(s, True))
    усл["предмета нет"], _ = прогон(
        H.ГРАНИЦА_T4T5, "предмета нет",
        lambda s: np.full(len(pos), 0.5))
    усл["перетасованное назначение"], _ = прогон(
        H.ГРАНИЦА_T4T5, "перетасованное назначение", край)
    усл["перетасованные подтипы"], _ = прогон(
        H.ГРАНИЦА_T4T5, "перетасованные подтипы", край,
        подтипы=(2, 3, 0, 1))
    rep["замеры"]["граница T4/T5"] = усл
    rep["замеры"]["сводка переходника, граница T4/T5"] = св_t
    print("   %-28s %8s %8s %8s %8s %8s %9s"
          % ("", "T4", "T5", "LC4", "LPLC2", "DNp01", "подано"),
          flush=True)
    for нм, d in усл.items():
        print("   %-28s %8.3f %8.3f %8.3f %8.3f %8.2f %9.0f"
              % (нм, d["T4"], d["T5"], d["LC4"], d["LPLC2"],
                 d["DNp01"], d["подано, Гц·кадров"]), flush=True)

    check("переходник даёт ноль, когда предмета нет — встречный замер "
          "на месте",
          усл["предмета нет"]["T4"] < 0.01
          and усл["предмета нет"]["подано, Гц·кадров"] < 1.0,
          "однородное поле: подано %.3f Гц·кадров, T4 %.4f Гц, LC4 "
          "%.4f, DNp01 %.3f. Детектор движения на неподвижной картинке "
          "обязан молчать, и молчит"
          % (усл["предмета нет"]["подано, Гц·кадров"],
             усл["предмета нет"]["T4"], усл["предмета нет"]["LC4"],
             усл["предмета нет"]["DNp01"]))

    a, b = усл["движение вперёд"], усл["перетасованное назначение"]
    вход_ок = abs(a["подано, Гц·кадров"] - b["подано, Гц·кадров"]) \
        <= 1e-6 * max(a["подано, Гц·кадров"], 1.0)
    check("суммарный вход при перетасованном назначении совпал "
          "побитово — значит различие может дать только структура",
          вход_ок,
          "подано %.4f против %.4f (разница %.2e)"
          % (a["подано, Гц·кадров"], b["подано, Гц·кадров"],
             abs(a["подано, Гц·кадров"] - b["подано, Гц·кадров"])))

    структ = {нм: round(a[нм] - b[нм], 4) for нм in ЗАМЕР}
    c = усл["перетасованные подтипы"]
    напр = {нм: round(a[нм] - c[нм], 4) for нм in ЗАМЕР}
    rep["замеры"]["структуре принадлежит (граница T4/T5)"] = структ
    rep["замеры"]["направленной структуре принадлежит"] = напр
    прошло = [нм for нм in ("LC4", "LPLC2", "DNp01")
              if abs(структ[нм]) > 0.01]
    check("зависит ли отклик ЗА границей от пространственной структуры "
          "подачи",
          True,
          ("зависит у %s: " % прошло + ", ".join(
              "%s %+.4f Гц" % (нм, структ[нм]) for нм in прошло)
           + ". Это принадлежит настоящим связям FlyWire за границей, "
             "потому что суммарный вход совпал побитово")
          if прошло else
          ("НЕ зависит ни у LC4, ни у LPLC2, ни у DNp01: "
           + ", ".join("%s %+.4f" % (нм, структ[нм])
                       for нм in ("LC4", "LPLC2", "DNp01"))
           + ". Значит за границей отклик держится количеством "
             "поданного, а не картиной"))

    # =================================================================
    # Граница LC4/LPLC2 — объявленная, более поверхностная
    # =================================================================
    print("\nГраница %s: подача ПРЯМО на проекционные. Отклик самих "
          "LC4 и LPLC2 НЕ принадлежит никаким синапсам"
          % H.ГРАНИЦА_ПРОЕКЦИОННЫЕ, flush=True)

    def нависание(s):
        return disc_frame(pos, 0.05 + 0.85 * min(1.0, s / float(STEPS)))

    def удаление(s):
        return disc_frame(pos, 0.90 - 0.85 * min(1.0, s / float(STEPS)))

    усл2 = {}
    усл2["нависание"], св_p = прогон(H.ГРАНИЦА_ПРОЕКЦИОННЫЕ,
                                     "нависание", нависание)
    усл2["удаление"], _ = прогон(H.ГРАНИЦА_ПРОЕКЦИОННЫЕ, "удаление",
                                 удаление)
    усл2["предмета нет"], _ = прогон(
        H.ГРАНИЦА_ПРОЕКЦИОННЫЕ, "предмета нет",
        lambda s: np.full(len(pos), 1.0))
    rep["замеры"]["граница LC4/LPLC2"] = усл2
    rep["замеры"]["сводка переходника, граница LC4/LPLC2"] = св_p
    print("   %-18s %8s %8s %8s %9s"
          % ("", "LC4", "LPLC2", "DNp01", "подано"), flush=True)
    for нм, d in усл2.items():
        print("   %-18s %8.3f %8.3f %8.2f %9.0f"
              % (нм, d["LC4"], d["LPLC2"], d["DNp01"],
                 d["подано, Гц·кадров"]), flush=True)

    нав = усл2["нависание"]
    уда = усл2["удаление"]
    check("различает ли переходник нависание и удаление — и где "
          "проходит граница этого различения",
          True,
          "подано при нависании %.1f против %.1f при удалении; DNp01 "
          "%.2f против %.2f Гц. РАЗЛИЧЕНИЕ СДЕЛАНО ВНЕ СЕТИ: отклик "
          "LC4 (%.3f) и LPLC2 (%.3f) здесь подан, а не получен по "
          "синапсам. Настоящим связям принадлежит только DNp01, и у "
          "него всего 2 нейрона — за 200 мс один спайк даёт 2,5 Гц"
          % (нав["подано, Гц·кадров"], уда["подано, Гц·кадров"],
             нав["DNp01"], уда["DNp01"], нав["LC4"], нав["LPLC2"]))
    note("граница переходника названа числом: при стыковке на T4/T5 "
         "внешне посчитаны только направленные сигналы, и откликам "
         "LC4/LPLC2/DNp01 принадлежит настоящая связность; при "
         "стыковке на LC4/LPLC2 отклик самих проекционных ПОДАН, и "
         "настоящей связности принадлежит только DNp01 на двух "
         "нейронах. Полная причинная цепь от омматидия до нисходящих "
         "в обоих случаях НЕ замкнута")

    # =================================================================
    # Развёртка усиления подачи: что нужно, чтобы дойти до цели
    # =================================================================
    #
    # Это и есть главное число переходника. `VISION_DEEP.md` §2 назвал
    # требуемые частоты: LPLC2 загорается от 48,8 Гц на T4 или 37,8 Гц
    # на T5, DNp01 — от 9,4 Гц на LPLC2 или 12,6 Гц на LC4. При
    # усилении по умолчанию переходник даёт на T4 всего 1,358 Гц, то
    # есть не хватает в 36 раз. Развёртка показывает, какое усиление
    # нужно и чего это стоит.
    print("\nРазвёртка усиления подачи, граница %s" % H.ГРАНИЦА_T4T5,
          flush=True)
    СЕТКА = (200.0, 2000.0, 20000.0, 200000.0)
    разв = {}
    print("   канал подачи насыщается на %.0f Гц на нейрон: "
          "`_poisson` делает одно испытание Бернулли на шаг 0,1 мс. "
          "Срез явный, и сколько нейронов он задел — в таблице"
          % (1000.0 / DT), flush=True)
    print("   %10s %8s %8s %8s %8s %8s %9s %10s %9s"
          % ("усиление", "T4", "T5", "LC4", "LPLC2", "DNp01", "мозг",
             "структуре", "срезано"), flush=True)
    for u in СЕТКА:
        a, _ = прогон(H.ГРАНИЦА_T4T5, "движение вперёд", край,
                      усиление=u)
        b, _ = прогон(H.ГРАНИЦА_T4T5, "перетасованное назначение",
                      край, усиление=u)
        стр = {нм: round(a[нм] - b[нм], 4) for нм in ЗАМЕР}
        разв[u] = {"движение вперёд": a, "перетасованное": b,
                   "структуре принадлежит": стр}
        с = a["срез канала подачи"]
        print("   %10.0f %8.3f %8.3f %8.3f %8.3f %8.2f %9.3f %10s %9s"
              % (u, a["T4"], a["T5"], a["LC4"], a["LPLC2"], a["DNp01"],
                 a["__мозг__"], "LC4 %+.3f" % стр["LC4"],
                 "%d/%d" % (с["срезано"], с["всего"])), flush=True)
    rep["замеры"]["развёртка усиления, граница T4/T5"] = {
        str(k): v for k, v in разв.items()}

    дошло = [u for u in СЕТКА
             if разв[u]["движение вперёд"]["LPLC2"] > 0.01
             or разв[u]["движение вперёд"]["LC4"] > 0.01]
    выжило = [u for u in дошло
              if max(разв[u]["структуре принадлежит"][нм]
                     for нм in ("LC4", "LPLC2")) > 0.01]
    check("какое усиление переходника нужно, чтобы отклик дошёл до "
          "проекционных популяций — и выживает ли он на перетасовке",
          True,
          ("дошло при усилении %s Гц (LC4 или LPLC2 выше 0,01 Гц); из "
           "них на перетасовке назначения выжило при %s"
           % (дошло, выжило or "НИ ОДНОМ")) if дошло else
          ("НЕ дошло ни при одном усилении из %s: LC4 и LPLC2 нигде не "
           "дают больше 0,01 Гц. Требование VISION_DEEP §2 — 48,8 Гц "
           "на T4 — переходник при этих усилениях не выполняет, потому "
           "что сам выход детектора движения на краю редок: он даёт "
           "всплеск только там, где край прямо сейчас проходит"
           % list(СЕТКА)))

    # =================================================================
    # Решающий контроль: перетасовка РАСПРЕДЕЛЕНИЕМ, как у физиологии
    # =================================================================
    #
    # Это требование симметрии, а не придирка. Утверждение
    # физиологического режима о структуре было ОТКЛОНЕНО именно
    # распределением по шести зёрнам (`probe/vision_phys_control.py`):
    # одна перетасовка показывала прибавку, распределение её съело.
    # Принять утверждение переходника на одном зерне после этого
    # нельзя — мерить надо тем же.
    U = 2000.0        # рабочая точка: до насыщения канала подачи
    print("\nРешающий контроль переходника: перетасовка назначения по "
          "%d зёрнам при усилении %.0f Гц" % (6, U), flush=True)
    наст, _ = прогон(H.ГРАНИЦА_T4T5, "движение вперёд", край,
                     усиление=U)
    ряды = []
    for зерно in range(6):
        g2 = np.random.default_rng(100 + зерно)
        тас = {t: g2.permutation(места[t]) for t in места}
        пер = H.Переходник(pos, граница=H.ГРАНИЦА_T4T5,
                           кадр_мс=кадр_мс, усиление_hz=U)
        drv = V.Привод.собрать(W, neurons, pops, maps,
                               режим=V.РЕЖИМ_ГИБРИД, граница=ПОДТИПЫ,
                               dev=dev, seed=0, snap=snap)
        acc = torch.zeros(n, device=dev)
        for s in range(STEPS):
            if s % every == 0:
                сиг, _ = пер.сигнал(край(s), места=тас)
                drv.подать_границу(сиг)
            drv.шаг()
            acc.add_(drv.eng.spikes[0])
        if dev == "cuda":
            torch.cuda.synchronize()
        ряды.append(свод(acc))
        del drv
        print("   зерно %d: " % зерно + "  ".join(
            "%s %8.3f" % (нм, ряды[-1][нм]) for нм in ЗАМЕР), flush=True)
    print("   НАСТОЯЩЕЕ: " + "  ".join(
        "%s %8.3f" % (нм, наст[нм]) for нм in ЗАМЕР), flush=True)

    расп = {}
    for нм in ЗАМЕР:
        v = np.array([r[нм] for r in ряды], dtype=float)
        m, sd = float(v.mean()), float(v.std(ddof=1))
        расп[нм] = {
            "настоящее, Гц": наст[нм],
            "перетасовки: среднее, Гц": round(m, 4),
            "перетасовки: СО, Гц": round(sd, 4),
            "перетасовки: размах, Гц": [round(float(v.min()), 4),
                                        round(float(v.max()), 4)],
            "z": (round((наст[нм] - m) / sd, 2) if sd > 1e-9 else None),
            "выше всего размаха": bool(наст[нм] > v.max()),
        }
    rep["замеры"]["переходник: перетасовка распределением"] = расп
    print("\n   %-7s %10s %10s %9s %7s %8s"
          % ("", "настоящее", "тасовки", "СО", "z", "выше всех"),
          flush=True)
    for нм in ЗАМЕР:
        d = расп[нм]
        print("   %-7s %10.3f %10.3f %9.3f %7s %8s"
              % (нм, d["настоящее, Гц"], d["перетасовки: среднее, Гц"],
                 d["перетасовки: СО, Гц"],
                 "—" if d["z"] is None else "%.2f" % d["z"],
                 "да" if d["выше всего размаха"] else "нет"), flush=True)

    выжили = [нм for нм in ЗАМЕР
              if расп[нм]["выше всего размаха"]
              and расп[нм]["z"] is not None and расп[нм]["z"] > 2.0]
    check("выживает ли структурная зависимость отклика ЗА границей над "
          "распределением перетасовок — тем же замером, которым "
          "отклонено утверждение физиологического режима",
          True,
          ("выжили: %s. " % выжили + "; ".join(
              "%s настоящее %.3f Гц против перетасовок %.3f ± %.3f "
              "(размах %.3f…%.3f), z = %.2f"
              % (нм, расп[нм]["настоящее, Гц"],
                 расп[нм]["перетасовки: среднее, Гц"],
                 расп[нм]["перетасовки: СО, Гц"],
                 расп[нм]["перетасовки: размах, Гц"][0],
                 расп[нм]["перетасовки: размах, Гц"][1], расп[нм]["z"])
              for нм in выжили)
           + ". Суммарный вход совпадает побитово, значит это "
             "принадлежит пространственной картине подачи и настоящим "
             "связям за границей") if выжили else
          ("НЕ выжил ни один: " + "; ".join(
              "%s %.3f против размаха %.3f…%.3f"
              % (нм, расп[нм]["настоящее, Гц"],
                 расп[нм]["перетасовки: размах, Гц"][0],
                 расп[нм]["перетасовки: размах, Гц"][1])
              for нм in ЗАМЕР)))

    rep["замеры"]["секунд на пробу"] = round(time.perf_counter() - t0, 1)
    (OUT / "vision_hybrid.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nпроверок %d, провалов %d, за %.0f с"
          % (len(rep["проверки"]), len(fails),
             time.perf_counter() - t0), flush=True)
    if fails:
        print("ПРОВАЛЫ: " + "; ".join(fails), flush=True)
    return 1 if fails else 0


