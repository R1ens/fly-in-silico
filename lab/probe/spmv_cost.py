"""Чего стоит откат умолчания на эталонную дорогу — на полном контуре.

Зачем отдельная проба. Событийное умножение связей выведено из приёмки
выпуска: причина единичного `CUDA illegal memory access` не названа
(`KERNEL_FAULT.md`, `FULL_LOOP_VALIDATION.md` §8.2), и умолчание
переведено на эталонную дорогу. Цена этого отката обязана быть
замеренной, а не оценённой: раздел 5 `FULL_LOOP_VALIDATION.md` называет
179,28 мс на шаг управления, и это число снято С событийным ядром.
Писать его как число выпуска, когда выпуск идёт эталонной дорогой, было
бы подлогом.

Меряется ТОЛЬКО одна разница — `spmv`. Всё прочее у обеих ветвей
одинаково: та же длина, то же семя, тот же съём, тот же контроллер
походки, та же обвязка MuJoCo. Поэтому снятое отношение — вклад дороги
умножения внутри настоящего встроенного контура, а не микробенчмарк
умножения.

Почему перемежающимися парами в ОДНОМ процессе. Замерено независимым
стендом: десять эпизодов одной конфигурации с одним семенем дают
побитово одну траекторию при медиане шага 464,91…643,69 мс, то есть
разброс в 1,385 раза. Отношение, снятое двумя отдельными прогонами, на
таком фоне не значит ничего. Поэтому круги чередуются, отношение
считается ВНУТРИ пары, в итог идёт медиана с размахом и числом пар.

Равенство проверяется в том же прогоне, а не отдельно: дороги объявлены
побитово равнозначными, значит обе ветви ОБЯЗАНЫ дать один отпечаток
траектории, активности, растра и позы. Если не дали — ускорение считать
не за что, и проба отказывает.

Записанная дорога сверяется у КАЖДОГО эпизода: `timing` берёт её у
движка, а не у настройки, поэтому подмена дороги видна. Без этой сверки
проба мерила бы одно и то же дважды и показывала отношение около
единицы, не заметив, что событийная ветвь не включилась.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\spmv_cost.py --пар 6
    ..\\.venv\\Scripts\\python.exe probe\\spmv_cost.py --пар 2 --длина 0.6

Коды: 0 — равенство и запись дороги сошлись; 1 — есть провал.
"""

import argparse
import hashlib
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent

fails = []
rep = {"проверки": {}, "пары": [], "ветви": {}}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""))
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def fp(a):
    return hashlib.sha256(np.ascontiguousarray(a).tobytes()).hexdigest()[:16]


def эпизод(дорога, длина, neurons, weights, device):
    """Один эпизод полного контура заданной дорогой умножения."""
    from flybrain import body as B

    cfg = B.BodyConfig(duration_s=длина, control_ms=20.0, seed=0,
                       device=device, readout="ALPN", spmv=дорога)
    t0 = time.perf_counter()
    run = B.run_episode(cfg=cfg, neurons=neurons, weights=weights,
                        progress=False)
    wall = time.perf_counter() - t0
    recs = run.records
    cols = ("x", "y", "theta", "odour_l", "odour_r", "dn_l", "dn_r",
            "amp_l", "amp_r", "dist", "grad_cos", "spikes")
    table = np.array([[r[c] for c in cols] for r in recs], dtype=np.float64)
    t = run.timing or {}
    return {
        "по стене, с": round(wall, 3),
        "счёт, с": t.get("sim_s"),
        "шагов": len(recs),
        "мс на шаг управления": (round(1000.0 * t["sim_s"] / len(recs), 2)
                                 if t.get("sim_s") and recs else None),
        "доля реального времени": t.get("realtime_ratio"),
        "траектория": fp(table[:, :3]),
        "активность": fp(run.counts),
        "всё по шагам": fp(table),
        "растр": fp(run.bins),
        "конец": ([round(float(recs[-1]["x"]), 4),
                   round(float(recs[-1]["y"]), 4),
                   round(float(recs[-1]["theta"]), 4)] if recs else None),
        # Что ЗАПИСАНО движком, а не что просили. Ключ — тот же, что
        # кладёт `Engine.spmv_info`, и взят у неё, а не по памяти.
        "записанная дорога": t.get("умножение связей"),
        "побитовое равенство обеспечено": t.get(
            "побитовое равенство обеспечено"),
        "ядро собрано": "сборка ядра" in t,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--пар", type=int, default=6)
    ap.add_argument("--длина", type=float, default=2.0)
    a = ap.parse_args()

    import torch
    from flybrain import data as D, sim

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print("— чего стоит откат на эталонную дорогу —")
    print("  устройство %s, пар %d, эпизод %.1f с модельного"
          % (device, a.пар, a.длина))
    print("  умолчание сейчас: %s" % sim.SPMV_DEFAULT)
    rep["умолчание"] = sim.SPMV_DEFAULT
    neurons = D.load_neurons()
    weights = D.load_weights(device=device)

    отн, эт, соб = [], [], []
    for i in range(a.пар):
        # Порядок внутри пары чередуется: ползущий фон не ложится всё
        # время на одну и ту же ветвь.
        if i % 2 == 0:
            e = эпизод(sim.SPMV_CSR, a.длина, neurons, weights, device)
            s = эпизод(sim.SPMV_EVENT, a.длина, neurons, weights, device)
        else:
            s = эпизод(sim.SPMV_EVENT, a.длина, neurons, weights, device)
            e = эпизод(sim.SPMV_CSR, a.длина, neurons, weights, device)
        if not e["счёт, с"] or not s["счёт, с"]:
            print("  пара %d: нет sim_s, пропущена" % (i + 1))
            continue
        r = e["счёт, с"] / s["счёт, с"]
        отн.append(r)
        эт.append(e)
        соб.append(s)
        rep["пары"].append({
            "пара": i + 1,
            "первой шла": "эталонная" if i % 2 == 0 else "событийная",
            "эталонная, мс на шаг": e["мс на шаг управления"],
            "событийная, мс на шаг": s["мс на шаг управления"],
            "отношение": round(r, 4),
        })
        print("  пара %d: эталонная %s мс, событийная %s мс — в %.3f раза"
              % (i + 1, e["мс на шаг управления"],
                 s["мс на шаг управления"], r))
        # Равенство — на КАЖДОЙ паре, а не на последней.
        for поле in ("траектория", "активность", "всё по шагам", "растр",
                     "конец"):
            check("пара %d, %s совпало" % (i + 1, поле),
                  e[поле] == s[поле], "%s / %s" % (e[поле], s[поле]))
        # Дорога — у каждой ветви своя, и записана та, что считала.
        check("пара %d: эталонная ветвь записана эталонной" % (i + 1),
              e["записанная дорога"] == sim.SPMV_CSR,
              e["записанная дорога"])
        check("пара %d: событийная ветвь записана событийной" % (i + 1),
              s["записанная дорога"] == sim.SPMV_EVENT,
              s["записанная дорога"])
        # Записи имени мало: имя могло бы попасть в отчёт при
        # неподнятом ядре. Сверяется и наличие блока сборки ядра —
        # он пишется только когда ядро действительно собрано.
        check("пара %d: у событийной ветви ядро собрано" % (i + 1),
              s["ядро собрано"], s["ядро собрано"])
        check("пара %d: у эталонной ветви ядра нет" % (i + 1),
              not e["ядро собрано"], e["ядро собрано"])

    if not отн:
        print("ни одной пары не снято")
        return 1

    med = statistics.median(отн)
    rep["итог"] = {
        "пар": len(отн),
        "медиана отношения": round(med, 4),
        "мин": round(min(отн), 4),
        "макс": round(max(отн), 4),
        "СО": round(statistics.stdev(отн), 4) if len(отн) > 1 else None,
        "эталонная, медиана мс на шаг": statistics.median(
            [x["мс на шаг управления"] for x in эт]),
        "событийная, медиана мс на шаг": statistics.median(
            [x["мс на шаг управления"] for x in соб]),
        "эталонная, медиана доли реального времени": statistics.median(
            [x["доля реального времени"] for x in эт]),
        "событийная, медиана доли реального времени": statistics.median(
            [x["доля реального времени"] for x in соб]),
    }
    rep["ветви"] = {"эталонная": эт[-1], "событийная": соб[-1]}

    print()
    print("  пар %d, медиана отношения %.4f (размах %.4f…%.4f)"
          % (len(отн), med, min(отн), max(отн)))
    print("  эталонная %.2f мс на шаг, событийная %.2f мс"
          % (rep["итог"]["эталонная, медиана мс на шаг"],
             rep["итог"]["событийная, медиана мс на шаг"]))
    print("  доля реального времени: эталонная %.4f, событийная %.4f"
          % (rep["итог"]["эталонная, медиана доли реального времени"],
             rep["итог"]["событийная, медиана доли реального времени"]))
    # Порог доверия назван ЗАРАНЕЕ и не подгоняется под итог: ниже 1,45
    # на малом числе пар отношение полного контура от фона неотличимо
    # (замер стенда — десять одинаковых эпизодов, разброс ×1,385).
    print("  порог доверия к отношению полного контура: 1,45 "
          "(ниже — от фона неотличимо)")
    rep["итог"]["порог доверия"] = 1.45
    rep["итог"]["выше порога"] = bool(med >= 1.45)

    (OUT / "spmv_cost.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print()
    if fails:
        print("ПРОВАЛЫ: %s" % ", ".join(fails))
        return 1
    print("равенство и запись дороги сошлись на всех парах")
    return 0


if __name__ == "__main__":
    sys.exit(main())
