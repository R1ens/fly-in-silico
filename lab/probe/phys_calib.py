"""Калибровка градуальной передачи: можно ли её сделать, не правя движок.

Это первая проба `physiological_visual`, и она не про зрение. Она
отвечает на один механический вопрос, от которого зависит всё
остальное: **можно ли заставить нейрон отдавать непрерывный поток
медиатора вместо спайков, ничем не тронув `sim.py`?**

Замысел. В `Engine._core` тензор `self.spikes` — это `float32`, и в
начале шага он идёт в матричное умножение `W @ (spikes * m_out)`, а
перезаписывается порогом только в КОНЦЕ того же шага. Значит, если
между шагами положить в `spikes` не 0/1, а дробное значение `s`,
то получатели получат в проводимость ровно `wScale · связей · s`, а сам
нейрон-отправитель от этого не пострадает: его рефрактерность, сброс
мембраны и обнуление собственной проводимости считаются по ДРУГОМУ,
пороговому, значению, полученному позже в том же шаге.

Что проверяется, и каждая проверка умеет провалиться:

1. **порядок внутри шага** — дробное значение в `spikes` действительно
   доходит до получателя (а не затирается до умножения);
2. **цена дробного значения в милливольтах** — установившаяся
   проводимость получателя обязана равняться `wScale · N · s · tauSyn /
   DT`. Это встречный счёт по тому же разностному уравнению: ошибка в
   реализации или в счёте разошлась бы;
3. **равнозначность частоте** — `s = r · DT/1000` обязано давать ту же
   установившуюся проводимость, что пуассоновский поток частотой `r`.
   Тогда «равнозначная частота» градуального нейрона сравнима с
   герцами всех прежних таблиц напрямую, а не по смыслу;
4. **отправитель не ломается** — при `m_fire = 0` градуальный нейрон не
   выдаёт порогового спайка, не сбрасывает мембрану и не обнуляет
   собственную проводимость, то есть ведёт себя как неспайковая клетка;
5. **побитовая неизменность эталона** — при `s = 0/1` и всех масках в
   единице шаг обязан дать ПОБИТОВО то же, что обычный шаг. Если бы не
   дал, вся затея трогала бы эталонный режим, а это запрещено.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\phys_calib.py
"""

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent

fails = []
rep = {"проверки": {}, "замеры": {}, "находки": []}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""), flush=True)
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def note(text):
    print("  НАХОДКА " + text, flush=True)
    rep["находки"].append(text)


def main():
    t0 = time.perf_counter()
    print("Градуальная передача: калибровка механики", flush=True)
    import torch

    from flybrain import sim

    dev = "cuda" if torch.cuda.is_available() else "cpu"
    p = dict(sim.MODEL_PARAMS)
    DT = sim.DT
    w_scale = p["wScale"]
    tau_syn = p["tauSyn"]
    tau_mem = p["tauMem"]
    v_rest = p["vRest"]
    thr_over_rest = p["vThreshold"] - p["vRest"]

    # Крошечная сеть: нейрон 0 отправляет на нейрон 1 через N связей.
    # Матрица плотная по виду, но это те же единицы измерения, что и в
    # большой: значение элемента — ЧИСЛО связей.
    N_SYN = 100.0
    n = 2
    W = torch.zeros(n, n, device=dev)
    W[1, 0] = N_SYN

    rep["замеры"]["устройство"] = {
        "устройство": dev, "шаг, мс": DT, "wScale, мВ": w_scale,
        "tauSyn, мс": tau_syn, "tauMem, мс": tau_mem,
        "порог над покоем, мВ": thr_over_rest,
        "связей в пробе": N_SYN,
    }

    def fresh(no_refractory=None):
        return sim.Engine(W, n, params=p, device=dev, seed=0,
                          no_refractory=no_refractory,
                          spmv=sim.SPMV_CSR)

    zero = torch.zeros(1, n, device=dev)

    # --- 1. доходит ли дробное значение до получателя ------------------
    #
    # Отправитель замолчан по порогу (m_fire = 0), и единственное, что он
    # отдаёт, — то, что мы положили в `spikes` руками. Если порядок
    # внутри шага не тот, что прочитан, получатель не получит ничего.
    # Значение берётся ПОДПОРОГОВЫМ нарочно, и первая редакция пробы на
    # этом провалилась — провал оказался содержательным и его стоит
    # записать. При s = 0,01 (равнозначно 100 Гц через 100 связей, то
    # есть 10 000 связей·Гц против порога 5091) получатель САМ начинает
    # спайкать, а шаг обнуляет проводимость спайкнувшего нейрона
    # (`conductance_new - conductance_new * spikes`). Установившегося
    # режима тогда не бывает вовсе: проводимость пилит от нуля до
    # порога, и встречный счёт разошёлся в 1,83 раза. Проверка умела
    # провалиться и провалилась — значит она не пустая.
    S = 0.002                    # равнозначно 20 Гц → 2000 связей·Гц
    STEPS = 4000                 # 400 мс — заведомо больше 5·tauMem
    eng = fresh()
    eng.m_fire[0, 0] = 0.0
    g_trace = np.zeros(STEPS, dtype=np.float64)
    v_trace = np.zeros(STEPS, dtype=np.float64)
    nsp_rcv = 0
    for s in range(STEPS):
        eng.spikes[0, 0] = S
        sp = eng.step(zero)
        nsp_rcv += int(float(sp[0, 1]))
        g_trace[s] = float(eng.conductance[0, 1])
        v_trace[s] = float(eng.v[0, 1]) - v_rest
    g_ss = float(g_trace[-1])
    v_ss = float(v_trace[-1])

    check("получатель остался подпороговым — иначе установившегося "
          "режима не бывает и встречный счёт нечему сверять",
          nsp_rcv == 0,
          "спайков получателя %d за %d шагов; проводимость %.4f мВ "
          "против порога %.1f мВ. Первая редакция пробы брала s = 0,01 "
          "(10 000 связей·Гц), получатель спайкал, шаг обнулял его "
          "проводимость — и встречный счёт разошёлся в 1,83 раза"
          % (nsp_rcv, STEPS, g_ss, thr_over_rest))

    check("дробное значение в `spikes` доходит до получателя в "
          "проводимость — порядок внутри шага такой, как прочитан",
          g_ss > 1e-9,
          "при s = %g через %d связей установившаяся проводимость "
          "получателя %.6f мВ. Если бы `spikes` затирался порогом ДО "
          "матричного умножения, здесь стоял бы ноль" % (S, N_SYN, g_ss))

    # --- 2. встречный счёт цены дробного значения ----------------------
    g_want = w_scale * N_SYN * S * tau_syn / DT
    err = abs(g_ss - g_want) / max(g_want, 1e-12)
    check("установившаяся проводимость совпала со счётом по тому же "
          "разностному уравнению — встречный счёт, а не доверие коду",
          err < 1e-4,
          "замерено %.6f мВ, посчитано wScale·N·s·tauSyn/DT = "
          "%.6f·%g·%g·%g/%g = %.6f мВ, расхождение %.2e"
          % (g_ss, w_scale, N_SYN, S, tau_syn, DT, g_want, err))

    check("установившаяся мембрана равна установившейся проводимости — "
          "значит проводимость в мВ сравнима с порогом напрямую",
          abs(v_ss - g_ss) / max(g_ss, 1e-12) < 1e-3,
          "мембрана над покоем %.6f мВ против проводимости %.6f мВ "
          "(расхождение %.2e). Отсюда и порог: %g мВ проводимости"
          % (v_ss, g_ss, abs(v_ss - g_ss) / max(g_ss, 1e-12),
             thr_over_rest))

    # --- 3. равнозначная частота --------------------------------------
    #
    # Это то, что делает все числа градуального режима сравнимыми с
    # герцами прежних таблиц: `s = r·DT/1000` обязано давать ту же
    # установившуюся проводимость, что пуассоновский поток частотой `r`.
    R_EQ = S * 1000.0 / DT        # равнозначная частота для нашего s
    # Порог в связях·герцах — то самое число 5090,9 из VISION_DEEP §1,
    # посчитанное здесь заново из уравнения.
    thr_syn_hz = thr_over_rest / (w_scale * tau_syn * 1e-3)
    check("порог в связях·герцах посчитан заново и совпал с 5090,9 из "
          "VISION_DEEP §1",
          abs(thr_syn_hz - 5090.9) < 1.0,
          "порог/(wScale·tauSyn) = %.3f/(%.3f·%.3f мс) = %.1f связей·Гц"
          % (thr_over_rest, w_scale, tau_syn, thr_syn_hz))
    rep["замеры"]["порог, связей·Гц"] = round(thr_syn_hz, 2)
    rep["замеры"]["равнозначная частота пробы, Гц"] = R_EQ

    # Пуассоновский поток той же частоты — через настоящий спайкующий
    # нейрон. Отправитель гонится входом так, чтобы спайкать с частотой
    # R_EQ; проще и чище — подать спайки руками как 0/1 по Бернулли с
    # вероятностью R_EQ·DT/1000.
    POIS_STEPS = 15000            # 1,5 с: заведомо больше 100·tauSyn
    skip = POIS_STEPS // 10

    def flow(s_val, poisson, seed, mute_rcv=False):
        """Один поток: градуальный (ровный) или пуассоновский (рваный).

        Возвращает среднюю проводимость получателя, его спайки и
        замеренную частоту отправителя. Отправитель замолчан по порогу,
        поэтому отдаёт ровно то, что мы положили в `spikes`.

        ``mute_rcv`` замалчивает и ПОЛУЧАТЕЛЯ. Это нужно ровно для
        одного: сравнить ядро проводимости и ничего кроме. Спайк
        получателя обнуляет его собственную проводимость
        (`conductance_new - conductance_new * spikes`), и без
        замалчивания сравнение средних мерило бы не ядро, а то, как
        часто получатель спайкнул. На этом первая редакция пробы и
        разошлась на 11,6 %.
        """
        e = fresh()
        e.m_fire[0, 0] = 0.0
        if mute_rcv:
            e.m_fire[0, 1] = 0.0
        if poisson:
            g = np.random.default_rng(seed)
            seq = (g.random(POIS_STEPS) < s_val).astype(np.float32)
        else:
            seq = np.full(POIS_STEPS, s_val, dtype=np.float32)
        acc, nspk, vmx = 0.0, 0, -1e9
        for i in range(POIS_STEPS):
            e.spikes[0, 0] = float(seq[i])
            sp = e.step(zero)
            if i >= skip:
                acc += float(e.conductance[0, 1])
                nspk += int(float(sp[0, 1]))
                vmx = max(vmx, float(e.v[0, 1]) - v_rest)
        # Частота отправителя считается ПО ТОМУ ЖЕ окну, по которому
        # усреднена проводимость. Иначе сравнивать нечего: при 23
        # событиях за прогон частота по всему прогону и по окну
        # расходятся на проценты, и расхождение приписалось бы режиму.
        win = seq[skip:]
        hz = float(win.sum()) * 1000.0 / (len(win) * DT)
        return (acc / (POIS_STEPS - skip), nspk, hz, vmx)

    # Поток берётся заведомо далёким от порога: 1000 связей·Гц против
    # 5091, то есть 1,375 мВ против 7,0. Иначе сравнивать средние
    # нельзя — см. следующую проверку, где это и показано замером.
    # Поток берётся ВЫСОКИМ (500 Гц равнозначно), а не слабым: при
    # замолчанном получателе спайков всё равно нет, зато событий в
    # окне 675 вместо 18, и собственный разброс выборки падает с 20 %
    # до 4 %. Сравнивать средние со разбросом больше расхождения
    # значило бы проверять ничем.
    S_LOW = 0.05                       # равнозначно 500 Гц
    g_lo_grad, sp_lo_grad, hz_lo_grad, _ = flow(S_LOW, False, 0,
                                                mute_rcv=True)
    # Пуассоновский путь усредняется по ВОСЬМИ зёрнам: при ~18 событиях
    # в окне одна выборка имеет собственный разброс около 20 %, и
    # сравнивать с ней было бы нечестно. Приведение к одной частоте
    # обязательно: реализованная частота от просимой отличается на
    # проценты, и без приведения это расхождение приписалось бы режиму.
    rows, sp_lo_pois = [], 0
    for sd in range(4):
        g_p, sp_p, hz_p, _ = flow(S_LOW, True, 100 + sd, mute_rcv=True)
        sp_lo_pois += sp_p
        if hz_p > 0:
            rows.append(g_p * (hz_lo_grad / hz_p))
    g_lo_pois_sc = float(np.mean(rows))
    sd_lo = float(np.std(rows))
    err2 = abs(g_lo_pois_sc - g_lo_grad) / max(g_lo_grad, 1e-12)
    check("градуальный поток и пуассоновский той же частоты дают одну и "
          "ту же СРЕДНЮЮ проводимость — значит «равнозначная частота» "
          "сравнима с герцами прежних таблиц напрямую",
          err2 < 0.03,
          "градуально %.6f мВ при %.3f Гц; пуассоновски по 4 зёрнам, "
          "приведённым к той же частоте, %.6f ± %.6f мВ; расхождение "
          "%.2f %% при собственном разбросе выборок %.1f %%. Получатель "
          "в обоих условиях замолчан (`m_fire = 0`), иначе сравнение "
          "мерило бы не ядро проводимости, а частоту его спайков — на "
          "этом первая редакция пробы и разошлась на 11,6 %%"
          % (g_lo_grad, hz_lo_grad, g_lo_pois_sc, sd_lo, 100 * err2,
             100 * sd_lo / max(g_lo_pois_sc, 1e-12)))

    # --- 3а. а вот чем они РАЗЛИЧАЮТСЯ, и это против градуальности ----
    #
    # Это надо замерить и назвать, потому что оно работает ПРОТИВ той
    # гипотезы, которую проба готовит. У подпорогового среднего
    # пуассоновский поток всё равно даёт спайки — колебаниями, — а
    # ровный градуальный не даёт ни одного. То есть шум помогает
    # подпороговой клетке, и градуальная передача этот костыль убирает.
    S_NEAR = 0.002                     # 2000 связей·Гц → 2,75 мВ из 7,0
    g_nr_grad, sp_nr_grad, hz_nr_grad, v_nr_grad = flow(S_NEAR, False, 0)
    g_nr_pois, sp_nr_pois, hz_nr_pois, v_nr_pois = flow(S_NEAR, True, 0)
    check("шум пуассоновского потока САМ даёт спайки там, где ровный "
          "градуальный не даёт ни одного — проверка, работающая против "
          "градуальной гипотезы, и она не скрыта",
          sp_nr_pois > 0 and sp_nr_grad == 0,
          "при одном и том же среднем (%.2f мВ из порога %.1f) "
          "пуассоновский поток дал получателю %d спайков и довёл "
          "мембрану до %.4f мВ, градуальный — %d спайков и %.4f мВ. "
          "Значит у подпороговой клетки шум — это костыль, и "
          "градуальная передача его УБИРАЕТ: часть её выигрыша уходит "
          "на возмещение потерянного шума"
          % (g_nr_grad, thr_over_rest, sp_nr_pois, v_nr_pois,
             sp_nr_grad, v_nr_grad))
    rep["замеры"]["шум против ровности"] = {
        "среднее, мВ": round(g_nr_grad, 4),
        "порог, мВ": thr_over_rest,
        "спайков: пуассоновски": sp_nr_pois,
        "спайков: градуально": sp_nr_grad,
        "пик мембраны: пуассоновски, мВ": round(v_nr_pois, 4),
        "пик мембраны: градуально, мВ": round(v_nr_grad, 4),
    }
    note("замер, работающий против градуальной гипотезы: при среднем "
         "%.2f мВ из порога %.1f пуассоновский поток даёт %d спайков, "
         "градуальный — ни одного. Шум подпороговую клетку ВЫРУЧАЕТ, и "
         "градуальный режим этой выручки лишается. Значит ×6,32 — "
         "верхняя оценка выигрыша, а не чистая прибавка"
         % (g_nr_grad, thr_over_rest, sp_nr_pois))
    rate_pois, g_pois = hz_lo_grad, g_lo_pois_sc

    # --- 4. чем градуальный режим ОТЛИЧАЕТСЯ от пуассоновского --------
    #
    # Средние совпали — а блокер держит не среднее, а пик. Градуальный
    # поток ровный, пуассоновский рваный: при одинаковом среднем у
    # пуассоновского мембрана гуляет. Это и надо замерить, иначе
    # «градуально» было бы пустым словом.
    v_grad_sd = float(np.std(v_trace[STEPS // 2:]))
    rep["замеры"]["мембрана получателя"] = {
        "градуально: среднее, мВ": round(v_ss, 6),
        "градуально: СО, мВ": float("%.3e" % v_grad_sd),
        "градуально: пик при 2000 связей·Гц, мВ": round(v_nr_grad, 4),
        "пуассоновски: пик при 2000 связей·Гц, мВ": round(v_nr_pois, 4),
    }

    # --- 5. отправитель остался неспайковым ---------------------------
    #
    # Градуальная клетка не должна сбрасывать мембрану по порогу. При
    # m_fire = 0 порог её не сбрасывает — и это надо замерить, а не
    # предположить: иначе «градуальность» держалась бы на вере в чтение
    # исходника.
    eng4 = fresh()
    eng4.m_fire[0, 0] = 0.0
    W2 = torch.zeros(n, n, device=dev)
    W2[0, 0] = 400.0            # сам на себя, чтобы погнать за порог
    eng5 = sim.Engine(W2, n, params=p, device=dev, seed=0,
                      spmv=sim.SPMV_CSR)
    eng5.m_fire[0, 0] = 0.0
    drive = torch.zeros(1, n, device=dev)
    drive[0, 0] = 400.0          # пуассоновский вход в мембрану
    vmax = -1e9
    nsp5 = 0
    for s in range(3000):
        sp = eng5.step(drive)
        nsp5 += int(float(sp[0, 0]))
        vmax = max(vmax, float(eng5.v[0, 0]) - v_rest)
    check("при `m_fire = 0` клетка не выдаёт порогового спайка и не "
          "сбрасывает мембрану — ведёт себя как неспайковая",
          nsp5 == 0 and vmax > thr_over_rest,
          "спайков %d за 3000 шагов при мембране до %.2f мВ над покоем "
          "(порог %.1f). Мембрана ушла за порог и осталась там — именно "
          "это и значит «градуальная клетка»" % (nsp5, vmax,
                                                 thr_over_rest))

    # --- 6. эталон не тронут: побитовая проверка ----------------------
    #
    # Самое важное для владельца. Если положить в `spikes` ровно то, что
    # туда положил бы порог, и оставить все маски в единице, шаг обязан
    # дать ПОБИТОВО то же состояние, что обычный шаг. Это и значит
    # «эталонный режим не тронут ни одной строкой».
    W3 = torch.zeros(n, n, device=dev)
    W3[1, 0] = N_SYN
    W3[0, 1] = N_SYN
    ref = sim.Engine(W3, n, params=p, device=dev, seed=0,
                     spmv=sim.SPMV_CSR)
    alt = sim.Engine(W3, n, params=p, device=dev, seed=0,
                     spmv=sim.SPMV_CSR)
    d2 = torch.zeros(1, n, device=dev)
    d2[0, 0] = 300.0
    same = True
    for s in range(2000):
        ref.step(d2)
        # то же самое, но со ВМЕШАТЕЛЬСТВОМ, которое ничего не меняет:
        # кладём в spikes его собственное значение
        alt.spikes.copy_(alt.spikes)
        alt.step(d2)
        for nm in ("v", "conductance", "spikes", "refrac"):
            if not torch.equal(getattr(ref, nm), getattr(alt, nm)):
                same = False
                break
        if not same:
            break
    check("тождественное вмешательство в `spikes` оставляет состояние "
          "ПОБИТОВО тем же — значит эталонный режим не тронут",
          same,
          "2000 шагов, сверка v, conductance, spikes, refrac на каждом; "
          "расхождений 0. Запись дробного значения — отдельный режим, и "
          "эталон его не видит")

    # --- 7. главное число режима: во сколько раз градуальность дешевле
    #
    # У одиночного всплеска мембрана берёт 0,158 проводимости
    # (VISION_DEEP §1), у ровного потока — 1,0. Это отношение и есть
    # бесплатная часть выигрыша градуальной передачи: она не добавляет
    # ни одной связи и не меняет wScale.
    eng6 = fresh()
    eng6.m_fire[0, 0] = 0.0
    eng6.spikes[0, 0] = 1.0
    peak_v, peak_g = 0.0, 0.0
    for s in range(2000):
        eng6.step(zero)
        peak_v = max(peak_v, float(eng6.v[0, 1]) - v_rest)
        peak_g = max(peak_g, float(eng6.conductance[0, 1]))
        eng6.spikes[0, 0] = 0.0
    took = peak_v / max(peak_g, 1e-12)
    took_flat = v_ss / max(g_ss, 1e-12)
    check("доля всплеска, которую берёт мембрана, воспроизведена: "
          "0,158 у одиночного события против 1,0 у ровного потока",
          abs(took - 0.15822) < 0.005 and abs(took_flat - 1.0) < 0.02,
          "одиночное событие: пик мембраны %.6f мВ при пике "
          "проводимости %.6f мВ, доля %.5f. Ровный поток: %.6f из "
          "%.6f, доля %.5f. Отношение **%.2f** — это и есть та часть "
          "выигрыша градуальной передачи, которая не стоит ни одной "
          "новой связи"
          % (peak_v, peak_g, took, v_ss, g_ss, took_flat,
             took_flat / max(took, 1e-12)))
    rep["замеры"]["мембрана берёт"] = {
        "одиночное событие": round(took, 5),
        "ровный поток": round(took_flat, 5),
        "отношение": round(took_flat / max(took, 1e-12), 3),
    }
    note("бесплатная часть градуальной передачи замерена: **×%.2f**. "
         "Ровный поток доводит мембрану до полной проводимости "
         "(%.4f), одиночный всплеск — до 0,158 её. Ни одной связи и ни "
         "одного множителя веса при этом не добавлено"
         % (took_flat / max(took, 1e-12), took_flat))

    rep["замеры"]["секунд на пробу"] = round(time.perf_counter() - t0, 2)
    (OUT / "phys_calib.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nпроверок %d, провалов %d, за %.1f с"
          % (len(rep["проверки"]), len(fails),
             time.perf_counter() - t0), flush=True)
