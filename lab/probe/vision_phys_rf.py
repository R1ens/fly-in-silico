"""Почему структура не выживает: есть ли у глубоких клеток поле зрения.

`probe/vision_phys_control.py` дал отрицательный результат на решающем
контроле: при полном градуальном наборе LC4 выдаёт 17,644 Гц, а
**перетасованная привязка выдаёт столько же** (16,779…17,740, z = 1,19).
То же у T5, T4, LPLC2 и DNp01. Значит глубокий отклик держится
количеством входа, а не пространственной картиной.

Отсюда вопрос, который решает, чья это беда — физиологии или привязки:
**сходится ли на один глубокий нейрон вход из ОДНОГО места поля
зрения?** Если нет — никакая динамика пространственной
избирательности дать не может, и отрицательный результат принадлежит
привязке, а не режиму.

Замер не требует движка вовсе, и это его достоинство: он мерит
устройство входа, а не отклик.

Как считается. Омматидий есть только у фоторецепторов — он задан
привязкой. Глубже он **наводится** по настоящим связям: место
нейрона-получателя — средневзвешенное по числу синапсов место его
пресинаптических нейронов предыдущего слоя. Слои берутся те, что
`VISION_DEEP.md` §2 назвал главными входами:

    R1-6,R7,R8 → L1,L2,L3,L4 → L5 → Mi1,Tm1,Tm2,Tm3,Tm4,Tm9 → T4,T5 → LC4,LPLC2

Мера — **разброс** мест входа на один нейрон-получатель, в долях
размаха поля зрения. Ноль значит «вход из одной точки», единица —
«вход со всего поля». У клетки с настоящим полем зрения разброс обязан
быть мал.

Встречные замеры, и каждый умеет провалить утверждение:

* **перетасованная привязка** — если разброс у настоящей и
  перетасованной одинаков, привязка не даёт ретинотопии вовсе, и
  отрицательный результат контроля объяснён;
* **положительный контроль на первом слое** — у L1 вход от R1-6 обязан
  быть локальным (это и значит соседство 0,089 из `VISION.md` §1). Если
  и он размазан, значит сломан сам замер, а не привязка;
* **случайные места** — то же вычисление на случайно расставленных
  омматидиях. Даёт разброс, которого стоит ждать при полном отсутствии
  ретинотопии, то есть верхнюю границу.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\vision_phys_rf.py
"""

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent

# Слои наведения: (имя слоя, популяции, от каких слоёв кормится).
# Набор входов взят из замера происхождения `VISION_DEEP.md` §2, а не
# из учебника: главный возбуждающий вход Mi1 — L5, а не L1.
СЛОИ = (
    ("рецепторы", ("R1-6", "R7", "R8"), ()),
    ("ламина", ("L1", "L2", "L3", "L4"), ("рецепторы",)),
    ("L5", ("L5",), ("ламина",)),
    ("медулла", ("Mi1", "Tm1", "Tm2", "Tm3", "Tm4", "Tm9"),
     ("ламина", "L5")),
    ("T4T5", ("T4a", "T4b", "T4c", "T4d",
              "T5a", "T5b", "T5c", "T5d"), ("медулла",)),
    ("проекционные", ("LC4", "LPLC2"), ("T4T5", "медулла")),
)
ПОКАЗАТЬ = ("L1", "L2", "L3", "L5", "Mi1", "Tm9", "T4a", "T5a",
            "LC4", "LPLC2")

fails = []
rep = {"проверки": {}, "замеры": {}, "находки": [], "сорвалось": []}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""), flush=True)
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def note(text):
    print("  НАХОДКА " + text, flush=True)
    rep["находки"].append(text)


def main():
    t0 = time.perf_counter()
    print("Есть ли у глубоких клеток поле зрения", flush=True)
    import scipy.sparse as sp
    import torch

    from flybrain import data as D, retina as R

    neurons = D.load_neurons()
    W = D.load_weights()
    n = len(neurons)
    om = R.ommatidia()
    pos_om = om["pos"]
    размах = float(np.linalg.norm(pos_om.max(0) - pos_om.min(0)))

    # Матрица связей как scipy CSR по ПОСТсинаптическому: нужен обход
    # входов нейрона-получателя, и только возбуждающих — тормозной вход
    # поле зрения не задаёт, а вычитает из него.
    w = W.coalesce()
    idx = w.indices().cpu().numpy()
    val = w.values().cpu().numpy()
    поз = val > 0
    A = sp.csr_matrix((val[поз], (idx[0][поз], idx[1][поз])),
                      shape=(n, n))
    print("  связей всего %d, возбуждающих %d (тормозные поле зрения "
          "не задают)" % (len(val), int(поз.sum())), flush=True)

    типы = {}
    for _, имена, _ in СЛОИ:
        for t in имена:
            типы[t] = D.select(neurons, "celltype=%s" % t)

    def места(maps, случайно=False):
        """Место каждого нейрона в поле зрения, наведённое по связям.

        Возвращает (xy, есть): ``xy`` — координаты в пикселях карты
        омматидиев, ``есть`` — у кого место определилось.
        """
        xy = np.full((n, 2), np.nan)
        p = pos_om
        if случайно:
            g = np.random.default_rng(7)
            p = pos_om[g.permutation(len(pos_om))]
        for key, m in maps.items():
            xy[m.neurons] = p[m.omma]
        слой_инд = {}
        for имя, имена, откуда in СЛОИ:
            idxs = np.unique(np.concatenate([типы[t] for t in имена]))
            слой_инд[имя] = idxs
            if not откуда:
                continue
            источник = np.unique(np.concatenate(
                [слой_инд[o] for o in откуда]))
            # средневзвешенное по числу синапсов место входов
            S = A[idxs][:, источник]
            px = xy[источник, 0]
            py = xy[источник, 1]
            ок = np.isfinite(px)
            S = S[:, ок]
            px, py = px[ок], py[ок]
            вес = np.asarray(S.sum(1)).ravel()
            сх = np.asarray(S @ px).ravel()
            су = np.asarray(S @ py).ravel()
            есть = вес > 0
            xy[idxs[есть], 0] = сх[есть] / вес[есть]
            xy[idxs[есть], 1] = су[есть] / вес[есть]
        return xy, слой_инд

    def разброс(xy, слой_инд):
        """Разброс мест входа на один нейрон-получатель, в долях размаха.

        Для каждого получателя: средневзвешенное расстояние его входов
        от их собственного центра тяжести. Это и есть размер поля
        зрения, если оно есть.
        """
        out = {}
        for имя, имена, откуда in СЛОИ:
            if not откуда:
                continue
            источник = np.unique(np.concatenate(
                [слой_инд[o] for o in откуда]))
            px, py = xy[источник, 0], xy[источник, 1]
            ок = np.isfinite(px)
            источник, px, py = источник[ок], px[ок], py[ок]
            for t in имена:
                idxs = типы[t]
                S = A[idxs][:, источник]
                вес = np.asarray(S.sum(1)).ravel()
                есть = вес > 0
                if not есть.any():
                    continue
                S2 = S[есть]
                w2 = вес[есть]
                cx = np.asarray(S2 @ px).ravel() / w2
                cy = np.asarray(S2 @ py).ravel() / w2
                # средневзвешенное расстояние входов от центра
                d2 = (np.asarray(S2 @ (px ** 2)).ravel() / w2 - cx ** 2
                      + np.asarray(S2 @ (py ** 2)).ravel() / w2 - cy ** 2)
                rms = np.sqrt(np.maximum(d2, 0.0))
                out[t] = {
                    "нейронов с входом": int(есть.sum()),
                    "нейронов всего": int(len(idxs)),
                    "разброс поля, доля размаха":
                        round(float(np.median(rms)) / размах, 4),
                    "партнёров на нейрон, медиана":
                        float(np.median(np.asarray(
                            (S2 > 0).sum(1)).ravel())),
                }
        return out

    maps = R.build_all(neurons, mode="whiten", assign="capacity")
    maps_sh = R.build_all(neurons, mode="whiten", assign="capacity",
                          shuffle=True, seed=0)

    xy_n, сл = места(maps)
    xy_s, _ = места(maps_sh)
    xy_r, _ = места(maps, случайно=True)
    р_наст = разброс(xy_n, сл)
    р_там = разброс(xy_s, сл)
    р_случ = разброс(xy_r, сл)
    rep["замеры"]["размах поля, пикселей"] = round(размах, 2)
    rep["замеры"]["разброс: настоящая привязка"] = р_наст
    rep["замеры"]["разброс: перетасованная"] = р_там
    rep["замеры"]["разброс: случайные места"] = р_случ

    print("\nРазброс мест входа на один нейрон-получатель, в долях "
          "размаха поля зрения (меньше — локальнее)", flush=True)
    print("  %-7s %10s %12s %12s %10s %12s"
          % ("тип", "настоящая", "перетасован", "случайные",
             "партнёров", "нейронов"), flush=True)
    for t in ПОКАЗАТЬ:
        if t not in р_наст:
            continue
        a = р_наст[t]["разброс поля, доля размаха"]
        b = р_там[t]["разброс поля, доля размаха"]
        c = р_случ[t]["разброс поля, доля размаха"]
        print("  %-7s %10.4f %12.4f %12.4f %10.0f %12d"
              % (t, a, b, c, р_наст[t]["партнёров на нейрон, медиана"],
                 р_наст[t]["нейронов с входом"]), flush=True)

    # --- положительный контроль: первый слой обязан быть локальным ---
    l1 = р_наст["L1"]["разброс поля, доля размаха"]
    l1_t = р_там["L1"]["разброс поля, доля размаха"]
    check("положительный контроль: вход L1 от фоторецепторов локален, "
          "а у перетасованной привязки — нет",
          l1 < 0.5 * l1_t,
          "разброс поля L1: настоящая привязка %.4f размаха против "
          "%.4f у перетасованной (в %.1f раза локальнее). Значит замер "
          "умеет отличать ретинотопию от её отсутствия, и нулевой "
          "результат глубже — это результат, а не поломка замера"
          % (l1, l1_t, l1_t / max(l1, 1e-9)))

    # --- главное: что с глубокими -----------------------------------
    строки = []
    for t in ("L1", "L2", "L5", "Mi1", "Tm9", "T4a", "T5a", "LC4",
              "LPLC2"):
        if t not in р_наст:
            continue
        a = р_наст[t]["разброс поля, доля размаха"]
        b = р_там[t]["разброс поля, доля размаха"]
        строки.append((t, a, b, a / max(b, 1e-9)))
    локальные = [t for t, a, b, k in строки if k < 0.7]
    rep["замеры"]["локальнее перетасованной"] = локальные
    check("сохраняется ли локальность входа глубже первого синапса",
          True,
          "локальнее перетасованной (в 1,4 раза и более): %s. "
          "Отношение разброса настоящей к перетасованной по слоям: %s"
          % (локальные or "НИ ОДИН глубже ламины",
             ", ".join("%s %.2f" % (t, k) for t, a, b, k in строки)))

    глуб = [(t, р_наст[t]["разброс поля, доля размаха"],
             р_там[t]["разброс поля, доля размаха"])
            for t in ("T4a", "T5a", "LC4", "LPLC2") if t in р_наст]
    note("поле зрения глубоких клеток при нашей привязке: "
         + "; ".join("%s разброс %.3f размаха против %.3f у "
                     "перетасованной" % (t, a, b) for t, a, b in глуб)
         + ". Там, где отношение близко к единице, вход на нейрон "
           "приходит со ВСЕГО поля, и пространственной "
           "избирательности не может дать никакая динамика — это "
           "предел привязки, а не режима")

    rep["замеры"]["секунд на пробу"] = round(time.perf_counter() - t0, 1)
    (OUT / "vision_phys_rf.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nпроверок %d, провалов %d, за %.0f с"
          % (len(rep["проверки"]), len(fails),
             time.perf_counter() - t0), flush=True)
    if fails:
        print("ПРОВАЛЫ: " + "; ".join(fails), flush=True)
    return 1 if fails else 0


if __name__ == "__main__":
    raise SystemExit(main())
