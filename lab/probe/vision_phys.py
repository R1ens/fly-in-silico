"""Физиологическая зрительная динамика против эталонного LIF.

Проба развёрнутых режимов `flybrain/visdyn.py`. Отвечает на один
вопрос, и отвечает замером: **снимается ли зрительный блокер
физиологически обоснованными средствами, не трогая эталонный режим?**

Что здесь разведено и почему это важно. `VISION_DEEP.md` §10 назвал две
величины, которые держат блокер, и обе принадлежат уравнению движка:
рабочая точка `wScale` 0,275 мВ (первый синапс даёт 45 % порога) и
отношение `tauSyn` 5 мс к `tauMem` 20 мс (мембрана берёт 0,20…0,34
пришедшего всплеска). Умножать веса запрещено. Остаётся второе — и оно
снимается не подкруткой, а **сменой кода передачи** на тот, который у
дрозофилы и есть: фоторецепторы и ламинарные монополярные клетки не
спайкуют вовсе, а отдают медиатор непрерывно.

**Темнота — это раздражитель, а не нейтраль.** У градуальной ламины с
биологическим знаком свет ГИПЕРПОЛЯРИЗУЕТ L1/L2/L3, значит в темноте
они деполяризованы и отдают больше всего. Поэтому «зрение выключено»
здесь — не ноль, а крайнее условие, и одного этого контроля мало.
Нейтраль — **однородное поле той же средней яркости**: входа столько
же, пространственной структуры и движения нет.

Условия, и ни одно не остаётся без встречного замера:

* **выключено** — кадра нет вовсе (полная темнота). Нужно, чтобы
  видеть собственную активность сети;
* **однородный** — однородное поле. Нейтральная база;
* **светлый край** — светлый край по тёмному полю (вход ON-канала);
* **тёмный край** — тёмный край по светлому полю (вход OFF-канала).
  Без него замер мерил бы только одну полярность, а ON и OFF у мухи
  разные пути, и путать их нельзя;
* **перемешано** — светлый край с перемешанной привязкой. Суммарный
  вход совпадает ПОБИТОВО, разрушена только пространственная
  структура. Решающий контроль: он уже отклонил `wScale` ×4 и
  `tauSyn` 20 мс.

Все выборки — точным односотбцовым `celltype=`: `type=` берёт
объединение трёх столбцов и склеивает популяции (`RESEARCH.md` §9).

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\vision_phys.py
"""

