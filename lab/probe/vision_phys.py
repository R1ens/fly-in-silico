DT = 0.1
WARM = 500
STEPS = 2000             # 200 мс модельного времени, как в прежних пробах
VIS_HZ = 100.0           # рабочая точка обновления кадра
CROSS = 2000             # шагов на пересечение поля: 785 °/с, рабочая точка
UNIFORM_L = 0.25         # однородное поле: тот же средний вход, что у края

CHAIN = (
    ("R1-6", ("R1-6",)), ("R7", ("R7",)), ("R8", ("R8",)),
    ("L1", ("L1",)), ("L2", ("L2",)), ("L3", ("L3",)),
    ("L4", ("L4",)), ("L5", ("L5",)),
    ("Mi1", ("Mi1",)), ("Tm1", ("Tm1",)), ("Tm2", ("Tm2",)),
    ("Tm3", ("Tm3",)), ("Tm4", ("Tm4",)), ("Tm9", ("Tm9",)),
    ("T4", ("T4a", "T4b", "T4c", "T4d")),
    ("T5", ("T5a", "T5b", "T5c", "T5d")),
    ("LPLC2", ("LPLC2",)), ("LC4", ("LC4",)), ("DNp01", ("DNp01",)),
)
# Популяции, которые решают вопрос: они и есть «глубже третьего
# синапса», где эталону принадлежит ровно 0,0000.
РЕШАЮЩИЕ = ("Mi1", "Tm9", "T4", "T5", "LC4", "LPLC2", "DNp01")
# Градуальные популяции спайков не выдают вовсе, и их «частота» — это
# равнозначная частота отдачи. Смешивать её с частотой разрядов нельзя.
УСЛОВИЯ = ("выключено", "однородный", "светлый край", "тёмный край",
           "перемешано")

fails = []
rep = {"проверки": {}, "замеры": {}, "находки": [], "сорвалось": []}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""), flush=True)
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def note(text):
    print("  НАХОДКА " + text, flush=True)
    rep["находки"].append(text)


def edge_frame(pos, phase, тёмный=False):
    """Движущийся край в координатах решётки омматидиев.

    ``тёмный=False`` — светлый край по тёмному полю: омматидий
    переходит из темноты в свет (вход ON-канала). ``тёмный=True`` —
    наоборот (вход OFF-канала). Средняя яркость по полю у обеих
    полярностей одна и та же, поэтому сравнивать их законно.
    """
    x = pos[:, 0]
    lo, hi = float(x.min()), float(x.max())
    cut = lo + (hi - lo) * float(phase)
    lit = (x <= cut).astype(np.float32)
    if тёмный:
        lit = 1.0 - lit
    return np.stack([lit, lit], axis=-1)


def flat_frame(level, n=721):
    lit = np.full(n, float(level), dtype=np.float32)
    return np.stack([lit, lit], axis=-1)


def both_eyes(fr):
    return np.stack([fr, fr])


def main():
    t0 = time.perf_counter()
    print("Физиологическая зрительная динамика", flush=True)
    import torch

    from flybrain import data as D, retina as R, sim, visdyn as V

    neurons = D.load_neurons()
    W = D.load_weights()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    n = len(neurons)
    om = R.ommatidia()

    pops, missing = {}, []
    for name, types in CHAIN:
        idx = np.unique(np.concatenate(
            [D.select(neurons, "celltype=%s" % t) for t in types]))
        if not len(idx):
            missing.append(name)
        pops[name] = idx
    if missing:
        raise SystemExit("нет в v783: " + ", ".join(missing))

    maps = R.build_all(neurons, mode="whiten", assign="capacity")
    maps_sh = R.build_all(neurons, mode="whiten", assign="capacity",
                          shuffle=True, seed=0)
    pr_idx = np.unique(np.concatenate([maps[k].neurons for k in maps]))

    every = max(1, int(round(1000.0 / VIS_HZ / DT)))
    кадр_мс = 1000.0 / VIS_HZ
    thr_syn_hz = (sim.MODEL_PARAMS["vThreshold"]
                  - sim.MODEL_PARAMS["vRest"]) / (
        sim.MODEL_PARAMS["wScale"] * sim.MODEL_PARAMS["tauSyn"] * 1e-3)

    rep["замеры"]["устройство"] = {
        "устройство": dev, "нейронов": n,
        "шагов замера": STEPS, "модельного времени, мс": STEPS * DT,
        "обновление кадра, Гц": VIS_HZ, "шагов на кадр": every,
        "пересечение поля, шагов": CROSS,
        "скорость края, °/с": round(157.0 / (CROSS * DT / 1000.0), 1),
        "фоторецепторов в привязке": int(len(pr_idx)),
        "порог, связей·Гц": round(thr_syn_hz, 1),
        "однородное поле, яркость": UNIFORM_L,
        "привязка": R.fingerprint_all(maps),
        "привязка перемешанная": R.fingerprint_all(maps_sh),
    }
    print("  %s, нейронов %d, фоторецепторов %d, порог %.0f связей·Гц"
          % (dev, n, len(pr_idx), thr_syn_hz), flush=True)
    rep["замеры"]["оговорка о привязке"] = (
        "привязка провалила внешнюю проверку зрительных колонок: 0 пар "
        "R7-R8 из 422 в одном омматидии, хуже перетасовки "
        "(VISUAL_COLUMNS.md). Ломается ВЗАИМНОЕ совмещение популяций, "
        "соседство внутри каждой цело (0,089 против 0,967 у "
        "перемешанной, меньше — лучше). Ранний путь кормится почти "
        "целиком от R1-6 (31,3 связи на нейрон L1 против 1,65 у R8), и "
        "его соседство не затронуто; но ЗНАК направленной "
        "избирательности на этой привязке недоказуем в принципе")
    print("  оговорка: привязка провалила внешнюю проверку колонок; "
          "соседство внутри R1-6 цело, знак направления недоказуем",
          flush=True)

    # Общее состояние после разогрева: условия обязаны стартовать с
    # одного и того же, иначе сравнение ничего не стоит.
    eng0 = sim.build_engine(weights=W, neurons=neurons, device=dev,
                            seed=0, no_refractory=pr_idx, graphs=True)
    z = torch.zeros(1, n, device=dev)
    for _ in range(WARM):
        eng0.step(z)
    snap = {"поля": {nm: getattr(eng0, nm).detach().clone()
                     for nm in ("v", "conductance", "spikes", "refrac",
                                "delay_buffer")},
            "ptr": eng0.ptr, "gen": eng0.gen.get_state().clone()}
    del eng0
    print("  состояние снято после %d шагов разогрева" % WARM, flush=True)

    pop_t = {k: torch.as_tensor(v, device=dev) for k, v in pops.items()}

    def прогон(drv, условие):
        """Один прогон одного условия на УЖЕ собранном приводе.

        Накопление идёт на видеокарте одним тензором на весь мозг: так
        шаг не распадается на девятнадцать выборок, и замер не мерит
        собственную цену съёма. Отдача градуальных клеток копится
        ОТДЕЛЬНО и до шага — после шага её там уже нет.
        """
        drv.сброс(snap)
        drv.привязка(maps_sh if условие == "перемешано" else maps)
        acc = torch.zeros(n, device=dev)
        acc_g = drv.копить_отдачу(drv.режим == V.РЕЖИМ_ФИЗИОЛОГИЯ)
        вход = 0.0
        тёмный = (условие == "тёмный край")
        for s in range(STEPS):
            if s % every == 0:
                if условие == "выключено":
                    drv.подать_кадр(None, вкл=False, кадр_мс=кадр_мс)
                elif условие == "однородный":
                    drv.подать_кадр(both_eyes(flat_frame(UNIFORM_L)),
                                    кадр_мс=кадр_мс)
                else:
                    ph = (s % max(CROSS, 1)) / max(CROSS - 1, 1)
                    drv.подать_кадр(
                        both_eyes(edge_frame(om["pos"], ph, тёмный)),
                        кадр_мс=кадр_мс)
                вход += float(drv._t["rates"].sum())
                pr = drv._t.get("pr_hz")
                if pr is not None:
                    вход += sum(float(v.sum()) for v in pr.values()
                                ) * (1000.0 / DT)
            drv.шаг()
            acc.add_(drv.eng.spikes[0])
        if dev == "cuda":
            torch.cuda.synchronize()
        win_ms = STEPS * DT
        out = {k: round(1e3 * float(acc[t].sum()) / len(pops[k])
                        / win_ms, 4) for k, t in pop_t.items()}
        out["__мозг__"] = round(1e3 * float(acc.sum()) / n / win_ms, 4)
        # Равнозначная частота отдачи градуальных клеток — отдельно, и
        # помечена: это не частота разрядов, их у неспайковой клетки нет.
        грд = {}
        if acc_g is not None:
            for k, t in pop_t.items():
                s = float(acc_g[t].sum())
                if s > 0.0:
                    грд[k] = round(s / len(pops[k]) / STEPS
                                   * (1000.0 / DT), 3)
        drv.копить_отдачу(False)
        return out, вход, drv.мембрана(), грд

    # =================================================================
    # 1. Эталон воспроизведён этим же приводом
    # =================================================================
    print("\n1. Эталонный режим: воспроизведение известных чисел",
          flush=True)
    drv_э = V.Привод.собрать(W, neurons, pops, maps,
                             режим=V.РЕЖИМ_ЭТАЛОН, dev=dev, seed=0)
    эт, вх_э, мем_э = {}, {}, None
    for усл in УСЛОВИЯ:
        t1 = time.perf_counter()
        эт[усл], вх_э[усл], м, _ = прогон(drv_э, усл)
        if усл == "светлый край":
            мем_э = м
        print("   %-13s R1-6 %7.2f  L1 %6.3f  L2 %6.3f  Tm1 %6.3f  "
              "Tm2 %6.3f  T4 %6.4f  мозг %6.3f   (%.0f с)"
              % (усл, эт[усл]["R1-6"], эт[усл]["L1"], эт[усл]["L2"],
                 эт[усл]["Tm1"], эт[усл]["Tm2"], эт[усл]["T4"],
                 эт[усл]["__мозг__"], time.perf_counter() - t1),
              flush=True)
    rep["замеры"]["эталон"] = эт
    rep["замеры"]["эталон: вход"] = {k: round(v, 1)
                                     for k, v in вх_э.items()}
    rep["замеры"]["эталон: мембрана и проводимость"] = {
        k: {"мембрана над покоем, мВ": round(v[0], 4),
            "проводимость, мВ": round(v[1], 4)}
        for k, v in мем_э.items()}
    del drv_э

    check("эталонный режим воспроизведён этим приводом: известные "
          "числа VISION.md §2 на месте",
          abs(эт["светлый край"]["L1"] - 6.05) < 0.7
          and abs(эт["светлый край"]["L2"] - 5.25) < 0.7
          and эт["выключено"]["__мозг__"] == 0.0,
          "L1 %.3f (ждали 6,050), L2 %.3f (5,250), L3 %.3f (0,950), "
          "Tm1 %.3f (0,945), Tm2 %.3f (0,519); весь мозг при "
          "выключенном зрении %.4f Гц — собственной активности у сети "
          "нет вовсе"
          % (эт["светлый край"]["L1"], эт["светлый край"]["L2"],
             эт["светлый край"]["L3"], эт["светлый край"]["Tm1"],
             эт["светлый край"]["Tm2"], эт["выключено"]["__мозг__"]))

    глухо_эт = {k: round(эт["светлый край"][k] - эт["однородный"][k], 4)
                for k in РЕШАЮЩИЕ}
    check("блокер эталона воспроизведён: глубже третьего синапса "
          "зрению не принадлежит ничего",
          max(abs(глухо_эт[k])
              for k in ("Tm9", "T4", "T5", "LC4", "LPLC2")) < 0.01,
          "зрению принадлежит (светлый край минус однородное поле): "
          + ", ".join("%s %+.4f" % (k, v) for k, v in глухо_эт.items()))
    rep["замеры"]["эталон: зрению принадлежит"] = глухо_эт

    # =================================================================
    # 2. Физиологический режим: развёртка усиления по коридору
    # =================================================================
    print("\n2. Физиологический режим: коридор усиления градуального "
          "синапса", flush=True)
    потолок = V.потолок_усиления(sim.MODEL_PARAMS, V.V_ТОНИК,
                                 V.V_НАСЫЩ_К)
    низ = V.поток_сохраняющее_усиление(эт["светлый край"]["L1"],
                                       V.V_ТОНИК)
    print("   коридор %.2f…%.1f Гц/мВ. Низ — сохранение потока "
          "медиатора относительно эталона (L1 отдавал %.3f Гц при "
          "%.0f мВ). Потолок — предел рефрактерности движка "
          "(1/tRefrac = %.1f Гц на %.0f мВ насыщения)"
          % (низ, потолок, эт["светлый край"]["L1"], V.V_ТОНИК,
             V.предел_отдачи(sim.MODEL_PARAMS),
             V.V_ТОНИК * V.V_НАСЫЩ_К), flush=True)
    rep["замеры"]["коридор усиления, Гц/мВ"] = {
        "низ: сохранение потока медиатора": round(низ, 3),
        "потолок: предел рефрактерности движка": round(потолок, 2),
        "откуда": V.ОТКУДА["G_ЛАМИНА"][1],
    }

    phys = V.Физиология(g_ламина=V.G_ЛАМИНА)
    drv_ф = V.Привод.собрать(W, neurons, pops, maps,
                             режим=V.РЕЖИМ_ФИЗИОЛОГИЯ, phys=phys,
                             dev=dev, seed=0)
    св_ф = drv_ф.сводка()
    rep["замеры"]["физиология: сводка режима"] = св_ф
    print("   знак фоторецепторов: перевёрнуто %d связей из %d "
          "(%d уже были тормозными); градуальных популяций %s"
          % (св_ф["переворот знака фоторецепторов"][
                 "перевёрнуто (были возбуждающими)"],
             св_ф["переворот знака фоторецепторов"][
                 "связей у фоторецепторов"],
             св_ф["переворот знака фоторецепторов"][
                 "уже были тормозными"],
             св_ф["градуальные популяции"]), flush=True)
    check("переворот знака фоторецепторов воспроизвёл число "
          "VISION_DEEP §5 независимо",
          св_ф["переворот знака фоторецепторов"][
              "перевёрнуто (были возбуждающими)"] == 38373,
          "перевёрнуто %d связей (VISION_DEEP §5: 38 373 из 56 386). "
          "Знак ставится отрицательным, а не умножается на −1: у "
          "20,9 %% R1-6 набор уже даёт тормозной знак, и умножение "
          "сделало бы их возбуждающими"
          % св_ф["переворот знака фоторецепторов"][
              "перевёрнуто (были возбуждающими)"])

    СЕТКА = [round(низ, 2), 2.0, 8.0, 16.0, round(потолок, 1)]
    разв = {}
    for g in СЕТКА:
        drv_ф.усиление(g_ламина=g)
        row, t1 = {}, time.perf_counter()
        for усл in УСЛОВИЯ:
            row[усл], вх, мем, грд = прогон(drv_ф, усл)
            row.setdefault("вход", {})[усл] = round(вх, 1)
            row.setdefault("отдача градуальных, равнозначных Гц",
                           {})[усл] = грд
            if усл == "светлый край":
                row["мембрана"] = {
                    k: {"мембрана, мВ": round(v[0], 4),
                        "проводимость, мВ": round(v[1], 4)}
                    for k, v in мем.items()}
        разв[g] = row
        c, u = row["светлый край"], row["однородный"]
        print("   g=%6.2f  L2сп %6.2f | Mi1 %7.3f Tm9 %6.3f T4 %6.3f "
              "T5 %6.3f LC4 %6.3f LPLC2 %6.3f DNp01 %6.2f | мозг "
              "%6.2f (одн %6.2f, темн %6.2f)  (%.0f с)"
              % (g, c["L2"], c["Mi1"], c["Tm9"], c["T4"], c["T5"],
                 c["LC4"], c["LPLC2"], c["DNp01"], c["__мозг__"],
                 u["__мозг__"], row["выключено"]["__мозг__"],
                 time.perf_counter() - t1), flush=True)
    rep["замеры"]["развёртка усиления"] = {str(k): v
                                           for k, v in разв.items()}

    # --- что принадлежит ЗРЕНИЮ -------------------------------------
    print("\n   Зрению принадлежит: светлый край минус однородное поле "
          "той же средней яркости, Гц на нейрон", flush=True)
    принадл = {}
    for g in СЕТКА:
        r = разв[g]
        принадл[g] = {k: round(r["светлый край"][k] - r["однородный"][k],
                               4) for k in РЕШАЮЩИЕ}
        print("   g=%6.2f  " % g + "  ".join(
            "%s %+.4f" % (k, принадл[g][k]) for k in РЕШАЮЩИЕ),
            flush=True)
    rep["замеры"]["зрению принадлежит (светлый край минус однородное)"] \
        = {str(k): v for k, v in принадл.items()}

    print("\n   Структуре принадлежит: настоящая привязка минус "
          "перемешанная (суммарный вход побитово тот же)", flush=True)
    структ = {}
    for g in СЕТКА:
        r = разв[g]
        структ[g] = {k: round(r["светлый край"][k] - r["перемешано"][k],
                              4) for k in РЕШАЮЩИЕ}
        print("   g=%6.2f  " % g + "  ".join(
            "%s %+.4f" % (k, структ[g][k]) for k in РЕШАЮЩИЕ),
            flush=True)
    rep["замеры"]["структуре принадлежит"] = {str(k): v
                                              for k, v in структ.items()}

    print("\n   ON против OFF: светлый край минус тёмный край", flush=True)
    онофф = {}
    for g in СЕТКА:
        r = разв[g]
        онофф[g] = {k: round(r["светлый край"][k] - r["тёмный край"][k],
                             4) for k in РЕШАЮЩИЕ}
        print("   g=%6.2f  " % g + "  ".join(
            "%s %+.4f" % (k, онофф[g][k]) for k in РЕШАЮЩИЕ), flush=True)
    rep["замеры"]["ON минус OFF"] = {str(k): v for k, v in онофф.items()}

    # --- вход двух привязок обязан совпасть --------------------------
    for g in СЕТКА:
        a = разв[g]["вход"]["светлый край"]
        b = разв[g]["вход"]["перемешано"]
        if abs(a - b) > 1e-3 * max(abs(a), 1.0):
            check("суммарный вход настоящей и перемешанной привязки "
                  "совпадает при g=%s" % g, False,
                  "подано %.3f против %.3f" % (a, b))
            break
    else:
        check("суммарный вход настоящей и перемешанной привязки "
              "совпадает на всех усилениях — значит различие может дать "
              "только пространственная структура",
              True,
              "наибольшее расхождение %.2e по %d усилениям"
              % (max(abs(разв[g]["вход"]["светлый край"]
                         - разв[g]["вход"]["перемешано"])
                     for g in СЕТКА), len(СЕТКА)))

    # --- главный вопрос ---------------------------------------------
    прошло = [g for g in СЕТКА
              if max(abs(принадл[g][k]) for k in ("T4", "T5", "LC4")) > 0.01]
    структурно = [g for g in СЕТКА
                  if max(структ[g][k] for k in ("T4", "T5", "LC4")) > 0.01]
    check("есть ли усиление, при котором зрению принадлежит отклик "
          "глубже третьего синапса",
          True,
          ("зрению принадлежит отклик в T4/T5/LC4 при усилении %s Гц/мВ "
           "из коридора %.2f…%.1f; из них СТРУКТУРЕ принадлежит при %s"
           % (прошло, низ, потолок, структурно or "НИ ОДНОМ"))
          if прошло else
          ("НЕ появляется ни при одном усилении коридора %.2f…%.1f: "
           "T4, T5 и LC4 остаются в пределах 0,01 Гц от однородного "
           "поля на всех %d значениях" % (низ, потолок, len(СЕТКА))))

    горит = {g: разв[g]["однородный"]["__мозг__"] for g in СЕТКА}
    темно = {g: разв[g]["выключено"]["__мозг__"] for g in СЕТКА}
    rep["замеры"]["мозг при однородном поле, Гц"] = {
        str(k): v for k, v in горит.items()}
    rep["замеры"]["мозг в темноте, Гц"] = {str(k): v
                                           for k, v in темно.items()}
    note("цена режима названа: собственная активность мозга при "
         "однородном поле по усилению — "
         + ", ".join("g=%s → %.2f Гц" % (g, горит[g]) for g in СЕТКА)
         + "; в полной темноте — "
         + ", ".join("g=%s → %.2f Гц" % (g, темно[g]) for g in СЕТКА)
         + ". Чем выше усиление, тем больше сеть горит от самой "
           "тонической отдачи ламины, и тем меньше смысла в абсолютных "
           "частотах — считать надо только разности с контролем")

    del drv_ф
    rep["замеры"]["секунд на пробу"] = round(time.perf_counter() - t0, 1)
    (OUT / "vision_phys.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nпроверок %d, провалов %d, за %.0f с"
          % (len(rep["проверки"]), len(fails),
             time.perf_counter() - t0), flush=True)
    if fails:
        print("ПРОВАЛЫ: " + "; ".join(fails), flush=True)
    return 1 if fails else 0


