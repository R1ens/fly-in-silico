"""Что слияние дало ВМЕСТЕ: перемежающиеся пары на полном контуре.

Отношения отдельных правок перемножать нельзя. Правка обвязки MuJoCo и
вендоренный шаг походки убирают частью одну и ту же избыточность
(повторное полное наблюдение), поэтому ×1,864 и ×1,35 — не множители, а
два замера, у которых есть общее слагаемое. Единственный ответ на «что
вышло вместе» — замер полного контура, и он здесь.

Почему в ОДНОМ процессе, а не двумя прогонами. Независимый стенд
замерил: десять эпизодов одной конфигурации с одним семенем дают
побитово одну траекторию и медиану шага 464,91…643,69 мс, то есть
разброс в 1,385 раза за 166 секунд. Ускорение меньше примерно 1,45× на
малом числе пар от фона неотличимо. Поэтому круги чередуются внутри
одного процесса, отношение считается ВНУТРИ пары, и в итог идёт медиана
с размахом и числом пар.

Прежняя дорога берётся не из другого дерева, а ручками, которые для
этого и сделаны: `gait="legacy"`, `acc_forward=False`, `fast_obs=False`,
`rule_obs=False`, `fast_gain=False`. Это и есть встречный замер, ради
которого ручки оставлены.

ЧЕГО ЭТОТ ЗАМЕР НЕ МЕРИТ, и это надо знать. Две правки съёма с
устройства (`index_fill_` и один `read_total` вместо пяти ожиданий)
ручки не имеют — они безусловны и присутствуют в ОБЕИХ ветвях пары.
Значит снятое здесь отношение — это вклад обвязки MuJoCo и контроллера
походки, а не всего слияния. Вклад тех двух правок замерен отдельно и на
полном контуре неотличим от нуля (1,0171 при разбросе 0,8414…1,1489).

Равенство проверяется в том же прогоне, а не отдельно: обе ветви обязаны
дать ОДИН И ТОТ ЖЕ отпечаток эпизода, и он обязан совпасть с эталоном
задания. Иначе ускорение считать не за что.

    cd D:\\fly-brain\\lab
    set PYTHONIOENCODING=utf-8
    ..\\.venv\\Scripts\\python.exe probe\\merged_pairs.py --пар 10
    ..\\.venv\\Scripts\\python.exe probe\\merged_pairs.py --пар 3 --длина 0.4
"""

import argparse
import hashlib
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import probe._isolate  # noqa: E402,F401

import numpy as np  # noqa: E402

OUT = Path(__file__).parent

# Отпечатки обычного эпизода, объявленные в задании и в SPEED.md §3.
# Длина эпизода у них 1,0 с; при другой длине сверка с эталоном
# пропускается, а равенство ветвей между собой проверяется всё равно.
ЭТАЛОН = {
    "траектория": "6ec405dc06c7ecae",
    "активность": "e538224ac7b1abd1",
    "конец": [2.481, 1.433, 1.6024],
    "выравнивание": 0.301,
}
ЭТАЛОН_ДЛИНА = 1.0

# Прежняя дорога: все ручки, которыми правки выключаются. Собрано
# отдельным словарём, чтобы в отчёте было видно, что именно считалось
# «прежним», а не «то, что было в голове».
ПРЕЖНЯЯ = {
    "gait": "legacy",
    "acc_forward": False,
    "fast_obs": False,
    "rule_obs": False,
    "fast_gain": False,
}

fails = []
rep = {"проверки": {}, "пары": [], "ветви": {}}


def check(name, ok, info=""):
    print(("  ok     " if ok else "  ПРОВАЛ ") + name
          + (("  " + str(info)) if info else ""))
    rep["проверки"][name] = {"пройдено": bool(ok), "замер": str(info)}
    if not ok:
        fails.append(name)


def fp(a):
    return hashlib.sha256(np.ascontiguousarray(a).tobytes()).hexdigest()[:16]


def эпизод(ручки, длина, neurons, weights, device):
    """Один эпизод полного контура. Возвращает время и отпечатки."""
    from flybrain import body as B

    cfg = B.BodyConfig(duration_s=длина, control_ms=20.0, seed=0,
                       device=device, readout="ALPN", **ручки)
    t0 = time.perf_counter()
    run = B.run_episode(cfg=cfg, neurons=neurons, weights=weights,
                        progress=False)
    wall = time.perf_counter() - t0
    recs = run.records
    cols = ("x", "y", "theta", "odour_l", "odour_r", "dn_l", "dn_r",
            "amp_l", "amp_r", "dist", "grad_cos", "spikes")
    table = np.array([[r[c] for c in cols] for r in recs], dtype=np.float64)
    t = run.timing or {}
    return {
        "по стене, с": round(wall, 3),
        # Считаем по `sim_s`, а не по стене: сборка тела и загрузка
        # данных в шаг управления не входят, а между ветвями они равны.
        "счёт, с": t.get("sim_s"),
        "шагов": len(recs),
        "мс на шаг управления": (round(1000.0 * t["sim_s"] / len(recs), 2)
                                 if t.get("sim_s") and recs else None),
        "доля реального времени": t.get("realtime_ratio"),
        "траектория": fp(table[:, :3]),
        "активность": fp(run.counts),
        "всё по шагам": fp(table),
        "растр": fp(run.bins),
        "выравнивание": (run.metrics or {}).get("grad_alignment"),
        "конец": ([round(float(recs[-1]["x"]), 4),
                   round(float(recs[-1]["y"]), 4),
                   round(float(recs[-1]["theta"]), 4)] if recs else None),
        "обвязка": t.get("обвязка"),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--пар", type=int, default=10)
    ap.add_argument("--длина", type=float, default=1.0)
    a = ap.parse_args()

    import torch
    from flybrain import data as D

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print("— что слияние дало вместе —")
    print("  устройство %s, пар %d, эпизод %.1f с модельного"
          % (device, a.пар, a.длина))
    neurons = D.load_neurons()
    weights = D.load_weights(device=device)

    отн, прежние, новые = [], [], []
    for i in range(a.пар):
        # Порядок внутри пары чередуется: если фон ползёт в одну
        # сторону, он не ложится всё время на одну и ту же ветвь.
        if i % 2 == 0:
            p = эпизод(ПРЕЖНЯЯ, a.длина, neurons, weights, device)
            n = эпизод({}, a.длина, neurons, weights, device)
        else:
            n = эпизод({}, a.длина, neurons, weights, device)
            p = эпизод(ПРЕЖНЯЯ, a.длина, neurons, weights, device)
        if not p["счёт, с"] or not n["счёт, с"]:
            print("  пара %d: нет sim_s, пропущена" % (i + 1))
            continue
        r = p["счёт, с"] / n["счёт, с"]
        отн.append(r)
        прежние.append(p)
        новые.append(n)
        rep["пары"].append({
            "пара": i + 1,
            "первой шла": "прежняя" if i % 2 == 0 else "новая",
            "прежняя, мс на шаг": p["мс на шаг управления"],
            "новая, мс на шаг": n["мс на шаг управления"],
            "отношение": round(r, 4),
        })
        print("  пара %d: прежняя %s мс, новая %s мс — в %.3f раза"
              % (i + 1, p["мс на шаг управления"],
                 n["мс на шаг управления"], r))

    if not отн:
        print("ни одной пары не снято")
        return 1

    med = statistics.median(отн)
    rep["итог"] = {
        "пар": len(отн),
        "медиана отношения": round(med, 4),
        "мин": round(min(отн), 4),
        "макс": round(max(отн), 4),
        "СО": round(statistics.stdev(отн), 4) if len(отн) > 1 else None,
        "прежняя, медиана мс на шаг": statistics.median(
            [p["мс на шаг управления"] for p in прежние]),
        "новая, медиана мс на шаг": statistics.median(
            [n["мс на шаг управления"] for n in новые]),
        "новая, медиана доли реального времени": statistics.median(
            [n["доля реального времени"] for n in новые]),
    }
    rep["ветви"] = {"прежняя": прежние[-1], "новая": новые[-1]}

    print("— равенство —")
    # Отпечатки обеих ветвей обязаны совпасть между собой на КАЖДОЙ паре,
    # а не только в последней: иначе расхождение, случившееся однажды,
    # потерялось бы.
    for поле in ("траектория", "активность", "всё по шагам", "растр",
                 "конец", "выравнивание"):
        разошлось = [i + 1 for i, (p, n) in enumerate(zip(прежние, новые))
                     if p[поле] != n[поле]]
        check("ветви дали один «%s» на всех парах" % поле,
              not разошлось,
              "расхождений 0 из %d" % len(отн) if not разошлось
              else "разошлось на парах %s" % разошлось)

    if abs(a.длина - ЭТАЛОН_ДЛИНА) < 1e-9:
        n = новые[-1]
        check("новая ветвь дала эталонную траекторию",
              n["траектория"] == ЭТАЛОН["траектория"],
              "%s против %s" % (n["траектория"], ЭТАЛОН["траектория"]))
        check("новая ветвь дала эталонную активность",
              n["активность"] == ЭТАЛОН["активность"],
              "%s против %s" % (n["активность"], ЭТАЛОН["активность"]))
        check("новая ветвь дала эталонную позу",
              n["конец"] == ЭТАЛОН["конец"],
              "%s против %s" % (n["конец"], ЭТАЛОН["конец"]))
        check("новая ветвь дала эталонное выравнивание",
              abs((n["выравнивание"] or 0) - ЭТАЛОН["выравнивание"]) < 5e-4,
              "%s против %s" % (n["выравнивание"], ЭТАЛОН["выравнивание"]))
    else:
        print("  (сверка с эталоном пропущена: длина %.2f с, а эталон на"
              " %.1f с)" % (a.длина, ЭТАЛОН_ДЛИНА))

    print("— в сохранённом видно, какой дорогой считалось —")
    о_новой = (новые[-1]["обвязка"] or {})
    о_прежней = (прежние[-1]["обвязка"] or {})
    check("новая ветвь записала себя новой",
          о_новой.get("контроллер походки") == "fast"
          and о_новой.get("пересчёт со ступени ускорений") is True
          and о_новой.get("дешёвое наблюдение") is True,
          json.dumps(о_новой, ensure_ascii=False)[:120])
    check("прежняя ветвь записала себя прежней",
          о_прежней.get("контроллер походки") == "legacy"
          and о_прежней.get("пересчёт со ступени ускорений") is False
          and о_прежней.get("дешёвое наблюдение") is False,
          json.dumps(о_прежней, ensure_ascii=False)[:120])

    print("— итог —")
    print("  пар %d, медиана отношения %.3f (%.3f…%.3f%s)"
          % (len(отн), med, min(отн), max(отн),
             ", СО %.3f" % statistics.stdev(отн) if len(отн) > 1 else ""))
    print("  прежняя %s мс на шаг, новая %s мс"
          % (rep["итог"]["прежняя, медиана мс на шаг"],
             rep["итог"]["новая, медиана мс на шаг"]))
    print("  доля реального времени новой ветви: %s"
          % rep["итог"]["новая, медиана доли реального времени"])
    # Порог назван ЗАРАНЕЕ и не из этого замера: он снят стендом на A/A
    # полного контура (разброс 1,385 за 166 с).
    if med < 1.45 and len(отн) < 8:
        print("  ВНИМАНИЕ: %.3f ниже порога 1,45, а пар всего %d —"
              " от фона не отличимо" % (med, len(отн)))

    (OUT / "merged_pairs.json").write_text(
        json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("проверок %d, провалов %d" % (len(rep["проверки"]), len(fails)))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
