"""Единственная таблица величин интерфейса.

Ни одного цвета, кегля, отступа и скругления мимо этого файла. Прежний
интерфейс развалился ровно потому, что числа брались по месту: каждая
панель задавала свои отступы, и общего ритма не возникало.

Работа идёт в **логических единицах**. Одна логическая единица — это
пиксель при масштабе 100 %. Перевод в пиксели устройства делает `Scale`,
и только он: размер текста и толщина линии не должны зависеть от того,
растянули панель или нет.
"""

import math

