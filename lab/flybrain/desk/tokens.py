class Scale:
    """Перевод логических единиц в пиксели устройства.

    Масштаб берётся **только** от DPI окна. Поправка по площади окна
    осталась в коде, но по умолчанию выключена, и это осознанно: бриф
    задаёт кегли при 100 % (основной текст 13–14) и прямо запрещает
    размер текста, зависящий от растягивания. При 1280×720 поправка
    давала 12 — то есть ровно то, что запрещено. Нехватку места решает
    не кегль, а отключение зон в `layout`.

    Включать `fit` имеет смысл разве что для снимков в нестандартном
    размере, и тогда это видно в вызове.
    """

    REF = 1600.0 * 900.0

    def __init__(self, dpi=1.0, w=1600, h=900, area_fit=False):
        self.dpi = float(dpi)
        self.area_fit = bool(area_fit)
        self.set_size(w, h)

    def set_size(self, w, h, area_fit=None):
        if area_fit is not None:
            self.area_fit = bool(area_fit)
        self.w, self.h = int(w), int(h)
        if self.area_fit:
            area = max(1.0, float(w) * float(h))
            # Зажато: иначе на 4K кегли скачут вдвое.
            self.fit = max(0.88, min(1.22, math.sqrt(area / self.REF)))
        else:
            self.fit = 1.0
        self.k = self.dpi * self.fit

    def px(self, v):
        """Логические единицы -> пиксели устройства, не меньше одного."""
        return max(1, int(round(float(v) * self.k)))

    def pxf(self, v):
        return float(v) * self.k

    def size(self, role):
        """Кегль по роли, в пикселях устройства."""
        return max(9, int(round(getattr(T, role) * self.k)))

    def hair(self):
        """Толщина разделительной линии: всегда целое число пикселей."""
        return max(1, int(round(self.dpi)))
