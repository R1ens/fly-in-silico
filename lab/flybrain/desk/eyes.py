"""Вид глаз: что муха видит на самом деле, и насколько это свежо.

Четыре картины, и все четыре — из массивов, которые получает сеть, а не
нарисованы «в духе» зрения мухи:

* **кадр левого и правого глаза** — то, что FlyGym кладёт в
  ``_curr_raw_visual_input``: кадр камеры после исправления рыбьего
  глаза, ровно тот, из которого считаются шестиугольные пиксели. Он
  едет в окно как uint8, и это не огрубление: ``physics.render``
  отдаёт целые 0…255, исправление рыбьего глаза их не размывает, а
  ``float32`` появляется уже после, при сборке массива;
* **показания омматидиев левого и правого глаза** — массив
  ``(2, 721, 2)``, который получает переходник сетчатки, разложенный
  обратно по шестиугольникам **картой самого NeuroMechFly**
  (``ommatidia_id_map.npy``). То есть это не наша картинка про
  омматидии, а обратное преобразование того, что ушло в сеть.

Почему раскладка здесь, а не вызов FlyGym. ``hex_pxls_to_human_readable``
делает ровно это, но живёт в пакете, который тянет за собой mujoco и
gymnasium, а окну по уговору движка иметь нельзя. Берётся поэтому только
карта — файл ``.npy``, читается ``numpy`` за 0,16 с и без единого
импорта движка, — а раскладка по ней делается здесь одним обращением по
индексу.

**Два канала сводятся наибольшим**, как в :func:`retina.intensity` и как
в официальной интеграции NeuroMechFly. Для показаний это не потеря:
``raw_image_to_hex_pxls`` кладёт значение омматидия ровно в ОДИН из двух
каналов — в тот, который отвечает его типу (бледный или жёлтый), —
а второй остаётся нулём. Наибольший из двух и есть само значение.

Чего здесь нет и быть не должно. Между приходами кадра картинка не
подрисовывается и не сглаживается: окно рисует последний настоящий
кадр и **говорит, сколько ему миллисекунд**. Промежуточных кадров не
придумывается ни одного, и поэтому число показанных кадров окна никогда
не выдаётся за число наблюдений.

Единственное сглаживание, которое здесь есть, названо прямо: кадр
450×512 вписывается в клетку билинейной выборкой — тем же ядром
`gpu.k_image`, которым рисуется вид тела. Это масштабирование ПРИ
ПОКАЗЕ и ничего больше: в сеть, в моторный путь и в физику уходит
исходный массив, а не то, что видно на экране. Сетчатке показанное
никогда не возвращается.
"""


import numpy as np

from . import layout as L
from . import widgets as W
from .tokens import C, R, S

__all__ = ["draw", "rows", "available"]

# Показания омматидиев лежат в 0…1 (`raw_image_to_hex_pxls` делит на
# 255). Шкала показа поэтому постоянная, а не подгоняется под кадр:
# подгонка делала бы тёмную сцену такой же яркой, как светлую, и по
# картинке нельзя было бы сказать, что муха видит темноту.
OMMA_FULL = 1.0

# Насколько старым кадр считается несвежим. 250 мс — это примерно два
# обновления сетчатки при 100 Гц модельного и скорости 0,077×; дольше
# значит, что окно отстало или счёт встал.
STALE_S = 0.25

_map = None          # карта омматидиев, читается один раз
_cache = {}          # "кадр" -> номер, 0/1 -> разложенная картинка глаза
_bufs = {}           # 0/1 -> буфер под картинку, переиспользуется


def _id_map():
    """Карта омматидиев. Читается один раз и без импорта движка."""
    global _map
    if _map is None:
        from .. import retina as RT

        m = np.asarray(RT.id_map(), dtype=np.int32)
        # Фон (0) и номера 1…721. Для обращения по индексу удобнее
        # держать «номер минус один», а фон увести в отдельную строку
        # таблицы, которую мы допишем нулями: так раскладка — одно
        # обращение по индексу, без маски и без ветвления.
        _map = np.where(m > 0, m - 1, -1)
    return _map


def available(ses):
    """Есть ли у сеанса кадр глаз. Без него панель говорит, почему нет."""
    return ses is not None and ses.eye_img is not None


def _mosaic(ses, eye):
    """Показания одного глаза, разложенные по шестиугольникам.

    Считается ТОЛЬКО когда пришёл новый кадр. Раскладка — это 230 тысяч
    обращений по индексу: **1,66 мс на оба глаза** после правки ниже и
    7,73 мс до неё. Наблюдений приходит около восьми в секунду, а окно
    рисует шестьдесят кадров, так что пересчёт на каждом кадре стоил бы
    почти половины бюджета кадра — и всё это на пересчёт одного и того
    же.
    """
    # У каждой картинки СВОЁ поколение, и общей чистки кэша нет. Первая
    # редакция чистила весь кэш, и выходило так: левый глаз разложили и
    # стёрли правый, разложили правый — стёрли левый, и на следующем
    # кадре окна всё повторялось. Обе мозаики пересобирались шестьдесят
    # раз в секунду вместо восьми — 7,7 мс кадра на пересчёт одного и
    # того же.
    key = ("мозаика", eye)
    om = ses.eye_omma
    if om is None:
        return None
    if _cache.get(key) == ses.eye_seq and key in _bufs:
        return _bufs[key]
    idx = _id_map()
    # Два канала -> наибольший: у каждого омматидия значение лежит
    # ровно в одном из них, второй ноль.
    vals = np.asarray(om[eye], dtype=np.float32).max(axis=1)
    # Таблица СРАЗУ в байтах, и это не мелочь. Первая редакция
    # раскладывала числа с плавающей точкой по 230 тысячам пикселей, а
    # потом умножала, обрезала и приводила к байтам — то есть четыре
    # прохода по большому массиву вместо одного по маленькому.
    # Замерено: 7,73 мс на оба глаза. Здесь в байты переводятся 722
    # числа, а по пикселям идёт одна выборка.
    #
    # Хвостовой элемент таблицы — фон: индекс -1 попадает именно в
    # него, и ветвления по маске не нужно.
    lut = np.empty(len(vals) + 1, dtype=np.uint8)
    lut[:len(vals)] = np.clip(vals * (255.0 / OMMA_FULL),
                              0.0, 255.0).astype(np.uint8)
    lut[-1] = 0
    g = lut[idx]
    # Три канала заполняются записью в заранее отведённый буфер, а не
    # `np.repeat`: тот каждый раз отводит 691 КБ заново — и, что важнее
    # отведённой памяти, отдаёт в ядро НОВЫЙ объект, на каждом из
    # которых Taichi оставляет своё (см. `_buf`).
    out = _buf(key, g.shape)
    out[:, :, 0] = g
    out[:, :, 1] = g
    out[:, :, 2] = g
    _cache[key] = ses.eye_seq
    return out


def _buf(key, shape):
    """Буфер под картинку, один на ключ и на всю жизнь окна.

    Буфер нужен ради ЦЕЛОСТНОСТИ показанного кадра. Картинка в кольце
    лежит в слоте, который работник перепишет через три наблюдения —
    это примерно четверть секунды, — и всё это время окно рисует её
    видом прямо из разделяемой памяти. Пока кадр рисуется, слот могут
    переписать, и на экране окажется половина одного наблюдения и
    половина другого, а рядом будет стоять **одна** отметка времени.
    Своя копия это исключает: показанное всегда соответствует подписи.

    Цена названа числом: 0,69 МБ на глаз РАЗ НА НАБЛЮДЕНИЕ, то есть
    около 5 МБ/с при четырёх наблюдениях в секунду, и буфер один и тот
    же на всю жизнь окна.

    Отдельная история, которую стоит записать, чтобы её не начали
    заново: сперва буфер поставили против утечки. Замер показал, что
    блит новым массивом стоит +0,26 МБ, а тем же — +0,013, и это
    выглядело причиной. Настоящей причиной оказалось другое —
    незавершённые запуски ядер (`gpu.Surface.finish`), — и после
    `ti.sync()` на кадр утечка исчезла целиком, независимо от буферов.
    Буфер остался по той причине, что названа выше, а не по той, по
    которой появился.
    """
    b = _bufs.get(key)
    if b is None or b.shape[:2] != tuple(shape[:2]):
        b = np.zeros((shape[0], shape[1], 3), dtype=np.uint8)
        _bufs[key] = b
    return b


def _photo(ses, eye):
    """Кадр камеры глаза в постоянном буфере.

    Копия делается РАЗ НА ДОШЕДШИЙ КАДР, а не раз на кадр окна. Это
    разные частоты, и путать их нельзя: кадров глаз доходит 3,7 в
    секунду (замерено), то есть копия стоит 0,69 МБ × 2 глаза × 3,7 =
    около 5 МБ/с, — а показывается картинка пятьдесят раз в секунду.
    """
    if ses.eye_img is None:
        return None
    key = ("фото", eye)
    if _cache.get(key) != ses.eye_seq or key not in _bufs:
        src = ses.eye_img[eye]
        _buf(key, src.shape)[...] = src
        _cache[key] = ses.eye_seq
    return _bufs[key]


def _tile(app, ctx, box, img, title, note=""):
    """Одна клетка: картинка, рамка и подпись под ней."""
    dl, sc, f = ctx.dl, app.sh.sc, app.sh.fonts
    lab_h = f.micro.gh + sc.px(S.xs)
    view = L.Rect(box.x, box.y, box.w, max(1, box.h - lab_h))
    dl.rect(view.x, view.y, view.x1, view.y1, C.bg, 1.0, sc.px(R.control))
    if img is not None:
        fit = view.inset(sc.px(2)).fit_aspect(img.shape[1] / img.shape[0])
        dl.image(img, fit.x, fit.y, fit.w, fit.h)
    else:
        W.label(ctx, L.Rect(view.x, view.cy - f.small.gh // 2, view.w,
                            f.small.gh), "нет кадра", role="small",
                color=C.faint, align="centre")
    row = L.Rect(box.x, box.y1 - f.micro.gh, box.w, f.micro.gh)
    W.label(ctx, row, title, role="micro", color=C.dim)
    if note:
        W.label(ctx, row, note, role="micro", color=C.faint, align="right")


def _num(v, nd=1, dash="—"):
    if v is None:
        return dash
    try:
        return ("{:,." + str(nd) + "f}").format(float(v)).replace(",", " ")
    except (TypeError, ValueError):
        return dash


def draw(app, ctx, r):                                        # noqa: C901
    """Весь вид глаз в отведённом прямоугольнике."""
    dl, sc, f = ctx.dl, app.sh.sc, app.sh.fonts
    ses = app.ses
    dl.rect(r.x, r.y, r.x1, r.y1, C.sunken, 1.0, sc.px(R.panel))
    view = r.inset(sc.px(S.md))

    # --- шапка: свежесть этого кадра --------------------------------
    head = L.Rect(view.x, view.y, view.w, f.body.gh + sc.px(S.xs))
    if not available(ses):
        why = "сеанс идёт без зрения"
        if ses is None or not ses.ready:
            why = "работник ещё не готов"
        elif ses.busy:
            why = "кадра глаз ещё не было"
        W.label(ctx, head, "Глаза: " + why, role="body", color=C.dim)
        box = L.Rect(view.x, head.y1 + sc.px(S.lg), view.w,
                     max(1, view.y1 - head.y1 - sc.px(S.lg)))
        W.label(ctx, L.Rect(box.x + box.w // 6, box.cy - sc.px(30),
                            box.w - box.w // 3, sc.px(80)),
                "Зрение включается до запуска: глаза создаются при "
                "сборке модели MuJoCo. Поставьте «подавать кадр глаз в "
                "сеть» в рейке слева и запустите сеанс заново.",
                role="small", color=C.faint, wrapped=True)
        return

    age = ses.eye_age_s
    stale = age > STALE_S
    W.label(ctx, head, "Кадр %d · модельное %s мс"
            % (ses.eye_seq, _num(ses.eye_t_ms, 1)), role="body", color=C.ink)
    W.label(ctx, head, "возраст %s мс · доставка %s мс"
            % (_num(age * 1000.0, 0), _num(ses.eye_lag_s * 1000.0, 0)),
            role="body", color=(C.warn if stale else C.dim), align="right")

    # --- подвал: четыре величины, и ни одна не выдаётся за другую ---
    foot_h = f.micro.gh * 2 + sc.px(S.xs)
    foot = L.Rect(view.x, view.y1 - foot_h, view.w, foot_h)
    grid = L.Rect(view.x, head.y1 + sc.px(S.sm), view.w,
                  max(1, foot.y - head.y1 - sc.px(S.md) * 2))

    # --- 2x2 ---------------------------------------------------------
    gap = sc.px(S.sm)
    cw = (grid.w - gap) // 2
    chh = (grid.h - gap) // 2
    om = ses.eye_omma
    for eye, name in ((0, "левый"), (1, "правый")):
        cx = grid.x + eye * (cw + gap)
        _tile(app, ctx, L.Rect(cx, grid.y, cw, chh), _photo(ses, eye),
              "%s глаз · кадр камеры" % name,
              "512×450, рыбий глаз исправлен")
        mos = _mosaic(ses, eye)
        note = ""
        if om is not None:
            v = np.asarray(om[eye], dtype=np.float32).max(axis=1)
            note = "%s…%s, среднее %s" % (_num(v.min(), 2), _num(v.max(), 2),
                                          _num(v.mean(), 2))
        _tile(app, ctx, L.Rect(cx, grid.y + chh + gap, cw, chh), mos,
              "%s глаз · 721 омматидий" % name, note)

    line = L.Rect(foot.x, foot.y, foot.w, f.micro.gh)
    W.label(ctx, line,
            "рендеров камер %s · обновлений сетчатки %s · кадров в окно %s"
            % (_num(ses.eye_renders, 0), _num(ses.eye_updates, 0),
               _num(ses.eye_taken, 0)), role="micro", color=C.dim)
    rr, ru, rt = (ses.rate_renders.value, ses.rate_updates.value,
                  ses.rate_taken.value)
    W.label(ctx, line, "%s · %s · %s в секунду по стене"
            % (_num(rr, 1), _num(ru, 1), _num(rt, 1)),
            role="micro", color=C.dim, align="right")
    lost = ses.eye_lost_in_step
    last = L.Rect(foot.x, foot.y + f.micro.gh + sc.px(2), foot.w, f.micro.gh)
    W.label(ctx, last, "вытеснено внутри шага %s · вытеснено кольцом %s"
            % (_num(lost, 0), _num(ses.eye_missed, 0)),
            role="micro", color=C.faint)
    # Частота показа окна стоит ЗДЕСЬ, рядом с частотой наблюдений, и
    # названа своим именем. Это то самое место, где два числа легче
    # всего перепутать: окно рисует шестьдесят кадров в секунду, а
    # наблюдений за ту же секунду восемь, и подписать их одинаково
    # значило бы соврать ровно тем способом, которого требует не
    # допустить задание.
    fps = float(getattr(app.sh, "fps", 0.0) or 0.0)
    W.label(ctx, last,
            ("окно рисует %s кадр/с — это показ, не наблюдения"
             % _num(fps, 0)) if fps > 0 else
            "частота показа не измеряется: кадр собирается без окна",
            role="micro", color=C.faint, align="right")


def rows(app, ctx, s):
    """Те же величины строками — для колонки показаний.

    Отдельной функцией, потому что сливать их в одну строку нельзя, а
    повторять руками в двух местах — верный способ развести их смысл.
    """
    sc = app.sh.sc
    ses = app.ses
    W.section(ctx, s, "Глаза", right=("идут" if available(ses) else "нет"))
    if not available(ses):
        W.label(ctx, s.take(sc.px(S.row)),
                "зрение в этом сеансе выключено", role="small",
                color=C.faint)
        return
    W.kv(ctx, s.take(sc.px(S.row)), "кадр", "%d" % ses.eye_seq,
         "по счёту")
    W.kv(ctx, s.take(sc.px(S.row)), "модельное время кадра",
         _num(ses.eye_t_ms, 1), "мс")
    W.kv(ctx, s.take(sc.px(S.row)), "возраст кадра",
         _num(ses.eye_age_s * 1000.0, 0), "мс")
    W.kv(ctx, s.take(sc.px(S.row)), "рендеров камер",
         _num(ses.eye_renders, 0), "шт")
    W.kv(ctx, s.take(sc.px(S.row)), "обновлений сетчатки",
         _num(ses.eye_updates, 0), "шт")
    W.kv(ctx, s.take(sc.px(S.row)), "кадров дошло до окна",
         _num(ses.eye_taken, 0), "шт")
    W.kv(ctx, s.take(sc.px(S.row)), "обновлений в секунду",
         _num(ses.rate_updates.value, 1), "1/с")
    W.kv(ctx, s.take(sc.px(S.row)), "кадров в секунду в окно",
         _num(ses.rate_taken.value, 1), "1/с")
    W.kv(ctx, s.take(sc.px(S.row)), "вытеснено внутри шага",
         _num(ses.eye_lost_in_step, 0), "шт")
    W.kv(ctx, s.take(sc.px(S.row)), "вытеснено кольцом",
         _num(ses.eye_missed, 0), "шт")


def reset():
    """Забыть разложенные картинки. Зовётся при новом сеансе.

    Буферы НЕ выбрасываются: это те самые объекты, за постоянство
    которых держится отсутствие утечки, а их содержимое всё равно
    перепишется первым же кадром нового сеанса.
    """
    _cache.clear()
