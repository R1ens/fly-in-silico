def draw(dl, name, x, y, size, color, alpha=1.0, width=None):
    """Положить иконку `name` в квадрат `size × size` с углом в (x, y).

    Опечатка в имени роняет вызов нарочно: иконка, молча не нарисованная в
    кадре, ищется дольше, чем исключение на первом же запуске.
    """
    fn = _DRAW.get(name)
    if fn is None:
        raise KeyError("нет иконки " + repr(name))
    w = stroke_for(size) if width is None else max(0.5, float(width))
    fn(dl, _Grid(x, y, size, w), color, alpha)
