"""Рабочая станция: оболочка приложения, компоновка, компоненты, ввод.

Отдельный пакет, а не правка прежнего `ui`: прежний интерфейс остаётся
рабочим и запускается как `fly app --old`, пока новый не согласован.

Что переиспользуется из `ui` без изменений:
    gpu        растеризатор на Taichi: плитки, порядок наложения, обрезка
    font       атлас глифов с ролями и верными метриками
    brainview  карта коннектома
    session    связь с процессом-работником
    query      модель сборщика селектора

Что здесь новое:
    tokens     единственная таблица величин: цвет, кегль, отступ, скругление
    layout     док-зоны с закреплением, пределами, разделителями и скроллом
    keys       откуда берутся события клавиатуры: подмена оконной процедуры
               Win32, потому что `get_events` в GGUI теряет раскладку,
               регистр и знаки препинания
    textinput  что с событиями делает поле ввода; чистая модель без рисования
    icons      иконки геометрией
    widgets    набор компонентов с полным набором состояний
    canvas     фасад над несколькими списками команд: по списку на атлас
    shell      окно и его повадки; `Offscreen` — то же самое без окна
    state      состояние приложения, разложенное по принадлежности
    app        оболочка: зоны, пространства, полоса исполнения
    ws_body    рабочее пространство «Тело»
    ws_brain   рабочее пространство «Мозг»: коннектом, поиск, связи
    eyes       вид глаз: кадр обеих камер, показания омматидиев и
               четыре частоты, которые нельзя сливать в одну

Подмодули здесь намеренно не импортируются: `tokens` и `layout` не должны
тянуть за собой ни Win32, ни Taichi, иначе их нельзя проверить без окна.
Берите их по имени: `from flybrain.desk import layout`.
"""

