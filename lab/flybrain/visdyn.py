@dataclass
class Привод:
    """Движок плюс зрительная динамика выбранного режима.

    Шаг остаётся шагом `Engine`: привод ничего не считает за него и
    ничего в нём не подменяет. Он делает ровно три вещи между шагами:

    1. кладёт в `rates` пуассоновский зрительный вход — только в
       эталонном режиме и только на фоторецепторы;
    2. кладёт в `spikes` дробную отдачу градуальных клеток — в
       физиологическом режиме;
    3. кладёт в `rates` внешне посчитанный сигнал на ОБЪЯВЛЕННОЙ
       границе — в гибридном.

    Маски ставятся один раз при сборке и больше не меняются: в
    физиологическом режиме у градуальных клеток `m_fire = 0`, то есть
    порогового спайка они не выдают и мембрану не сбрасывают — именно
    это и значит «неспайковая клетка» (замерено, `probe/phys_calib.py`).
    """

    eng: object
    n: int
    dev: str
    режим: str
    pops: dict                      # имя → индексы (numpy)
    maps: dict                      # привязка омматидиев
    phys: object = None             # Физиология или None
    граница: tuple = ()             # имена популяций стыковки (гибрид)
    _t: dict = field(default_factory=dict, repr=False)

    # --- сборка -------------------------------------------------------

    @classmethod
    def собрать(cls, W, neurons, pops, maps, режим=РЕЖИМ_ЭТАЛОН,
                phys=None, граница=(), dev=None, seed=0, snap=None,
                spmv=None, graphs=True):
        """Собрать привод.

        Эталонная матрица подменяется ТОЛЬКО если режим физиологический
        и знак рецепторов просили биологический; число перевёрнутых
        связей возвращается в сводке, а не замалчивается.
        """
        import torch

        from . import sim

        if режим not in РЕЖИМЫ:
            raise ValueError("не режим: %r, есть %s" % (режим, РЕЖИМЫ))
        dev = dev or ("cuda" if torch.cuda.is_available() else "cpu")
        n = len(neurons)
        pr_idx = np.unique(np.concatenate([maps[k].neurons for k in maps]))

        знак, Wu = None, W
        if (режим == РЕЖИМ_ФИЗИОЛОГИЯ and phys is not None
                and phys.биологический_знак):
            Wu, знак = матрица_биологического_знака(W, pr_idx)

        # Рефрактерность снимается с фоторецепторов — так же, как это
        # делает эталонный режим и как проект делает для обонятельных
        # рецепторов: иначе пуассоновская частота не воспроизводится.
        eng = sim.build_engine(weights=Wu, neurons=neurons, device=dev,
                               seed=seed, no_refractory=pr_idx,
                               graphs=graphs, spmv=spmv)
        if snap is not None:
            for nm, val in snap["поля"].items():
                getattr(eng, nm).copy_(val)
            eng.ptr = snap["ptr"]
            eng.gen.set_state(snap["gen"].clone())

        self = cls(eng=eng, n=n, dev=dev, режим=режим, pops=pops,
                   maps=maps, phys=phys, граница=tuple(граница))
        self._t["знак"] = знак
        self._t["pr_idx"] = pr_idx
        self._t["pr_t"] = torch.as_tensor(pr_idx, device=dev)
        self._t["rates"] = torch.zeros(1, n, device=dev)
        self._t["pops_t"] = {k: torch.as_tensor(v, device=dev)
                             for k, v in pops.items()}
        self._t["map_t"] = {k: torch.as_tensor(m.neurons, device=dev)
                            for k, m in maps.items()}
        self._t["кадр_мс"] = 10.0
        self._t["L_half"] = None
        if режим == РЕЖИМ_ФИЗИОЛОГИЯ and phys is not None:
            self._поставить_градуальные()
        return self

    def _поставить_градуальные(self):
        """Замолчать по порогу те популяции, что объявлены неспайковыми."""
        import torch

        p = self.phys
        grad = {}
        if p.градуальные_рецепторы:
            grad["рецепторы"] = self._t["pr_idx"]
        # Отказ ГРОМКИЙ, и это не придирка. Первая редакция
        # `probe/vision_phys_control.py` не включила L4, Tm3 и Tm4 в
        # свой перечень популяций, и режим тихо собрался БЕЗ них — тот
        # же названный набор дал LC4 0,433 Гц вместо 17,644. Сравнение
        # двух проб при этом выглядело законным и не было им. Молча
        # выбрасывать объявленную популяцию нельзя: это подменяет
        # модель, не говоря об этом.
        нет = []
        for поле, вкл in (("ламина", p.градуальная_ламина),
                          ("медулла", p.градуальная_медулла)):
            if not вкл:
                continue
            for nm in getattr(p, поле):
                if nm not in self.pops or not len(self.pops[nm]):
                    нет.append("%s (%s)" % (nm, поле))
                else:
                    grad[nm] = self.pops[nm]
        if нет:
            raise ValueError(
                "градуальными объявлены популяции, которых нет в "
                "перечне привода: %s. Собрать режим без них значило бы "
                "подменить его молча — добавьте их в перечень "
                "популяций или уберите из набора" % ", ".join(нет))
        self._t["градуальные"] = grad
        if not grad:
            self._t["lam_t"] = self._t["med_t"] = None
            return
        all_idx = np.unique(np.concatenate(list(grad.values())))
        t = torch.as_tensor(all_idx, device=self.dev)
        # Вот и всё вмешательство: порогового спайка эти клетки не
        # выдают. Мембрана при этом НЕ сбрасывается и проводимость не
        # обнуляется — клетка ведёт себя как неспайковая, и это
        # замерено, а не предположено.
        self.eng.m_fire[0, t] = 0.0
        self._t["grad_all"] = t

        lam = [nm for nm in p.ламина if nm in grad]
        med = ([nm for nm in p.медулла if nm in grad and nm not in lam]
               if p.градуальная_медулла else [])
        # Одна популяция в двух наборах получила бы два разных усиления,
        # и побеждало бы то, что пишется вторым. Отказ громкий: тихо
        # выбранное усиление сделало бы любое число непроверяемым.
        пересечение = set(p.ламина) & set(p.медулла)
        if p.градуальная_медулла and пересечение:
            raise ValueError(
                "популяции %s объявлены и ламиной, и медуллой — у них "
                "вышло бы два разных усиления на одну клетку"
                % sorted(пересечение))
        self._t["lam_t"] = (
            torch.as_tensor(np.unique(np.concatenate(
                [self.pops[nm] for nm in lam])), device=self.dev)
            if lam else None)
        self._t["med_t"] = (
            torch.as_tensor(np.unique(np.concatenate(
                [self.pops[nm] for nm in med])), device=self.dev)
            if med else None)

    # --- сброс между условиями ----------------------------------------

    def сброс(self, snap):
        """Поставить состояние движка на место и забыть адаптацию.

        Нужно, чтобы не пересобирать движок на каждое условие: сборка
        читает 15 091 983 связи и захватывает 19 CUDA-графов, а условий
        в развёртке десятки. Маски вмешательств при этом НЕ сбрасываются
        — они часть устройства режима, а не состояния шага, и в
        `snap` их нет (`Engine.STATE_TENSORS` масок не содержит).

        Проверка, что сброс полон, не рассуждением, а замером: два
        подряд одинаковых условия обязаны дать побитово один результат.
        Это и проверяет `probe/vision_phys.py`.
        """
        for nm, val in snap["поля"].items():
            getattr(self.eng, nm).copy_(val)
        self.eng.ptr = snap["ptr"]
        self.eng.gen.set_state(snap["gen"].clone())
        self._t["L_half"] = None
        self._t["pr_hz"] = None
        self._t["rates"].zero_()

    def привязка(self, maps):
        """Сменить привязку омматидиев, не пересобирая движок.

        Привязка входит только в пересчёт кадра в отдачу рецепторов, а
        матрицы связей не касается вовсе. Поэтому перемешанный
        встречный замер идёт на ТОМ ЖЕ движке — и это не удобство:
        иначе разница между настоящей и перемешанной привязкой могла бы
        прийти от разной сборки, а не от структуры.
        """
        import torch

        if set(maps) != set(self.maps):
            raise ValueError("другой набор популяций рецепторов")
        self.maps = maps
        self._t["map_t"] = {k: torch.as_tensor(m.neurons, device=self.dev)
                            for k, m in maps.items()}

    def усиление(self, g_ламина=None, g_медулла=None):
        """Сменить усиление градуального синапса, не пересобирая движок.

        Усиление входит только в передаточную функцию отдачи, а она
        считается на каждом шаге заново. Ни матрицы, ни масок это не
        касается, поэтому развёртка по усилению идёт на одном движке.
        """
        if self.phys is None:
            raise ValueError("усиление есть только у физиологического режима")
        if g_ламина is not None:
            self.phys.g_ламина = float(g_ламина)
        if g_медулла is not None:
            self.phys.g_медулла = float(g_медулла)

    # --- подача кадра -------------------------------------------------

    def подать_кадр(self, кадр, вкл=True, кадр_мс=10.0):
        """Пересчитать зрительный вход по кадру ``(2, 721, 2)``.

        В эталонном режиме это пуассоновская частота на фоторецепторы.
        В физиологическом — равнозначная частота градуального
        фоторецептора, которая кладётся не в `rates`, а запоминается и
        подаётся в `spikes` на каждом шаге.
        """
        import torch

        from . import retina as R, sim

        self._t["кадр_мс"] = float(кадр_мс)
        rates = self._t["rates"]
        rates.zero_()
        if not вкл:
            self._t["pr_hz"] = None
            return

        p = self.phys
        if (self.режим != РЕЖИМ_ФИЗИОЛОГИЯ or p is None
                or not p.градуальные_рецепторы):
            hz = R.rates(self.maps, кадр,
                         max_hz=(p.pr_max_hz if p is not None
                                 else PR_MAX_HZ),
                         ref=VIS_REF)
            for key, v in hz.items():
                rates[0, self._t["map_t"][key]] = torch.as_tensor(
                    np.asarray(v, dtype=np.float32), device=self.dev)
            self._t["pr_hz"] = None
            return

        inten = R.intensity(self.maps, кадр)
        half = None
        if p.адаптация:
            # Полунасыщение следует за средней яркостью поля зрения с
            # объявленным временем. Среднее берётся по всем нейронам
            # привязки, а не по одной клетке: световая адаптация у мухи
            # тоже не поклеточная мгновенная.
            cur = float(np.mean(np.concatenate(
                [np.asarray(v).ravel() for v in inten.values()])))
            prev = self._t.get("L_half")
            if prev is None:
                half = cur
            else:
                a = min(1.0, float(кадр_мс) / max(p.адапт_мс, 1e-6))
                half = (1.0 - a) * prev + a * cur
            self._t["L_half"] = half

        # В `spikes` кладётся не частота, а дробная доля на шаг:
        # s = hz · DT/1000. Это и делает равнозначную частоту сравнимой
        # с герцами прежних таблиц (сверено до 0,13 %).
        s = {}
        for key, v in inten.items():
            hz = отклик_рецептора(v, pr_max_hz=p.pr_max_hz,
                                  полунасыщение=half, ref=VIS_REF)
            s[key] = torch.as_tensor(
                np.asarray(hz, dtype=np.float32) * (sim.DT / 1000.0),
                device=self.dev)
        self._t["pr_hz"] = s

    def подать_границу(self, сигнал_hz):
        """Гибридный режим: внешне посчитанный сигнал на границу.

        ``сигнал_hz`` — словарь «имя популяции → частота в герцах»
        (число или массив по нейронам популяции). Имена обязаны входить
        в объявленную ``граница``: иначе стыковка перестала бы быть
        названной, а это и есть то, что запрещено.
        """
        import torch

        from . import sim

        # Канал пуассоновского входа НАСЫЩАЕТСЯ, и это не настройка, а
        # устройство движка: `_poisson` делает одно испытание Бернулли
        # на шаг 0,1 мс, то есть не может доставить больше **10 000 Гц**
        # на нейрон. Выше этого `torch.bernoulli` падает утверждением
        # на видеокарте, и первая редакция этой пробы на нём и упала.
        # Срез здесь явный, и сколько нейронов он задел — записывается:
        # тихий срез сделал бы развёртку усиления непроверяемой.
        предел = 1000.0 / sim.DT
        rates = self._t["rates"]
        rates.zero_()
        срезано, всего = 0, 0
        for nm, hz in сигнал_hz.items():
            if nm not in self.граница:
                raise ValueError(
                    "подача на %r вне объявленной границы %s — стыковка "
                    "обязана быть названной" % (nm, list(self.граница)))
            t = self._t["pops_t"][nm]
            val = np.asarray(hz, dtype=np.float32)
            if val.ndim:
                срезано += int((val > предел).sum())
                всего += int(val.size)
                rates[0, t] = torch.clamp(
                    torch.as_tensor(val, device=self.dev), max=предел)
            else:
                всего += 1
                срезано += int(float(val) > предел)
                rates[0, t] = min(float(val), предел)
        п = self._t.setdefault("срез", {"срезано": 0, "всего": 0,
                                        "предел, Гц": предел})
        п["срезано"] += срезано
        п["всего"] += всего
        return п

    # --- шаг ----------------------------------------------------------

    def шаг(self):
        """Один тик 0,1 мс со всей динамикой режима."""
        import torch

        from . import sim

        p = self.phys
        if self.режим == РЕЖИМ_ФИЗИОЛОГИЯ and p is not None:
            pr = self._t.get("pr_hz")
            if p.градуальные_рецепторы:
                if pr is None:
                    self.eng.spikes[0, self._t["pr_t"]] = 0.0
                else:
                    for key, s in pr.items():
                        self.eng.spikes[0, self._t["map_t"][key]] = s
            k = sim.DT / 1000.0
            for ключ, g in (("lam_t", p.g_ламина),
                            ("med_t", p.g_медулла or p.g_ламина)):
                t = self._t.get(ключ)
                if t is None:
                    continue
                v = self.eng.v[0, t] - self.eng.v_rest + p.v_тоник
                v = torch.clamp(v, 0.0, p.v_тоник * p.v_насыщ_к)
                self.eng.spikes[0, t] = v * (g * k)
            # Отдача градуальных клеток существует только ДО шага:
            # `_core` перезаписывает `spikes` порогом в конце. Копить её
            # можно только здесь, и копится она ОТДЕЛЬНО от спайков —
            # складывать равнозначную частоту с частотой разрядов было
            # бы подменой.
            acc = self._t.get("acc_grad")
            if acc is not None:
                acc.add_(self.eng.spikes[0])
        return self.eng.step(self._t["rates"])

    def копить_отдачу(self, вкл=True):
        """Включить накопление отдачи градуальных клеток.

        Возвращает тензор-накопитель (или None). Величина в нём — сумма
        дробных долей на шаг; равнозначная частота получается делением
        на `DT/1000`, то есть умножением на 10 000 при DT 0,1 мс.
        """
        import torch

        if not вкл:
            self._t["acc_grad"] = None
            return None
        self._t["acc_grad"] = torch.zeros(self.n, device=self.dev)
        return self._t["acc_grad"]

    # --- съём ---------------------------------------------------------

    def отдача(self):
        """Что каждая популяция отдала на этом шаге.

        У градуальных клеток «спайков» нет: в их `spikes` лежит дробная
        отдача, и складывать её со спайками спайковых клеток было бы
        подменой. Поэтому возвращается ещё и множество имён
        градуальных популяций, и в таблицах они помечены как
        равнозначная частота, а не как частота разрядов.
        """
        grad = set(self._t.get("градуальные", {}))
        out = {k: float(self.eng.spikes[0, t].sum())
               for k, t in self._t["pops_t"].items()}
        return out, grad

    def мембрана(self):
        """Максимум мембраны над покоем и проводимости по популяциям.

        Это то, чем `VISION_DEEP.md` §3 отличил «мало» от «не
        успевает», и в новых режимах различать это надо тем же
        способом, иначе числа несравнимы.
        """
        out = {}
        for k, t in self._t["pops_t"].items():
            v = self.eng.v[0, t] - self.eng.v_rest
            out[k] = (float(v.max()),
                      float(self.eng.conductance[0, t].max()))
        return out

    def сводка(self) -> dict:
        d = {"режим": self.режим, "устройство": self.dev}
        if self.режим == РЕЖИМ_ФИЗИОЛОГИЯ and self.phys is not None:
            d["физиология"] = self.phys.сводка()
            if self._t.get("знак"):
                d["переворот знака фоторецепторов"] = self._t["знак"]
            d["градуальные популяции"] = {
                k: int(len(v))
                for k, v in self._t.get("градуальные", {}).items()}
        if self.режим == РЕЖИМ_ГИБРИД:
            d["ГРАНИЦА СТЫКОВКИ"] = list(self.граница)
            d["предупреждение"] = (
                "отклики за этой границей посчитаны ВНЕ сети и "
                "смоделированным вышележащим синапсам не принадлежат")
        return d
