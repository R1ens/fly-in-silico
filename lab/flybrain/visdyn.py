def предел_отдачи(params) -> float:
    """Потолок равнозначной частоты из устройства модели: 1/tRefrac.

    Это не литературное число и не подгонка — это то, чего физически не
    может превысить спайковая клетка того же движка. Отдача градуальной
    клетки выше этого потолка означала бы, что градуальность не
    воспроизводит клетку, а добавляет усиление, которого в модели нет.
    """
    return 1000.0 / float(params["tRefrac"])


def потолок_усиления(params, v_тоник=V_ТОНИК, k=V_НАСЫЩ_К) -> float:
    """Потолок `g_ламина` в Гц/мВ, из того же устройства модели."""
    return предел_отдачи(params) / max(v_тоник * k, 1e-9)


def поток_сохраняющее_усиление(hz_эталон, v_тоник=V_ТОНИК) -> float:
    """Нижняя привязка `g_ламина`: тот же поток медиатора, что в эталоне.

    Если градуальная клетка в рабочей точке отдаёт столько же, сколько
    спайковая отдавала в эталонном режиме, добавленного усиления нет
    вовсе. Это самая осторожная из возможных привязок, и проба
    показывает, что одной её не хватает.
    """
    return float(hz_эталон) / max(float(v_тоник), 1e-9)


# ------------------------------------------------------- знак рецепторов

def матрица_биологического_знака(W, pr_idx):
    """Копия матрицы, где ВЫХОД фоторецепторов сделан тормозным.

    Матрица движка — ``W[post, pre]``, значит переворачивать надо
    СТОЛБЦЫ фоторецепторов. Переворот не молчаливый: возвращается ещё и
    число изменённых связей, и оно идёт в отчёт прогона. Эталонная
    матрица не трогается — собирается отдельная.

    Знак ставится **отрицательным**, а не умножается на −1: у части
    фоторецепторов набор уже даёт тормозной знак (20,9 % у R1-6), и
    умножение сделало бы их возбуждающими, то есть внесло бы ровно ту
    ошибку, которую режим исправляет.
    """
    import torch

    w = W.coalesce()
    idx = w.indices().clone()
    val = w.values().clone()
    pre = idx[1]
    mark = torch.zeros(w.shape[1], dtype=torch.bool, device=val.device)
    mark[torch.as_tensor(np.asarray(pr_idx, dtype=np.int64),
                         device=val.device)] = True
    hit = mark[pre]
    было_возбужд = int((hit & (val > 0)).sum())
    было_тормозн = int((hit & (val < 0)).sum())
    val[hit] = -val[hit].abs()
    from . import data as D
    with D._quiet_sparse():
        out = torch.sparse_coo_tensor(idx, val, w.shape).coalesce()
    отчёт = {
        "связей у фоторецепторов": int(hit.sum()),
        "перевёрнуто (были возбуждающими)": было_возбужд,
        "уже были тормозными": было_тормозн,
        "фоторецепторов": int(len(pr_idx)),
    }
    return out, отчёт


# ------------------------------------------------- передаточные функции

def отклик_рецептора(яркость, pr_max_hz=PR_MAX_HZ, полунасыщение=None,
                     ref=VIS_REF):
    """Равнозначная частота градуального фоторецептора.

    Два правила, и выбор между ними объявлен:

    * **без адаптации** — то же правило, что у эталонного режима
      (`retina.rates`): ``hz = max · min(1, яркость/ref)``. Нужно, чтобы
      градуальность можно было сравнить с эталоном при ОДНОМ И ТОМ ЖЕ
      правиле яркость-в-частоту, то есть отделить вклад градуальности
      от вклада нового правила;
    * **с адаптацией** — Нака-Рашто с полунасыщением по текущей средней
      яркости: ``hz = max · L/(L + L½)``. Это световая адаптация
      фоторецептора: кривая отклика сдвигается так, что рабочая точка
      садится на окружающую среднюю (Laughlin & Hardie 1978; Juusola &
      Hardie 2001).

    При ``L = L½`` отдача равна половине потолка — то есть рабочая точка
    стоит ровно посередине, и отклик двусторонний: светлее среднего
    усиливает, темнее ослабляет. Это и есть то, что делает возможным
    расторможение по контрасту.
    """
    L = np.asarray(яркость, dtype=np.float64)
    if полунасыщение is None:
        return float(pr_max_hz) * np.minimum(
            1.0, L / max(float(ref), 1e-12))
    h = max(float(полунасыщение), 1e-6)
    return float(pr_max_hz) * (L / (L + h))


def отдача_градуальной(v_над_покоем, v_тоник, g, v_насыщ):
    """Равнозначная частота неспайковой клетки, Гц.

    ``v_над_покоем`` — деполяризация мембраны модели над покоем;
    ``v_тоник`` — стоячая деполяризация, с которой клетка сидит в
    отсутствие входа (свойство клетки, в сеть ничем не подаётся);
    ``g`` — усиление градуального синапса, Гц/мВ; ``v_насыщ`` — где
    отдача упирается в потолок.

    Отдача срезана снизу нулём и сверху насыщением. Срез снизу — не
    удобство: отдача ниже нуля значила бы, что клетка забирает медиатор
    обратно, чего не бывает. Срез сверху — объявленное насыщение
    градуального синапса, без него отдача росла бы без границы, потому
    что порогового сброса у неспайковой клетки нет.
    """
    v = np.asarray(v_над_покоем, dtype=np.float64) + float(v_тоник)
    return float(g) * np.clip(v, 0.0, float(v_насыщ))


