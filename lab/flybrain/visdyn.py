"""Зрительная динамика: три РАЗВЕДЁННЫХ режима поверх одного движка.

Этот модуль не правит ни одной строки `sim.py`, `body.py`, `spec.py`.
Он надстраивается над `Engine` штатными средствами — масками
вмешательств и записью в тензор `spikes` между шагами, — и калибровка
этой механики снята отдельно (`probe/phys_calib.py`, 10 проверок,
0 провалов). Главное её число: **тождественное вмешательство оставляет
состояние побитово тем же**, то есть эталонный режим этого модуля не
видит.

Три режима, и смешивать их запрещено:

``РЕЖИМ_ЭТАЛОН`` (`reference_lif`)
    Исторический LIF без изменений. Фоторецепторы — пуассоновский вход
    по правилу `retina.rates`, знак связей из набора, все нейроны
    спайковые. По нему посчитаны 28 сохранённых прогонов и стоят
    побитовые шлюзы. **Ни одной строки не добавлено и не отнято.**

``РЕЖИМ_ФИЗИОЛОГИЯ`` (`physiological_visual`)
    Опытная зрительная динамика, у которой каждое допущение названо и
    привязано к литературе или помечено подогнанным. Четыре
    составляющие, и ни одна не добавляет ни одной связи и не меняет
    `wScale`:

    1. **градуальные фоторецепторы.** У дрозофилы R1-6 не спайкуют
       вовсе — они отдают медиатор непрерывно, пропорционально
       деполяризации (Hardie 1989; Juusola & Hardie 2001). В движке
       клетка замалчивается по порогу (`m_fire = 0`), а в её `spikes`
       кладётся дробное значение — **равнозначная частота**, сравнимая
       с герцами прежних таблиц напрямую (сверено до 0,13 %);
    2. **световая адаптация.** Отклик берётся по Нака-Рашто с
       полунасыщением, которое следует за текущей средней яркостью
       (Laughlin & Hardie 1978; Juusola & Hardie 2001). Это
       единственный источник временной фильтрации здесь, и он не
       подогнан под результат;
    3. **гистаминергическое торможение.** R1-6 гистаминергические и
       ТОРМОЗЯТ L1/L2/L3 через HisCl1 (Hardie 1989; Gengs et al. 2002).
       В наборе eonsystemspbc знак фоторецепторов возбуждающий, и это
       недостоверно **по построению**: гистамина в словаре
       предсказателя FlyWire нет вовсе (`VISION_DEEP.md` §5). Здесь
       знак ставится биологический — явно, отдельной матрицей, с
       записью числа перевёрнутых связей в отчёт;
    4. **рабочая точка ламины и расторможение по контрасту.** Свет
       усиливает гистаминергическое торможение, значит L1/L2/L3 в
       темноте деполяризованы, а свет их гиперполяризует (Laughlin &
       Hardie 1978). В токовой модели шунт хлором так не выражается,
       поэтому у градуальной ламины объявляется **стоячая
       деполяризация** `V_ТОНИК`, от которой торможение отнимает. И
       отсюда ON-путь получается тем, чем он является у мухи:
       **расторможением** — свет снимает торможение L1 с Mi1, L5 и Tm3
       (в v783 это −77,4, −71,9 и −46,6 связи на нейрон).

    Стоячая деполяризация НЕ подаётся в сеть ничем: это свойство
    передаточной функции самой градуальной клетки. Поэтому встречный
    замер с выключенным зрением получает **ровно ту же** стоячую
    отдачу, и зрению принадлежит только разность.

``РЕЖИМ_ГИБРИД`` (`hybrid_visual`)
    Зрительная обработка, посчитанная ВНЕ сети, с **явно обозначенной**
    инженерной границей стыковки. Граница называется в каждом выводе
    (`граница` в сводке), и отклики за ней не приписываются
    смоделированным вышележащим синапсам. Это не зрение по коннектому и
    так не называется.

Чего здесь нет нарочно: умножения всех весов на множитель (запрещено
владельцем), молчаливого переворота знаков (знак переворачивается
только у фоторецепторов, только явно и только с записью числа связей),
фона на все оптические доли (отклонён своим же контролем,
`VISION.md` §3).
"""

