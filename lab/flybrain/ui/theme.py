# Границы светлоты: ниже цвет пропадает на графитовом фоне, выше слепит.
L_MIN, L_MAX = 0.33, 0.88


def _oklab_to_linear(L, a, b):
    l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (+4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
            -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
            -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)


def _gamma(c):
    if c <= 0.0031308:
        return 12.92 * c
    return 1.055 * (max(c, 0.0) ** (1 / 2.4)) - 0.055


def lch_to_rgb(L, C, hue_deg):
    a = C * math.cos(math.radians(hue_deg))
    b = C * math.sin(math.radians(hue_deg))
    return tuple(min(1.0, max(0.0, _gamma(v))) for v in _oklab_to_linear(L, a, b))


def _in_gamut(L, C, hue_deg, tol=1e-4):
    a = C * math.cos(math.radians(hue_deg))
    b = C * math.sin(math.radians(hue_deg))
    return all(-tol <= v <= 1 + tol for v in _oklab_to_linear(L, a, b))


def hex_of(c):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(x * 255))) for x in c)


def magma_at(t):
    """Цвет magma для t в [0, 1]."""
    t = 0.0 if t < 0.0 else (1.0 if t > 1.0 else t)
    p = t * (len(MAGMA) - 1)
    i = int(p)
    j = min(i + 1, len(MAGMA) - 1)
    f = p - i
    a, b = MAGMA[i], MAGMA[j]
    return (a[0] + (b[0] - a[0]) * f,
            a[1] + (b[1] - a[1]) * f,
            a[2] + (b[2] - a[2]) * f)


def super_color(name):
    name = name if name in SUPER_HUES else "other"
    lc, _ = SUPER_L[name]
    return lch_to_rgb(lc, SUPER_C[name], SUPER_HUES[name])


def region_colors(region_to_super):
    """Цвет на каждый нейропиль.

    Внутри супер-области держится тон, а расходятся светлота и насыщенность:
    семейство читается с одного взгляда, области внутри него различимы.
    Порядок внутри семейства — по имени, чтобы цвет области не менялся от
    прогона к прогону.
    """
    families = {}
    for region, sup in sorted(region_to_super.items()):
        families.setdefault(sup if sup in SUPER_HUES else "other", []).append(region)

    out = {}
    for sup, regions in families.items():
        hue = SUPER_HUES[sup]
        lc, span = SUPER_L[sup]
        c0 = SUPER_C[sup]
        k = len(regions)
        # Полоса растягивается по числу областей: шесть нейропилей
        # центрального комплекса в узкой полосе сливались.
        span = max(span, min(0.34, 0.085 * (k - 1)))
        for i, region in enumerate(regions):
            t = 0.0 if k == 1 else (i / (k - 1)) * 2 - 1      # -1 .. +1
            L = min(L_MAX, max(L_MIN, lc + t * span * 0.5))
            # Насыщенность падает к светлому краю — иначе светлые вылетают из
            # охвата, — и заодно работает второй осью различия внутри семейства.
            C = c0 * (1.0 - 0.34 * t)
            hh = hue + t * 7.0
            while not _in_gamut(L, C, hh) and C > 0.005:
                C *= 0.93
            out[region] = lch_to_rgb(L, C, hh)
    return out
