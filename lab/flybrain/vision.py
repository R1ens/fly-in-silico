"""Зрительный переходник: кадр сетчатки тела -> частоты фоторецепторов.

Это ПЛУМБИНГ, а не модель. Здесь нет ни одной буквы про то, как
устроено зрение мухи: вся содержательная часть живёт в переходнике,
который выбирается **по имени**, и подменить его можно, не тронув ни
`body.py`, ни спеку, ни окно.

Зачем имя, а не класс в `body.py`
---------------------------------

Параллельно идут две работы, каждая из которых даёт свой переходник:
настоящая ретинотопия по зрительным колонкам FlyWire (вместо нынешней
инженерной привязки) и физиологическая динамика раннего зрения. Обе
обязаны встать на место без переделки обмена с работником. Поэтому
контракт переходника объявлен здесь целиком, а новый регистрируется
одной строкой :func:`register`.

Контракт переходника
--------------------

* ``name``, ``version`` — имя и версия; едут в сохранённый прогон;
* ``attach(neurons, device)`` — построиться на настоящей таблице
  нейронов. Зовётся ОДИН раз, до разогрева;
* ``indices`` — ``np.int64`` номера нейронов, в которые переходник
  пишет. Нужны движку: по ним снимается рефрактерность, как у
  обонятельных каналов;
* ``feed(rates, frame, contrast=1.0)`` — записать частоты в тензор
  ``rates`` формы ``(1, n)``. Зовётся на каждом шаге управления, после
  ``rates.zero_()`` и сенсорных каналов;
* ``provenance()`` — **происхождение**: по какому правилу считалась
  привязка, с какими отпечатками. Уезжает в `timing["зрение"]`
  сохранённого прогона, и по нему прогон опознаётся однозначно;
* ``caveat()`` — ограничение словами, или ``None``. Оно едет в
  `timing["оговорки"]`, а не прячется.

Что здесь считается придуманным и помечено
------------------------------------------

Две вещи, и обе объявлены в самом прогоне.

**Привязка омматидиев инженерная, и внешний свидетель её опроверг.**
`retina.py` строит её по объявленному правилу, а не восстанавливает:
ретинотопия из координат сом v783 доказанно невосстановима
(`probe/retinotopy.py`). Опубликованные назначения зрительных колонок
FlyWire дали первый внешний свидетель, и по решающему признаку — R7 и
R8 одной колонки обязаны лечь в один омматидий — привязка оказалась
**хуже случайной**: 0 пар из 430 против 2 из 430 у перемешанной
(`probe/columns_witness.py`, `VISUAL_COLUMNS.md`). Поэтому единственное
обеспеченное свойство этих каналов — **соседство внутри одной
популяции**, и ретинотопией их называть нельзя. Это сказано и в
происхождении прогона, и в оговорках, а не только здесь.

Отпечаток привязки — в происхождении, встречный замер — ``shuffle=True``.

**Яркость в герцы — наше правило**, ровно такое же, как у обоняния:
``hz = max_hz · min(1, яркость / ref)``. Ни одного нейрона оно не
выделяет.

Чего переходник НЕ делает: не трогает свет сцены. Свет — это настоящие
источники MuJoCo (`light_top`, `light_bottom` арены FlyGym), и правит
их :func:`scene_light` прямо в модели, то есть меняется сам кадр, а не
его пересчёт. Контраст, наоборот, считается здесь по объявленной
формуле вокруг середины шкалы, и в происхождении написано, что это
преобразование кадра, а не свойство сцены.
"""

from __future__ import annotations

import numpy as np

__all__ = ["ADAPTERS", "register", "make", "names", "about", "EYES",
           "CHANNELS", "RetinaAdapter", "scene_light", "light_state"]

# Какие глаза подаются. `both` — оба сложных глаза, и это значение по
# умолчанию: муха видит двумя, и односторонняя подача есть контроль, а
# не рабочая точка.
EYES = ("both", "left", "right")

# Что делать с двумя каналами фоторецептора. Перечислено здесь, чтобы
# окно и справочник брали список из одного места.
CHANNELS = ("max", "pale", "yellow")

# Имя -> (фабрика, пояснение). Заполняется ниже и пополняется
# :func:`register`.
ADAPTERS: dict = {}


def register(name, factory, about=""):
    """Зарегистрировать переходник под именем.

    Отказ при попытке занять уже занятое имя — громкий. Молча
    подменённый переходник значит, что сохранённый прогон называет одно,
    а считало другое.
    """
    name = str(name)
    if name in ADAPTERS:
        raise ValueError(
            "зрительный переходник %r уже зарегистрирован (%s). Имя — это "
            "то, по чему прогон опознаётся; подменять его молча нельзя"
            % (name, ADAPTERS[name][1] or "без пояснения"))
    ADAPTERS[name] = (factory, str(about))
    return name


def names():
    """Имена всех зарегистрированных переходников, по алфавиту."""
    return tuple(sorted(ADAPTERS))


def about(name=None):
    """Пояснение к переходнику или ко всем сразу."""
    if name is None:
        return {k: v[1] for k, v in sorted(ADAPTERS.items())}
    return ADAPTERS[str(name)][1]


def make(name, **kw):
    """Собрать переходник по имени. Неизвестное имя — отказ со списком."""
    name = str(name or "retina")
    if name not in ADAPTERS:
        raise ValueError(
            "неизвестный зрительный переходник %r; есть: %s"
            % (name, ", ".join(names()) or "ни одного"))
    return ADAPTERS[name][0](**kw)


# ------------------------------------------------------------ свет сцены


def scene_light(body, factor):
    """Умножить свет арены на ``factor``. Возвращает, что получилось.

    Это НАСТОЯЩИЙ свет: `light_ambient` и `light_diffuse` источников
    MuJoCo, то есть меняется сам рендер кадра глаза, а не его пересчёт.
    Опора — не догадка: `flygym_gymnasium/arena/base.py:init_lights`
    создаёт `light_top` и `light_bottom` с ambient (0,2) и diffuse (0,7),
    и они есть у любой арены FlyGym, в том числе у `OdorArena`.

    Исходные значения запоминаются при первом вызове, и множитель
    применяется К НИМ, а не к текущим: иначе два вызова подряд давали бы
    произведение, и «свет 1,0» не возвращал бы сцену в исходное
    состояние.
    """
    m = body.physics.model.ptr
    n = int(getattr(m, "nlight", 0) or 0)
    if n <= 0:
        raise ValueError(
            "в модели нет ни одного источника света: менять нечего. "
            "Арена FlyGym их создаёт (`arena/base.py:init_lights`), и "
            "их отсутствие значит другую сцену")
    base = getattr(body, "_fb_light0", None)
    if base is None:
        base = (np.array(m.light_ambient, dtype=float).copy(),
                np.array(m.light_diffuse, dtype=float).copy())
        body._fb_light0 = base
    f = float(factor)
    if f < 0.0:
        raise ValueError("свет не бывает отрицательным: пришло %r" % (f,))
    m.light_ambient[:] = np.clip(base[0] * f, 0.0, 1.0)
    m.light_diffuse[:] = np.clip(base[1] * f, 0.0, 1.0)
    return light_state(body)


def light_state(body):
    """Что со светом сейчас: для записи сеанса и для подтверждения."""
    m = body.physics.model.ptr
    n = int(getattr(m, "nlight", 0) or 0)
    if n <= 0:
        return {"источников света": 0}
    base = getattr(body, "_fb_light0", None)
    amb = np.array(m.light_ambient, dtype=float)
    dif = np.array(m.light_diffuse, dtype=float)
    out = {"источников света": n,
           "ambient": [round(float(v), 4) for v in amb[0]],
           "diffuse": [round(float(v), 4) for v in dif[0]]}
    if base is not None:
        b = float(base[1][0][0])
        out["множитель"] = round(float(dif[0][0]) / b, 4) if b else None
        out["исходный diffuse"] = [round(float(v), 4) for v in base[1][0]]
    return out


# ------------------------------------------------ переходник «retina»


class RetinaAdapter:
    """Инженерная привязка омматидиев (`flybrain.retina`) как переходник.

    Вся арифметика совпадает с :func:`flybrain.retina.rates` до бита при
    ``contrast == 1``, и это не рассуждение: при единичном контрасте
    преобразование кадра НЕ ИСПОЛНЯЕТСЯ вовсе, а частота считается тем
    же выражением. Проверяется `probe/vision_product.py`, пункт 2.

    Отличие от прямого вызова `retina.rates` одно, и оно про цену:
    вместо шести словарей на шаг здесь один плоский сбор. Номера
    «глаз × омматидий» сложены в один массив при сборке, поэтому шаг —
    это одна выборка по индексу и одно умножение на 10 582 числа, а не
    шесть выборок со склейкой.
    """

    name = "retina"
    version = 1

    # Какой это вариант привязки. Поле отдельное от `version` нарочно:
    # `version` — это версия ПЕРЕХОДНИКА (кода, который кадр превращает
    # в частоты), а здесь — версия самой ПРИВЯЗКИ, то есть правила
    # «нейрон -> омматидий».
    #
    # Решение владельца: ретинотопию чинит отдельная работа —
    # СОВМЕСТНАЯ подгонка R1-6, R7 и R8 вместо независимой, — а эта
    # привязка сохраняется как историческая. Значит в прогоне обязано
    # быть видно, какая из них считала, и видно это здесь: имя
    # переходника плюс вот эта строка плюс отпечаток набора.
    #
    # Исправленная привязка придёт ОТДЕЛЬНЫМ ИМЕНЕМ в
    # :data:`ADAPTERS`, а не правкой этого класса: иначе прогоны,
    # посчитанные исторической, стали бы называть себя чужим именем.
    binding = "историческая v1: каждая популяция подогнана НЕЗАВИСИМЫМ "
    binding += ("SVD, взаимное совмещение не задано и опровергнуто "
                "внешним свидетелем")

    def __init__(self, mode="whiten", assign="capacity", align=None,
                 shuffle=False, seed=0, channel="max", max_hz=150.0,
                 ref=0.5, eyes="both", fit=None):
        from . import retina as R

        if channel not in CHANNELS:
            raise ValueError("неизвестный канал зрения %r; есть: %s"
                             % (channel, ", ".join(CHANNELS)))
        if eyes not in EYES:
            raise ValueError("неизвестный выбор глаз %r; есть: %s"
                             % (eyes, ", ".join(EYES)))
        if mode not in R.MODES:
            raise ValueError("неизвестный способ совмещения %r; есть: %s"
                             % (mode, ", ".join(R.MODES)))
        if assign not in R.ASSIGNS:
            raise ValueError("неизвестный способ назначения %r; есть: %s"
                             % (assign, ", ".join(R.ASSIGNS)))
        fit = R.FIT_OWN if fit is None else str(fit)
        if fit not in R.FITS:
            raise ValueError("неизвестная подгонка %r; есть: %s"
                             % (fit, ", ".join(R.FITS)))
        self.fit = fit
        self.mode = str(mode)
        self.assign = str(assign)
        self.align = tuple(align or R.ALIGN_DEFAULT)
        self.shuffle = bool(shuffle)
        self.seed = int(seed)
        self.channel = str(channel)
        self.max_hz = float(max_hz)
        self.ref = max(float(ref), 1e-12)
        self.eyes = str(eyes)
        self.maps = None
        self.indices = np.array([], dtype=np.int64)
        self._gather = None     # номера «глаз·721 + омматидий» на нейрон
        self._idx_t = None      # те же indices тензором на устройстве
        self._n_omma = 0

    # -- сборка ---------------------------------------------------------

    def attach(self, neurons, device="cpu"):
        import torch

        from . import retina as R

        sides = ("left", "right") if self.eyes == "both" else (self.eyes,)
        self.maps = R.build_all(neurons, mode=self.mode, assign=self.assign,
                                fit=self.fit,
                                align=self.align, shuffle=self.shuffle,
                                seed=self.seed, sides=sides)
        self._n_omma = len(R.ommatidia()["pos"])
        eye_of = {"left": 0, "right": 1}
        idx, gat = [], []
        # Порядок ключей фиксирован сортировкой: от него зависит
        # `indices`, а от `indices` — снятая рефрактерность и отпечаток.
        for key in sorted(self.maps, key=lambda t: (t[0], t[1])):
            m = self.maps[key]
            idx.append(np.asarray(m.neurons, dtype=np.int64))
            gat.append(eye_of[key[0]] * self._n_omma
                       + np.asarray(m.omma, dtype=np.int64))
        self.indices = (np.concatenate(idx) if idx
                        else np.array([], dtype=np.int64))
        self._gather = (np.concatenate(gat) if gat
                        else np.array([], dtype=np.int64))
        self._idx_t = torch.as_tensor(self.indices, device=device)
        self._dev = device
        return self

    # -- шаг ------------------------------------------------------------

    def per_omma(self, frame):
        """Яркость на омматидий обоих глаз, развёрнутая в одну строку.

        Форма кадра проверяется, а не предполагается: `(2, 721, 2)` у
        NeuroMechFly, и если она изменится, подача пойдёт не туда молча.
        """
        v = np.asarray(frame, dtype=np.float32)
        if v.ndim != 3 or v.shape[0] != 2 or v.shape[1] != self._n_omma \
                or v.shape[2] != 2:
            raise ValueError(
                "кадр зрения имеет форму %s, ожидалось (2, %d, 2)"
                % (tuple(v.shape), self._n_omma))
        if self.channel == "max":
            per = v.max(axis=-1)
        elif self.channel == "pale":
            per = v[..., 0]
        else:
            per = v[..., 1]
        return per.reshape(-1)

    def hz(self, frame, contrast=1.0):
        """Частоты фоторецепторов, в порядке :attr:`indices`.

        Контраст — ОБЪЯВЛЕННОЕ преобразование кадра вокруг середины
        шкалы: ``I' = clip(0,5 + (I − 0,5)·k, 0, 1)``. При ``k == 1``
        оно не исполняется вовсе, поэтому частоты совпадают с
        `retina.rates` до бита.
        """
        val = self.per_omma(frame)[self._gather]
        k = float(contrast)
        if k != 1.0:
            if k < 0.0:
                raise ValueError("контраст не бывает отрицательным: %r" % (k,))
            val = np.clip(0.5 + (val - 0.5) * k, 0.0, 1.0)
        return (self.max_hz * np.minimum(1.0, val / self.ref)
                ).astype(np.float32)

    def feed(self, rates, frame, contrast=1.0):
        """Записать частоты в `rates` формы (1, n). Возвращает сводку.

        Запись идёт `index_copy_` по строке, а не присваиванием по
        срезу: та же причина, что у `body.drive_brain` — присваивание по
        срезу уезжает через `index_put_` с передачей на устройство,
        которая ждёт.
        """
        import torch

        from . import sim

        hz = self.hz(frame, contrast=contrast)
        # Проверка ДО записи и на хосте: `hz` здесь уже числами, и
        # проверка бесплатна. Выше предела `bernoulli` упал бы ассертом
        # карты, а тот портит контекст CUDA необратимо
        # (`sim.MAX_RATE_HZ`). Под поставленным потолком 150 Гц предел
        # недостижим, но `vision_max_hz` задаётся человеком.
        sim.check_rates_hz(hz, "подача фоторецепторов (vision.feed)")
        t = torch.as_tensor(hz, device=rates.device)
        rates[0].index_copy_(0, self._idx_t, t)
        # Сводка считается на хосте по тому же массиву, который уже
        # посчитан: лишнего съёма с устройства нет.
        return {"нейронов": int(len(hz)),
                "средняя, Гц": float(hz.mean()) if len(hz) else 0.0,
                "наибольшая, Гц": float(hz.max()) if len(hz) else 0.0,
                "в потолке, доля": float((hz >= self.max_hz - 1e-6).mean())
                if len(hz) else 0.0}

    # -- происхождение --------------------------------------------------

