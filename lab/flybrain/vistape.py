"""Запись и воспроизведение зрительного входа. Детерминированная дорога.

Зачем это есть
--------------

Замерено (`probe/retina_repro.py`, `probe/vision_repro.py`): эпизод БЕЗ
зрения воспроизводим побитово и в одном процессе, и между процессами, а
СО зрением — только в одном процессе. Первая расходящаяся ступень
названа и это **сырые пиксели**: отпечаток кадра, который отдаёт
`physics.render`, отличается между свежими процессами уже на шаге 0
(`07f250ca8d302f75` против `247969038e8ea99c`), при побитово совпавшем
всём остальном. То есть виноват не пересчёт и не сеть, а выход
видеокарты.

Живой рендер от этого не становится неправильным: он остаётся тем, что
муха видит в сцене. Но **научный прогон, который надо воспроизвести
побитово, не может зависеть от выхода видеокарты.** Поэтому здесь две
раздельные вещи, и их нельзя путать:

``воспроизводимость живого рендера``
    её нет между процессами, и это свойство видеокарты, а не дефект
    модели;

``воспроизводимость воспроизведения записи``
    её можно обеспечить: если кадры записаны, то эпизод, который их
    проигрывает, не зависит от рендера вовсе.

Что записывается
----------------

**Один кадр на шаг управления** — ровно тот массив, который этот шаг
получил. Не на обновление зрения, а на шаг: так синхронизация
проверяема тождеством «номер записи = номер шага», и её не надо
выводить из частоты обновления. Между обновлениями FlyGym отдаёт тот же
массив, поэтому запись содержит повторы — это плата за проверяемую
синхронизацию, и она названа.

Вместе с кадрами пишется происхождение: форма, тип, число шагов, шаг
управления, частота обновления зрения, отпечаток КАЖДОГО кадра и
отпечаток всей ленты. Модельное время каждого шага пишется тоже, и при
воспроизведении оно **сверяется**, а не предполагается.

Почему в текстах отказа стоят ASCII-метки
-----------------------------------------

``[TAPE-STEP]``, ``[TAPE-END]``, ``[TAPE-TIME]``, ``[TAPE-HASH]`` и
прочие. Сообщение читают и люди, и пробы, а кодировка стандартного
вывода дочернего процесса читателю не подчинена: кириллица в нём
приходит искажённой, и проверка «отказал ли он по той причине»
проваливается на исправном отказе. Поймано дважды — на метке отпечатка
и на этих текстах, — поэтому причина отказа опознаётся по ASCII-метке, а
человеку рядом стоит русский текст.

Чего запись НЕ делает
---------------------

Она не делает прогон научно иным: кадры те же, что отдала сцена. Но
прогон, проигранный из записи, **не является** прогоном с живым
зрением, и в его происхождении это сказано отдельным полем. Сравнивать
их между собой нельзя: у живого кадры с видеокарты, у
воспроизведённого — с диска.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

ВЕРСИЯ = 1


def _отп(a) -> str:
    return hashlib.sha256(
        np.ascontiguousarray(a).tobytes()).hexdigest()[:16]


class Запись:
    """Пишет зрительный вход по шагам управления.

    Кадры накапливаются в памяти и сбрасываются одним файлом в
    :meth:`закрыть`. Это сделано нарочно: дописывать `npz` по кадрам
    нельзя, а держать открытый поток значит получить обрезанную запись
    при обрыве эпизода — то есть запись, которая выглядит целой.
    """

    def __init__(self, путь, control_ms, vision_hz, зерно=None):
        self.путь = Path(путь)
        self.control_ms = float(control_ms)
        self.vision_hz = float(vision_hz)
        self.зерно = зерно
        self._кадры = []
        self._время = []
        self._отпечатки = []

    def шаг(self, номер, t_ms, кадр):
        """Записать кадр этого шага управления.

        ``кадр`` может быть ``None`` — тогда записывается, что кадра не
        было, и воспроизведение отдаст ``None`` на этом шаге. Молча
        подставлять предыдущий нельзя: прогон тогда считался бы по
        кадру, которого на этом шаге не было.
        """
        a = None if кадр is None else np.ascontiguousarray(
            np.asarray(кадр, dtype=np.float32))
        self._кадры.append(a)
        self._время.append(float(t_ms))
        self._отпечатки.append(None if a is None else _отп(a))
        if len(self._кадры) != int(номер) + 1:
            raise RuntimeError(
                "[TAPE-SYNC] запись зрения разошлась с номером шага: записей %d, шаг "
                "%d. Синхронизация записи проверяется тождеством «номер "
                "записи = номер шага», и нарушать его нельзя"
                % (len(self._кадры), int(номер)))

    def закрыть(self):
        """Сбросить ленту и манифест. Возвращает манифест."""
        есть = [a for a in self._кадры if a is not None]
        if есть:
            форма = есть[0].shape
            if any(a.shape != форма for a in есть):
                raise RuntimeError(
                    "[TAPE-SHAPE] кадры записи разной формы: %s"
                    % sorted({a.shape for a in есть}))
        пусто = np.zeros((0,), dtype=np.float32)
        лента = np.stack(есть) if есть else пусто
        манифест = {
            "версия": ВЕРСИЯ,
            "что это": "запись зрительного входа по шагам управления",
            "шагов": len(self._кадры),
            "кадров непустых": len(есть),
            "форма кадра": list(есть[0].shape) if есть else None,
            "тип": str(есть[0].dtype) if есть else None,
            "шаг управления, мс": self.control_ms,
            "частота обновления зрения, Гц": self.vision_hz,
            "зерно записи": self.зерно,
            "модельное время, мс": self._время,
            "отпечаток каждого шага": self._отпечатки,
            "отпечаток ленты": _отп(лента),
            "ОГОВОРКА": (
                "прогон, проигранный из этой записи, НЕ является "
                "прогоном с живым зрением: у живого кадры приходят с "
                "видеокарты, у воспроизведённого — с диска. Сравнивать "
                "их между собой нельзя. Запись содержит повторы: кадр "
                "пишется на КАЖДЫЙ шаг управления, а зрение обновляется "
                "реже, и это плата за проверяемую синхронизацию"),
        }
        self.путь.parent.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(self.путь, лента=лента,
                            пустые=np.array(
                                [a is None for a in self._кадры],
                                dtype=bool))
        self.путь.with_suffix(".json").write_text(
            json.dumps(манифест, ensure_ascii=False, indent=1),
            encoding="utf-8")
        return манифест


class Воспроизведение:
    """Отдаёт записанные кадры вместо живого рендера.

    Сверка, а не доверие: на каждом шаге проверяется и номер, и
    модельное время, и отпечаток кадра. Расхождение — отказ, а не
    подстановка ближайшего: прогон, который молча проиграл чужой кадр,
    хуже прогона, который остановился.
    """

    def __init__(self, путь, control_ms=None, допуск_мс=1e-6):
        self.путь = Path(путь)
        d = np.load(self.путь)
        self.манифест = json.loads(
            self.путь.with_suffix(".json").read_text(encoding="utf-8"))
        if int(self.манифест.get("версия", 0)) != ВЕРСИЯ:
            raise RuntimeError(
                "[TAPE-VERSION] запись зрения версии %r, а читатель версии %d"
                % (self.манифест.get("версия"), ВЕРСИЯ))
        пустые = d["пустые"]
        лента = d["лента"]
        self._кадры = []
        k = 0
        for пусто in пустые:
            if пусто:
                self._кадры.append(None)
            else:
                self._кадры.append(лента[k])
                k += 1
        self._время = list(self.манифест["модельное время, мс"])
        self._отпечатки = list(self.манифест["отпечаток каждого шага"])
        self.допуск_мс = float(допуск_мс)
        if control_ms is not None:
            свой = float(self.манифест["шаг управления, мс"])
            if abs(свой - float(control_ms)) > 1e-9:
                raise RuntimeError(
                    "[TAPE-STEP] запись зрения снята при шаге управления %g мс, а "
                    "прогон идёт при %g: кадры пришлись бы на другое "
                    "модельное время" % (свой, float(control_ms)))
        self.шагов = len(self._кадры)
        self.сверено = 0

    def кадр(self, номер, t_ms):
        """Кадр этого шага. Номер и время сверяются, а не подразумеваются."""
        i = int(номер)
        if i >= self.шагов:
            raise RuntimeError(
                "[TAPE-END] запись зрения кончилась: в ней %d шагов, а прогон "
                "просит шаг %d. Проигрывать по кругу нельзя — прогон "
                "считался бы по чужому кадру" % (self.шагов, i))
        ждём = self._время[i]
        if abs(ждём - float(t_ms)) > self.допуск_мс:
            raise RuntimeError(
                "[TAPE-TIME] запись зрения разошлась по модельному времени: шаг %d "
                "записан на %g мс, а прогон на %g. Подставлять ближайший "
                "кадр нельзя" % (i, ждём, float(t_ms)))
        a = self._кадры[i]
        if a is not None and _отп(a) != self._отпечатки[i]:
            raise RuntimeError(
                "[TAPE-HASH] кадр шага %d не сошёлся с отпечатком манифеста: лента "
                "испорчена" % i)
        self.сверено += 1
        return a

    def состояние(self):
        """Происхождение воспроизведения — в прогон."""
        return {
            "ЗРЕНИЕ ВОСПРОИЗВЕДЕНО ИЗ ЗАПИСИ, А НЕ ЖИВОЕ": True,
            "запись": str(self.путь),
            "отпечаток ленты": self.манифест["отпечаток ленты"],
            "шагов в записи": self.шагов,
            "шагов сверено": self.сверено,
            "шаг управления записи, мс": self.манифест["шаг управления, мс"],
            "частота обновления записи, Гц": self.манифест[
                "частота обновления зрения, Гц"],
            "зерно записи": self.манифест.get("зерно записи"),
            "почему это нужно": (
                "живой рендер не воспроизводим между процессами: первая "
                "расходящаяся ступень — сырые пиксели `physics.render` "
                "(probe/retina_repro.py). Воспроизведение из записи от "
                "видеокарты не зависит вовсе"),
        }
