"""Мозг в теле: коннектом FlyWire управляет ногами NeuroMechFly v2.

Отличие от :mod:`flybrain.loop` — там арена и физика были написаны нами, а
«нисходящие нейроны → скорость и поворот» я придумывал сам. Здесь обе
половины заменены на опубликованные:

* запах берётся с антенн мухи в MuJoCo, а не считается из гауссова шлейфа;
* нисходящий выход уходит в ``HybridTurningController`` — тот самый
  контроллер походки из NeuroMechFly v2, который ожидает ровно два числа,
  «нисходящий сигнал поворота». Ноги, их фазы, прилипание и спотыкание
  считает он.

Придуманными остаются два места: пересчёт интенсивности запаха в частоту
рецепторов — он здесь, и помечен, — и пересчёт активности в команду телу.
Второй с этапа 2 живёт не здесь, а в :mod:`flybrain.motor`: там у каждого
нефизиологичного преобразования есть имя, версия и список параметров, и
оттуда они уезжают в блок ``engineered`` снимка прогона. Заместителем
грудного ганглия работает контроллер FlyGym.

Семантика команды (прочитана из turning_controller.py): ``action[0]`` задаёт
амплитуду шага левых трёх ног, ``action[1]`` — правых, знак задаёт
направление. Замер показал, что более сильные левые ноги уводят муху вправо,
поэтому связь мозга с ногами перекрёстная: левое полушарие — правые ноги.

Разведённые имена в записи по шагам
-----------------------------------

* ``readout_<зонд>_l/r`` — ИЗМЕРЕНИЕ: частота прямого зонда в герцах,
  сумма спайков на число нейронов и длительность блока. Шесть названных
  нисходящих (DNp01, DNp04, DNa01, DNa02, DNp09, MDN) плюс теневые
  зонды — см. :mod:`flybrain.motor`;
* ``cmd_turn``, ``cmd_drive``, ``cmd_escape`` — ИНЖЕНЕРНАЯ команда;
* ``dn_l``, ``dn_r``, ``asym``, ``z``, ``amp_l``, ``amp_r`` — прежние
  поля, оставлены как есть: на них держатся ряды, графики, отчёт,
  песочница и отпечатки эталонных прогонов.

Значения по умолчанию (``motor = "legacy"``, моста через обрыв Giant
Fiber нет, стабилизации головы нет) воспроизводят прежний эпизод
ПОБИТОВО — проверено `probe/motor_equal.py` на двух деревьях кода.
"""

from __future__ import annotations

import json
import math
import time
from bisect import bisect_left as _bisect_left
from dataclasses import dataclass, asdict, field, fields
from pathlib import Path

import numpy as np

from . import data as D, motor, sim, world


@dataclass
class BodyConfig:
    duration_s: float = 4.0
    control_ms: float = 20.0
    physics_dt: float = 2e-4
    seed: int = 0
    device: str | None = None

    # С какой популяции снимается выход мозга. **Значение по умолчанию
    # `ALPN` — СЕНСОРНАЯ популяция, а не нисходящий моторный путь**, и
    # это замер, а не мнение: 685 нейронов, пересечение с
    # `super:descending` ноль, с `DNp01` ноль, `super_class` у всех
    # `central`. То есть по умолчанию ноги ведёт популяция, в которой
    # премоторных нейронов нет вовсе, и Giant Fiber там не «растворён в
    # среднем», а отсутствует.
    #
    # Значение оставлено прежним нарочно: по нему посчитаны все
    # сохранённые прогоны, и менять его молча нельзя. Нисходящий путь
    # выбирается отдельно — `motor="dn_linear"` плюс `readout`
    # соответствующего зонда, см. `flybrain/motor.py` и `MOTOR.md`.
    # Справка о том, какая популяция вела команду, уезжает в блок
    # `engineered` каждого прогона (`motor.readout_provenance`), и
    # оговорка о сенсорном съёме — в `timing["оговорки"]`.
    readout: str = "ALPN"
    dn_tau_s: float = 0.5
    swap_antennae: bool = False
    cross: bool = True  # левое полушарие управляет правыми ногами

    # Откуда берутся курс и положение для метрики `grad_cos`. Это
    # ИЗМЕРЕНИЕ, а не управление: на поведение не влияет никак (метрика
    # никуда не возвращается), но на `grad_alignment` всех прогонов
    # влияет прямо.
    #
    # `"thorax"` — как было с самого начала и как посчитаны все прежние
    # прогоны: курс из `obs["fly_orientation"]` (ось x КОРНЕВОГО тела),
    # положение — грудь. Остаётся значением по умолчанию, иначе прежние
    # числа станут несравнимыми.
    #
    # `"antennae"` — явно помеченная альтернатива: положение берётся как
    # середина между обонятельными сенсорами, курс — из их собственной
    # оси. Основание: антенны висят на `LFuniculus`/`RFuniculus`, за
    # шейными и антеннальными суставами, и на 1,03 мм впереди груди
    # (`ANTENNA.md` §4), поэтому курс корневого тела — не тот курс, с
    # которого муха нюхает. Какой из двух вариантов правильнее, здесь не
    # решается: сравнение их на одном зерне — `probe/grad_ref.py`.
    #
    # В `spec.py` и `catalog.py` эта ручка НЕ объявлена нарочно: прогоны
    # из окна и из командной строки должны считаться исторической
    # метрикой, а альтернативу ставит только проба.
    grad_ref: str = "thorax"

    # --- придуманная часть: запах -> частота рецепторов ---
    orn_max_hz: float = 150.0
    odour_ref_factor: float = 2.5  # во сколько раз выше стартовой яркости насыщение
    grn_hz: float = 200.0
    food_radius_mm: float = 3.0

    # --- придуманная часть: асимметрия -> амплитуда шага ---
    amp_base: float = 0.9   # амплитуда при нулевой асимметрии
    amp_span: float = 0.8   # на сколько её меняет одна сигма асимметрии
    amp_min: float = 0.1
    amp_max: float = 1.4
    turn_sign: float = 1.0  # +1: как считались все прежние эпизоды

    # --- инженерный моторный путь (`flybrain.motor`) ---
    #
    # `motor` — какой декодер превращает активность в команду телу:
    #
    # * `"legacy"` — то, что было: среднее по ОДНОЙ популяции на
    #   полушарие (`readout`), асимметрия, нормировка на собственный шум.
    #   Значение по умолчанию, и менять его нельзя: иначе эталонные
    #   прогоны станут несравнимыми молча.
    # * `"dn_linear"` — вариант А: линейная карта по шести ПРЯМЫМ зондам
    #   (DNp01, DNp04, DNa01, DNa02, DNp09, MDN) с объявленными
    #   коэффициентами.
    # * `"dn_trained"` — вариант Б: те же зонды, веса из файла
    #   (`motor_weights`), обучены гребневой регрессией.
    #
    # `gf_bridge` — инженерный мост через обрыв «Giant Fiber →
    # мотонейроны». По умолчанию `"none"`: биологического пути в v783 нет
    # вовсе, и подменять его молча хуже, чем не иметь реакции.
    #
    # `head_stab` — опубликованная ОБУЧЕННАЯ стабилизация головы. По
    # умолчанию выключена: при включении в модель тела добавляются
    # приводы на шею, то есть модель становится ДРУГОЙ.
    #
    # Прямые зонды пишутся в запись ВСЕГДА, при любом декодере: это
    # измерение, оно ничего не меняет и стоит доли процента шага.
    motor: str = "legacy"
    motor_weights: str | None = None
    gf_bridge: str = "none"
    gf_ref_hz: float = 100.0
    escape_gain: float = 0.5
    head_stab: bool = False
    neck_kp: float | None = None
    probes: bool = True  # писать readout_* прямых зондов в запись

    # --- прямое вмешательство в названные популяции (`motor.DnIntervention`) ---
    #
    # `dn_drive` — постоянная пуассоновская частота на нейроны названной
    # популяции: `"DNa02:left=200"`, `"sel:celltype=DNp03=150"`. Это
    # ВХОД опыта, как запах: он подаётся в сеть, а не обходит её.
    # `dn_silence` — маска `fire` на названную популяцию, то есть
    # отрицательный контроль: `"DNa02"` или любая другая популяция через
    # `sel:`, например `"sel:class:ALPN"` — прежний сенсорный съём.
    #
    # Оба по умолчанию выключены, и при выключенных обоих объекта
    # вмешательства в прогоне нет вовсе — эталонные прогоны считаются
    # побитово как раньше. Включённое вмешательство пишет оговорку и с
    # эталонными не сравнивается.
    dn_drive: str | None = None
    dn_silence: str | None = None

    # Файл адресации «зонд → вес поворота и тяги» для `motor="dn_linear"`.
    # None — коэффициенты из кода (`motor.TURN_WEIGHTS_V1`), как считались
    # все прежние прогоны. Смысл ручки в том, что лучше определённая
    # адресация подключается ДАННЫМИ: файл едет в `engineered` с sha256 и
    # записанным происхождением, как семя, и прогоны с разными файлами
    # машинно различимы. См. `motor.load_weight_map`.
    motor_map: str | None = None

    # --- запись видео ---
    video: bool = False
    fps: int = 30
    play_speed: float = 0.2  # замедление: муха быстрая, иначе ничего не видно

    # --- живое окно MuJoCo ---
    view: bool = False

    # Пропуск лишнего пересчёта прямой динамики. Выключено по умолчанию,
    # пока равенство не доказано на этой модели: см. `_fly_class`.
    fast_physics: bool = False

    # Чем считать умножение связей в движке LIF: `sim.SPMV_CSR` или
    # `sim.SPMV_EVENT`. None — по `sim.SPMV_DEFAULT`, то есть по
    # окружению `FLYBRAIN_SPMV`.
    #
    # Это НЕ `fast_physics`: там траектория другая, здесь произведение
    # обязано совпадать побитово, и проверяется это
    # `probe/lif_event.py`. Поле есть потому, что выбор дороги должен
    # быть видимым в карточке прогона, а не только в окружении.
    #
    # Умолчание — ЭТАЛОННАЯ дорога, и это откат: событийная выведена из
    # приёмки выпуска, пока не названа причина единичного
    # `CUDA illegal memory access` (`KERNEL_FAULT.md`, разбор не нашёл
    # её; `sim.SPMV_DEFAULT` объясняет решение). `nvcc` для событийной
    # дороги не нужен — ядро едет готовым PTX (`KERNEL_SHIP.md`).
    spmv: str | None = None

    # Какой контроллер походки крутит ноги.
    #
    # * `"fast"` — вендоренная копия шага из `flybrain.gait`: те же числа,
    #   но правила, фазовый множитель и кусочный полином считаются на все
    #   шесть ног сразу, а наблюдение прошлого шага не читается заново.
    #   Значение по умолчанию: равенство проверено отпечатками эпизода
    #   (`probe/body_equal.py`), арифметикой по частям
    #   (`probe/gait_equal.py`) и продолжением из снимка
    #   (`probe/resume_state.py --part body`).
    # * `"legacy"` — `HybridTurningController` из пакета, как было. Нужен
    #   встречному замеру и остаётся дорогой назад.
    #
    # Ускорение — не приближение: ни одна частота обновления не понижена
    # и ни один шаг не пропущен, см. заголовок `flybrain/gait.py`.
    gait: str = "fast"
    # --- съём обвязки вокруг шага MuJoCo ---
    #
    # Три правки, и у каждой своя ручка — не чтобы выбирать режим, а
    # чтобы у каждой был ВСТРЕЧНЫЙ ЗАМЕР в одном процессе. Все три
    # сохраняют значения побитово (разбор — в `MUJOCO_PERF.md`), поэтому
    # по умолчанию включены; выключенные дают прежнюю дорогу шаг в шаг.
    #
    # `acc_forward` — повторный расчёт прямой динамики считается только с
    # ступени ускорений (`mj_forwardSkip`), потому что позиционную и
    # скоростную ступени на том же состоянии уже посчитал `mj_step1` в
    # конце `Physics.step`. Это НЕ `fast_physics`: пересчёт не
    # пропускается, у него убран заведомо повторный кусок.
    #
    # `fast_obs` — наблюдение читает `data.sensordata`, `cfrc_ext` и
    # `xpos` по целым индексам вместо именованной индексации dm_control,
    # а поправка на прилипание считается без питоновского цикла по
    # контактам.
    #
    # `rule_obs` и `fast_gain` действуют только на дороге
    # `gait="legacy"`. При `gait="fast"` их работу делает сам
    # `flybrain.gait`: его шаг не зовёт `super().get_observation()`
    # вовсе, а фазовый множитель считает массивами. В
    # `timing["обвязка"]` пишется действительное значение, а
    # не просьба.
    #
    # `rule_obs` — правила походки (втягивание и спотыкание) получают
    # только те четыре поля наблюдения, которые читают, а не всё
    # наблюдение целиком: `HybridTurningController.step` зовёт
    # `get_observation` на том же состоянии, которое уже посчитал
    # `post_step` предыдущего шага физики.
    # `fast_gain` — фазовый множитель поправки считается тем же
    # выражением, что `scipy.interpolate.interp1d` с линейным ядром, но
    # без её обвязки: по пяти узлам, шесть раз на шаг физики.
    acc_forward: bool = True
    fast_obs: bool = True
    rule_obs: bool = True
    fast_gain: bool = True

    # --- сеанс песочницы ---
    #
    # `duration_s <= 0` — сеанс без заранее заданного конца: его
    # заканчивает только остановка. Такой сеанс ОБЯЗАН держать кольцо
    # записи (`keep_s > 0`), иначе плотный `bins` растёт без предела:
    # 138 639 × 2 байта = 277 КБ на шаг управления, при шаге 20 мс это
    # 13,9 МБ на секунду модельного времени.
    keep_s: float = 0.0

    # Яркость, которая считается насыщением рецепторов. `None` — мерить
    # на разогреве по тому, что муха чует в начале (так считались все
    # прежние эпизоды). Песочнице нужно число: если сеанс начинается с
    # выключенными источниками, измеренная яркость будет нулевой, и
    # первый же включённый источник насытит рецепторы до потолка.
    odour_ref: float | None = None

    view_every: int = 1  # обновлять окно раз в столько шагов управления

    # ------------------------------------------------------ зрение
    #
    # ВСЁ ЗРЕНИЕ ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ, и это не осторожность, а
    # требование сравнимости: все 28 сохранённых прогонов посчитаны без
    # зрения, и прежний опыт, открытый новой сборкой, обязан считаться
    # ровно как раньше. При `vision=False` ни одна строка ниже не
    # исполняется: тело собирается без `enable_vision`, переходник не
    # строится, пул объектов не вписывается. Побитовое равенство с
    # прежним эпизодом проверяется `probe/vision_product.py`, пункт 1.
    #
    # Содержательная часть живёт не здесь: `vision_adapter` выбирает
    # переходник ПО ИМЕНИ (`flybrain.vision.ADAPTERS`), и настоящая
    # ретинотопия или физиологическая динамика раннего зрения встают на
    # место, не меняя ни одного из полей ниже.
    vision: bool = False

    # Подаётся ли кадр в сеть ПРЯМО СЕЙЧАС. Отдельно от `vision`, и
    # разница существенная: `vision` решается при сборке тела (глаза
    # либо есть в модели, либо нет, и добавить их на ходу нельзя), а это
    # — живая ручка песочницы, выключающая и включающую ПОДАЧУ, пока
    # глаза продолжают рисовать кадр. В спеке её нет нарочно: опыт
    # запускают с зрением или без, а не «с глазами, но молча».
    vision_feed: bool = True

    # Частота обновления зрения, Гц. **Рабочая точка, а не
    # биологическая постоянная**: 100 Гц выбраны по замеру цены
    # (без зрения 497,5 мс на шаг; 50 Гц ×1,11, 100 Гц ×1,16,
    # 250 Гц ×1,36, 500 Гц ×1,66 — `RESEARCH.md` §6). Более высокие
    # частоты нужны быстрым переходным процессам, и ставятся этим же
    # полем. FlyGym округляет её до целого числа герц.
    vision_hz: float = 100.0

    # Имя зрительного переходника. `"retina"` — инженерная привязка
    # омматидиев (`flybrain/retina.py`), единственная в этой сборке.
    vision_adapter: str = "retina"

    # Потолок частоты фоторецепторов и яркость, считающаяся насыщением.
    # Правило придумано и объявлено ровно одно:
    # `hz = vision_max_hz · min(1, яркость / vision_ref)`. Ни одного
    # нейрона оно не выделяет; то же самое сделано у обоняния
    # (`orn_max_hz`, `odour_ref`).
    vision_max_hz: float = 150.0
    vision_ref: float = 0.5

    # Что делать с двумя каналами фоторецептора кадра NeuroMechFly:
    # `"max"` (как делает и официальная интеграция — хроматика при этом
    # теряется), `"pale"`, `"yellow"`.
    vision_channel: str = "max"

    # Какие глаза подаются: `"both"` — ОБА сложных глаза, значение по
    # умолчанию. Односторонняя подача есть контроль на двусторонний
    # путь, а не рабочая точка.
    vision_eyes: str = "both"

    # Привязка: совмещение, назначение и ВСТРЕЧНЫЙ ЗАМЕР.
    # `vision_shuffle` перемешивает назначение, сохраняя число нейронов
    # на омматидий: суммарный вход тот же до последнего разряда,
    # разрушена только пространственная структура. Без такого прогона
    # ни одно утверждение про пространственное зрение не стоит ничего.
    vision_mode: str = "whiten"
    vision_assign: str = "capacity"
    vision_shuffle: bool = False

    # Свет сцены: множитель к `light_ambient` и `light_diffuse`
    # НАСТОЯЩИХ источников MuJoCo (`light_top`, `light_bottom` арены
    # FlyGym). Меняется сам рендер кадра глаза, а не его пересчёт.
    vision_light: float = 1.0

    # Контраст: ОБЪЯВЛЕННОЕ преобразование кадра вокруг середины шкалы,
    # `I' = clip(0,5 + (I − 0,5)·k, 0, 1)`. Это не свойство сцены, и так
    # написано в происхождении прогона. При k = 1 преобразование не
    # исполняется вовсе, и частоты совпадают с `retina.rates` до бита.
    vision_contrast: float = 1.0

    # --- гибридный зрительный переходник (`flybrain.vislink`) ---
    #
