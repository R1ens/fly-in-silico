# числа. Основание у всех трёх одно и то же: `HybridTurningController`
# зовёт на один шаг физики `mj_step2` + `mj_step1` + `mj_forward` и ДВА
# полных наблюдения, и часть этой работы доказуемо повторная.
#
# Замер обвязки (`probe/mj_profile.py`, та же модель): шаг физики стоит
# 2,7–3,1 мс, из них в самом MuJoCo — 1,20 мс
# (`mj_step2` + `mj_step1` + `mj_forward`), остальное — Python и
# dm_control.


_EMPTY_SENSORDATA = np.empty(0)


class _LinearGain:
    """Линейная интерполяция по пяти узлам — та же, что у scipy, но без
    её обвязки.

    Откуда она берётся. `HybridTurningController` держит на каждую ногу
    `interp1d(step_points, increment_vals, kind="linear",
    fill_value="extrapolate")` — фазовый множитель поправки — и зовёт её
    по разу на ногу на каждый шаг физики, то есть шесть раз. Узлов там
    пять, а вызов стоит около 15 мкс: `_prepare_x`, `_asarray_validated`,
    `searchsorted` по массиву из пяти чисел, широковещательное умножение
    и `_finish_y` с переформированием.

    Здесь считается ровно то же выражение, что в
    `scipy.interpolate._interpolate.interp1d._call_linear`:

        y = ((x - x_lo)/(x_hi - x_lo)) * y_hi
          + ((x_hi - x)/(x_hi - x_lo)) * y_lo

    с тем же выбором отрезка (`searchsorted` слева, затем зажим в
    `1 … n-1`, как делает сам scipy «чтобы не промахнуться на
    `x == x[0]`»). Арифметика — обычные числа Python, то есть те же
    двойной точности IEEE и в том же порядке, поэтому совпадение
    побитовое, а не близкое. `bisect_left` по списку из пяти чисел
    отвечает то же, что `np.searchsorted(..., side="left")`.

    Ставится только на тот самый случай: `kind="linear"` плюс
    `fill_value="extrapolate"`. Это видно по тому, какой `_call` scipy
    выбрал при сборке (`_call_linear`, а не `_call_linear_np`), и
    проверяется, а не предполагается — у `np.interp` краевые значения
    другие.
    """

    __slots__ = ("xs", "ys", "last")

    def __init__(self, src):
        self.xs = np.asarray(src.x, dtype=np.float64).reshape(-1).tolist()
        self.ys = np.asarray(src._y, dtype=np.float64).reshape(-1).tolist()
        self.last = len(self.xs) - 1
        if self.last < 1 or len(self.ys) != len(self.xs):
            raise ValueError("узлов меньше двух или длины не совпали")

    @staticmethod
    def suitable(src):
        """Тот ли это случай. `interp1d` с `fill_value="extrapolate"` и
        `kind="linear"` ставит `_call = _call_linear`; при любом другом
        наборе там стоит что-то ещё, и подменять нельзя."""
        try:
            return (getattr(src, "_kind", None) == "linear"
                    and getattr(src, "_call", None)
                    is type(src)._call_linear
                    and np.asarray(src.x).ndim == 1
                    and np.asarray(src._y).reshape(-1).size
                    == np.asarray(src.x).size)
        except Exception:
            return False

    def __call__(self, x_new):
        x = x_new if type(x_new) is float else float(x_new)
        xs, ys = self.xs, self.ys
        i = _bisect_left(xs, x)
        if i < 1:
            i = 1
        elif i > self.last:
            i = self.last
        x_lo = xs[i - 1]
        x_hi = xs[i]
        d = x_hi - x_lo
        return ((x - x_lo) / d) * ys[i] + ((x_hi - x) / d) * ys[i - 1]


def _install_fast_gain(sim):
    """Заменить фазовые множители контроллера на :class:`_LinearGain`.

    Подменяются значения в словаре `sim.phasic_multiplier`, то есть ни
    одной строки апстрима переписывать не надо. Не подошедшие (если
    FlyGym когда-нибудь соберёт их иначе) остаются как были.
    """
    gains = getattr(sim, "phasic_multiplier", None)
    if not isinstance(gains, dict):
        return 0
    done = 0
    for leg, src in list(gains.items()):
        if isinstance(src, _LinearGain) or not _LinearGain.suitable(src):
            continue
        try:
            gains[leg] = _LinearGain(src)
        except ValueError:
            continue
        done += 1
    return done


def _mark_ctrl_only_dirty(physics):
    """Отметить, что с прошлой синхронизации написан только ``ctrl``.

    Зовётся из `pre_step` нашей мухи сразу после записи управляющих
    сигналов. `ctrl` влияет только на ступень УСКОРЕНИЙ прямой динамики
    (`mj_fwdActuation`), поэтому позиционная и скоростная ступени
    остаются верными — и именно это даёт право считать пересчёт с
    середины.
    """
    st = getattr(physics, "_fb_accfwd", None)
    if st is not None:
        st["ctrl_only"] = True


def _install_acc_only_forward(physics, acc_forward=True):
    """Повторный расчёт прямой динамики — только со ступени ускорений.

    Что тут происходит на самом деле. `Fly.pre_step` пишет `ctrl` через
    биндинг dm_control, тот помечает состояние «грязным», и первое же
    чтение наблюдений в `post_step` зовёт `physics.forward()`, то есть
    полный `mj_forward`. Но `Physics.step` в dm_control работает в
    «legacy» режиме и заканчивается `mj_step1` — а `mj_step1` это ровно
    `mj_fwdPosition` + `mj_sensorPos` + `mj_energyPos` + `mj_fwdVelocity`
    + `mj_sensorVel` + `mj_energyVel` на том же `qpos`/`qvel`. Значит
    полный `mj_forward` пересчитывает две первые ступени второй раз,
    включая самое дорогое — обнаружение столкновений (`mj_collision`) и
    сборку ограничений.

    `mj_forwardSkip(m, d, mjSTAGE_VEL, 0)` — это тот же `mj_forward` без
    двух первых ступеней: это документированная ручка MuJoCo ровно для
    такого случая. Ступень ускорений (`mj_fwdActuation`,
    `mj_fwdAcceleration`, `mj_fwdConstraint`, `mj_sensorAcc`) считается
    полностью, то есть ни один из 179 сенсоров не остаётся устаревшим.

    **Чем это отличается от отклонённого `fast_physics`.** Тот
    пропускал пересчёт целиком, и сенсоры ступени ускорений (силы,
    моменты, `cfrc_ext`) оставались с прошлого шага — траектория
    разъехалась уже на втором шаге управления (`SPEED.md` §3). Здесь
    ступень ускорений считается, а выброшено только то, что `mj_step1`
    уже посчитал на этом же состоянии. Значения совпадают побитово.

    Замер на той же модели: `mj_forward` 552 мкс,
    `mj_forwardSkip(STAGE_VEL)` 200 мкс.

    Условия, при которых дешёвая дорога разрешена, проверяются по двум
    отметкам, а не по вере:

    * `stepped` — с прошлой синхронизации был `Physics.step`, то есть
      `mj_step1` посчитал позиционную и скоростную ступени на нынешнем
      состоянии;
    * `ctrl_only` — с тех пор написан только `ctrl` (отметку ставит
      `pre_step`).

    Обе отметки одноразовые: `forward` их съедает. Поэтому любое второе
    чтение, любое продолжение из снимка (`replay.restore_body` пишет
    `qpos`) и любой сброс получают полный `mj_forward`.

    Заодно здесь живёт **номер состояния** (`эпоха`): он растёт на каждом
    `Physics.step` и на каждом `forward`, то есть на каждом месте, где
    MuJoCo пересчитывает что-нибудь производное. По нему наблюдение
    узнаёт, что состояние не менялось, и не считает одно и то же дважды
    (см. `_fb_contact_forces`). Если ``acc_forward`` выключен, номер всё
    равно ведётся: он нужен и без дешёвого пересчёта.
    """
    import mujoco

    if getattr(physics, "_fb_accfwd", None) is not None:
        return physics._fb_accfwd
    if acc_forward and not getattr(physics, "legacy_step", True):
        # Без «legacy» шага `mj_step1` в конце не зовётся, и позиционная
        # ступень после шага НЕ свежая. Тогда дешёвой дороги нет.
        acc_forward = False

    cls = type(physics)
    full_forward, full_step = cls.forward, cls.step
    stage_vel = int(mujoco.mjtStage.mjSTAGE_VEL)
    st = {"stepped": False, "ctrl_only": False, "дешёвых": 0, "полных": 0,
          "эпоха": 0, "со ступени ускорений": bool(acc_forward)}

    def step(nstep=1):
        st["stepped"] = False
        st["эпоха"] += 1
        full_step(physics, nstep)
        st["stepped"] = True

    def forward():
        st["эпоха"] += 1
        if acc_forward and st["stepped"] and st["ctrl_only"]:
            st["stepped"] = st["ctrl_only"] = False
            st["дешёвых"] += 1
            with physics.check_invalid_state():
                mujoco.mj_forwardSkip(physics.model.ptr, physics.data.ptr,
                                      stage_vel, 0)
            physics._dirty = False
            return
        st["stepped"] = st["ctrl_only"] = False
        st["полных"] += 1
        full_forward(physics)

    # Подмена на экземпляре, а не на классе: dm_control зовёт
    # `self._physics.forward()`, то есть обычным поиском атрибута, и
    # другие объекты `Physics` в процессе остаются нетронутыми.
    physics.step = step
    physics.forward = forward
    physics._fb_accfwd = st
    return st


def _fast_obs_mixin():
    """Наблюдение без именованной индексации и без цикла по контактам.

    Значения те же до бита — меняется только дорога к ним:

    * `physics.bind(датчики).sensordata` на каждом чтении зовёт
      `Binding.__getattr__`, тот синхронизирует вид с подложкой
      (`_synchronize_from_backing_array`). Индекс в `data.sensordata`
      при этом один и тот же; берём его один раз у самого dm_control и
      дальше читаем подложку напрямую. Индекс взят у dm_control нарочно:
      так он не может разъехаться с тем, что читал биндинг;
    * `physics.named.data.cfrc_ext[список имён]` разбирает 36 строковых
      имён на каждом чтении (`convert_key_item`, 29 мкс на вызов против
      2,7 мкс по целым идентификаторам тел);
    * поправка на прилипание шла питоновским циклом по контактам с двумя
      `np.where` на контакт — 117 мкс на наблюдение, то есть почти треть
      его. Считается то же самое numpy'ем, с сохранением ПОРЯДКА
      добавления нормалей (от него зависит `np.mean`, то есть последние
      биты) и порядка первого появления датчика.

    Пересчёт прямой динамики по «грязному» флагу делается явно в начале:
    в прежней дороге его звало первое же чтение через биндинг, здесь
    биндингов нет, и забыть про него нельзя.
    """
    from flygym_gymnasium import Fly
    from scipy.spatial.transform import Rotation as R

    class _FastObsFly(Fly):

        _fb_ready = False
        # Одноразовая отметка «идёт съём для правил походки». Ставит её
        # `_sim_class` на время `HybridTurningController.step`, снимает
        # первое же чтение наблюдения — то самое, повторное.
        _fb_rule_stage = False
        _fb_rule_epoch = -2
        # Запомненные контактные силы и номер состояния, на котором они
        # посчитаны. `-1` — «ещё ничего не считали».
        _fb_cf = None
        _fb_cf_active = None
        _fb_cf_epoch = -1

        def post_init(self, sim):
            super().post_init(sim)
            self._fb_prepare(sim.physics)

        def _fb_prepare(self, physics):
            model = physics.model

            def sensor_index(elements):
                b = physics.bind(elements)
                if not callable(getattr(b, "_get_cached_array_and_index",
                                        None)):
                    # Пустая группа датчиков (в этой модели такова
                    # `_non_actuated_joint_sensors`): dm_control отдаёт
                    # на неё `_EmptyBinding`, а та на любое поле —
                    # пустой массив. Отвечаем тем же.
                    return None
                return b._get_cached_array_and_index("sensordata")

            self._fb_sd = {}
            names = ["act", "nonact", "ee", "ant"]
            groups = [self._actuated_joint_sensors,
                      self._non_actuated_joint_sensors,
                      self._end_effector_sensors,
                      self._antennae_sensors]
            for i in range(7):
                names.append("body%d" % i)
                groups.append(self._body_sensors[i])
            for nm, grp in zip(names, groups):
                if grp is None:
                    self._fb_sd[nm] = None
                    continue
                self._fb_sd[nm] = sensor_index(grp)

            ids = np.array([model.name2id(nm, "body")
                            for nm in self.contact_sensor_placements])
            if ids.size and int(ids.min()) < 0:
                raise RuntimeError(
                    "не нашлось тела для контактного датчика: "
                    + ", ".join(nm for nm, i in
                                zip(self.contact_sensor_placements, ids)
                                if i < 0))
            self._fb_body_ids = ids

            # Прилипание: геом -> место привода. Строим только если
            # идентификаторы геомов и датчиков различны — иначе
            # `np.where(...)[0]` в прежнем коде давал бы больше одного
            # попадания, и numpy'ем это пришлось бы считать иначе.
            gid = np.asarray(getattr(self, "_adhesion_actuator_geom_id", []))
            csid = np.asarray(
                getattr(self, "_adhesion_bodies_with_contact_sensors", []))
            self._fb_geom_slot = None
            if (self.enable_adhesion and gid.size
                    and len(set(gid.tolist())) == gid.size
                    and len(set(csid.tolist())) == csid.size):
                slot = np.full(int(model.ngeom), -1, dtype=np.int64)
                slot[gid] = np.arange(gid.size)
                self._fb_geom_slot = slot
                self._fb_csid = csid.astype(np.int64)
            self._fb_ready = True

        # ---------------------------------------------------- куски
        def _fb_sd_read(self, key):
            got = self._fb_sd[key]
            if got is None:
                return _EMPTY_SENSORDATA
            arr, idx = got
            return arr[idx]

        def _fb_contact_forces(self, physics, use_cache=False):
            """`cfrc_ext` строк контактных датчиков плюс поправка на
            прилипание. Один в один то, что считает `Fly.get_observation`.

            На один шаг физики наблюдение снимается дважды — правилами
            походки перед шагом и `post_step` после него, — и съём
            правил приходится ровно на то состояние, которое уже
            посчитал `post_step` предыдущего шага. Поэтому результат
            запоминается по номеру состояния (`эпоха` из
            :func:`_install_acc_only_forward`), который растёт на каждом
            `Physics.step` и на каждом `forward`, то есть на каждом
            месте, где MuJoCo пересчитывает производные величины.

            **Из запомненного читает только съём правил**
            (``use_cache=True``), а полное наблюдение всегда считает
            заново и запомненное обновляет. Это не осторожность ради
            осторожности, а закрытая дыра: `replay.restore_body` зовёт
            `mujoco.mj_forward` НАПРЯМУЮ, минуя `Physics.forward`, то
            есть номер состояния не растёт, хотя состояние другое. Если
            бы из запомненного читал кто угодно, продолжение из снимка
            получило бы контактные силы с прошлого состояния. А так
            после продолжения первым идёт полное наблюдение (`body.py`
            зовёт его сразу после `restore_body`), оно и обновляет
            запомненное; съём правил приходит уже после него.

            Отдаётся копия: `get_observation` кладёт этот массив в
            `last_obs`, и отдавать два раза один объект не стоит.
            """
            data = physics.data
            st = getattr(physics, "_fb_accfwd", None)
            ep = None if st is None else st["эпоха"]
            if use_cache and ep is not None and self._fb_cf_epoch == ep:
                self._active_adhesion = self._fb_cf_active
                return self._fb_cf.copy()
            contact_forces = data.cfrc_ext[self._fb_body_ids][:, 3:].copy()
            if not self.enable_adhesion:
                return contact_forces
            slot = self._fb_geom_slot
            if slot is None:
                return self._fb_contact_forces_loop(physics, contact_forces)
            active = np.zeros(self.n_legs, dtype=bool)
            ncon = int(data.ncon)
            if ncon:
                con = data.ptr.contact
                ok = np.asarray(con.exclude[:ncon]) == 0
                s1 = slot[np.asarray(con.geom1[:ncon])]
                s2 = slot[np.asarray(con.geom2[:ncon])]
                m1 = ok & (s1 >= 0)
                m2 = ok & (s2 >= 0)
                if m1.any():
                    active[s1[m1]] = True
                if m2.any():
                    active[s2[m2]] = True
                hit = np.unique(np.concatenate((s1[m1], s2[m2])))
                if hit.size:
                    frames = np.asarray(con.frame[:ncon])
                    for sl in hit.tolist():
                        if not (self._last_adhesion[sl] > 0):
                            continue
                        # Строки нормалей — в порядке возрастания номера
                        # контакта, то есть ровно в том, в каком их
                        # добавлял прежний цикл: один геом не может быть
                        # и `geom1`, и `geom2` одного контакта. От
                        # порядка зависит `np.mean`, поэтому он и важен.
                        # Порядок самих мест (`hit`) не важен: каждое
                        # пишет свою строку `contact_forces`.
                        sel = (m1 & (s1 == sl)) | (m2 & (s2 == sl))
                        rows = frames[sel, :3]
                        normal = rows[0] if len(rows) == 1 else \
                            np.add.reduce(rows, axis=0) / len(rows)
                        contact_forces[int(self._fb_csid[sl]), :] -= \
                            self.adhesion_force * normal
            self._active_adhesion = active
            if ep is not None:
                self._fb_cf, self._fb_cf_epoch = contact_forces, ep
                self._fb_cf_active = active
                return contact_forces.copy()
            return contact_forces

        def _fb_contact_forces_loop(self, physics, contact_forces):
            """Прежняя дорога: цикл по контактам. Остаётся на случай
            неуникальных геомов прилипания — чтобы поведение не зависело
            от того, угадали мы структуру модели или нет."""
            contactid_normal = {}
            self._active_adhesion = np.zeros(self.n_legs, dtype=bool)
            for contact in physics.data.contact:
                for gid in (contact.geom1, contact.geom2):
                    id_ = np.where(self._adhesion_actuator_geom_id == gid)
                    if len(id_[0]) > 0 and contact.exclude == 0:
                        cs = self._adhesion_bodies_with_contact_sensors[id_][0]
                        contactid_normal.setdefault(cs, []).append(
                            contact.frame[:3])
                        self._active_adhesion[id_] = True
            for cs, normal in contactid_normal.items():
                mask = self._adhesion_bodies_with_contact_sensors == cs
                if self._last_adhesion[mask] > 0:
                    if len(np.shape(normal)) > 1:
                        normal = np.mean(normal, axis=0)
                    contact_forces[cs, :] -= self.adhesion_force * normal
            return contact_forces

        # ---------------------------------------------------- наблюдения
        def get_observation(self, sim):
            if self._fb_rule_stage:
                # Съём для правил походки: он повторный и ему нужны
                # четыре поля из семи. Отметка одноразовая — следующее
                # чтение в этом же шаге (из `post_step`) получит полное
                # наблюдение, то, которое уезжает наружу. И вторая
                # защёлка: номер состояния должен быть тем же, что при
                # постановке отметки. После `physics.step` он другой,
                # поэтому `post_step` сокращённого наблюдения не
                # получит ни при каком порядке вызовов.
                self._fb_rule_stage = False
                st = getattr(sim.physics, "_fb_accfwd", None)
                if st is not None and st["эпоха"] == self._fb_rule_epoch:
                    return self.rule_observation(sim)
            physics = sim.physics
            if not self._fb_ready:
                self._fb_prepare(physics)
            if physics.is_dirty:
                # Прежде это делало первое чтение через биндинг.
                physics.forward()

            joint_obs = np.zeros((3, len(self.monitored_joints)))
            a = self._fb_sd_read("act")
            na = self._fb_sd_read("nonact")
            n_act = len(self.actuated_joints)
            # Прежний цикл ставил столбец `i` равным `a[3i:3i+3]` — то
            # есть перекладывал 126 чисел по три, 42 раза на Python. Это
            # ровно транспонирование, и делается одним движением.
            if a.size == 3 * n_act:
                joint_obs[:, :n_act] = a.reshape(n_act, 3).T
            else:
                for i in range(n_act):
                    joint_obs[:3, i] = a[i * 3: i * 3 + 3]
            for i in range(len(self.monitored_joints) - n_act):
                base_idx = i * 5
                joint_torques = np.linalg.norm(na[base_idx + 1: base_idx + 5])
                joint_obs[:3, n_act + i] = [
                    *na[base_idx: base_idx + 2], joint_torques]
            joint_obs[2, :] *= 1e-9
            joint_obs = joint_obs[:, self._monitored_joint_order]

            cart_pos = self._fb_sd_read("body0")
            cart_vel = self._fb_sd_read("body1")
            quat = self._fb_sd_read("body2")
            ang_pos = R.from_quat(quat[[1, 2, 3, 0]]).as_euler("ZYX")
            ang_vel = self._fb_sd_read("body3")
            fly_pos = np.array([cart_pos, cart_vel, ang_pos, ang_vel])
            self.last_obs["rot"] = ang_pos
            self.last_obs["pos"] = cart_pos

            contact_forces = self._fb_contact_forces(physics)
            self.last_obs["contact_forces"] = contact_forces
            # `last_obs["contact_pos"]` читает РОВНО один потребитель —
            # `Camera._draw_contacts`, и только при `draw_contacts`. В
            # апстриме условие даже написано, но закомментировано
            # (`fly.py`: «if draw contacts same last contact forces and
            # positions»). Здесь оно восстановлено и спрашивается у
            # настоящих камер, а не задано числом: если рисование
            # контактов включат, положения снова будут считаться.
            # `last_obs["rot"]`/`["pos"]` так НЕ закрыты: их читает
            # `Camera._update_camera` на каждом кадре.
            if any(getattr(c, "draw_contacts", False)
                   for c in getattr(sim, "cameras", ())):
                self.last_obs["contact_pos"] = \
                    physics.data.xpos[self._fb_body_ids].copy().T

            ee_pos = self._fb_sd_read("ee").reshape((self.n_legs, 3))
            orientation_vec = self._fb_sd_read("body4")
            cardinal_vectors = [orientation_vec,
                                self._fb_sd_read("body5"),
                                self._fb_sd_read("body6")]
            obs = {
                "joints": joint_obs.astype(np.float32),
                "fly": fly_pos.astype(np.float32),
                "contact_forces": contact_forces.astype(np.float32),
                "end_effectors": ee_pos.astype(np.float32),
                "fly_orientation": orientation_vec.astype(np.float32),
                "cardinal_vectors": np.array(cardinal_vectors).astype(
                    np.float32),
            }
            if self.enable_olfaction:
                antennae_pos = self._fb_sd_read("ant")
                obs["odor_intensity"] = sim.arena.get_olfaction(
                    antennae_pos.reshape(4, 3)).astype(np.float32)
            if self.enable_vision:
                self._update_vision(sim)
                obs["vision"] = self._curr_visual_input
            return obs

        def rule_observation(self, sim):
            """Только то, что читают правила походки.

            `HybridTurningController.step` берёт полное наблюдение, а
            пользуется из него четырьмя величинами:
            `_retraction_rule_find_leg` читает `obs["fly"][0][2]` и
            `obs["end_effectors"][:, 2]`, `_stumbling_rule_check_condition`
            — `obs["contact_forces"]` и `obs["fly_orientation"]`. Всё
            остальное (42 суставных датчика, скорости, углы Эйлера через
            scipy, кардинальные векторы, обоняние, `xpos` контактных тел)
            считается и выбрасывается.

            Значения те же до бита: приведение к `float32` поэлементное,
            поэтому `obs["fly"][0][2]` не зависит от остальных строк, и
            строку `cart_pos` можно отдать одну.

            Побочные записи прежнего наблюдения (`last_obs`,
            `_active_adhesion`) здесь либо делаются (`_active_adhesion` —
            внутри поправки на прилипание), либо уже стоят с тем же
            значением: `post_step` предыдущего шага физики посчитал их
            на ЭТОМ же состоянии модели.
            """
            physics = sim.physics
            if not self._fb_ready:
                self._fb_prepare(physics)
            if physics.is_dirty:
                physics.forward()
            contact_forces = self._fb_contact_forces(physics, use_cache=True)
            return {
                "fly": np.asarray(self._fb_sd_read("body0"),
                                  dtype=np.float64).reshape(1, 3)
                .astype(np.float32),
                "end_effectors": self._fb_sd_read("ee")
                .reshape((self.n_legs, 3)).astype(np.float32),
                "contact_forces": contact_forces.astype(np.float32),
                "fly_orientation": self._fb_sd_read("body4")
                .astype(np.float32),
            }

    return _FastObsFly


def _sim_class(rule_obs):
    """Контроллер походки FlyGym; при ``rule_obs`` — с сокращённым
    наблюдением для правил.

    Почему отметкой, а не переопределением метода. `get_observation`
    зовётся в `HybridTurningController.step` как
    `super().get_observation()`, то есть явно у РОДИТЕЛЯ
    (`SingleFlySimulation`) — переопределение в подклассе обойдено
    `super()` и не сработает (проверено замером: правка не давала ничего,
    пока стояла подклассом). Переписывать же весь `step` ради одной
    строки значит держать копию шестидесяти строк апстрима.

    Поэтому отметка ставится на время `step` и снимается первым же
    чтением наблюдения — тем самым повторным. Второе чтение в этом же
    шаге, из `post_step`, получает полное наблюдение, и именно оно
    уезжает наружу. Границы ровные: за пределами `step` отметки нет,
    поэтому `body.py` со своими `fly.get_observation(body)` (после
    живых условий и после продолжения из снимка) и `reset` всегда
    получают полное наблюдение.
    """
    from flygym_gymnasium.examples.locomotion import HybridTurningController

    if not rule_obs:
        return HybridTurningController

    class _RuleObsController(HybridTurningController):

        def step(self, action):
            fly = self.fly
            if not hasattr(fly, "rule_observation") \
                    or getattr(fly, "enable_vision", False):
                # Со зрением сокращать нельзя. `Fly.get_observation`
                # зовёт `_update_vision(sim)`, а тот ведёт
                # `_last_vision_update_time` — то есть у повторного съёма
                # есть последствие, и выбросить его значит изменить
                # расписание обновления зрения. Зрение в продукте есть
                # (`BodyConfig.vision`), по умолчанию выключено, и
                # ловушка держится ПРОВЕРКОЙ признака у тела, а не
                # предположением о сборке.
                return super().step(action)
            # Отметка привязывается к НОМЕРУ СОСТОЯНИЯ, а не только к
            # дынамическому отрезку `step`. Причина названа, а не
            # придумана: съём правил стоит в апстриме ПЕРЕД
            # `physics.step()`, а `post_step` — после, и после шага номер
            # состояния уже другой. Поэтому сокращённое наблюдение не
            # может достаться `post_step`, даже если порядок вызовов в
            # апстриме (или в чьей-нибудь замене `step`) изменится и
            # съёма правил не случится вовсе. Публичное наблюдение так
            # защищено устройством, а не тем, что мы угадали порядок.
            st = getattr(self.physics, "_fb_accfwd", None)
            if st is None:
                return super().step(action)
            fly._fb_rule_stage = True
            fly._fb_rule_epoch = st["эпоха"]
            try:
                return super().step(action)
            finally:
                fly._fb_rule_stage = False

    return _RuleObsController


def _build_body(cfg: BodyConfig, sources, video_path=None, head_stab=None):
    """Тело FlyGym. ``head_stab`` — переходник :class:`motor.HeadStabilizer`.

    Передавать его — не настройка, а ПРАВКА МОДЕЛИ: при включённой
    стабилизации `Fly` добавляет два привода на шейные суставы
    (`joint_Head_yaw`, `joint_Head`), которых без неё в модели нет
    вовсе. Поэтому эпизод со стабилизацией и без неё — это две разные
    механические модели, а не два режима одной.
    """
    from flygym_gymnasium import YawOnlyCamera
    from flygym_gymnasium.arena import OdorArena
    from flygym_gymnasium.preprogrammed import default_leg_sensor_placements

    from . import gait as G

    acc_forward = bool(getattr(cfg, "acc_forward", True))
    Fly = _fly_class(getattr(cfg, "fast_physics", False),
                     fast_obs=bool(getattr(cfg, "fast_obs", True)),
                     acc_forward=acc_forward)
    HybridTurningController = _sim_class(
        bool(getattr(cfg, "rule_obs", True))
        and str(getattr(cfg, "gait", "fast")) == "legacy")

    arena = OdorArena(
        odor_source=sources,
        peak_odor_intensity=np.ones((len(sources), 1)),
    )
    # Пул зрительных объектов вписывается ДО компиляции модели: MuJoCo
    # не добавляет тела в собранную модель. При `vis_objects = 0` не
    # вписывается ничего, и сцена остаётся прежней — проверено
    # побитовым совпадением траектории (`probe/objects.py`).
    n_obj = int(getattr(cfg, "vis_objects", 0) or 0)
    if n_obj > 0:
        from . import objects as _objects

        if n_obj > _objects.POOL:
            raise ValueError(
                "слотов зрительных объектов просят %d, а предел пула %d: "
                "каждый слот это тело MJCF и шесть лишних геометрий уже "
                "меняют порядок растеризации кадра (`objects.py`)"
                % (n_obj, _objects.POOL))
        _objects.inject(arena, n=n_obj)
    extra = {}
    if head_stab is not None:
        extra = {"head_stabilization_model": head_stab,
                 "neck_kp": head_stab.neck_kp}
    # Зрение передаётся ТОЛЬКО когда оно нужно. Передача
    # `enable_vision=False` не равна непередаче: `Fly.__init__` на
    # выключенном зрении всё равно проходит по ветке настройки, и
    # сравнивать прежние прогоны пришлось бы с другой дорогой кода.
    if bool(getattr(cfg, "vision", False)):
        extra["enable_vision"] = True
        hz = float(getattr(cfg, "vision_hz", 100.0) or 0.0)
        if hz <= 0.0:
            raise ValueError(
                "зрение включено, а частота обновления %r: кадр глаза "
                "не обновится ни разу" % (hz,))
        # FlyGym держит её целым числом герц
        # (`_eff_visual_render_interval = 1 / vision_refresh_rate`),
        # и дробную просьбу надо округлить ЗДЕСЬ, а не оставить
        # расхождение между заказанным и действительным: в прогон
        # уезжает то, что действительно считало.
        extra["vision_refresh_rate"] = int(round(hz))
    fly = Fly(
        enable_adhesion=True,
        enable_olfaction=True,
        contact_sensor_placements=default_leg_sensor_placements,
        init_pose="stretch",
        control="position",
        spawn_pos=(0.0, 0.0, 0.2),
        **extra,
    )
    cams = []
    if video_path is not None:
        # Камера следит за курсом, но не за креном: иначе картинка качается
        # вместе с телом и смотреть невозможно.
        cams = [YawOnlyCamera(
            attachment_point=fly.model.worldbody,
            camera_name="camera_top",
            targeted_fly_names=[fly.name],
            play_speed=cfg.play_speed,
            fps=cfg.fps,
            output_path=str(video_path),
        )]
    # Две дороги к одной избыточности, и включена ровно одна.
    #
    # `gait="fast"` (по умолчанию) — вендоренная копия шага из
    # `flybrain.gait`: она не зовёт `super().get_observation()` вовсе,
    # поэтому сокращать наблюдение правил нечему, а фазовый множитель
    # она уже считает массивами. Значит `rule_obs` и `fast_gain`
    # относятся к дороге `legacy` и при `fast` НЕ ставятся — не потому
    # что мешают, а потому что иначе остались бы непотреблёнными
    # крючками, которые следующий читающий примет за работающие.
    #
    # `acc_forward` и `fast_obs` от дороги походки не зависят: первый
    # живёт на `Physics`, второй — в `Fly`, и оба работают при любом
    # контроллере.
    #
    # Повторное чтение наблюдения прошлого шага выключается при открытом
    # окне MuJoCo: пассивное окно умеет двигать состояние мышью мимо
    # `dm_control`, то есть не помечая его грязным. В счётных прогонах
    # окна нет.
    legacy_gait = str(getattr(cfg, "gait", "fast")) == "legacy"
    sim = G.build(gait="legacy" if legacy_gait else "fast",
                  reuse_obs=not getattr(cfg, "view", False),
                  base=HybridTurningController if legacy_gait else None,
                  fly=fly, cameras=cams, arena=arena,
                  timestep=cfg.physics_dt)
    # Крючки на `Physics.step`/`forward` ставятся, если нужна хотя бы
    # одна из двух вещей: дешёвый пересчёт или номер состояния, по
    # которому наблюдение не считает контактные силы дважды. При
    # `fast_physics` пересчёта нет вовсе, и дешёвой дороги тоже.
    want_acc = acc_forward and not getattr(cfg, "fast_physics", False)
    if want_acc or bool(getattr(cfg, "fast_obs", True)):
        _install_acc_only_forward(sim.physics, acc_forward=want_acc)
    if legacy_gait and bool(getattr(cfg, "fast_gain", True)):
        _install_fast_gain(sim)
    return sim, cams


def _odour_channels(fly):
    """Какие столбцы `odor_intensity` — антенны, а какие щупики.

    Порядок задаётся словарём `config["olfaction"]["sensor_positions"]`
    и равен `LMaxillaryPalp, RMaxillaryPalp, LAntenna, RAntenna`. Раньше
    здесь стояли жёсткие индексы 0 и 1 — то есть читались **максиллярные
    щупики**, хотя в подписи значились антенны. Лево и право при этом
    были верны, но разнос щупиков 0,60 мм против 0,17 мм у антенн, и
    билатеральная разница выходила в 3,4 раза больше настоящей.

    Ищем по имени: порядок в словаре — не обещание FlyGym, и молча
    разъехаться он не должен второй раз.
    """
    names = list(fly.config["olfaction"]["sensor_positions"])
    left = right = None
    for i, name in enumerate(names):
        low = name.lower()
        if "antenna" not in low:
            continue
        if low.startswith("l") and left is None:
            left = i
        elif low.startswith("r") and right is None:
            right = i
    if left is None or right is None:
        raise ValueError(
            "в olfaction.sensor_positions не нашлось пары антенн: "
            + ", ".join(names))
    return left, right


def _pose(obs):
    """Положение в мм и курс в радианах из наблюдения FlyGym."""
    pos = np.asarray(obs["fly"])[0]
    fwd = np.asarray(obs["fly_orientation"])
    return float(pos[0]), float(pos[1]), math.atan2(float(fwd[1]), float(fwd[0]))


def run_episode(cfg: BodyConfig | None = None, neurons=None, weights=None,
                sources=None, progress=True, on_step=None, should_stop=None,
                video_path=None, on_body=None, live=None, engine=None,
                resume=None, counts0=None, tape=None):
    """Эпизод в теле. ``on_body(body)`` зовётся один раз, когда тело собрано
    и сброшено: живому окну нужен доступ к физической модели, чтобы снимать
    кадры своим ``mujoco.Renderer`` — камера FlyGym отмеряет кадры по
    модельному времени и для живого вида не годится.

    ``live`` — состояние живых условий (:class:`flybrain.live.BodyLive`) или
    ``None``. Контракт ровно из двух вызовов, и оба на виду:

    * ``live.attach(body, sources, cfg, neurons, device, engine)`` — раз,
      когда тело собрано: состояние получает ссылки на настоящую модель
      MuJoCo, на массив положений источников и на настройку, и дальше
      меняет их на месте;
    * ``live.add_drive(rates)`` — на каждом шаге, после того как в
      ``rates`` записаны сенсорные каналы: так в расчёт попадают прямые
      нейронные стимулы;
    * ``live.active_sources()`` — на каждом шаге: какие слоты источника
      включены. Выключенный слот остаётся в модели, но едой не является.

    Без ``live`` ни один из вызовов не делается, и эпизод считается в
    точности как раньше.

    ``engine``, ``resume``, ``counts0`` и ``tape`` нужны продолжению
    сеанса с сохранённого места (``flybrain.replay``), и контракт у них
    тот же, что у арены:

    * ``engine`` — готовый движок с поставленным состоянием; без него
      собирается здесь, как и раньше;
    * ``resume`` — снимок состояния (:class:`flybrain.replay.State`
      вида ``body``). При нём **разогрев калибровки не идёт**: он звал бы
      движок 75 раз и сдвинул бы то самое состояние, из которого
      продолжают. Перекос, шум и яркость насыщения берутся из снимка, а
      состояние MuJoCo и фаза походки ставятся сразу после сборки тела;
    * ``counts0`` — счётчики спайков сеанса, чтобы частоты считались по
      всему сеансу, а не по его последнему отрезку;
    * ``tape`` — лента таймлайна; модель она не трогает.
    """
    import torch

    cfg = cfg or BodyConfig()
    # Копия обязательна в обеих ветках. `BodyLive` пишет в этот массив
    # на месте, когда пользователь переносит слот, и без копии правка
    # уехала бы в сам `DEFAULT_SOURCES` — то есть в КАЖДЫЙ следующий
    # эпизод этого процесса работника, молча и невидимо по файлам.
    sources = (DEFAULT_SOURCES.copy() if sources is None
               else np.array(sources, dtype=float))
    if neurons is None:
        neurons = D.load_neurons()
    device = cfg.device or ("cuda" if torch.cuda.is_available() else "cpu")
    n = len(neurons)

    # --- кого слушаем и кого зажигаем ---
    cands = world.probe_candidates(neurons)
    # Прямые зонды доступны и как съём для прежнего декодера — под
    # именами с приставкой `зонд:`. В общий список они не входят: там
    # порог восемь нейронов на сторону (см. `world.dn_probe_candidates`).
    cands = {**cands, **world.dn_probe_candidates()}
    if cfg.readout not in cands:
        raise SystemExit(f"нет популяции {cfg.readout!r}; см. вывод `fly lateral`")
    ql, qr = cands[cfg.readout]
    motor_l, motor_r = D.select(neurons, ql), D.select(neurons, qr)

    sensor_idx = {
        "odour_left": D.select(neurons, world.SENSORS["odour_left"]),
        "odour_right": D.select(neurons, world.SENSORS["odour_right"]),
        "taste": D.select(neurons, world.SENSORS["taste"]),
    }
    for name, idx in list(sensor_idx.items()) + [("выход L", motor_l), ("выход R", motor_r)]:
        print(f"  {name:12s} {len(idx):6d} нейронов")

    # --- зрение: переходник по имени, до сборки движка ---
    #
    # Здесь, а не после сборки, по одной причине: фоторецепторы обязаны
    # попасть в `no_refractory` так же, как обонятельные каналы. Иначе
    # та же частота даёт меньше спайков, и числа этого прогона
    # несравнимы с замерами проб (`probe/vision_chain.py`,
    # `probe/vision_live.py` — обе снимают рефрактерность с
    # фоторецепторов).
    vis = None
    vbr = None                 # гибридный переходник, если его просили
    if bool(getattr(cfg, "vision", False)):
        from . import vision as V

        vis = V.make(str(getattr(cfg, "vision_adapter", "retina")),
                     mode=str(getattr(cfg, "vision_mode", "whiten")),
                     assign=str(getattr(cfg, "vision_assign", "capacity")),
                     shuffle=bool(getattr(cfg, "vision_shuffle", False)),
                     seed=cfg.seed,
                     channel=str(getattr(cfg, "vision_channel", "max")),
                     max_hz=float(getattr(cfg, "vision_max_hz", 150.0)),
                     ref=float(getattr(cfg, "vision_ref", 0.5)),
                     eyes=str(getattr(cfg, "vision_eyes", "both")))
        vis.attach(neurons, device)
        print(f"  зрение      {len(vis.indices):6d} фоторецепторов "
              f"({vis.name} v{vis.version}, {cfg.vision_eyes})")
        # Переходник строится здесь же и из того же набора: ему нужна
        # матрица связей, чтобы НАВЕСТИ омматидий на T4/T5 по
        # возбуждающим синапсам через ламину и медуллу. Строится он
        # только когда его просили: при `vision_bridge=None` ни одного
        # обращения к `vislink` в прогоне нет.
        if getattr(cfg, "vision_bridge", None):
            from . import vislink as VBR

            реж = str(cfg.vision_bridge)
            if реж != "гибрид":
                raise ValueError(
                    "`vision_bridge` знает одно значение — \"гибрид\"; "
                    "дано %r. Физиологический режим (`visdyn`) отвергнут "
                    "своим нулевым контролем и умолчанием не бывает "
                    "(FULL_LOOP_VALIDATION.md §2.4)" % (реж,))
            vbr = VBR.Мост(
                neurons, weights, device=device,
                граница=str(getattr(cfg, "vision_bridge_boundary",
                                    "T4/T5")),
                усиление_hz=float(getattr(cfg, "vision_bridge_gain",
                                          200.0)),
                потолок_hz=float(getattr(cfg, "vision_bridge_max_hz",
                                         1000.0)),
                задержка_мс=float(getattr(cfg, "vision_bridge_delay_ms",
                                          30.0)),
                кадр_мс=float(cfg.control_ms),
                тасовка=bool(getattr(cfg, "vision_bridge_shuffle", False)),
                подтипы_тасовка=bool(getattr(
                    cfg, "vision_bridge_subtypes_shuffle", False)),
                seed=cfg.seed,
                mode=str(getattr(cfg, "vision_mode", "whiten")),
                assign=str(getattr(cfg, "vision_assign", "capacity")))
            нав, вс = vbr.наведено
            print("  переходник  %6d нейронов границы %s "
                  "(ИНЖЕНЕРНЫЙ, место наведено у %d из %d)"
                  % (sum(len(i) for i, _ in vbr._адрес.values()),
                     vbr.граница, нав, вс))

    if vbr is None and getattr(cfg, "vision_bridge", None):
        # Переходник берёт яркость у кадра глаза, и без зрения её нет
        # вовсе. Тихо его пропустить нельзя: прогон тогда утверждал бы
        # режимом то, чего в нём не было.
        raise ValueError(
            "`vision_bridge` просили при выключенном зрении: переходник "
            "берёт яркость у кадра глаза, поставьте `vision=True`")

    driven = np.unique(np.concatenate(list(sensor_idx.values())))
    if vis is not None and len(vis.indices):
        driven = np.unique(np.concatenate([driven, vis.indices]))
    if engine is None:
        engine = sim.build_engine(weights=weights, neurons=neurons,
                                  device=device, seed=cfg.seed,
                                  no_refractory=driven,
                                  spmv=getattr(cfg, "spmv", None))

    # Прямое вмешательство. Строится ПОСЛЕ движка, потому что маска
    # заглушения ставится на движок, и ставится она один раз — до
    # разогрева, иначе перекос и шум измерились бы на незаглушённой
    # сети, а отрицательный контроль сравнил бы две разные опоры.
    interv = None
    if cfg.dn_drive or cfg.dn_silence:
        interv = motor.DnIntervention(neurons, device, drive=cfg.dn_drive,
                                      silence=cfg.dn_silence)
        interv.apply_masks(engine)

    t_sens = {k: torch.as_tensor(v, device=device) for k, v in sensor_idx.items()}
    t_ml = torch.as_tensor(motor_l, device=device)
    t_mr = torch.as_tensor(motor_r, device=device)
    rates = torch.zeros(1, n, device=device)

    # --- прямые зонды и инженерный декодер (`flybrain.motor`) ---
    #
    # Измеритель строится ВСЕГДА, при любом декодере: прямые зонды — это
    # измерение, они ничего не меняют, а без них спайк Giant Fiber
    # остаётся невидимым (2 нейрона из 1299 в усреднённом съёме). Прежний
    # съём по полушарию подключён к тому же измерителю под именем
    # `__readout__`, чтобы у старого и нового декодера был один вход.
    # Строгость размеров зондов нужна ровно тогда, когда от них зависят
    # ЧИСЛА. У `legacy` они не зависят: зонды там только записываются, а
    # команду считает прежний съём `__readout__`. Поэтому при `legacy`
    # расхождение размера пишется в прогон строкой «совпало: false» и
    # оговоркой, а прогон считается; при новых декодерах оно по-прежнему
    # останавливает счёт. Иначе смена версии набора данных ломала бы и
    # те прогоны, которые воспроизводят эталон и зондов не используют, —
    # то есть побитовая сверка легаси стала бы недоступна первой.
    strict_probes = cfg.motor != "legacy"
    readout = motor.DnReadout(
        neurons, device, pairs={"__readout__": (ql, qr)},
        strict=strict_probes) \
        if cfg.probes or cfg.motor != "legacy" else None
    shape = motor.DecoderShape(
        amp_base=cfg.amp_base, amp_span=cfg.amp_span, amp_min=cfg.amp_min,
        amp_max=cfg.amp_max, cross=cfg.cross, turn_sign=cfg.turn_sign,
        dn_tau_s=cfg.dn_tau_s)
    dec_kw = {}
    if cfg.motor == "dn_trained":
        dec_kw["weights_path"] = cfg.motor_weights
    if cfg.motor == "dn_linear" and cfg.motor_map:
        dec_kw["map_path"] = cfg.motor_map
    elif cfg.motor_map and cfg.motor != "dn_linear":
        # Молча не применять нельзя: прогон выглядел бы настроенным по
        # файлу адресации, а считался бы не по нему.
        raise ValueError(
            "motor_map задан, а декодер %r его не читает: файл адресации "
            "относится только к `dn_linear`" % cfg.motor)
    decoder = motor.make_decoder(cfg.motor, shape=shape, **dec_kw)
    bridge = motor.GiantFiberBridge(kind=cfg.gf_bridge,
                                    gf_ref_hz=cfg.gf_ref_hz,
                                    escape_gain=cfg.escape_gain)
    if readout is None:
        # Декодер `legacy` без зондов: измеритель всё равно нужен, но
        # только под один прежний съём. Так выключение зондов ничего не
        # меняет в числах, а не «почти ничего».
        readout = motor.DnReadout(neurons, device, probes={}, shadow=False,
                                  pairs={"__readout__": (ql, qr)})
    if cfg.motor != "legacy":
        missing = [k for k in getattr(decoder, "turn_weights", {})
                   if k not in readout.names]
        if missing:
            raise ValueError("декодер %r просит зонды, которых нет: %s"
                             % (cfg.motor, ", ".join(missing)))

    dt_s = cfg.control_ms / 1000.0
    brain_steps = max(1, int(round(cfg.control_ms / sim.DT)))
    body_steps = max(1, int(round(dt_s / cfg.physics_dt)))
    block_s = brain_steps * sim.DT / 1000.0
    endless = cfg.duration_s is not None and cfg.duration_s <= 0
    keep_steps = 0
    if cfg.keep_s and cfg.keep_s > 0:
        keep_steps = max(1, int(round(cfg.keep_s / dt_s)))
    if endless:
        if not keep_steps:
            raise ValueError(
                "сеанс без заданного конца требует кольца записи: укажите "
                "keep_s, иначе `bins` растёт без предела (277 КБ на шаг "
                "управления, 13,9 МБ на секунду модельного времени)")
        # Предела у сеанса нет, но у счёта шагов он должен быть: иначе
        # `range` не построить, а бесконечность в арифметике времени
        # превращает каждую оценку в nan.
        n_steps = ENDLESS_STEPS
    else:
        n_steps = int(round(cfg.duration_s / dt_s))
    requested_steps = n_steps

    print("собираю тело...")
    t0 = time.perf_counter()
    if cfg.video and video_path is None:
        # Раньше здесь подставлялся `walk.mp4` в текущем каталоге: файл
        # уходил мимо папки прогона, а в серии каждый эпизод затирал
        # предыдущий. Молча писать не туда хуже, чем отказаться.
        raise ValueError("включено видео, но путь не задан: укажите "
                         "video_path — иначе файл уйдёт мимо прогона")
    head_stab = motor.HeadStabilizer(neck_kp=cfg.neck_kp) \
        if cfg.head_stab else None
    body, cams = _build_body(cfg, sources, video_path if cfg.video else None,
                             head_stab=head_stab)
    obs, _ = body.reset(seed=cfg.seed)
    t_setup = time.perf_counter() - t0
    if live is not None:
        # До разогрева: то, что состояние применит здесь, — исходные
        # условия сеанса, а не правка на ходу.
        live.attach(body, sources, cfg, neurons, device, engine=engine)
        # Наблюдение надо перечитать. `reset` снял его ДО применения
        # условий, и дальше по нему считается и калибровка разогрева, и
        # нулевой шаг: при выключенных источниках муха «чуяла» бы
        # 0,005 и получала 150 Гц в рецепторы вместо нуля, а опора,
        # перекос и шум мерились бы на возбуждённом мозге.
        obs = body.fly.get_observation(body)
    resume_report = None
    resume_smooth = (None, None)
    if resume is not None:
        # Состояние ставится ПОСЛЕ сборки и сброса тела, но ДО разогрева:
        # разогрев зовёт движок 75 раз и сдвинул бы то самое состояние,
        # из которого продолжают. Модель при этом не пересобирается —
        # состояние ставится в неё.
        from . import replay as RP

        resume_smooth, resume_report = RP.restore_body(resume, body, engine)
        obs = body.fly.get_observation(body)
    # --- зрительная сцена: свет, пул объектов, заданная траектория ---
    #
    # Всё это ставится ПОСЛЕ живых условий и ПОСЛЕ продолжения из
    # снимка, но ДО разогрева: свет и объекты меняют кадр глаза, то есть
    # вход, и мерить на них калибровку значило бы считать опору в одних
    # условиях, а эпизод — в других.
    vis_pool, vis_track = None, None
    vis_light = None
    if bool(getattr(cfg, "vision", False)):
        from . import vision as V

        want = float(getattr(cfg, "vision_light", 1.0) or 1.0)
        # Свет правится только когда его просили менять: при множителе 1
        # модель не трогается вовсе, и кадр остаётся прежним до бита.
        vis_light = (V.scene_light(body, want) if want != 1.0
                     else V.light_state(body))
    if int(getattr(cfg, "vis_objects", 0) or 0) > 0:
        from . import objects as O

        # Владелец пула один. Живые условия уже нашли его по именам тел
        # (`live.attach` -> `objects.discover`), и второй `Pool` на ту
        # же модель означал бы два источника истины о слотах.
        vis_pool = (live.pool if live is not None and live.pool is not None
                    else O.discover(body, n=int(cfg.vis_objects)))
        if vis_pool is None:
            raise RuntimeError(
                "слоты зрительных объектов просили, а в модели их нет: "
                "`objects.inject` зовётся в `_build_body` до компиляции")
        if getattr(cfg, "vis_track", None):
            vis_track = O.Track(cfg.vis_track)
            need = vis_track.need_slots()
            if need > len(vis_pool.slots):
                raise ValueError(
                    "трек просит %d слотов, а вписано %d: поднимите "
                    "`vis_objects`" % (need, len(vis_pool.slots)))
            # Нулевое модельное время — часть трека, а не «ещё не
            # началось»: объект, заданный с t0 = 0, обязан стоять на
            # месте уже на первом шаге, а не появиться на втором.
            vis_track.apply(vis_pool, 0.0, cmd="трек: начало")
    elif getattr(cfg, "vis_track", None):
        raise ValueError(
            "траектория объектов задана, а слотов не просили: укажите "
            "`vis_objects` (тела MuJoCo создаются до компиляции модели и "
            "на ходу не добавляются)")

    if on_body is not None:
        on_body(body)

    viewer = None
    if cfg.view:
        import mujoco.viewer

        # Пассивный просмотр: окно не крутит физику само, мы сами зовём sync()
        # после каждого шага. Мышью можно вертеть камеру и ставить на паузу.
        viewer = mujoco.viewer.launch_passive(
            body.physics.model.ptr, body.physics.data.ptr,
            show_left_ui=False, show_right_ui=False)
        print("  открыто окно MuJoCo: мышь вращает камеру, "
              "закрытие окна останавливает эпизод")

    ant_l, ant_r = _odour_channels(body.fly)
    # Что со зрением случилось за сеанс. Считается, а не объявляется:
    # «обновлений зрения» берётся из той самой маски, которую ведёт
    # `Fly.post_step`, и измеренная частота обновления сравнивается с
    # заказанной в самом прогоне.
    vis_seen = {"шагов с подачей": 0, "обновлений": 0, "подача": None,
                "последнее обновление, мс": None,
                "шагов с переходником": 0, "переходник": None}

    def pose_antennae():
        """Положение и курс ОТ ОБОНЯТЕЛЬНЫХ СЕНСОРОВ, а не от груди.

        Читается то же, что читает `Fly.get_observation`: `framepos`
        датчиков, привязанных к `LFuniculus`/`RFuniculus`. Положение —
        середина между антеннами, курс — из их собственной оси,
        повёрнутой на 90°: ось антенн поперечна курсу, и `ANTENNA.md`
        §3 показал замером, что отходит она от «курс + 90°» всего на
        −1,31…+1,02° за эпизод.

        Отличие от `_pose` не только в точке отсчёта. `_pose` зовётся в
        начале шага управления, то есть курс в метрике взят ДО 100
        шагов физики, а положение — после них; здесь и то и другое
        читается из текущего состояния модели. Это тоже часть
        альтернативы, и она объявлена, а не сделана молча.
        """
        raw = np.asarray(
            body.physics.bind(body.fly._antennae_sensors).sensordata,
            dtype=float).reshape(-1, 3)
        p_l, p_r = raw[ant_l], raw[ant_r]
        mid = 0.5 * (p_l + p_r)
        ax, ay = float(p_l[0] - p_r[0]), float(p_l[1] - p_r[1])
        # Курс — ось антенн минус 90°: при курсе 0 левая антенна лежит
        # севернее правой, то есть ось смотрит на +y, и поворот на −90°
        # даёт +x. Знак проверен пробой `probe/grad_ref.py`.
        return (float(mid[0]), float(mid[1]),
                math.atan2(ay, ax) - 0.5 * math.pi)

    def read_odour(obs):
        """Интенсивность на левой и правой АНТЕННЕ.

        Столбцы найдены по имени (`_odour_channels`), а не заданы числом.
        """
        oi = np.asarray(obs["odor_intensity"])[0]
        return float(oi[ant_l]), float(oi[ant_r])

    def drive_brain(left_i, right_i, taste_hz, ref, frame=None):
        """Придуманная часть: интенсивность -> частота рецепторов.

        ``frame`` — кадр ``obs["vision"]`` или ``None``. Подача зрения
        стоит ЗДЕСЬ, между сенсорными каналами и прямыми стимулами, и
        порядок не случаен: `rates.zero_()` стирает всё, поэтому
        зрение обязано лечь после него, а прямые стимулы из окна —
        после зрения, иначе окно не смогло бы поднять частоту
        фоторецептора поверх кадра.

        Частоты ставятся `index_fill_`, а не записью по срезу
        (`rates[0, idx] = rl`). Разница не в арифметике, а в том, что
        запись по срезу идёт через `index_put_`: питоновское число
        сначала становится тензором на хосте и уезжает на устройство
        отдельной передачей, и эта передача ЖДЁТ. `index_fill_` берёт
        число скаляром прямо в ядро.

        Значение то же до бита — это тот же float32 в те же позиции, — и
        это не рассуждение: проба сравнивает `rates` после обеих дорог
        побайтово (`probe/lifperf_ab.py`, пункт 2). Замерено там же,
        попарно: три записи стоили 1,2974 мс на шаг управления против
        0,1944 мс, то есть **в 6,67 раза** (6,22…13,75 по 21 паре).
        """
        if cfg.swap_antennae:
            left_i, right_i = right_i, left_i
        rl = cfg.orn_max_hz * min(1.0, left_i / ref)
        rr = cfg.orn_max_hz * min(1.0, right_i / ref)
        rates.zero_()
        rates.index_fill_(1, t_sens["odour_left"], rl)
        rates.index_fill_(1, t_sens["odour_right"], rr)
        if taste_hz > 0:
            rates.index_fill_(1, t_sens["taste"], taste_hz)
        # Три скаляра — проверка на хосте и бесплатна. Выше предела
        # `bernoulli` падает ассертом карты, а тот портит контекст CUDA
        # необратимо и докладывается потом чужой строкой
        # (`sim.MAX_RATE_HZ`). `orn_max_hz` и `taste_hz` задаются
        # человеком; окно свой прямой стимул уже держит на 1000 Гц
        # (`live.MAX_STIM_HZ`, и там названа та же причина).
        sim.check_rates_hz([rl, rr, taste_hz], "сенсорные каналы тела")
        # Сводка подачи сбрасывается ПЕРЕД попыткой, а не после удачной.
        # Иначе она остаётся с прошлого шага, и запись шага сообщает
        # частоту, которой на этом шаге никто не подавал: проба
        # `probe/vision_live_app.py` поймала ровно это — после
        # выключения подачи в записи стояло 117,985 Гц. Поле, которое
        # врёт, хуже отсутствующего поля.
        vis_seen["подача"] = None
        vis_seen["переходник"] = None
        if vis is not None and frame is not None \
                and bool(getattr(cfg, "vision_feed", True)):
            # Потолок и насыщение перечитываются из настройки на каждом
            # шаге, а не берутся один раз до цикла: иначе живая правка
            # подтверждалась бы как применённая и попадала в журнал
            # прогона, ничего при этом не меняя. Так же здесь устроены
            # `odour_ref` и `dn_tau_s`. При неизменной настройке
            # значения те же.
            vis.max_hz = float(cfg.vision_max_hz)
            vis.ref = max(float(cfg.vision_ref), 1e-12)
            vis_seen["подача"] = vis.feed(
                rates, frame,
                contrast=float(getattr(cfg, "vision_contrast", 1.0) or 1.0))
            vis_seen["шагов с подачей"] += 1
            # Переходник — ПОСЛЕ фоторецепторов и по тому же кадру.
            # Популяции не пересекаются (фоторецепторы и T4/T5
            # непересекающиеся множества нейронов), поэтому записи не
            # затирают друг друга; проверено отдельно в
            # `probe/looming_loop.py`.
            #
            # Контраст переходнику НЕ передаётся: он считает производную
            # яркости по времени, и преобразование вокруг середины шкалы
            # поменяло бы её на постоянный множитель, то есть выдало бы
            # изменение чувствительности за изменение сцены.
            if vbr is not None:
                vis_seen["переходник"] = vbr.feed(rates,
                                                  vis.per_omma(frame))
                vis_seen["шагов с переходником"] += 1
        if live is not None:
            # Прямые нейронные стимулы — после сенсорных каналов и после
            # `rates.zero_()`: иначе их стирало бы каждым шагом.
            live.add_drive(rates)
        if interv is not None:
            # Накачка настройкой прогона — там же и по той же причине.
            # Порядок с `live.add_drive` задан: если пользователь мышью
            # накачал ту же популяцию, побеждает настройка прогона, и
            # это записано, а не оставлено на догадку.
            interv.apply(rates)
        return rl, rr

    def step_brain():
        acc = torch.zeros(n, device=device)
        for _ in range(brain_steps):
            acc += engine.step(rates)[0]
        return acc

    def step_measure():
        """Один блок управления: мозг + ИЗМЕРЕНИЕ всех зондов.

        `readout_*` здесь и остаются измерением: ни одного
        преобразования, только сумма спайков на число нейронов и
        длительность блока.

        Съём с устройства ОДИН на весь шаг управления, а не четыре.
        Прежде здесь ждали поток CUDA пять раз: `float(acc[t_ml].sum())`,
        `float(acc[t_mr].sum())`, `readout.read`, `int(acc.sum())` в
        записи и копия строки растра. Первые четыре сведены в
        `readout.read_total`: все зонды и общая сумма едут одной
        передачей, а `dn_l`/`dn_r` берутся из пары `__readout__` — она
        собрана по ТЕМ ЖЕ селекторам `ql`/`qr`, по которым построены
        `t_ml`/`t_mr`, так что это то же число, а не близкое. Почему до
        бита то же — см. `motor.DnReadout.read_total`; сверено
        `probe/lifperf_ab.py` (пункт 3), замерено там же попарно: 0,4603
        против 0,3795 мс на спокойной машине (в 1,63 раза) и 2,447
        против 0,640 мс при фоне втрое (в 3,81 раза). Ожидание тем
        дороже, чем занятее видеокарта.
        """
        acc = step_brain()
        rd, total = readout.read_total(acc, block_s)
        dl, dr = rd["__readout__"]
        return acc, dl, dr, rd, total

    # --- разогрев: симметричный вход, меряем опору, перекос и шум ---
    li, ri = read_odour(obs)
    if cfg.odour_ref is not None:
        # Песочница задаёт яркость насыщения числом: сеанс может
        # начинаться с выключенными источниками, и измеренная по началу
        # яркость была бы нулевой — первый же включённый источник
        # насытил бы рецепторы до потолка и градиент стал бы не виден.
        odour_ref = max(float(cfg.odour_ref), 1e-9)
    else:
        odour_ref = max((li + ri) / 2.0 * cfg.odour_ref_factor, 1e-9)
    warm = max(5, int(round(3000.0 * cfg.dn_tau_s / cfg.control_ms)))
    # Постоянной сглаживания здесь больше нет. С этапа 2 фильтр живёт
    # внутри `motor.Decoder` (`_sm`, `shape.dn_tau_s`), и `k` считался
    # тут — и перед разогревом, и на каждом шаге цикла — но никуда не
    # уходил. Это не ускорение (один `math.exp` на шаг управления), а
    # снятая ловушка: по виду строки читающий решал бы, что τ
    # применяется здесь.
    mean_i = (li + ri) / 2.0
    stopped = False
    per_probe = {}
    if resume is not None:
        # Продолжение: калибровка взята из снимка, разогрев не идёт.
        # Пересчитать её заново нельзя — разогрев двигает движок.
        cal = resume.arrays.get("calib") or {}
        bias = float(cal.get("bias", 0.0))
        noise = float(cal.get("noise", 1e-4))
        odour_ref = float(cal.get("odour_ref", odour_ref))
        calib = {
            "odour_ref": round(odour_ref, 8),
            "dn_ref_hz": round(float(cal.get("dn_ref_hz", 0.0)), 4),
            "asym_bias": round(bias, 6),
            "asym_noise": round(noise, 6),
            "warm_steps": 0,
            "откуда": "снимок состояния: разогрев не повторялся, он "
                      "сдвинул бы то состояние, из которого продолжают",
        }
        # Калибровку надо отдать ДЕКОДЕРУ, а не только положить в
        # `calib`. Прежний съём читает перекос и шум из самого декодера
        # (`self.bias`, `self.noise`), и без этих двух строк продолжение
        # считало бы с перекосом 0 и шумом 1e-4 вместо снятых на
        # разогреве — то есть молча с другим коэффициентом усиления и с
        # невычтенным перекосом. Числа берутся НЕОКРУГЛЁННЫЕ, из
        # `calib` снимка, по той же причине, по которой в снимок уехал
        # `calib_exact`: на границе округления `asym` расходится.
        decoder.bias["__readout__"] = bias
        decoder.noise["__readout__"] = noise
        decoder._calibrated = True
    else:
        drive_brain(mean_i, mean_i, 0.0, odour_ref)
        tot = 0.0
        for _ in range(warm):
            _, dl, dr, rd, _tot = step_measure()
            tot += (dl + dr) / 2
            # Разогрев идёт ЧЕРЕЗ декодер: перекос и шум считаются для
            # каждого зонда сразу, одним и тем же кодом. Прежняя
            # арифметика при этом та же — просто у популяции
            # `__readout__` она теперь не отдельной веткой.
            decoder.observe(rd, dt_s)
            if should_stop is not None and should_stop():
                # Разогрев при большой tau длиннее самого эпизода, и
                # ждать его конца значит не отвечать на «стоп» десяток
                # секунд.
                stopped = True
                break
        per_probe = decoder.calibrate()
        bias = decoder.bias.get("__readout__", 0.0)
        noise = decoder.noise.get("__readout__", 1e-4)
        decoder.reset_state()
        calib = {
            "odour_ref": round(odour_ref, 8),
            "dn_ref_hz": round(tot / warm, 4),
            "asym_bias": round(bias, 6),
            "asym_noise": round(noise, 6),
            "warm_steps": warm,
            "зонды": per_probe,
        }
    print(f"  опора {calib['dn_ref_hz']} Гц, перекос {bias:+.5f}, "
          f"шум {noise:.5f}, яркость насыщения {odour_ref:.5f}")

    # Накачка включается ЗДЕСЬ, после калибровки, и ни шагом раньше.
    # Причина измерима: `calibrate` считает `bias_hz` как среднюю
    # разницу сторон по разогреву и дальше вычитает её из каждого шага.
    # Накачка, шедшая и на разогреве, попала бы в `bias_hz` целиком и
    # вычиталась бы из самой себя. Заодно первый шаг эпизода становится
    # ступенью, по которой видна динамика отклика. См.
    # `motor.DnIntervention`.
    if interv is not None:
        interv.enabled = True

    # В снимок состояния калибровка уходит НЕОКРУГЛЁННОЙ. Числа в
    # `calib` округлены для чтения глазами и для `embodied.json` (перекос
    # до шестого знака, яркость насыщения до восьмого), а цикл считает по
    # вот этим значениям. Разница не больше 5e-7 — и её хватает: `asym`
    # на границе своего округления расходится, и продолжение держалось
    # ОДИН шаг вместо всего хвоста. Поймано замером
    # (`probe/resume_state.py --part body`), а не рассуждением; после
    # правки — все проверенные шаги побитово.
    calib_exact = {"bias": bias, "noise": noise, "odour_ref": odour_ref,
                   "dn_ref_hz": float(calib["dn_ref_hz"])}

    # --- эпизод ---
    if stopped:
        # Один шаг всё же делаем: на пустой записи не считаются ни метрики,
        # ни итог, и вызывающему пришлось бы разбирать особый случай.
        n_steps = min(n_steps, 1)
    counts = torch.zeros(n, dtype=torch.int64, device=device)
    if counts0 is not None and len(counts0) == n:
        counts += torch.as_tensor(np.asarray(counts0, np.int64),
                                  device=device)
    if not keep_steps:
        keep_steps = n_steps
    keep_steps = min(keep_steps, n_steps)
    bins = torch.zeros(keep_steps, n, dtype=torch.int16, device=device)
    records = []
    # Накопитель сглаживания: у продолжения он из снимка, иначе пуст.
    # Пустой — это не ноль: первый шаг берёт значение как есть, без
    # фильтра, и подменять это нулём значит начинать сеанс с нуля герц.
    #
    # С этапа 2 накопитель живёт ВНУТРИ декодера (`motor.Decoder._sm`),
    # по значению на зонд. Снимок состояния знает только про пару прежнего
    # съёма, поэтому здесь ровно одна связка в две стороны: из снимка
    # значение кладётся декодеру, а `el`/`er` после каждого шага читаются
    # обратно из него — их захватывает `_grab` в снимок. Без чтения
    # обратно снимок посреди сеанса записал бы накопитель разогрева, а не
    # нынешний, и продолжение с него разошлось бы с первого же шага.
    el, er = resume_smooth
    if el is not None and er is not None:
        decoder._sm["__readout__"] = (el, er)

    bar = None
    if progress:
        try:
            from tqdm import tqdm

            bar = tqdm(total=n_steps, unit="шаг", ncols=78, desc="тело")
        except ImportError:
            bar = None

    if tape is not None:
        def _grab(t_now_ms):
            from . import replay as RP

            return RP.capture_body(
                body, engine, cfg, calib_exact, (el, er), sources,
                slots=(live._read_sources() if live is not None else []),
                counts=counts, t_ms=t_now_ms,
                meta={"семя": int(cfg.seed),
                      "шаг управления, мс": cfg.control_ms,
                      "устройство": device,
                      "популяция съёма": cfg.readout})

        tape.begin(engine, grab=_grab)

    t1 = time.perf_counter()
    for step in range(n_steps):
        x, y, theta = _pose(obs)
        d = np.linalg.norm(sources[:, :2] - np.array([x, y]), axis=1)
        # Выключенный слот источника остаётся в модели, но едой не
        # является: выбрать его ближайшим значило бы кормить муху тем,
        # чего нет. Маску даёт состояние живых условий; без него, как и
        # раньше, считаются все источники.
        act = live.active_sources() if live is not None else None
        if act is not None and len(act) == len(d):
            if not any(act):
                nearest, d_near = -1, None
            else:
                dd = np.where(np.asarray(act, bool), d, np.inf)
                nearest = int(np.argmin(dd))
                d_near = float(dd[nearest])
        else:
            nearest = int(np.argmin(d))
            d_near = float(d[nearest])
        li, ri = read_odour(obs)
        taste = (cfg.grn_hz if (d_near is not None
                                and d_near < cfg.food_radius_mm) else 0.0)
        # Обе величины перечитываются из настройки на каждом шаге, а не
        # берутся один раз до цикла: иначе живая правка `odour_ref` или
        # `dn_tau_s` подтверждалась бы как применённая и попадала в
        # журнал прогона, ничего при этом не меняя. При неизменной
        # настройке значения те же, что и прежде.
        ref_now = (max(float(cfg.odour_ref), 1e-9)
                   if cfg.odour_ref is not None else odour_ref)
        k = math.exp(-dt_s / max(cfg.dn_tau_s, 1e-6))
        # Заданная траектория объектов — на границе шага управления,
        # там же, где живые правки: внутри шага состояние модели не
        # целостно. Трек правит модель только когда заказанное
        # изменилось, поэтому неподвижный объект не стоит ничего.
        if vis_track is not None:
            vis_track.apply(vis_pool, step * cfg.control_ms)
        # Отметка времени ТОГО кадра, который этот шаг подаёт в сеть, —
        # снимается ДО подачи. Снятая после физики относилась бы к
        # самому свежему кадру, а подан был прошлый: разница ровно в
        # шаг управления, и по ней читающий решил бы, что зрение
        # опережает мозг. Поймано на первом же прогоне.
        vis_t_ms = None
        if vis is not None:
            _last = float(getattr(body.fly, "_last_vision_update_time", 0.0)
                          or 0.0)
            # `-inf` до первого кадра: это признак «кадра ещё не было»,
            # а не отметка времени, и писать его в запись нельзя.
            vis_t_ms = (round(_last * 1000.0, 4)
                        if math.isfinite(_last) else None)
        rl, rr = drive_brain(li, ri, taste, ref_now,
                             frame=(obs.get("vision") if vis is not None
                                    else None))

        acc, dl, dr, rd, spikes_total = step_measure()
        # Счётчики копятся за весь сеанс, запись — только за окно:
        # иначе частоты (`counts / t_run_s`) считались бы по обрезанной
        # записи и врали бы во столько раз, во сколько окно короче.
        bins[step % keep_steps] = acc.to(torch.int16)
        counts += acc.to(torch.int64)

        # Инженерная часть: измеренные частоты -> команда телу. Вся
        # арифметика живёт в `flybrain.motor`; здесь только вызов, и
        # `dn_tau_s` подхватывается с настройки на каждом шаге, как и
        # раньше, чтобы живая правка применялась, а не подтверждалась.
        decoder.shape.dn_tau_s = cfg.dn_tau_s
        escape = bridge.escape(rd)
        cmd = decoder.command(rd, dt_s, escape=escape)
        # Прежние поля записи. Берутся из самого декодера, а не
        # пересчитываются рядом: пересчёт «эквивалентным» выражением уже
        # один раз развёл траектории на последнем бите мантиссы.
        asym = cmd.detail.get("asym")
        if asym is None:
            asym = (decoder._asym(*decoder._sm["__readout__"])
                    - decoder.bias.get("__readout__", 0.0))
        z = cmd.detail.get("z_raw", cmd.u_turn * 3.0)
        action = cmd.as_array()
        # Накопитель сглаживания — обратно в `el`/`er`, чтобы снимок
        # состояния (`_grab`) взял нынешний, а не оставшийся с разогрева.
        el, er = decoder._sm.get("__readout__", (el, er))

        for _ in range(body_steps):
            obs, _, term, trunc, _ = body.step(action)
            if cfg.video:
                body.render()
            if term or trunc:
                break
        # --- сколько раз кадр обновился за этот шаг управления ---
        #
        # Берётся у самого FlyGym, а не считается делением частот: он
        # дописывает `_vision_update_mask` на каждом шаге физики, по
        # `True` на каждое обновление. Поэтому «кадр обновился дважды за
        # шаг управления» — замер, а не арифметика.
        #
        # Маска после подсчёта ОЧИЩАЕТСЯ, и это не мелочь: она растёт по
        # одному питоновскому `bool` на шаг физики, то есть при шаге
        # 2e-4 с по 5000 записей на секунду модельного времени. У сеанса
        # без заданного конца это утечка — список из 5000 ссылок стоит
        # около 40 КБ на секунду модельного времени и не освобождается
        # никогда. Свойство `fly.vision_update_mask` читают только
        # примеры апстрима, которых здесь нет, и вот эта запись.
        vis_n = 0
        if vis is not None:
            _mask = getattr(body.fly, "_vision_update_mask", None)
            if _mask:
                vis_n = int(sum(1 for b in _mask if b))
                del _mask[:]
            vis_seen["обновлений"] += vis_n
            _l = float(getattr(body.fly, "_last_vision_update_time", 0.0)
                       or 0.0)
            vis_seen["последнее обновление, мс"] = (
                round(_l * 1000.0, 4) if math.isfinite(_l) else None)
        closed = False
        if viewer is not None and step % cfg.view_every == 0:
            if not viewer.is_running():
                print("  окно закрыто, останавливаюсь")
                # Выйти здесь нельзя: строка `bins` этого шага уже
                # записана, а запись шага ещё нет — вышло бы на одну
                # строку записи меньше, чем шагов, и `metrics["steps"]`
                # разошёлся бы с `timing["steps_done"]`. Поэтому шаг
                # доводится до конца, а выход — после записи.
                closed = True
            else:
                viewer.sync()

        nx, ny, _ = _pose(obs)
        # Точка отсчёта метрики. По умолчанию — как было всегда: курс
        # корневого тела, снятый в начале шага управления, и положение
        # груди после него.
        gx, gy, gtheta = nx, ny, theta
        if cfg.grad_ref == "antennae":
            gx, gy, gtheta = pose_antennae()
        if nearest < 0:
            # Ни одного включённого источника: курс сравнивать не с чем,
            # и расстояние до «ближайшего» было бы выдумкой. Минус
            # единица в записи значит именно это, а не ноль миллиметров.
            grad_cos, dist_mm = 0.0, -1.0
        else:
            to_src = sources[nearest, :2] - np.array([gx, gy])
            norm = float(np.linalg.norm(to_src))
            grad_cos = float((to_src @ np.array([math.cos(gtheta),
                                                 math.sin(gtheta)])) / norm) \
                if norm > 1e-6 else 0.0
            dist_mm = float(np.linalg.norm(sources[nearest, :2] - [gx, gy]))

        rec = {
            "t_ms": step * cfg.control_ms,
            "x": round(nx, 3), "y": round(ny, 3), "theta": round(theta, 4),
            "odour_l": round(li, 7), "odour_r": round(ri, 7),
            "orn_l": round(rl, 1), "orn_r": round(rr, 1),
            "taste": round(taste, 1),
            "dn_l": round(dl, 3), "dn_r": round(dr, 3),
            "asym": round(asym, 5), "z": round(z, 3),
            "amp_l": round(float(action[0]), 3), "amp_r": round(float(action[1]), 3),
            "dist": round(dist_mm, 2),
            "grad_cos": round(grad_cos, 4),
            "source": int(nearest),
            # Берётся из той же посылки, что и зонды (`read_total`), а не
            # отдельным ожиданием потока CUDA. Число то же: это тот же
            # `acc.sum()`, только снятый один раз вместе со всем прочим.
            "spikes": spikes_total,
        }
        # Разведённые имена. `readout_*` — ИЗМЕРЕНИЕ: частота зонда в
        # герцах, без единого преобразования. `cmd_*` — ИНЖЕНЕРНАЯ
        # команда: поворот, тяга и вклад моста через обрыв GF. Старые
        # ключи (`dn_l`, `asym`, `z`, `amp_l`, `amp_r`) остаются на
        # месте — на них держатся ряды, графики, отчёт и песочница.
        if cfg.probes:
            for name in readout.names:
                if name == "__readout__":
                    continue
                l, r = rd[name]
                rec["readout_%s_l" % name] = round(l, 3)
                rec["readout_%s_r" % name] = round(r, 3)
        rec["cmd_turn"] = round(cmd.u_turn, 5)
        rec["cmd_drive"] = round(cmd.u_drive, 5)
        rec["cmd_escape"] = round(cmd.escape, 5)
        # Зрение в записи шага. Поля появляются ТОЛЬКО при включённом
        # зрении: у прежнего эпизода их не было, и дописывать нули
        # значило бы менять форму `track.parquet` всем сохранённым
        # прогонам.
        #
        # `vis_t_ms` — модельное время того кадра, который этот шаг
        # ПОДАЛ в сеть, снятое до подачи; `vis_lag_ms` — на сколько он
        # отстал от шага. `vis_n` — сколько раз кадр обновился за шаг.
        if vis is not None:
            rec["vis_t_ms"] = vis_t_ms
            rec["vis_lag_ms"] = (None if vis_t_ms is None
                                 else round(rec["t_ms"] - vis_t_ms, 4))
            rec["vis_n"] = int(vis_n)
            # Кадр глаза рисуется и при выключенной подаче, поэтому
            # отметки времени выше пишутся всегда, а частоты — только
            # когда подача была. Ноль здесь означал бы «подали нулевую
            # частоту», а не «не подавали»; отсутствие ключа таймлайн
            # честно читает как «значения в записи шага не было».
            fed = vis_seen.get("подача")
            if fed is not None:
                rec["vis_hz"] = round(float(fed["средняя, Гц"]), 3)
                rec["vis_sat"] = round(float(fed["в потолке, доля"]), 4)
            # То же правило у переходника: ключей нет, когда подачи не
            # было, а не ноль. `vbr_loom` — нависание, то есть наружное
            # движение тёмного края, сумма по обоим глазам.
            bridged = vis_seen.get("переходник")
            if bridged is not None:
                rec["vbr_hz"] = round(float(bridged["средняя, Гц"]), 4)
                rec["vbr_max_hz"] = round(float(bridged["наибольшая, Гц"]), 2)
                rec["vbr_sat"] = round(float(bridged["в потолке, доля"]), 5)
                rec["vbr_loom"] = round(
                    float(sum(bridged["нависание"].values())), 6)
        records.append(rec)
        row_cpu = None
        if on_step is not None or tape is not None:
            # Одна копия строки записи на шаг: она нужна и окну, и ленте.
            row_cpu = bins[step % keep_steps].cpu().numpy()
        if tape is not None:
            tape.step(rec["t_ms"], rec, counts=row_cpu)
        if on_step is not None:
            on_step(step, rec, row_cpu)
        if closed:
            n_steps = step + 1
            break
        if should_stop is not None and should_stop():
            n_steps = step + 1
            break
        if bar is not None:
            bar.update(1)

    if device == "cuda":
        torch.cuda.synchronize()
    t_sim = time.perf_counter() - t1
    if bar is not None:
        bar.close()
    if cfg.video and cams:
        cams[0].save_video(video_path)
        print(f"  видео: {video_path}")
    if viewer is not None:
        viewer.close()
    # Со зрения снимается всё, что живёт в модели, ДО её закрытия:
    # после `close()` ни частоту обновления, ни свет спросить уже не у
    # кого, а живая правка могла их поменять посреди сеанса. Записывать
    # в прогон надо последнее действительное, а не заказанное в начале.
    if vis is not None:
        from . import vision as V

        vis_seen["частота у FlyGym"] = int(
            getattr(body.fly, "vision_refresh_rate", 0) or 0)
        vis_light = V.light_state(body)
        if vis_pool is not None:
            vis_seen["объекты"] = vis_pool.state()
    body.close()

    # Фактическую длительность считаем по пройденным шагам и только если
    # эпизод оборвали: n_steps * dt_s не обязано совпадать с заказанной
    # длительностью при неделимом control_ms, и подменять её зря нельзя.
    cut = n_steps < requested_steps
    dur_s = n_steps * dt_s if (cut or endless) else cfg.duration_s

    # Кольцо — по времени. До этого места строка шага `i` лежит в слоте
    # `i % keep_steps`: при провернувшемся кольце самая старая строка
    # стоит не первой, и расставить их можно только зная окончательное
    # число шагов.
    kept = min(n_steps, keep_steps)
    if n_steps > keep_steps:
        bins = torch.roll(bins, -(n_steps % keep_steps), dims=0)
    else:
        bins = bins[:kept]
    bins_t0_ms = (n_steps - kept) * cfg.control_ms
    _legacy = str(getattr(cfg, "gait", "fast")) == "legacy"
    timing = {
        "setup_s": round(t_setup, 2),
        "sim_s": round(t_sim, 2),
        "device": device,
        "realtime_ratio": round(dur_s / t_sim, 4) if t_sim else None,
        # Шаги пишутся всегда, а не только у оборванного эпизода: по ним
        # видно, дошёл ли прогон до конца, даже когда `duration_s`
        # совпадает с заказанной. Заказанная остаётся в `config` и не
        # подменяется.
        "steps_done": int(n_steps),
        "steps_requested": int(requested_steps),
        "duration_s": round(dur_s, 6),
        # Какими дорогами считалась обвязка MuJoCo. Оговорки здесь не
        # нужны: все три правки численно равнозначны прежней дороге
        # (`probe/mj_equal.py` — побитово, `probe/body_equal.py` — на
        # эпизоде). Но по сохранённому прогону должно быть видно, как он
        # считался, — как это уже сделано для `speed` и `graphs` в
        # `sim.run`.
        "обвязка": {
            "пересчёт со ступени ускорений":
                bool(getattr(cfg, "acc_forward", True)),
            "дешёвое наблюдение": bool(getattr(cfg, "fast_obs", True)),
            # Два следующих записываются ДЕЙСТВИТЕЛЬНЫМИ, а не по
            # просьбе: при `gait="fast"` сокращать наблюдение
            # правил нечему, а фазовый множитель считает сам
            # `flybrain.gait`. Если писать сюда `cfg`, сохранённый
            # прогон утверждал бы, что считался дорогой, которая
            # не работала.
            "наблюдение правил":
                bool(getattr(cfg, "rule_obs", True)) and _legacy,
            "фазовый множитель без scipy":
                bool(getattr(cfg, "fast_gain", True)) and _legacy,
            "контроллер походки": str(getattr(cfg, "gait", "fast")),
        },
        # Чем считалось умножение связей в движке. Берётся у ДВИЖКА, а не
        # у настройки: просьба может прийти из окружения, а тихого отката
        # нет, поэтому записанное — это то, что действительно считало.
        **(engine.spmv_info() if hasattr(engine, "spmv_info") else {}),
    }
    accfwd = getattr(getattr(body, "physics", None), "_fb_accfwd", None)
    if accfwd is not None:
        timing["обвязка"]["пересчётов прямой динамики"] = {
            "дешёвых": int(accfwd["дешёвых"]),
            "полных": int(accfwd["полных"]),
        }
    # --- происхождение зрения: что именно считало этот прогон ---
    #
    # Блок пишется ТОЛЬКО при включённом зрении: отсутствие ключа и
    # значит «зрение было выключено», как у всех 28 прежних прогонов.
    # Внутри — не просьба, а действительное: частота обновления
    # измерена по отметкам FlyGym, отпечаток привязки взят у самой
    # привязки, свет прочитан из модели. По этому блоку прогон
    # опознаётся однозначно, и его хватает, чтобы собрать такой же.
    if vis is not None:
        meas_hz = (vis_seen["обновлений"] / dur_s) if dur_s else None
        timing["зрение"] = {
            "включено": True,
            "частота обновления заказана, Гц": float(
                getattr(cfg, "vision_hz", 100.0)),
            "частота обновления у FlyGym, Гц": int(
                vis_seen.get("частота у FlyGym", 0)),
            "частота обновления измерена, Гц": (round(meas_hz, 3)
                                                if meas_hz is not None
                                                else None),
            "обновлений кадра за сеанс": int(vis_seen["обновлений"]),
            "шагов с подачей": int(vis_seen["шагов с подачей"]),
            "последнее обновление, мс": vis_seen["последнее обновление, мс"],
            "рабочая точка, а не постоянная":
                "100 Гц выбраны по замеру цены шага (RESEARCH.md §6), а "
                "не выведены из биологии; поле `vision_hz` меняет её, и "
                "более высокие частоты замерены отдельно",
            "на разогреве": "не подавалось: перекос и шум съёма мерятся "
                            "на симметричном обонятельном входе, как во "
                            "всех прежних эпизодах",
            "контраст": float(getattr(cfg, "vision_contrast", 1.0)),
            "контраст — чей": "объявленное преобразование КАДРА "
                              "(clip(0,5 + (I − 0,5)·k)), а не свойство "
                              "сцены",
            "свет сцены": vis_light,
            "свет — чей": "множитель к light_ambient и light_diffuse "
                          "настоящих источников MuJoCo арены FlyGym: "
                          "меняется сам рендер кадра глаза",
            "привязка": vis.provenance(),
        }
        if vbr is not None:
            # Происхождение переходника — отдельным полем, а не
            # примечанием: по сохранённому прогону должно быть видно,
            # какие отклики посчитаны синапсами FlyWire, а какие поданы
            # снаружи. Сводку даёт сам мост, а не настройка.
            timing["зрение"]["переходник"] = vbr.сводка()
            timing["зрение"]["шагов с переходником"] = int(
                vis_seen["шагов с переходником"])
            timing.setdefault("оговорки", []).append(
                "в прогоне работал ГИБРИДНЫЙ ЗРИТЕЛЬНЫЙ ПЕРЕХОДНИК "
                "(граница %s): направленные сигналы T4/T5 посчитаны ВНЕ "
                "сети, соответствие подтип-направление задано "
                "соглашением, омматидий у T4/T5 наведён по возбуждающим "
                "синапсам. Это инженерный интерфейс, а НЕ передача по "
                "глубокому зрительному пути оригинальной сети FlyWire. "
                "Настоящим связям принадлежит то, что за границей: "
                "T4/T5 -> LPLC2, LC4 -> DNp01 и глубже."
                % vbr.граница)
        if vis_seen.get("объекты") is not None:
            timing["зрение"]["объекты"] = vis_seen["объекты"]
        if vis_track is not None:
            timing["зрение"]["траектория"] = vis_track.state()
        c = vis.caveat()
        if c:
            timing.setdefault("оговорки", []).append(c)
    if endless:
        timing["steps_requested"] = None   # предела не было
        timing.setdefault("оговорки", []).append(
            "сеанс без заранее заданного конца: его закончила остановка, "
            "а не исчерпание заказанного времени. «Отменён» в карточке "
            "для такого сеанса — норма, а не обрыв расчёта.")
    if kept < n_steps:
        # Запись короче сеанса. Молчать нельзя: по `bins` считают растр
        # и ход активности, и без подписи они выглядели бы как целый
        # прогон, начинающийся с нуля.
        timing["окно записи, с"] = round(kept * dt_s, 6)
        timing["запись с, мс"] = round(bins_t0_ms, 3)
        timing.setdefault("оговорки", []).append(
            "запись активности — последнее окно %.3g с из %.3g с сеанса "
            "(с %.0f мс). Счётчики и частоты посчитаны по всему сеансу, "
            "растр и ход активности — только по окну."
            % (kept * dt_s, dur_s, bins_t0_ms))
    if getattr(cfg, "fast_physics", False):
        # Прогон в быстрой физике сравнивать с эталонным нельзя, и
        # молчать об этом тоже: оговорка едет вместе с результатом в
        # `meta.json`, а оттуда в отчёт и в сверку.
        timing.setdefault("оговорки", []).append(
            "включена быстрая физика (`fast_physics`): пропущен повторный "
            "расчёт прямой динамики после записи управляющих сигналов. "
            "Замер `probe/body_equal.py`: ускорение 1,73 раза, но "
            "траектория другая — расхождение начинается на втором шаге "
            "управления и накапливается. С эталонными прогонами такой "
            "эпизод не сравнивается.")
    if resume_report is not None:
        # Продолжение — часть результата, а не способ его получить: по
        # сохранённому файлу должно быть видно, что сеанс начат не с
        # нуля, с какого модельного времени и что в состоянии было.
        timing["продолжение"] = resume_report
        from . import replay as RP

        timing.setdefault("оговорки", []).append(
            "сеанс продолжен из сохранённого состояния на %.0f мс "
            "модельного времени: разогрев калибровки не повторялся, "
            "перекос и шум взяты из снимка. Траектория до этого момента "
            "лежит в прежнем прогоне, а не здесь. Побитовое совпадение с "
            "непрерывным сеансом измерено на %d шагах управления "
            "(%.0f мс) и на всей этой длине полное: записи шагов, "
            "состояние движка, счётчики и ось модельного времени. Где "
            "оно кончается, не установлено — дальше сверка не гонялась "
            "(probe/resume_state.py --part body)."
            % (float(resume_report.get("модельное, мс") or 0.0),
               RP.EXACT_STEPS["body"],
               RP.EXACT_STEPS["body"] * cfg.control_ms))
    if tape is not None:
        tape.finish(n_steps)
        timing["таймлайн"] = {
            k: v for k, v in tape.tl.schema().items()
            if k in ("окно записи, с", "шагов записано", "шагов в сеансе",
                     "запись с, мс", "запись до, мс", "предел памяти")}
    # Блок `engineered`: всё нефизиологичное моторного пути с именем,
    # версией, параметрами и, где есть файл весов, его sha256. Он едет в
    # `embodied.json`, а оттуда в отчёт и в сверку — то есть отличить
    # инженерную часть от измеренной можно машинно, а не на глаз.
    # Справка о популяции съёма — замером, а не названием. Нужна затем,
    # что прежний съём `ALPN` сенсорный, и прогон обязан говорить это о
    # себе сам: читают его, а не исходники.
    src = motor.command_source(neurons, cfg.motor, cfg.readout, ql, qr)
    engineered = motor.engineered_block(
        decoder=decoder, bridge=bridge, head_stab=head_stab,
        readout_rows=readout.rows if cfg.probes else None,
        readout_src=src,
        extra=({"прямое вмешательство": interv.spec()}
               if interv is not None else None))
    # В оговорки идёт только то, что ведёт команду: иначе прогон на
    # нисходящем декодере нёс бы оговорку про сенсорный ALPN, который в
    # нём команду не ведёт вовсе.
    for row in src:
        if row.get("ведёт команду") and row.get("оговорка"):
            timing.setdefault("оговорки", []).append(row["оговорка"])
    for obj in (bridge, head_stab, interv):
        c = obj.caveat() if obj is not None else None
        if c:
            timing.setdefault("оговорки", []).append(c)
    # Зонды не сошлись по размеру, а прогон всё равно посчитался (это
    # возможно только при `legacy`, где от них не зависят числа). Молчать
    # об этом нельзя: `readout_*` такого прогона относятся не к тем
    # популяциям, про которые сказано в отчёте.
    bad_probes = [r["зонд"] for r in readout.rows if not r.get("совпало")]
    if bad_probes:
        timing.setdefault("оговорки", []).append(
            "прямые зонды не сошлись с таблицей нейронов: %s. Команду "
            "считал прежний съём `%s`, и на неё это не влияет, но поля "
            "`readout_*` этих зондов относятся НЕ к тем популяциям, "
            "которые названы: размер в таблице изменился. Числа таких "
            "зондов из этого прогона брать нельзя."
            % (", ".join(bad_probes), cfg.readout))
    if cfg.motor != "legacy":
        timing.setdefault("оговорки", []).append(
            "моторная команда посчитана ИНЖЕНЕРНЫМ декодером "
            "`%s` v%d по прямым зондам нисходящих, а не прежним средним "
            "по полушарию. Коэффициенты (или веса) этого декодера — не "
            "условия прогона, а его модель: см. блок `engineered`. С "
            "эталонными прогонами, посчитанными `legacy`, такой эпизод "
            "не сравнивается."
            % (decoder.name, decoder.version))
    # Продолжение из снимка не несёт калибровки ЗОНДОВ: в снимке лежат
    # только перекос и шум прежнего съёма (`__readout__`), потому что
    # формат снимка старше прямых зондов. При `legacy` это ничего не
    # меняет — он читает только `__readout__`. При новых декодерах
    # перекос каждого зонда оказывается нулевым вместо снятого на
    # разогреве, и это надо сказать, а не обнаружить потом по числам.
    if resume is not None and cfg.motor != "legacy":
        timing.setdefault("оговорки", []).append(
            "сеанс продолжен из снимка, а декодер `%s` работает по "
            "прямым зондам, калибровки которых в снимке НЕТ: формат "
            "снимка старше зондов, и в нём лежат только перекос и шум "
            "прежнего съёма. Перекос каждого зонда поэтому равен нулю "
            "вместо снятого на разогреве, то есть у `z` сдвинут нуль. С "
            "непрерывным сеансом такой эпизод не сравнивается."
            % decoder.name)
    metrics = _metrics(records, dt_s)
    metrics.update(_motor_metrics(records))
    run = EmbodiedRun(records, counts.cpu().numpy(), bins.cpu().numpy(),
                      neurons, cfg, sources, timing, metrics, calib,
                      sensor_idx)
    run.engineered = engineered
    # Таймлайн и снимок состояния едут вместе с прогоном: их пишет
    # `save`, один и тот же путь для окна и для командной строки.
    run.timeline = None if tape is None else tape.tl
    run.state = None if tape is None else tape.state
    return run


def _metrics(records, dt_s):
    if not records:
        return {}
    # При одном шаге (отмена на разогреве) вторая половина выходила
    # пустой, и `np.mean` отдавал nan с предупреждением. Тогда обе
    # половины — это сам единственный шаг.
    # Шаги, на которых не было ни одного включённого источника, пишут
    # `dist = -1` и `grad_cos = 0` — это «не с чем сравнивать», а не
    # «ноль миллиметров». Считать их наравне значило бы подмешать в
    # среднее расстояние минус единицу, а в выравнивание — нули, и обе
    # величины поехали бы тем сильнее, чем дольше источники были выключены.
    aimed = [r for r in records if r.get("dist", 0.0) >= 0.0]
    skipped = len(records) - len(aimed)
    if not aimed:
        return {"steps": len(records), "шагов без источника": skipped,
                "примечание": "ни на одном шаге не было включённого "
                              "источника: расстояние и выравнивание по "
                              "градиенту не определены"}
    half = len(aimed) // 2
    d = [r["dist"] for r in aimed]
    d_first = d[:half] if half else d
    d_second = d[half:] if half < len(d) else d
    path = sum(math.dist((records[i]["x"], records[i]["y"]),
                         (records[i - 1]["x"], records[i - 1]["y"]))
               for i in range(1, len(records)))
    out = {} if not skipped else {"шагов без источника": skipped}
    out.update({
        "steps": len(records),
        "grad_alignment": round(float(np.mean([r["grad_cos"]
                                               for r in aimed])), 4),
        "dist_first_half_mm": round(float(np.mean(d_first)), 2),
        "dist_second_half_mm": round(float(np.mean(d_second)), 2),
        "dist_start_mm": round(d[0], 2),
        "dist_end_mm": round(d[-1], 2),
        "path_mm": round(path, 2),
        "speed_mm_s": round(path / max(len(records) * dt_s, 1e-9), 2),
        "food_steps": int(sum(1 for r in records if r["taste"] > 0)),
        "mean_dn_hz": round(float(np.mean([(r["dn_l"] + r["dn_r"]) / 2
                                           for r in records])), 3),
    })
    return out


def _motor_metrics(records):
    """Насколько команда вообще ШЕВЕЛИЛАСЬ и следовала ли за раздражителем.

    Две величины, и обе нужны вместе. Разброс команды отвечает на «а
    зависит ли выход хоть от чего-нибудь»: при заглушённом съёме он
    обязан уйти в ноль. Корреляция с асимметрией раздражителя отвечает
    на «от ЧЕГО именно»: при заглушённом съёме она обязана перестать
    существовать. По одной из них ничего не доказывается: постоянная
    команда даёт нулевую корреляцию честно, а шумящая ни с чем не
    связанная команда даёт большой разброс так же честно.
    """
    if len(records) < 3:
        return {}
    turn = np.array([r.get("cmd_turn", 0.0) for r in records], float)
    amp = np.array([r["amp_l"] - r["amp_r"] for r in records], float)
    stim = np.array([(r["orn_l"] - r["orn_r"])
                     / (r["orn_l"] + r["orn_r"] + 1e-9) for r in records],
                    float)
    out = {
        "cmd_turn_sd": round(float(np.std(turn)), 6),
        "cmd_amp_diff_sd": round(float(np.std(amp)), 6),
        "stim_asym_sd": round(float(np.std(stim)), 6),
    }
    for name, a in (("r_cmd_stim", turn), ("r_amp_stim", amp)):
        if np.std(a) < 1e-12 or np.std(stim) < 1e-12:
            # Постоянный ряд: корреляции НЕ существует, и ноль здесь был
            # бы выдумкой. None читается как «не определена».
            out[name] = None
        else:
            out[name] = round(float(np.corrcoef(a, stim)[0, 1]), 4)
    return out


def bench(n_runs=6, duration_s=3.0, neurons=None, weights=None, device=None,
          base: BodyConfig | None = None, seed0=100, progress=True,
          on_episode=None, should_stop=None, out_dir=None):
    """Норма против переставленных антенн, один эпизод — одно наблюдение.

    Та же схема, что и для плоской арены: внутри эпизода курс и градиент
    меняются медленно, поэтому посчитать значимость по шагам нельзя.

    ``on_episode(cond, i, n, metrics)`` зовётся после каждого эпизода, где
    ``cond`` — название условия, ``i`` — номер эпизода с единицы.
    ``should_stop()`` проверяется между эпизодами и уходит внутрь эпизода:
    эпизод в теле идёт секунды, и ждать его конца значит не отвечать на
    «стоп». У оборванной серии в ``n_runs`` стоит фактическое число эпизодов,
    а не заказанное — по нему же считаются sd и sem.
    """
    import torch

    if neurons is None:
        neurons = D.load_neurons()
    device = device or ("cuda" if torch.cuda.is_available() else "cpu")
    if weights is None:
        weights = D.load_weights(device=device)
    base = base or BodyConfig()

    out = {}
    stopped = False
    # Видео эпизодов: каждому своё имя внутри папки прогона. Без папки
    # `run_episode` писал `walk.mp4` в текущий каталог, и каждый
    # следующий эпизод затирал предыдущий.
    out_dir = Path(out_dir) if out_dir else None
    if base.video and out_dir is None:
        raise ValueError("видео в серии просят, а папку прогона не задали: "
                         "эпизоды затёрли бы друг друга")
    for ci, (label, swap) in enumerate((("норма", False),
                                        ("перестановка антенн", True))):
        vals, dists, visits, eps = [], [], [], []
        for i in range(n_runs):
            cfg = BodyConfig(**{**asdict(base), "swap_antennae": swap,
                                "duration_s": duration_s, "seed": seed0 + i,
                                "device": device})
            video = None
            if cfg.video:
                out_dir.mkdir(parents=True, exist_ok=True)
                video = out_dir / ("walk-%s-%02d.mp4"
                                   % ("norm" if ci == 0 else "swap", i + 1))
            r = run_episode(cfg=cfg, neurons=neurons, weights=weights,
                            progress=False, should_stop=should_stop,
                            video_path=video)
            m = r.metrics
            if "grad_alignment" not in m:
                # Эпизод, прошедший целиком без включённых источников:
                # ни выравнивания по градиенту, ни расстояния у него нет
                # (см. `_metrics`). Включить его в серию наравне с
                # остальными значило бы подмешать выдуманные нули;
                # молча пропустить — тоже нельзя, поэтому отказ громкий.
                raise ValueError(
                    "эпизод %d условия %r прошёл без единого включённого "
                    "источника: выравнивания по градиенту и расстояния у "
                    "него нет, и в серию он не идёт. Серии нужны условия, "
                    "в которых источник включён." % (i + 1, label))
            vals.append(m["grad_alignment"])
            dists.append(m["dist_end_mm"] - m["dist_start_mm"])
            visits.append(m["food_steps"])
            eps.append({"i": i + 1, "seed": int(cfg.seed),
                        "grad_alignment": round(m["grad_alignment"], 4),
                        "dist_change_mm": round(m["dist_end_mm"]
                                                - m["dist_start_mm"], 2),
                        "food_steps": int(m["food_steps"]),
                        "video": str(video.name) if video else None})
            if progress:
                print(f"  {label:20s} [{i + 1}/{n_runs}] "
                      f"градиент {m['grad_alignment']:+.3f}, "
                      f"до еды {m['dist_start_mm']:.1f} -> {m['dist_end_mm']:.1f} мм")
            if on_episode is not None:
                on_episode(label, i + 1, n_runs, m)
            if should_stop is not None and should_stop():
                stopped = True
                break
        n_done = len(vals)
        out[label] = {
            "n_runs": n_done,
            "duration_s": duration_s,
            "readout": base.readout,
            "dn_tau_s": base.dn_tau_s,
            "grad_alignment_mean": round(float(np.mean(vals)), 4),
            "grad_alignment_sd": round(float(np.std(vals, ddof=1)), 4) if n_done > 1 else None,
            "grad_alignment_sem": round(
                float(np.std(vals, ddof=1) / math.sqrt(n_done)), 4) if n_done > 1 else None,
            "runs": [round(v, 4) for v in vals],
            "seeds": [int(e["seed"]) for e in eps],
            "seed0": int(seed0),
            "episodes": eps,
            "dist_change_mm": round(float(np.mean(dists)), 2),
            "food_steps_total": int(sum(visits)),
        }
        if stopped:
            # Второе условие не считаем: сравнивать его с оборванным первым
            # нечестно, а делать вид, что серия целая, — тем более.
            break
    return out


def load(out_dir, neurons=None) -> EmbodiedRun:
    """Собрать сохранённый эпизод в теле обратно из файлов.

    Физика при этом не считается и MuJoCo не поднимается: траектория
    лежит в `track.parquet`, растр и счётчики — в `bins.npz` и
    `rates.parquet`, настройки и метрики — в `embodied.json`. Это
    зеркало `save`, которого до сих пор не было: `cli.cmd_report` на
    папке с телом молча уходил в `sim.load` и терял и траекторию, и
    метрики, и калибровку разогрева.

    Чего в файлах нет, то и не восстанавливается, и об этом говорится
    прямо: отсутствие `track.parquet` — не повод вернуть пустой эпизод
    молча.
    """
    import pandas as pd

    out_dir = Path(out_dir)
    meta_path = out_dir / "embodied.json"
    if not meta_path.exists():
        raise FileNotFoundError(
            f"{out_dir}: нет embodied.json — это не прогон в теле")
    meta = json.loads(meta_path.read_text(encoding="utf-8"))

    res = sim.load(out_dir, neurons=neurons)

    track = out_dir / "track.parquet"
    if not track.exists():
        raise FileNotFoundError(
            f"{out_dir}: есть embodied.json, но нет track.parquet — "
            "записи по шагам в этом прогоне не сохранено, восстановить "
            "траекторию, амплитуды ног и сигналы неоткуда")
    records = pd.read_parquet(track).to_dict("records")

    known = {f.name for f in fields(BodyConfig)}
    raw_cfg = meta.get("config") or {}
    cfg = BodyConfig(**{k: v for k, v in raw_cfg.items() if k in known})
    unknown = sorted(set(raw_cfg) - known)

    sources = np.asarray(meta.get("sources") or DEFAULT_SOURCES, float)

    # Сенсорные каналы: сперва из `meta.json` (их туда положил `sim.save`
    # вместе с индексами), иначе пересобираются из `world.SENSORS` — это
    # чистый отбор по таблице нейронов, без всякого счёта.
    sensor_idx = {st.name: np.asarray(st.indices, np.int64)
                  for st in res.stimuli
                  if st.name in ("odour_left", "odour_right", "taste")
                  and len(st.indices)}
    if len(sensor_idx) < 3:
        nn = res.neurons
        sensor_idx = {name: D.select(nn, world.SENSORS[name])
                      for name in ("odour_left", "odour_right", "taste")}

    timing = dict(meta.get("timing") or res.timing or {})
    if unknown:
        timing["unknown_config_keys"] = unknown
    run = EmbodiedRun(records, res.counts, res.bins, res.neurons, cfg,
                      sources, timing, meta.get("metrics") or {},
                      meta.get("calibration") or {}, sensor_idx)
    # Блок нефизиологичных деталей восстанавливается как есть. Его
    # отсутствие — не ошибка: прогоны до этого этапа его не писали, и у
    # них он равен None, а не пустому словарю. Разница существенная:
    # пустой словарь читался бы как «инженерных деталей не было».
    run.engineered = meta.get("engineered")
    return run


def save(run: EmbodiedRun, out_dir):
    import pandas as pd

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "embodied.json").write_text(
        json.dumps(run.meta(), ensure_ascii=False, indent=2), encoding="utf-8")
    tl = getattr(run, "timeline", None)
    if tl is not None:
        tl.save(out_dir)
    st = getattr(run, "state", None)
    if st is not None:
        st.save(out_dir)
    pd.DataFrame(run.records).to_parquet(out_dir / "track.parquet")
    sim.save(run.as_result(), out_dir)
    return out_dir
