"""Гибридный зрительный переходник, вставленный в ТЕЛО. ИНЖЕНЕРНОЕ.

Зачем этот модуль существует
----------------------------

Продуктовое зрение (`flybrain.vision`) подаёт только фоторецепторы, и
замерено, что дальше третьего синапса сигнал не доходит: при включённом
зрении и настоящем предмете в сцене T4, T5, LPLC2, LC4 и DNp01 дают
**ровно 0,000 Гц** (`FULL_LOOP_VALIDATION.md` §2.0, §2.3). Причина
разобрана и не снята: порог 7 мВ требует **160,9 синапса в одном шаге**,
а глубже третьего синапса столько сходящегося возбуждения нет.
Физиологический режим (`flybrain.visdyn`) воспроизводит механизм мухи,
но отвергнут собственным нулевым контролем (z = 1,19 на шестисеменной
полосе).

Поэтому сквозной опыт с нависанием ставится через **переходник**
(`flybrain.vishybrid`): ранняя зрительная обработка считается ВНЕ сети, а
дальше сигнал идёт по настоящим связям FlyWire. Этот модуль — только
стыковка переходника с телом: он не считает ни одной новой величины.

ЧТО ЭТО НЕ ЕСТЬ, и это не оговорка в конце, а условие опыта
------------------------------------------------------------

**Это не передача по глубокому зрительному пути оригинальной сети
FlyWire.** Граница стыковки — T4/T5, и за ней стоят три инженерные
величины, каждая названная:

1. **направленные сигналы T4a…d и T5a…d посчитаны вне сети** —
   коррелятором Хассенштайна-Райхардта по решётке омматидиев, а не
   синапсами ламины и медуллы;
2. **соответствие «подтип — направление» задано соглашением**
   `vishybrid`, а не данными: в коннектоме такого поля нет;
3. **омматидий у T4/T5 наведён**, а не дан: он есть только у
   фоторецепторов, глубже он средневзвешен по числу возбуждающих
   синапсов через ламину и медуллу. Локальность такого наведения
   замерена отдельно (`probe/vision_phys_rf.py`: разброс поля 0,023
   размаха у T4a против 0,101 у перетасованной привязки).

**Что за границей принадлежит настоящим связям:** T4/T5 → LPLC2,
LC4 → DNp01 и всё глубже. Отклики LPLC2 и DNp01 при границе T4/T5
посчитаны синапсами FlyWire, и только это о них и утверждается.

**Привязка омматидиев опровергнута внешним свидетелем**
(`FULL_LOOP_VALIDATION.md` §3.1: R7 и R8 одной колонки попадают в один
омматидий 0 раз из 430 против 2 из 430 у перетасованной). Значит
пространственная структура подачи — наша, а не мухи, и ни одно
утверждение о направлении движения в поле зрения на ней не стоит.
Нависание как рост углового размера тёмного предмета от этого не
зависит: оно считается по наружному движению тёмного края от центра
поля, то есть по знаку радиальной проекции, а он при любой перестановке
решётки остаётся наружным. Это и есть причина, по которой опыт ставится
на нависании, а не на направлении.

Стороны
-------

Левый оптический лоб служит левому глазу, правый — правому. Сторона
нейрона берётся из столбца `side` таблицы (ровно того, а не из имени
типа), и каждому полушарию подаётся яркость своего глаза. Нейрон без
стороны не подаётся вовсе, и число таких записано в сводке.

Встречные замеры — те же, что у переходника, и каждый умеет провалить
утверждение: ``тасовка`` (те же числа другим адресатам, суммарный вход
побитово тот же), ``подтипы`` (перемешанное соответствие подтип →
направление), пустая сцена (переходник обязан дать ноль).
"""

from __future__ import annotations

import time

import numpy as np

from . import retina as R, sim as S, vishybrid as H

# Популяции границы T4/T5 и те, что за ней. Имена — ключи, по которым
# нейроны выбираются ТОЧНЫМ однополевым селектором `celltype=`, а не
# `type:` и не `type=`: `type:T4` даёт 6400 нейронов, среди которых нет
# ни одного T4, а `type=` сравнивает с тремя столбцами и объединяет.
ПОДАЧА = H.ПОДТИПЫ_T4 + H.ПОДТИПЫ_T5
ПРОЕКЦИОННЫЕ = ("LC4", "LPLC2")

# Промежуточные популяции, по которым наводится омматидий. Это те же
# ступени и тот же замысел, что в `probe/vision_phys_rf.py`.
ЛАМИНА = ("L1", "L2", "L3", "L4")
МЕДУЛЛА = ("Mi1", "Tm9")


# Замеренное ограничение переходника на границе T4/T5. Уезжает в КАЖДЫЙ
# сохранённый прогон, потому что без него числа подачи читаются как
# отклик на предмет, а это не так.
#
# Замерено `probe/looming_loop.py` на эпизоде 1,4 с при усилении 2e6,
# тёмный нависающий шар 1 мм с 30 мм до 3 мм по курсу:
#
# * у ИДУЩЕЙ мухи переходник подаёт 33,2 Гц **без единого предмета в
#   сцене**. Муха идёт, арена едет по полю зрения, и коррелятор
#   Хассенштайна-Райхардта отвечает на ОПТИЧЕСКИЙ ПОТОК ОТ СОБСТВЕННОГО
#   ХОДА. Предмет добавляет к этому ×1,108 (36,8 против 33,2), а по
#   LPLC2 ×1,093 (10,11 против 9,25);
# * на ЗАМОРОЖЕННОМ теле, где единственное движение в поле — предмет,
#   фон подачи всё равно 5,36 Гц против 6,86 с предметом, а по LPLC2
#   0,65 против 0,99, то есть ×1,53;
# * `DNp04` на замороженном теле МОЛЧИТ и с предметом, и без (0 спайков
#   против 0), хотя у идущей мухи даёт 3 спайка. Значит отклик
#   нисходящего одним предметом не объясняется: он требует фона от
#   собственного хода, на который предмет лишь добавляет.
#
# Почему так, и это не предположение, а связь с уже замеренным. На
# границе T4/T5 подаются НАПРАВЛЕННЫЕ сигналы — то, что T4/T5 и кодируют
# у мухи. Избирательность к нависанию (наружное движение тёмного края от
# центра поля) переходник СЧИТАЕТ (`нависание` 38,8 при нависании против
# 27,9 при движении поперёк курса, ×1,39 — заметно лучше, чем ×1,11 у
# подачи), но на этой границе НЕ ПОДАЁТ: её должны были бы собрать
# настоящие связи T4/T5 -> LPLC2. Собрать её они могут только по
# ретинотопии, а наша привязка омматидиев ОПРОВЕРГНУТА внешним
# свидетелем (`FULL_LOOP_VALIDATION.md` §3.1: R7 и R8 одной колонки
# попадают в один омматидий 0 раз из 430 против 2 из 430 у
# перетасованной). Поэтому радиальная структура настоящими синапсами не
# восстанавливается, и сигнал угрозы остаётся в фоне собственного хода.
#
# Что это значит для утверждений: на границе T4/T5 замерена ПЕРЕДАЧА по
# настоящим связям до LPLC2 и LC4 с монотонной дозовой кривой и с
# зависимостью от пространственной структуры (тасовка адресатов роняет
# LPLC2 с 10,11 до 5,11), но НЕ замерен сквозной причинный ход от угрозы
# до движения. Граница `LC4/LPLC2` подаёт нависание прямо на
# проекционные, и тогда их отклик — поданный, а не посчитанный.
ОГРАНИЧЕНИЕ = {
    "на границе T4/T5 подача определяется прежде всего ОПТИЧЕСКИМ "
    "ПОТОКОМ ОТ СОБСТВЕННОГО ХОДА": True,
    "у идущей мухи без предмета, Гц": 33.2,
    "у идущей мухи с нависанием, Гц": 36.8,
    "вклад предмета у идущей мухи, раз": 1.108,
    "вклад предмета по LPLC2 у идущей мухи, раз": 1.093,
    "на замороженном теле по LPLC2, раз": 1.53,
    "DNp04 на замороженном теле": "молчит и с предметом, и без: 0 "
                                  "спайков против 0, тогда как у идущей "
                                  "мухи 3 спайка",
    "почему": "избирательность к нависанию переходник СЧИТАЕТ (38,8 "
              "против 27,9 при движении поперёк), но на границе T4/T5 не "
              "подаёт: её должны собрать настоящие связи T4/T5 -> LPLC2, "
              "а собрать её можно только по ретинотопии, которая у нас "
              "ОПРОВЕРГНУТА внешним свидетелем (FULL_LOOP_VALIDATION "
              "§3.1)",
    "что замерено": "передача по настоящим связям до LPLC2 и LC4, "
                    "монотонная дозовая кривая, зависимость от "
                    "пространственной структуры (тасовка роняет LPLC2 с "
                    "10,11 до 5,11)",
    "что НЕ замерено": "сквозной причинный ход от угрозы до движения",
}


def _выбрать(neurons, имя):
    """Нейроны популяции ТОЧНЫМ однополевым селектором."""
    from . import data as D
    return D.select(neurons, "celltype=%s" % имя)


class Мост:
    """Переходник, стыкованный с телом. Строится один раз на эпизод."""

    def __init__(self, neurons, weights, device="cpu",
                 граница=H.ГРАНИЦА_T4T5, усиление_hz=H.УСИЛЕНИЕ_HZ,
                 задержка_мс=H.ЗАДЕРЖКА_МС, кадр_мс=20.0,
                 тасовка=False, подтипы_тасовка=False, seed=0,
                 mode="whiten", assign="capacity", потолок_hz=1000.0):
        import scipy.sparse as sp
        import torch
        from scipy.spatial import cKDTree

        t0 = time.perf_counter()
        self.граница = граница
        self.device = device
        om = R.ommatidia()
        self.pos = np.asarray(om["pos"], dtype=np.float64)
        n_omma = len(self.pos)
        n = len(neurons)

        # --- кому подавать ------------------------------------------
        цели = (ПОДАЧА if граница == H.ГРАНИЦА_T4T5 else ПРОЕКЦИОННЫЕ)
        pops = {k: _выбрать(neurons, k) for k in
                set(цели) | set(ЛАМИНА) | set(МЕДУЛЛА) | {"L5"}}

        # --- наведение омматидия ------------------------------------
        #
        # Берутся только ВОЗБУЖДАЮЩИЕ связи: место рецептивного поля
        # наводится тем, что нейрон возбуждает, а не тем, что его
        # тормозит. Так же сделано в `probe/vision_phys_rf.py`.
        maps = R.build_all(neurons, mode=mode, assign=assign)
        pr_idx = np.unique(np.concatenate([maps[k].neurons for k in maps]))
        w = weights.coalesce()
        ii = w.indices().cpu().numpy()
        vv = w.values().cpu().numpy()
        поз = vv > 0
        A = sp.csr_matrix((vv[поз], (ii[0][поз], ii[1][поз])), shape=(n, n))
        xy = np.full((n, 2), np.nan)
        for _, m in maps.items():
            xy[m.neurons] = self.pos[m.omma]

        def навести(куда, откуда):
            S = A[куда][:, откуда]
            px, py = xy[откуда, 0], xy[откуда, 1]
            ок = np.isfinite(px)
            S, px, py = S[:, ок], px[ок], py[ок]
            вес = np.asarray(S.sum(1)).ravel()
            есть = вес > 0
            xy[куда[есть], 0] = np.asarray(S @ px).ravel()[есть] / вес[есть]
            xy[куда[есть], 1] = np.asarray(S @ py).ravel()[есть] / вес[есть]
            return int(есть.sum()), int(len(куда))

        лам = np.unique(np.concatenate([pops[k] for k in ЛАМИНА]))
        навести(лам, pr_idx)
        навести(pops["L5"], лам)
        мед = np.unique(np.concatenate([pops[k] for k in МЕДУЛЛА]))
        навести(мед, np.concatenate([лам, pops["L5"]]))
        источник = np.concatenate([мед, лам, pops["L5"]])
        наведено, всего = 0, 0
        for к in цели:
            e, a = навести(pops[к], источник)
            наведено += e
            всего += a
        self.наведено = (наведено, всего)

        # --- сторона берётся из столбца `side`, а не из имени --------
        side = np.asarray(neurons["side"]).astype(str)
        дерево = cKDTree(self.pos)
        g = np.random.default_rng(seed)
        self._адрес = {}        # (сторона, популяция) -> (idx нейронов, омма)
        без_стороны = 0
        for к in цели:
            idx = pops[к]
            p = xy[idx]
            ок = np.isfinite(p[:, 0])
            ном = np.zeros(len(idx), dtype=np.int64)
            if ок.any():
                ном[ок] = дерево.query(p[ок], k=1)[1]
            for с in ("left", "right"):
                берём = ок & (side[idx] == с)
                if not берём.any():
                    continue
                о = ном[берём]
                if тасовка:
                    # Те же числа, другой адресат: суммарный вход
                    # сохраняется побитово, разрушена только
                    # пространственная структура.
                    о = g.permutation(о)
                self._адрес[(с, к)] = (
                    torch.as_tensor(idx[берём], device=device,
                                    dtype=torch.long),
                    о.astype(np.int64))
            без_стороны += int((~np.isin(side[idx], ("left", "right"))).sum())
        self.без_стороны = без_стороны

        # --- переходник на каждый глаз ------------------------------
        порядок = (tuple(g.permutation(len(H.НАПРАВЛЕНИЯ)))
                   if подтипы_тасовка else None)
        self._пер = {}
        for с in ("left", "right"):
            п = H.Переходник(pos=self.pos, граница=граница,
                             задержка_мс=задержка_мс,
                             усиление_hz=усиление_hz, кадр_мс=кадр_мс)
            if порядок is not None:
                п.подтипы(порядок)
            self._пер[с] = п
        # ПОТОЛОК ПОДАЧИ. Объявленное правило, а не страховка:
        # `hz = min(hz, потолок)`, и доля упёршихся в него уезжает в
        # сводку — ровно так же устроен потолок фоторецепторов
        # (`vision_max_hz` и `в потолке, доля`).
        #
        # Почему он обязателен именно здесь. Значение коррелятора на
        # настоящем кадре глаза растёт с угловым размером предмета, и
        # при одном и том же усилении пик подачи зависит от длины
        # эпизода: замерено — при усилении 20 000 на эпизоде 0,8 с пик
        # остаётся под пределом, а на 1,4 с доходит до 13 320 Гц на
        # `T5c left`, то есть выше `sim.MAX_RATE_HZ`. Без потолка
        # годность усиления зависела бы от того, докуда успел подойти
        # предмет, и один и тот же переходник то работал бы, то
        # отказывал.
        #
        # Умолчание 1000 Гц — то же число и по той же причине, по
        # которой его выбрал прямой стимул из окна
        # (`live.MAX_STIM_HZ`): десятикратный запас до 10 000 Гц, где
        # вероятность доходит до единицы и пуассоновский вход
        # перестаёт быть пуассоновским вовсе — это уже не стимул, а
        # постоянная единица на каждом тике.
        self.потолок_hz = float(потолок_hz)
        if not (0.0 < self.потолок_hz <= S.MAX_RATE_HZ):
            raise ValueError(
                "потолок подачи переходника %r вне (0, %.0f]: выше "
                "предела пуассоновский вход перестаёт быть "
                "пуассоновским" % (потолок_hz, S.MAX_RATE_HZ))
        self._в_потолке = [0, 0]      # [упёрлось, всего]
        self.тасовка = bool(тасовка)
        self.подтипы_тасовка = bool(подтипы_тасовка)
        self.порядок_подтипов = порядок
        self.n_omma = n_omma
        self.сборка_с = round(time.perf_counter() - t0, 2)
        self._последнее = None

    # --- подача ------------------------------------------------------

    def feed(self, rates, per_omma):
        """Записать частоты границы в `rates` формы (1, n).

        ``per_omma`` — яркость на омматидий ОБОИХ глаз одной строкой,
        ровно то, что отдаёт `vision.RetinaAdapter.per_omma`: сторона 0
        — левый глаз. Форма проверяется, а не предполагается.
        """
        import torch

        v = np.asarray(per_omma, dtype=np.float64).ravel()
        if v.size != 2 * self.n_omma:
            raise ValueError(
                "яркость на омматидий имеет размер %d, ожидалось 2*%d"
                % (v.size, self.n_omma))
        глаз = {"left": v[:self.n_omma], "right": v[self.n_omma:]}
        свод = {"нейронов": 0, "средняя, Гц": 0.0, "наибольшая, Гц": 0.0,
                "нависание": {}, "по популяциям, Гц": {},
                "в потолке, доля": 0.0}
        было = list(self._в_потолке)
        сумма, число = 0.0, 0
        for с, п in self._пер.items():
            места = {}
            for (сс, к), (_, о) in self._адрес.items():
                if сс == с:
                    места[к] = о
            if not места:
                continue
            сиг, о = п.сигнал(глаз[с], места=места)
            свод["нависание"][с] = round(float(о["нависание"]), 6)
            for к, hz in сиг.items():
                idx, _ = self._адрес[(с, к)]
                hz = np.asarray(hz, dtype=np.float64)
                if hz.ndim == 0:
                    # На границе `LC4/LPLC2` переходник отдаёт ОДНО
                    # число на всю популяцию, а не частоту на нейрон:
                    # у LC4 и LPLC2 поле зрения широкое (замерено:
                    # разброс 0,070 и 0,076 размаха при 124 и 118
                    # партнёрах), и делать вид, что подача
                    # пространственная, нельзя. Здесь оно
                    # расписывается по нейронам популяции — то есть
                    # подаётся ВСЕЙ популяции одинаково, и это ровно
                    # то, что объявлено.
                    hz = np.full(len(idx), float(hz))
                упёрлось = int((hz >= self.потолок_hz).sum())
                self._в_потолке[0] += упёрлось
                self._в_потолке[1] += int(hz.size)
                hz = np.minimum(hz, self.потолок_hz)
                # Усиление переходника задаётся человеком и ничем не
                # ограничено, а выше предела `bernoulli` падает ассертом
                # карты, который портит контекст CUDA необратимо. Отказ
                # здесь громкий и называет глаз и популяцию.
                S.check_rates_hz(hz, "подача переходника на %s %s" % (к, с))
                t = torch.as_tensor(np.asarray(hz, dtype=np.float32),
                                    device=rates.device)
                rates[0].index_copy_(0, idx, t)
                сумма += float(np.sum(hz))
                число += int(np.size(hz))
                ключ = "%s %s" % (к, с)
                свод["по популяциям, Гц"][ключ] = round(
                    float(np.mean(hz)) if np.size(hz) else 0.0, 4)
