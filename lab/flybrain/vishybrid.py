"""Переходник: зрительная обработка ВНЕ сети с названной границей.

Это **инженерный переходник**, а не зрение по коннектому, и так он
называется везде: в коде, в сводке прогона и в отчёте. Он нужен там,
где опубликованной физиологии не хватает, чтобы сигнал прошёл по
настоящим связям, — и он обязан быть не выдуман, а **измерен**.

Что он считает и чего не считает.

**Считает — то, что у мухи считает ранняя зрительная система**, по
опубликованным схемам, прямо на решётке омматидиев:

* **каналы ON и OFF** — временной верхний фильтр яркости каждого
  омматидия с полуволновым выпрямлением. ON — нарастание яркости, OFF —
  спад. Это каноническое разделение (Joesch et al. 2010, Nature
  468:300: T4 отвечает на ON, T5 на OFF);
* **направленная избирательность** — корреляционный детектор
  Хассенштайна-Райхардта между соседними омматидиями (Hassenstein &
  Reichardt 1956). Четыре направления по гексагональной решётке;
* **нависание** — наружное движение тёмного края, то есть рост
  углового размера тёмного предмета.

**Не считает и не притворяется:** ни одна из этих величин не выведена
из коннектома. Соответствие «подтип T4a…d — направление» задано
соглашением этого модуля, а не данными; знак направления на нашей
привязке не определён в принципе (`VISION.md`, `VISUAL_COLUMNS.md`).

**Граница стыковки называется явно** и входит в сводку прогона. Два
положения, и они дают разное:

``ГРАНИЦА_T4T5``
    подача на T4a…d и T5a…d. Дальше сигнал идёт по **настоящим связям
    FlyWire**: T4/T5 → LPLC2, LC4 → DNp01. Отклики LC4, LPLC2 и DNp01
    при этой границе принадлежат настоящей связности, а смоделированы
    только сами направленные сигналы;

``ГРАНИЦА_ПРОЕКЦИОННЫЕ``
    подача прямо на LC4 и LPLC2. Это **ближе к выходу**, и отклики
    самих LC4 и LPLC2 тогда НЕ принадлежат никаким синапсам — они
    подана́ны. Настоящей связности принадлежит только то, что за
    ними, то есть DNp01. Такую границу выбирать можно, но называть
    отклик LC4 зрительным — нельзя.

Встречные замеры переходника — его собственные, и каждый умеет
провалить утверждение:

* **предмета нет** — однородное поле. Переходник обязан дать ноль;
* **обратное движение** — направления меняются местами;
* **перетасованное назначение** — те же числа подаются тем же
  популяциям, но нейронам в случайном порядке. Суммарный вход
  сохраняется побитово, разрушена только пространственная структура;
* **перетасованные подтипы** — соответствие «подтип — направление»
  перемешано. Суммарный вход тот же, разрушена только направленная
  структура.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

ГРАНИЦА_T4T5 = "T4/T5"
ГРАНИЦА_ПРОЕКЦИОННЫЕ = "LC4/LPLC2"
ГРАНИЦЫ = (ГРАНИЦА_T4T5, ГРАНИЦА_ПРОЕКЦИОННЫЕ)

# Подтипы T4 и T5 и направление, назначенное каждому. **Это
# соглашение модуля, а не данные.** В коннектоме нет поля, связывающего
# подтип с направлением взгляда, а знак направления к тому же задаёт
# наше совмещение привязки. Соглашение объявлено здесь одно и
# записывается в сводку прогона.
ПОДТИПЫ_T4 = ("T4a", "T4b", "T4c", "T4d")
ПОДТИПЫ_T5 = ("T5a", "T5b", "T5c", "T5d")
НАПРАВЛЕНИЯ = (0.0, 90.0, 180.0, 270.0)      # градусы в плоскости поля

ОТКУДА = {
    "разделение ON и OFF": (
        "литература",
        "T4 отвечает на нарастание яркости, T5 на спад: Joesch et al. "
        "2010, Nature 468:300; Maisak et al. 2013, Nature 500:212"),
    "корреляционный детектор": (
        "литература",
        "Hassenstein & Reichardt 1956, Z Naturforsch 11b:513 — "
        "умножение задержанного сигнала одного омматидия на текущий "
        "сигнал соседнего, с вычитанием обратного плеча"),
    "подтип → направление": (
        "СОГЛАШЕНИЕ ЭТОГО МОДУЛЯ, не данные",
        "в v783 нет поля, связывающего подтип T4 с направлением "
        "взгляда; знак направления к тому же задаёт совмещение "
        "привязки `ALIGN_DEFAULT`. Четыре направления назначены "
        "подтипам по порядку букв"),
    "задержка детектора": (
        "ПОДОГНАНО, с литературным коридором",
        "время задержки плеча коррелятора. У мухи постоянная времени "
        "зрительной задержки — десятки миллисекунд (Borst & Egelhaaf "
        "1989, Trends Neurosci 12:297). Взято 30 мс"),
    "усиление подачи": (
        "ПОДОГНАНО",
        "сколько герц подать на единицу выхода детектора. Чистая "
        "инженерная величина: ни из коннектома, ни из литературы не "
        "следует. Развёртывается пробой"),
}

ЗАДЕРЖКА_МС = 30.0
УСИЛЕНИЕ_HZ = 200.0


def соседи(pos, сколько=6):
    """Соседи каждого омматидия и направление на каждого, в градусах.

    Решётка гексагональная и это замерено (`retina.ommatidia`: шаг
    16,41 px, шестой сосед 16,62 px, разница 1,2 %), поэтому шесть
    ближайших — это и есть шесть соседей, а не произвольная выборка.
    """
    from scipy.spatial import cKDTree

    d, who = cKDTree(pos).query(pos, k=сколько + 1)
    who, d = who[:, 1:], d[:, 1:]
    dx = pos[who][:, :, 0] - pos[:, None, 0]
    dy = pos[who][:, :, 1] - pos[:, None, 1]
    ang = (np.degrees(np.arctan2(dy, dx)) + 360.0) % 360.0
    return who, d, ang


def сосед_по_направлению(pos, направления=НАПРАВЛЕНИЯ):
    """Для каждого омматидия — сосед, ближайший к каждому направлению.

    Возвращает массив ``(омматидиев, направлений)`` с номером соседа.
    Если подходящего соседа нет, стоит сам омматидий — тогда плечо
    детектора даёт ноль, и это честнее, чем взять дальнего.
    """
    who, d, ang = соседи(pos)
    out = np.empty((len(pos), len(направления)), dtype=np.int64)
    for k, целевое in enumerate(направления):
        раз = np.abs(((ang - целевое + 180.0) % 360.0) - 180.0)
        лучший = np.argmin(раз, axis=1)
        годен = раз[np.arange(len(pos)), лучший] <= 35.0
        сосед = who[np.arange(len(pos)), лучший]
        out[:, k] = np.where(годен, сосед, np.arange(len(pos)))
    return out


@dataclass
class Переходник:
    """Внешняя зрительная обработка с объявленной границей стыковки."""

    pos: np.ndarray                   # положения омматидиев
    граница: str = ГРАНИЦА_T4T5
    задержка_мс: float = ЗАДЕРЖКА_МС
    усиление_hz: float = УСИЛЕНИЕ_HZ
    кадр_мс: float = 10.0
    _сосед: np.ndarray = None
    _ист: list = None                 # история яркости
    _подтип_напр: tuple = None        # какому подтипу какое направление

    def __post_init__(self):
        if self.граница not in ГРАНИЦЫ:
            raise ValueError("не граница: %r, есть %s"
                             % (self.граница, ГРАНИЦЫ))
        self._сосед = сосед_по_направлению(self.pos)
        self._ист = []
        if self._подтип_напр is None:
            self._подтип_напр = tuple(range(len(НАПРАВЛЕНИЯ)))

    def сброс(self):
        self._ист = []

    def подтипы(self, порядок=None):
        """Сменить соответствие «подтип — направление».

        Это и есть встречный замер «перетасованные подтипы»: суммарный
        вход тот же, разрушена только направленная структура.
        """
        self._подтип_напр = tuple(порядок if порядок is not None
                                  else range(len(НАПРАВЛЕНИЯ)))

    # --- внешняя обработка -------------------------------------------

    def обработать(self, яркость):
        """Кадр яркости (721,) → каналы ON/OFF, движение, нависание.

        Временной верхний фильтр — разность с кадром, отстоящим на
        ``задержка_мс``. Это и фильтрация, и то самое плечо задержки,
        которое нужно коррелятору: одна величина, а не две подогнанные
        по отдельности.
        """
        L = np.asarray(яркость, dtype=np.float64).ravel()
        self._ист.append(L)
        шагов = max(1, int(round(self.задержка_мс / self.кадр_мс)))
        if len(self._ист) <= шагов:
            z = np.zeros(len(L))
            нд = np.zeros((len(L), len(НАПРАВЛЕНИЯ)))
            return {"ON": z, "OFF": z, "движение": нд,
                    "движение OFF": нд, "нависание": 0.0}
        пред = self._ист[-1 - шагов]
        d = L - пред
        on, off = np.maximum(d, 0.0), np.maximum(-d, 0.0)

        # Коррелятор: текущий сигнал омматидия на задержанный сигнал
        # соседа минус обратное плечо. Знак положителен для движения
        # в сторону направления.
        on_п = np.maximum(пред - (self._ист[-1 - 2 * шагов]
                                  if len(self._ист) > 2 * шагов
                                  else пред), 0.0)
        дв = np.empty((len(L), len(НАПРАВЛЕНИЯ)))
        for k in range(len(НАПРАВЛЕНИЯ)):
            j = self._сосед[:, k]
            дв[:, k] = on * on_п[j] - on[j] * on_п
        # Нависание: наружное движение тёмного края от центра поля.
        c = self.pos.mean(0)
        r = self.pos - c
        rn = np.linalg.norm(r, axis=1, keepdims=True)
        r = r / np.maximum(rn, 1e-9)
        напр_век = np.array([[np.cos(np.radians(a)), np.sin(np.radians(a))]
                             for a in НАПРАВЛЕНИЯ])
        наружу = (r @ напр_век.T)                 # проекция на направления
        off_дв = np.empty_like(дв)
        off_п = np.maximum((self._ист[-1 - 2 * шагов]
                            if len(self._ист) > 2 * шагов else пред)
                           - пред, 0.0)
        for k in range(len(НАПРАВЛЕНИЯ)):
            j = self._сосед[:, k]
            off_дв[:, k] = off * off_п[j] - off[j] * off_п
        нав = float(np.sum(np.maximum(off_дв, 0.0) * np.maximum(наружу,
                                                                0.0)))
        return {"ON": on, "OFF": off, "движение": дв,
                "движение OFF": off_дв, "нависание": нав}

    # --- подача на границу -------------------------------------------

    def сигнал(self, яркость, места, тасовка=None):
        """Частоты на популяции границы.

        ``места`` — словарь «имя популяции → номер омматидия для каждого
        её нейрона». Для T4/T5 это наведённое место (см.
        `probe/vision_phys_rf.py`), и оно объявлено инженерным.
        ``тасовка`` — словарь той же формы с перемешанными номерами: то
        же суммарное число, другой адресат.
        """
        о = self.обработать(яркость)
        места = тасовка if тасовка is not None else места
        out = {}
        if self.граница == ГРАНИЦА_T4T5:
            for i, нм in enumerate(ПОДТИПЫ_T4):
                if нм not in места:
                    continue
                k = self._подтип_напр[i]
                v = np.maximum(о["движение"][:, k], 0.0)
                out[нм] = self.усиление_hz * v[места[нм]]
            for i, нм in enumerate(ПОДТИПЫ_T5):
                if нм not in места:
                    continue
                k = self._подтип_напр[i]
                v = np.maximum(о["движение OFF"][:, k], 0.0)
                out[нм] = self.усиление_hz * v[места[нм]]
        else:
            # Прямо на проекционные. Нависание — одно число на всю
            # популяцию: у LC4 и LPLC2 поле зрения широкое (замерено:
            # разброс 0,070 и 0,076 размаха при 124 и 118 партнёрах),
            # и делать вид, что подача пространственная, нельзя.
            for нм in ("LC4", "LPLC2"):
                if нм in места:
                    out[нм] = float(self.усиление_hz * о["нависание"]
                                    / max(len(self.pos), 1))
        return out, о

    def сводка(self) -> dict:
        return {
            "ЭТО ПЕРЕХОДНИК, А НЕ ЗРЕНИЕ ПО КОННЕКТОМУ": True,
            "ГРАНИЦА СТЫКОВКИ": self.граница,
            "что за границей посчитано ВНЕ сети":
                (["направленные сигналы T4a…d и T5a…d"]
                 if self.граница == ГРАНИЦА_T4T5 else
                 ["отклик LC4 и LPLC2 на нависание целиком"]),
            "что принадлежит настоящим связям FlyWire":
                (["T4/T5 → LPLC2", "LC4 → DNp01", "всё глубже T4/T5"]
                 if self.граница == ГРАНИЦА_T4T5 else
                 ["LC4/LPLC2 → DNp01 и глубже"]),
            "задержка детектора, мс": self.задержка_мс,
            "усиление подачи, Гц": self.усиление_hz,
            "подтип → направление": {
                нм: НАПРАВЛЕНИЯ[self._подтип_напр[i]]
                for i, нм in enumerate(ПОДТИПЫ_T4)},
            "откуда числа": ОТКУДА,
        }
